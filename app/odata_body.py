# -*- coding: utf-8 -*-
"""Сборка тела авансового отчёта для 1С (1C-21, заход ③).

⚠️ ЧИСТАЯ ФУНКЦИЯ, БЕЗ БАЗЫ И БЕЗ СЕТИ. Всё, что нужно, приходит
аргументами: отчёт, чеки, настройки организации. Так её можно проверить
целиком, не поднимая ни 1С, ни PostgreSQL, — а проверять здесь есть что:
раскладка чека по ставкам НДС и подстановки счетов.

⚠️ ВСЁ, ЧТО НИЖЕ, — ЗАМЕР, А НЕ ДОГАДКА. Состав полей взят из живой схемы
(1C-20), поведение полей — из ПРОБНОЙ ЗАПИСИ в тестовую базу бюро, цифры
заполненности — из замера прода (1C-01). Где замера не было, стоит
отдельная пометка.

═══ ЧТО ИМЕННО ЗАМЕРЕНО И ПОЧЕМУ СДЕЛАНО ТАК ═══════════════════════════

① ИСТОЧНИК НДС — `receipts.vat_breakdown`, А НЕ `vat_total`. Замер прода
   16.09.2026: `vat_total` заполнен у НУЛЯ чеков из 106, свод — у 34.
   Колонка есть, данных в ней нет ни одной.

② СТРОКА «ПРОЧЕЕ» = ЧЕК × СТАВКА НДС. У строки в 1С ставка ОДНА
   (`СтавкаНДС`), а у чека их бывает несколько — значит один чек
   разворачивается в несколько строк. Пустой свод даёт ОДНУ строку
   «БезНДС»: ставки 0% и «без НДС» в свод не кладутся намеренно
   (`fns_parser._vat_breakdown`), и пустота означает именно их,
   а не потерю данных.

③ `Номенклатура_Key` НЕ ПЕРЕДАЁМ — проверено живой записью: документ
   записался и провёлся с пустой ссылкой. Это решение 1C-08: номенклатуру
   не создаём, чтобы не засорять справочник клиента наименованиями
   из чеков, как делает Pilx.

④ СУБКОНТО НЕ ПЕРЕДАЁМ — платформа подставляет их САМА по счёту затрат
   (проверено той же записью: пришли номенклатурная группа и статья
   затрат). ⚠️ НО СТАТЬЮ ОНА СТАВИТ СВОЮ, ПО УМОЛЧАНИЮ, и не ту, что
   в существующих документах базы. Поэтому своя статья передаётся явно
   через `Субконто2`, когда правило для категории есть.

⑤ ФД ОТСУТСТВУЕТ У 6 ЧЕКОВ ИЗ 106 (замер 1C-01). Пустое поле
   документа-основания хуже суррогатного номера, поэтому в
   `НомерВходящегоДокумента` едет номер чека в НАШЕЙ системе с приставкой.

⑥ ВАЛЮТА ПУСТА У 2 ЧЕКОВ — подставляется рубль.

⑦ ⚠️⚠️ ИНН ПРОДАВЦА ОТСУТСТВУЕТ У 5 ЧЕКОВ, И КОНТРАГЕНТ ДЛЯ НИХ
   НЕ НАХОДИТСЯ. Здесь НИЧЕГО НЕ ДОДУМЫВАЕТСЯ: `Поставщик_Key` остаётся
   пустым, а чек попадает в список `без_контрагента`, который ручка
   обязана показать человеку. Неверный контрагент в первичном документе
   хуже отсутствующего — то же основание, что в строке 33 про фото-чеки.
"""

from __future__ import annotations

from decimal import Decimal

# Ставка, которой в 1С называется её отсутствие. Значение из живого
# перечисления `Enum_СтавкиНДС` (замер 1C-20).
БЕЗ_НДС = "БезНДС"

# ⚠️⚠️ СЧЁТА ПО УМОЛЧАНИЮ ЗДЕСЬ БОЛЬШЕ НЕТ (1C-22, решение владельца
# 17.09.2026). Он переехал в профиль организации, `org_accounting_profile`.
# Довод замером: константа «20.01» пришла из пробной записи 1C-20 и для бюро
# НЕВЕРНА — у счёта 20.01 три вида субконто, первое из них номенклатурная
# группа, которой у нас нет и не будет (замер 17.09.2026). У бюро счёт 26,
# у следующего клиента будет свой. Это данные, и живут они в базе.

# Режимы НДС организации. Значения совпадают с CHECK в `org_accounting_profile`.
НДС_НЕ_ПЛАТЕЛЬЩИК = "not_payer"
НДС_В_СТОИМОСТИ = "included"
НДС_К_ВЫЧЕТУ = "deductible"

# Отражение в УСН пишется ТОЛЬКО на упрощёнке: на ОСНО этого поля
# в документе быть не должно вовсе.
РЕЖИМЫ_УСН = ("usn_income_expense", "usn_income")

# Как наши коды ставок ложатся на перечисление 1С. Ключи — то, что кладёт
# в свод `fns_parser`; значения — члены `Enum_СтавкиНДС` из живой схемы.
СТАВКА_В_1С = {
    "20": "НДС20",
    "10": "НДС10",
    "20/120": "НДС20_120",
    "10/110": "НДС10_110",
    "0": "НДС0",
    "5": "НДС5",
    "7": "НДС7",
    "5/105": "НДС5_105",
    "7/107": "НДС7_107",
    "без НДС": БЕЗ_НДС,
}


def _число(значение) -> float:
    """Decimal из базы → число для JSON. Пусто → ноль."""
    if значение is None:
        return 0.0
    if isinstance(значение, Decimal):
        return float(значение)
    return float(значение)


def _свод_ндс(чек: dict) -> dict:
    """{ставка: сумма} по чеку. Не словарь — считаем, что свода нет."""
    свод = чек.get("vat_breakdown")
    return свод if isinstance(свод, dict) and свод else {}


def строки_чека(
    чек: dict,
    правило: dict | None,
    контрагент: str | None = None,
    счета: dict | None = None,
    профиль: dict | None = None,
) -> list:
    """Чек → строки «Прочего». Сколько строк — решает режим НДС профиля.

    `правило` — запись `odata_category_map` для категории чека либо `None`.
    `контрагент` — найденная по ИНН ссылка на `Catalog_Контрагенты` либо `None`.
    `счета` — {код счёта: ссылка на элемент ChartOfAccounts_Хозрасчетный}.
    `профиль` — запись `org_accounting_profile`: режим налогообложения,
    режим НДС, счёт по умолчанию.

    ⚠️ ДРОБЛЕНИЕ ПО СТАВКАМ ЕСТЬ НЕ ВСЕГДА (1C-22). Разносить чек по ставкам
    имеет смысл там, где входящий НДС ПРИНИМАЕТСЯ К ВЫЧЕТУ: только тогда
    суммы налога живут в учёте отдельно. У неплательщика и там, где налог
    сидит в стоимости, отдельная строка НДС не значит ничего — чек уезжает
    одной строкой «БезНДС» на полную сумму.
    """
    профиль = профиль or {}
    режим_ндс = профиль.get("vat_mode")
    код_счёта = (правило or {}).get("account_code") or профиль.get(
        "default_account_code"
    )
    # ⚠️⚠️ В ПОЛЕ `СчетЗатрат_Key` ЕДЕТ ССЫЛКА, А НЕ КОД. Первая редакция
    # клала туда «20.01» — а 1С ждёт GUID элемента плана счетов: в пробной
    # записи 1C-20 уходил именно GUID из живого образца. Код счёта — то, что
    # пишет человек в настройке; ссылка — то, что понимает 1С. Переводит
    # одно в другое ручка отдельным чтением плана счетов.
    счёт = (счета or {}).get(код_счёта)
    статья = (правило or {}).get("expense_ref")

    основание = чек.get("fd_num") or ("чек №%s" % чек.get("id"))
    общая = _число(чек.get("amount"))
    свод = _свод_ндс(чек)

    def строка(ставка_1с, сумма, ндс):
        ряд = {
            "ВидДокВходящий": "Кассовый чек",
            "НомерВходящегоДокумента": основание,
            "ДатаВходящегоДокумента": _дата(чек.get("date")),
            "Содержание": (чек.get("статья") or чек.get("org") or "Расход")[:200],
            "Сумма": сумма,
            "СтавкаНДС": ставка_1с,
            "СуммаНДС": ндс,
            "СчетЗатрат_Key": счёт,
        }
        # ⚠️⚠️ ОтражениеВУСН — ИЗ СООТВЕТСТВИЯ И ТОЛЬКО НА УПРОЩЁНКЕ
        # (решение владельца 17.09.2026). Константа «Принимаются» врала дважды:
        # она отвечала за бухгалтера там, где расход в налоговом учёте
        # НЕ принимается, и уезжала в документ организации на ОСНО, где поля
        # этого быть не должно вовсе. Из статьи затрат признак не выводится:
        # в справочнике 1С его нет (замер 17.09.2026, 21 запись).
        if (профиль.get("tax_regime") in РЕЖИМЫ_УСН) and (правило or {}).get(
            "usn_reflection"
        ):
            ряд["ОтражениеВУСН"] = правило["usn_reflection"]
        # ⚠️ ПОСТАВЩИК — ССЫЛКОЙ, НАЙДЕННОЙ ПО ИНН, И ТОЛЬКО ЕЮ.
        # Первая редакция клала сюда «ИНН_поставщика» — поле, которого НЕТ
        # в схеме «Прочего» (замер 1C-20: 38 полей, ИНН среди них нет). Оно
        # уехало бы в чужую базу лишним и в лучшем случае было бы проигнорировано.
        # Контрагент в 1С — элемент справочника, и ищется он отдельным чтением.
        if контрагент:
            ряд["Поставщик_Key"] = контрагент
        # ⚠️ СТАТЬЯ — ТОЛЬКО ЯВНАЯ. Без неё платформа поставит свою,
        # и это замерено: в пробной записи пришла НЕ та, что в документах базы.
        if статья:
            ряд["Субконто2"] = статья
            ряд["Субконто2_Type"] = "StandardODATA.Catalog_СтатьиЗатрат"
        return ряд

    # ⚠️ РЕЖИМ НДС РЕШАЕТ РАНЬШЕ СВОДА. У неплательщика и там, где налог сидит
    # в стоимости, чек уезжает ОДНОЙ строкой на полную сумму: разносить нечего,
    # к вычету не принимается ничего, а лишние строки бухгалтер будет сверять
    # руками. Дробление остаётся только при `deductible`.
    if режим_ндс in (НДС_НЕ_ПЛАТЕЛЬЩИК, НДС_В_СТОИМОСТИ):
        return [строка(БЕЗ_НДС, общая, 0.0)]

    if not свод:
        # Пустой свод — это «0% и без НДС», а не потеря данных: такие ставки
        # в свод не кладутся намеренно.
        return [строка(БЕЗ_НДС, общая, 0.0)]

    ряды = []
    разнесено = 0.0
    for ставка, сумма_ндс in свод.items():
        ндс = _число(сумма_ндс)
        ряды.append(строка(СТАВКА_В_1С.get(str(ставка), БЕЗ_НДС), ндс, ндс))
        разнесено += ндс

    # ⚠️ ОСТАТОК ЧЕКА — ЭТО НЕ ОШИБКА, А УСТРОЙСТВО СВОДА: в нём лежат СУММЫ
    # НДС, а не суммы строк. Всё, что не попало в ставки, едет отдельной
    # строкой «БезНДС», иначе документ не сойдётся с чеком по сумме —
    # и это заметит бухгалтер клиента, а не мы.
    остаток = round(общая - разнесено, 2)
    if остаток > 0:
        ряды.append(строка(БЕЗ_НДС, остаток, 0.0))
    return ряды


def _дата(значение) -> str:
    """date/datetime → ISO без зоны, как принимает 1С."""
    if значение is None:
        return ""
    if hasattr(значение, "isoformat"):
        строка = значение.isoformat()
        return строка if "T" in строка else строка + "T00:00:00"
    return str(значение)


def собрать(отчёт: dict, чеки: list, настройки: dict) -> dict:
    """Тело документа для 1С плюс то, что обязан увидеть человек.

    `настройки` — что известно про организацию:
        организация, склад, ответственный, валюта — ссылки на элементы 1С;
        человек — ссылка на `Catalog_ФизическиеЛица` подотчётного лица;
        правила — {category_id: запись odata_category_map};
        контрагенты — {ИНН: ссылка на Catalog_Контрагенты};
        счета — {код счёта: ссылка на ChartOfAccounts_Хозрасчетный};
        профиль — запись `org_accounting_profile` организации.

    Возвращает `{"тело": …, "без_соответствия": […], "без_контрагента": […]}`.
    ⚠️ ДВА ПОСЛЕДНИХ СПИСКА — НЕ ОТЛАДКА, А ЧАСТЬ ДОГОВОРА: без них
    «сработало» прочитается как «разнесено верно», а это разные вещи.

    ⚠️ «БЕЗ СООТВЕТСТВИЯ» — ЭТО БЛОКЕР ПРОВЕДЕНИЯ (1C-22, Р1). Раньше список
    назывался «по умолчанию» и означал «счёт подставлен»: документ уезжал
    проведённым, а всё лежало на одном счёте без статьи. Теперь категория
    без правила проведение ОСТАНАВЛИВАЕТ, и её имя обязано дойти до человека.
    """
    правила = настройки.get("правила") or {}
    контрагенты = настройки.get("контрагенты") or {}
    счета = настройки.get("счета") or {}
    профиль = настройки.get("профиль") or {}
    строки, без_соответствия, без_контрагента, нет_счёта = [], [], [], []

    for чек in чеки:
        правило = правила.get(чек.get("category_id"))
        # ⚠️ ПРАВИЛО БЕЗ СТАТЬИ — НЕ ПРАВИЛО. База такую строку не примет
        # (expense_ref NOT NULL), но проверка стоит и здесь: сборка обязана
        # вести себя одинаково с любыми данными, а не только с чистыми.
        if not правило or not правило.get("expense_ref"):
            правило = None
            имя = чек.get("статья") or "без категории"
            if имя not in без_соответствия:
                без_соответствия.append(имя)
        # ⚠️ ДВА РАЗНЫХ СЛУЧАЯ ОДНОГО ИСХОДА: ИНН нет вовсе (5 чеков из 106)
        # или ИНН есть, а контрагента с ним в базе клиента нет. В обоих
        # поставщик НЕ ставится и НЕ СОЗДАЁТСЯ — пополнять чужой справочник
        # в этом заходе запрещено, а додумывать контрагента нельзя вообще.
        контрагент = контрагенты.get(чек.get("org_inn")) if чек.get("org_inn") else None
        if not контрагент:
            без_контрагента.append(чек.get("id"))
        # ⚠️ СЧЁТА С ТАКИМ КОДОМ В БАЗЕ КЛИЕНТА МОЖЕТ НЕ БЫТЬ ВОВСЕ. Это не
        # «подставим умолчание», а отказ: документ со ссылкой в никуда 1С
        # не проведёт, а разбираться будет её бухгалтер.
        код = (правило or {}).get("account_code") or профиль.get("default_account_code")
        if код not in счета and код not in нет_счёта:
            нет_счёта.append(код)
        строки.extend(строки_чека(чек, правило, контрагент, счета, профиль))

    for номер, ряд in enumerate(строки, start=1):
        ряд["LineNumber"] = str(номер)

    тело = {
        "Date": _дата(отчёт.get("created")),
        # ⚠️ ВИД ОПЕРАЦИИ ВСЕГДА «ПокупкаОплатаПрочее»: типа отчёта у нас нет
        # ни в каком виде (подтверждено замером 1C-01 по обоим репозиториям),
        # а командировку из категорий чеков не вывести — в одном отчёте лежат
        # чеки разных групп. Заводится строкой 1C-05.
        "ВидОперации": "ПокупкаОплатаПрочее",
        "Организация_Key": настройки.get("организация"),
        "ФизЛицо_Key": настройки.get("человек"),
        "ВалютаДокумента_Key": настройки.get("валюта"),
        "Склад_Key": настройки.get("склад"),
        "Ответственный_Key": настройки.get("ответственный"),
        "СуммаДокумента": round(sum(_число(ч.get("amount")) for ч in чеки), 2),
        # Эти четыре заполнял живой образец из базы бюро; без них документ
        # записывается, но выглядит непривычно для бухгалтера.
        "КурсДокумента": 1,
        "КратностьДокумента": "1",
        "СуммаВключаетНДС": True,
        "НДСВключенВСтоимость": True,
        "Комментарий": "АОЦГ: отчёт №%s" % отчёт.get("id"),
        "Прочее": строки,
    }
    return {
        "тело": тело,
        "без_соответствия": без_соответствия,
        "без_контрагента": без_контрагента,
        # Коды счетов, которых НЕТ в плане счетов клиента. Непустой список —
        # это отказ, а не предупреждение: ручка документ не отправит.
        "нет_счёта": нет_счёта,
    }
