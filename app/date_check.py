"""Правдоподобность даты чека — чистая функция, без SQL и без сети (строка 24).

ЗАЧЕМ. 12.08.2026 распознавание вернуло на сегодняшний чек дату 2024-12-26,
а на августовский — 2026-01-12 (перепутаны день и месяц). Оба чека сохранились
МОЛЧА: проверки правдоподобности не было вообще, и в базе спокойно лежит чек
2024 года, попавший туда ошибкой.

ЧТО ЭТО НЕ ДЕЛАЕТ. Не блокирует сохранение — решение владельца: «чек может
быть и правда старым». Задача функции — дать ТЕКСТ ПРЕДУПРЕЖДЕНИЯ, который
увидит человек ДО сохранения, а решение оставить за ним.

ДОПУСК В БУДУЩЕЕ — ОДНИ СУТКИ, И ЭТО НЕ ЩЕДРОСТЬ. Сервер живёт по UTC,
а чек несёт СТЕННОЕ время кассы; в России одиннадцать часовых поясов, и чек,
пробитый ночью во Владивостоке, по серверным меркам оказывается «завтрашним».
Без допуска мы предупреждали бы о нормальных чеках — то есть учили бы
не смотреть на предупреждения. Тот же довод, по которому мы отказались
помечать время чека московской зоной (строка 20).
"""

from __future__ import annotations

from datetime import date, timedelta
from typing import Optional

# Насколько давно чек считается подозрительно старым. Год — не догма,
# а порог, за которым авансовый отчёт уже не сдают.
MAX_AGE_DAYS = 365

# Допуск на разницу часовых поясов (см. шапку).
FUTURE_TOLERANCE_DAYS = 1


def date_warning(value: Optional[date], today: Optional[date] = None) -> Optional[str]:
    """Текст предупреждения или None, если с датой всё в порядке.

    None на пустой и на нормальной дате — намеренно ОДИНАКОВО: «нечего
    сказать» и «сказать нечего» здесь совпадают, а отсутствующую дату
    ловит обязательность поля, а не эта проверка.
    """
    if value is None:
        return None
    today = today or date.today()

    if value > today + timedelta(days=FUTURE_TOLERANCE_DAYS):
        return (
            "Дата чека — %s, это будущее. Проверьте: обычно так выглядит "
            "ошибка распознавания." % value.strftime("%d.%m.%Y")
        )

    age = (today - value).days
    if age > MAX_AGE_DAYS:
        years = age // 365
        сколько = "%d года" % years if years > 1 else "года"
        return (
            "Дата чека — %s, это старше %s. Проверьте: обычно так выглядит "
            "ошибка распознавания." % (value.strftime("%d.%m.%Y"), сколько)
        )
    return None
