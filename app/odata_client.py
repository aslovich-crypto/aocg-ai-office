# -*- coding: utf-8 -*-
"""Клиент OData к 1С организации (1C-21, заход ①).

⚠️ ОТДЕЛЬНЫМ МОДУЛЕМ ВЕРХНЕГО УРОВНЯ, А НЕ В `app/routers`. В роутерах
лежат ручки, а работа с внешним миром вынесена — `storage/s3.py`,
`receipt_photo.py`, `email_service.py`. Клиент чужой системы — из этого же
ряда: у него своя жизнь, свои таймауты и своя граница доверия.

⚠️ ОБРАЗЕЦ ВЗЯТ У `спросить_фнс` (`app/routers/fns.py`) ЦЕЛИКОМ, И ЭТО
НЕ ЛЕНЬ, А РЕШЕНИЕ: там уже оплачено разбирательство, чем отличается
транспортная ошибка от ответа сервиса. **Повтор делается ТОЛЬКО на
транспортной ошибке.** Получен любой HTTP-код — значит чужая система нас
услышала и ответила; повторять такой запрос нельзя, особенно когда
следующим шагом будет ЗАПИСЬ в чужую бухгалтерию.

⚠️⚠️ ДОСТУПЫ ЖИВУТ В ПЕРЕМЕННЫХ ОКРУЖЕНИЯ (решение владельца 16.09.2026).
Довод записан там же: `aocg_security/crypto.py` — ПУСТОЙ ФАЙЛ, 0 строк,
то есть «шифровать в БД» означает написать криптографию с нуля ради одной
организации, а мастер-ключ всё равно лёг бы в переменную окружения.
Таблица доступов заводится, когда появятся клиенты, — не раньше.

⚠️⚠️ НИ ЛОГИН, НИ ПАРОЛЬ, НИ СТРОКА АВТОРИЗАЦИИ НЕ ПОПАДАЮТ НИКУДА:
ни в журнал, ни в текст ошибки, ни в приёмник событий. В журнал уходят
только путь без имени хоста, код ответа и длительность. Адрес базы тоже
не печатаем целиком: в нём видно, чья это база.

⚠️ ГРАНИЦА ЭТОГО МОДУЛЯ, НАЗВАНА ЯВНО. В заходе ① 1C-21 здесь было только
чтение; с выгрузкой авансового отчёта (1C-23) через `запросить` идёт
и ЗАПИСЬ — создание документа и его проведение, методом POST. Прежняя
фраза «здесь только чтение» устарела и снята 22.09.2026 (1C-29).
Зелёные тесты на этот модуль НЕ означают, что запись авансового отчёта
работает — они означают ровно то, что проверяют: состав запроса и разбор
ответа.

⚠️⚠️ МЕТОДЫ — ТОЛЬКО ИЗ СПИСКА `ДОПУСТИМЫЕ_МЕТОДЫ`, И DELETE В НЁМ НЕТ
НАМЕРЕННО (1C-29, решение владельца 22.09.2026). В OData 1С метод DELETE
удаляет объект ФИЗИЧЕСКИ, без пометки на удаление: документ исчезает из
базы клиента безвозвратно, и бухгалтер его не увидит. Пометка ставится
только PATCH с `DeletionMark`. Правило в CLAUDE.md держится на внимании
человека; здесь оно держится кодом — отказ ДО сети, а не после.
"""

from __future__ import annotations

import asyncio
import logging
import os
import re
import time
from typing import Optional

import httpx

logger = logging.getLogger(__name__)

# Имена переменных окружения — в одном месте, чтобы `env_check` и клиент
# спрашивали одно и то же, а не две похожие строки в разных файлах.
ПЕРЕМЕННАЯ_АДРЕСА = "ODATA_URL"
ПЕРЕМЕННАЯ_ЛОГИНА = "ODATA_LOGIN"
ПЕРЕМЕННАЯ_ПАРОЛЯ = "ODATA_PASSWORD"

# ⚠️ ТАЙМАУТ КОРОЧЕ, ЧЕМ У ФНС (там 30 с): 1С:Фреш отвечает на чтение схемы
# за секунды, а долгое ожидание внешней системы держит наш воркер.
ТАЙМАУТ = float(os.getenv("ODATA_TIMEOUT", "20"))
ПАУЗА_МЕЖДУ_ПОПЫТКАМИ = 1.0
ПОПЫТОК = 2

# ⚠️ СПИСОК РАЗРЕШЁННОГО, А НЕ ЗАПРЕЩЁННОГО: метод, которого здесь нет,
# не уходит в 1С вовсе — в том числе тот, о котором мы сегодня не подумали
# (PUT, MERGE). DELETE не добавлять — см. докстроку модуля.
ДОПУСТИМЫЕ_МЕТОДЫ = ("GET", "POST", "PATCH")


class НетДоступов(RuntimeError):
    """Переменные окружения не заданы — обмен с 1С выключен целиком."""


def настройки() -> tuple[str, str, str]:
    """(адрес, логин, пароль) или `НетДоступов`.

    Адрес нормализуется по хвосту: с косой чертой на конце и без неё —
    один и тот же адрес, а склейка «адрес + /$metadata» на разнице ломается.
    """
    адрес = (os.getenv(ПЕРЕМЕННАЯ_АДРЕСА) or "").strip().rstrip("/")
    логин = (os.getenv(ПЕРЕМЕННАЯ_ЛОГИНА) or "").strip()
    пароль = os.getenv(ПЕРЕМЕННАЯ_ПАРОЛЯ) or ""
    if not (адрес and логин and пароль):
        raise НетДоступов(
            "Обмен с 1С не настроен: задайте %s, %s и %s"
            % (ПЕРЕМЕННАЯ_АДРЕСА, ПЕРЕМЕННАЯ_ЛОГИНА, ПЕРЕМЕННАЯ_ПАРОЛЯ)
        )
    return адрес, логин, пароль


def настроено() -> bool:
    """Есть ли доступы. Без исключения — для ручек, которые сами решают."""
    try:
        настройки()
        return True
    except НетДоступов:
        return False


def безопасный_адрес(адрес: str) -> str:
    """Адрес для журнала: схема и хвост пути, без хоста и без учётки.

    ⚠️ ХОСТ УБИРАЕТСЯ НАМЕРЕННО. В нём имя площадки и номер области данных
    клиента — то есть по журналу видно, ЧЬЮ бухгалтерию мы дёргаем. Для
    разбора сбоя достаточно знать, какой ресурс спрашивали.
    """
    без_учётки = re.sub(r"//[^/@]*@", "//", адрес or "")
    м = re.match(r"^(https?)://[^/]+(/.*)?$", без_учётки)
    if not м:
        return "<адрес скрыт>"
    хвост = м.group(2) or "/"
    # Показываем только последние два сегмента пути: этого хватает, чтобы
    # отличить $metadata от документа, и мало, чтобы узнать базу.
    куски = [к for к in хвост.split("/") if к]
    return "%s://…/%s" % (м.group(1), "/".join(куски[-2:]) if куски else "")


async def запросить(
    путь: str,
    *,
    метод: str = "GET",
    параметры: Optional[dict] = None,
    тело: Optional[dict] = None,
) -> tuple[int, object]:
    """(код, тело). Код 200 — тело разобрано. 503 — до 1С не дошли.

    ⚠️⚠️ ПОВТОР ДЕЛАЕТСЯ ТОЛЬКО ПРИ ЧТЕНИИ. Это уточнение захода ③,
    и оно строже прежнего правила. Раньше повтор запрещался после ОТВЕТА
    сервера; теперь при ЗАПИСИ он запрещён ВООБЩЕ, даже на обрыве связи.
    Довод: оборванный POST мог ДОЙТИ и создать документ, а ответ потеряться
    по дороге. Повторив, мы заведём второй авансовый отчёт в учёте клиента
    и узнаем об этом от его бухгалтера. Лучше честное «не знаю, дошло ли»
    — на него у ручки есть ответ: журнал выгрузок и путь «отменить».

    ⚠️ МЕТОД ВНЕ `ДОПУСТИМЫЕ_МЕТОДЫ` — ИСКЛЮЧЕНИЕ ДО ДОСТУПОВ И ДО СЕТИ,
    а не код ответа. Код ответа вызывающий может не разобрать и пойти
    дальше; исключение остановит его на месте. Это ошибка программиста,
    а не событие обмена, и выглядеть она обязана как ошибка.
    """
    if метод.upper() not in ДОПУСТИМЫЕ_МЕТОДЫ:
        raise ValueError(
            "метод %s к 1С запрещён: разрешены только %s"
            % (метод, ", ".join(ДОПУСТИМЫЕ_МЕТОДЫ))
        )
    try:
        адрес, логин, пароль = настройки()
    except НетДоступов as e:
        return 503, {"status": "odata_not_configured", "message": str(e)}

    полный = адрес + "/" + путь.lstrip("/")
    для_журнала = безопасный_адрес(полный)
    ответ = None
    последняя_беда: Optional[str] = None
    начало = time.monotonic()

    # ⚠️ ЧТЕНИЕ ПОВТОРЯЕМ, ЗАПИСЬ — НИКОГДА, см. докстроку.
    попыток = ПОПЫТОК if метод.upper() == "GET" else 1

    async with httpx.AsyncClient(timeout=ТАЙМАУТ) as клиент:
        for попытка in range(1, попыток + 1):
            try:
                ответ = await клиент.request(
                    метод,
                    полный,
                    params=параметры,
                    json=тело,
                    auth=(логин, пароль),
                    headers={"Accept": "application/json"},
                )
                break  # получен HTTP-ответ — повтора нет, см. докстроку
            except (httpx.TimeoutException, httpx.HTTPError) as e:
                # ⚠️ В ЖУРНАЛ — ТИП ОШИБКИ, А НЕ ЕЁ ТЕКСТ. httpx кладёт в текст
                # адрес целиком, а в адресе видно чужую базу.
                последняя_беда = type(e).__name__
                logger.warning(
                    "OData: попытка %d из %d не удалась (%s), %s",
                    попытка,
                    попыток,
                    последняя_беда,
                    для_журнала,
                )
                ответ = None
            if попытка < попыток:
                await asyncio.sleep(ПАУЗА_МЕЖДУ_ПОПЫТКАМИ)

    прошло = round((time.monotonic() - начало) * 1000)
    if ответ is None:
        logger.warning("OData: недоступна (%s), %s мс", последняя_беда, прошло)
        return 503, {
            "status": "odata_unavailable",
            "message": "1С не отвечает",
            "причина": последняя_беда,
            "мс": прошло,
        }

    logger.info(
        "OData: %s %s → %s, %s мс", метод, для_журнала, ответ.status_code, прошло
    )
    if ответ.status_code >= 400:
        # ⚠️ ТЕЛО ЧУЖОЙ ОШИБКИ НАРУЖУ НЕ ОТДАЁМ И В ЖУРНАЛ НЕ ПИШЕМ: 1С кладёт
        # туда имя пользователя и путь. Наружу — код и наше слово.
        return ответ.status_code, {
            "status": "odata_error",
            "message": "1С ответила отказом",
            "код": ответ.status_code,
            "мс": прошло,
        }
    # ⚠️ РАЗБИРАТЬ JSON ОБЯЗАТЕЛЬНО МЯГКО: `$metadata` отдаётся XML-ом, и это
    # не ошибка, а устройство OData. Схему мы не парсим — нам довольно того,
    # что она пришла и сколько её.
    try:
        тело = ответ.json()
    except ValueError:
        тело = {"размер": len(ответ.content)}
    return 200, {
        "тело": тело,
        "мс": прошло,
        "тип": ответ.headers.get("content-type", ""),
        # Версия интерфейса приходит ЗАГОЛОВКОМ, а не в теле (замер 1C-20).
        "версия": ответ.headers.get("DataServiceVersion", ""),
    }


async def проверить_связь() -> dict:
    """Проба: дошли ли мы до 1С. ТОЛЬКО ЧТЕНИЕ схемы, ничего не создаёт.

    Спрашивается `$metadata`: это самый дешёвый ресурс, который отвечает
    только при верных доступах, и он же называет версию интерфейса —
    ЗАГОЛОВКОМ `DataServiceVersion`, а не в теле (замерено в 1C-20; сама
    схема приходит XML-ом, и разбирать её здесь незачем).
    """
    код, тело = await запросить("$metadata")
    if код == 503:
        return {"дошли": False, **(тело if isinstance(тело, dict) else {})}
    if код >= 400:
        return {"дошли": False, **(тело if isinstance(тело, dict) else {})}
    т = тело if isinstance(тело, dict) else {}
    return {
        "дошли": True,
        "мс": т.get("мс"),
        "версия": т.get("версия") or "—",
        "тип_ответа": т.get("тип") or "—",
    }
