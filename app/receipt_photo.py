"""Отдача снимка чека БАЙТАМИ — один источник для человека и для ключа.

⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ВТОРАЯ ТАКАЯ ЖЕ РУЧКА. Заход ⑥ даёт снимок
машине, и данные у него те же, что у человека: три источника в строгом
порядке — ключ в приватном бакете, внешний адрес, base64 внутри `raw_data`.
Скопировать эту лесенку значит завести две, которые разойдутся молча: обе
ручки ответят 200 и отдадут разное. Ровно тот же довод, по которому сбор
отчёта вынесен в `app/reports_data.py` (заход ①).

⚠️ ПОРЯДОК ИСТОЧНИКОВ ЗНАЧИМ И ЗАКРЕПЛЁН ТЕСТАМИ. До конца S-40 старые и
новые чеки живут ОДНОВРЕМЕННО: у старых снимок в базе, у новых — в хранилище.
Перевернётся порядок — часть чеков начнёт отдавать устаревший источник, и
снаружи это выглядит как «фото просто другое», а не как ошибка.

⚠️ `no-store` ВО ВСЕХ ТРЁХ ВЕТКАХ, РЕШЕНИЕ ВЛАДЕЛЬЦА 13.09.2026. До этого
захода заголовок стоял только на первой: ветка внешнего адреса и ветка
base64 отдавали снимок без него. Снимок — персональные данные в ЛЮБОЙ ветке,
и промежуточному узлу его кэшировать нельзя независимо от того, откуда мы
его достали. Расширение объёма на отдачу человеку разрешено исключением
13а.17: тот же файл и тот же класс.

⚠️ РАЗНИЦА МЕЖДУ ЧЕЛОВЕКОМ И КЛЮЧОМ РОВНО ОДНА — ВЕТКА ВНЕШНЕГО АДРЕСА.
Человеку она отвечает 302 на сам адрес: браузер сходит туда сам. Ключу
302 не отдаётся НИ В КАКОМ ВИДЕ (решение владельца 13.09.2026) — адрес уехал
бы на чужую машину и зажил своей жизнью, а это ровно то, ради чего подписанных
ссылок в машинном ответе нет вовсе. Поэтому у ключа байты идут через нас
во всех трёх ветках. Признак передаётся ЯВНЫМ параметром, а не выводится
из роли: роль здесь ни при чём, разница в том, кто на другом конце провода.

⚠️⚠️ И ПОЧЕМУ ЧУЖОЙ АДРЕС НЕ КАЧАЕТСЯ КУДА ПОПАЛО. `receipts.photo_url` —
колонка, которую клиент задаёт САМ при заведении чека (`photo_url` есть
в теле POST). Пока мы отвечали человеку редиректом, ходил по этому адресу
его браузер. Для ключа по адресу пойдёт НАШ сервер — то есть произвольный
адрес из базы превращается в запрос изнутри нашей сети, к внутренним службам
и служебным адресам облака в том числе. Поэтому качаем только по https и
только с хостов, которые назвали заранее. Всё прочее — тот же 404, что и
«снимка нет»: разные ответы рассказали бы, какой адрес сервер согласился
попробовать.
"""

import base64
import binascii
import logging
from urllib.parse import urlparse

from fastapi import HTTPException
from fastapi.responses import RedirectResponse, Response

from app.storage import s3

logger = logging.getLogger(__name__)

# Три колонки, из которых собирается снимок. Один список на оба запроса —
# человеческий и ключевой, чтобы выборки не разошлись по составу.
ПОЛЯ_СНИМКА = "photo_key, photo_url, raw_data"

# ⚠️ ПЕРСОНАЛЬНЫЕ ДАННЫЕ НЕ КЭШИРУЮТСЯ НИГДЕ ПО ДОРОГЕ. Заголовок один
# и тот же для всех веток и обоих потребителей — разные значения означали бы,
# что у одного и того же снимка разная чувствительность.
ЗАГОЛОВКИ_СНИМКА = {"Cache-Control": "no-store"}

# Хосты, с которых МОЖНО качать снимок по внешнему адресу, сверх адреса
# самого хранилища (он добавляется из настроек в момент запроса).
#
# ⚠️ СПИСОК ПУСТ НАМЕРЕННО, И ЭТО НЕ ЗАГЛУШКА. Какие адреса реально лежат
# в `photo_url` на бою — неизвестно: замер делает владелец на бастионе
# (SQL приложен к заходу ⑥). Вписывать сюда хосты по догадке значит открыть
# нашему серверу дорогу туда, куда мы её не открывали осознанно. Пока список
# пуст, ключ получает по внешнему адресу тот же 404, и это названо хвостом
# захода, а не выдано за работающую ветку.
ДОПОЛНИТЕЛЬНЫЕ_ХОСТЫ_СНИМКОВ = ()

СРОК_ЧУЖОГО_АДРЕСА = 15.0


def _нет_снимка() -> HTTPException:
    """Единственный отказ «снимка нет». Один текст на все случаи: адрес не с того
    хоста, объекта нет в бакете, в строке пусто — снаружи это одно и то же."""
    return HTTPException(status_code=404, detail="No photo for this receipt")


def _адрес_разрешён(адрес: str, cfg) -> bool:
    """Внешний адрес годится к скачиванию НАМИ: https и заранее названный хост."""
    try:
        разобран = urlparse(адрес)
    except ValueError:
        return False
    if разобран.scheme != "https" or not разобран.hostname:
        return False
    хосты = set(ДОПОЛНИТЕЛЬНЫЕ_ХОСТЫ_СНИМКОВ)
    if cfg is not None:
        # `host` может нести порт — сравниваем по имени, как его видит разбор.
        хосты.add(cfg.host.split("/", 1)[0].split(":", 1)[0])
    return разобран.hostname in хосты


async def _скачать(адрес: str, номер: int):
    """Байты чужого адреса. Ошибку наружу не пересказываем."""
    import httpx

    try:
        async with httpx.AsyncClient(
            timeout=СРОК_ЧУЖОГО_АДРЕСА, follow_redirects=False
        ) as клиент:
            ответ = await клиент.get(адрес)
    except httpx.HTTPError:
        logger.warning("Внешний адрес снимка недоступен, чек id=%s", номер)
        raise HTTPException(status_code=502, detail="Storage is unavailable")
    if ответ.status_code >= 300:
        # ⚠️ 3xx ТОЖЕ ОТКАЗ, А НЕ УСПЕХ: `follow_redirects=False` стоит
        # намеренно — иначе проверка хоста обходится одним перенаправлением
        # на любой внутренний адрес.
        logger.warning(
            "Внешний адрес снимка отдал HTTP %d, чек id=%s", ответ.status_code, номер
        )
        raise _нет_снимка()
    return ответ.content, ответ.headers.get("content-type") or "image/jpeg"


async def отдать(строка, *, номер: int, редиректом: bool):
    """Снимок чека по строке из базы. Три источника, порядок закреплён.

    `редиректом=True` — человеку: ветка внешнего адреса отвечает 302, туда
    идёт его браузер. `редиректом=False` — ключу: байты во всех трёх ветках.
    """
    if строка["photo_key"]:
        cfg = s3.S3Config.from_env()
        if cfg is None:
            # Ключ есть, а хранилище не настроено — это расхождение настроек,
            # а не отсутствие фото. Молчать нельзя: 404 читался бы как «снимка нет».
            raise HTTPException(status_code=503, detail="Storage is not configured")
        try:
            содержимое, тип = await s3.get_object(cfg, строка["photo_key"])
        except s3.ObjectNotFound:
            # Ключ в базе есть, объекта в бакете нет — рассинхрон, но для
            # потребителя это именно «фото нет».
            logger.warning("Фото по ключу отсутствует в хранилище, чек id=%s", номер)
            raise _нет_снимка()
        except s3.StorageError:
            # 152-ФЗ: наружу не отдаём ни ключ, ни адрес, ни ответ поставщика.
            logger.warning("Хранилище не отдало фото, чек id=%s", номер)
            raise HTTPException(status_code=502, detail="Storage is unavailable")
        return Response(content=содержимое, media_type=тип, headers=ЗАГОЛОВКИ_СНИМКА)

    if строка["photo_url"]:
        if редиректом:
            return RedirectResponse(
                url=строка["photo_url"],
                status_code=302,
                headers=ЗАГОЛОВКИ_СНИМКА,
            )
        cfg = s3.S3Config.from_env()
        if not _адрес_разрешён(строка["photo_url"], cfg):
            logger.warning(
                "Внешний адрес снимка не в списке разрешённых, чек id=%s", номер
            )
            raise _нет_снимка()
        содержимое, тип = await _скачать(строка["photo_url"], номер)
        return Response(content=содержимое, media_type=тип, headers=ЗАГОЛОВКИ_СНИМКА)

    сырое = строка["raw_data"] if isinstance(строка["raw_data"], dict) else {}
    снимок = сырое.get("photo_base64") if сырое else None
    if not снимок:
        raise _нет_снимка()
    try:
        байты = base64.b64decode(снимок, validate=True)
    except (binascii.Error, ValueError):
        raise HTTPException(status_code=500, detail="Corrupt photo data")
    return Response(content=байты, media_type="image/jpeg", headers=ЗАГОЛОВКИ_СНИМКА)
