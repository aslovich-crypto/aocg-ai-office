"""Сборка динамической части UPDATE — одним местом на все роутеры (T38).

ПОЧЕМУ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ. Одна и та же операция была написана ЧЕТЫРЕЖДЫ
своими словами: `receipts.py` (patch_receipt), `users.py` дважды (PATCH /me
и PATCH /{id}), `categories.py`. Каждый раз надо было собрать `col=$1, col2=$2`,
не сбиться в нумерации плейсхолдеров и не забыть фильтр по белому списку.

ГЛАВНОЕ ЗДЕСЬ НЕ УДОБСТВО, А ГАРАНТИЯ. Инъекции в тех четырёх местах не было
(проверено по коду 08.08.2026, задача S-22): имена колонок всюду приходили
из белых списков. Но держалось это на внимательности — в каждом месте кто-то
не забыл фильтр. Теперь имя колонки, которого нет в разрешённых, не доедет
до текста запроса физически: функция откажется его собирать.

ЧТО НЕ ДЕЛАЕТ: не строит WHERE и не решает, что менять. Нумерация плейсхолдеров
начинается с $1, дальше вызывающий продолжает своими значениями — так же,
как было в каждом из четырёх мест.
"""

from __future__ import annotations

import re
from typing import Any, Iterable

# Имя колонки: только строчные латинские буквы, цифры и подчёркивание.
# Кавычек, пробелов и точек здесь быть не может по определению — этот шаблон
# вторая линия после белого списка, а не замена ему.
ИМЯ_КОЛОНКИ = re.compile(r"^[a-z_][a-z0-9_]*$")


def собрать_set(
    поля: dict[str, Any], разрешено: Iterable[str]
) -> tuple[str, list[Any]]:
    """`("payment=$1, org=$2", [значение1, значение2])` из словаря полей.

    Пустой словарь — не ошибка: возвращается `("", [])`, а решение «нечего
    менять» принимает вызывающий, у каждого оно своё (чек отдаёт себя,
    пользователь и категория отвечают 400).

    Имя вне `разрешено` — ValueError. Это не защита от злоумышленника
    (значения и так идут параметрами), а защита от БУДУЩЕЙ ПРАВКИ: чтобы
    нельзя было завести ручку, где имя колонки приходит из тела запроса,
    и не заметить этого при ревью.
    """
    разрешённые = set(разрешено)
    куски: list[str] = []
    значения: list[Any] = []
    for имя, значение in поля.items():
        if имя not in разрешённые:
            raise ValueError(
                f"Колонка {имя!r} не в белом списке {sorted(разрешённые)}. "
                "Имена колонок в SQL берутся только из кода, никогда из запроса."
            )
        if not ИМЯ_КОЛОНКИ.match(имя):
            raise ValueError(
                f"Колонка {имя!r} не похожа на имя колонки. Белый список "
                "пропустил недопустимое имя — проверьте сам список."
            )
        значения.append(значение)
        куски.append(f"{имя}=${len(значения)}")
    return ", ".join(куски), значения
