"""Сбор отчёта с чеками из базы — ОДИН источник для всех потребителей.

⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ВТОРОЙ ЗАПРОС В НОВОЙ РУЧКЕ. Шаг 3 (API
и клиентский ключ) отдаёт наружу ТЕ ЖЕ данные, что и выгрузка в xlsx. Если
новая ручка соберёт их своим запросом рядом, продублируется не сборка строк —
она уже общая, — а именно ЭТО: соединение со справочником статей, фильтр
организации, порядок сортировки и склейка «Фамилия И.». Расхождение таких
копий тихое: обе ручки отвечают 200, просто отдают разное.

⚠️ ПОЧЕМУ ЗДЕСЬ, А НЕ В `app/exports/`. Тот пакет объявил про себя, что
в базу не ходит и про HTTP не знает, — и это правда, которую не хочется
портить. Сбор из базы к форматированию не относится, значит живёт отдельным
модулем бизнес-логики, как требует раскладка репозитория.

⚠️ ССЫЛКУ НА СНИМОК ЗДЕСЬ НЕ СТАВИМ НАМЕРЕННО, и это решение владельца
12.09.2026. Выгрузке в xlsx нужна ПОДПИСАННАЯ ссылка (файл открывают
в Excel, где заголовков нет), а машинному ответу подписанная ссылка
противопоказана: она живёт своей жизнью, отзыв ключа её не гасит, и семь
суток спустя протухает молча. Значит оформление снимка — дело потребителя,
а не сборщика: каждый ставит своё.
"""

from app.auth import can_see_all

# ⚠️ СКЛЕЙКА ИМЕНИ БЕРЁТСЯ ОТТУДА, ГДЕ ОНА УЖЕ ЕСТЬ И ПОКРЫТА ТЕСТОМ.
# Первая редакция этого модуля завела ВТОРУЮ копию `фамилия_и_инициал`, и
# мутация это поймала не сразу: копия жила без собственного теста, а тест
# оригинала мутанта в копии не видел. Две функции с одним смыслом расходятся
# молча — ровно то, ради чего весь этот модуль и заводился.
from app.exports.report_xlsx import фамилия_и_инициал

# ⚠️ СТАТЬЯ РАСХОДА НУЖНА СЛОВОМ, А В ЧЕКЕ ЛЕЖИТ ТОЛЬКО `category_id`.
# Ни один запрос отчётов справочник не соединяет, поэтому соединение живёт
# здесь — в единственном месте, где собираются данные отчёта.
ЧЕКИ_ОТЧЁТА = """SELECT receipts.*, categories.name AS статья
     FROM report_items ri
     JOIN receipts        ON receipts.id = ri.receipt_id
LEFT JOIN categories      ON categories.id = receipts.category_id
    WHERE ri.report_id = $1 AND receipts.org_id = $2
 ORDER BY receipts.date, receipts.id"""


async def _отчёт(conn, id: int, user: dict):
    """Отчёт с org-scope и author-scope — та же выборка, что у остальных ручек.

    Повторяет `_fetch_report` из роутера отчётов дословно по смыслу и
    намеренно не импортирует его: тянуть приватную функцию роутера в слой
    данных значит связать их в обратную сторону. Разойтись им не дадут
    живые тесты доступа — они бьют по обеим дорогам.
    """
    if can_see_all(user["role"]):
        return await conn.fetchrow(
            "SELECT * FROM reports WHERE id=$1 AND org_id=$2", id, user["org_id"]
        )
    return await conn.fetchrow(
        "SELECT * FROM reports WHERE id=$1 AND org_id=$2 AND user_id=$3",
        id,
        user["org_id"],
        user["id"],
    )


async def собрать(p, id: int, user: dict):
    """Отчёт, подотчётник и чеки состава. `None`, если отчёта нет или он чужой.

    Возвращает `(отчёт, подотчётник, чеки)`, где отчёт и чеки — обычные
    словари, а подотчётник — уже склеенная строка. Поле «снимок» не заполнено:
    его ставит потребитель, см. докстроку модуля.
    """
    отчёт = await _отчёт(p, id, user)
    # Чужой отчёт неотличим от несуществующего — как во всех ручках отчётов.
    if not отчёт:
        return None

    чеки = await p.fetch(ЧЕКИ_ОТЧЁТА, id, user["org_id"])
    автор = await p.fetchrow(
        "SELECT first_name, last_name FROM users WHERE id=$1 AND org_id=$2",
        отчёт["user_id"],
        user["org_id"],
    )
    return (
        dict(отчёт),
        фамилия_и_инициал(dict(автор) if автор else None),
        [dict(ч) for ч in чеки],
    )
