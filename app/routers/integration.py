"""API для машинного приёмника: одобренные отчёты по ключу (шаг 3, заход ⑤).

⚠️ ЗДЕСЬ ВПЕРВЫЕ ПОДКЛЮЧАЕТСЯ ЗАВИСИМОСТЬ КЛЮЧА из захода ④. До этого файла
она была написана и не стояла нигде — и это было ожидаемым состоянием между
двумя заходами, а не мусором (класс [[T192]], пометка в самом модуле).

⚠️ ОБЛАСТЬ ПРАВ ВЫРАЖЕНА МЕСТОМ, А НЕ РОЛЬЮ. Ключ получает ровно то, где
стоит его зависимость. Роль `integration` не входит ни в один набор людей,
поэтому `can_see_all` и `can_delete_any` для неё ложны по построению —
ни одна ручка человека ключ не пустит, даже если её случайно повесят рядом.

⚠️ ОТВЕТ СТРОИТСЯ БЕЛЫМ СПИСКОМ, А НЕ «ВСЁ МИНУС ЛИШНЕЕ», и это главное
решение файла. Чёрный список МОЛЧИТ при появлении новой колонки — она уедет
на чужую машину сама, и не заметит никто. Белый молчит в обратную сторону:
новое поле не появится, пока его не впишут руками. Для ответа наружу это
единственная честная сторона умолчания.

⚠️ ЧТО СЮДА НЕ ПОПАДАЕТ И ПОЧЕМУ — ПОИМЁННО, ЧТОБЫ НЕ ВЕРНУЛИ «НА ВСЯКИЙ
СЛУЧАЙ»:
  · `raw_data` — там может лежать САМ СНИМОК (`photo_base64` кладёт путь
    распознавания). Отдав его, мы протащили бы фотографию целиком — притом
    что подписанные ссылки на снимки решением владельца в ответ не кладутся
    вовсе. По старому замеру снимки составляли 44% всей базы;
  · `photo_key`, `photo_url` — адреса в хранилище. Снимок отдаёт отдельная
    ручка по ключу, заход ⑥;
  · `org_id` — организация задана САМИМ КЛЮЧОМ. Дублировать её в ответе
    значит дать приёмнику повод ей поверить;
  · `user_id`, `card_id`, `category_id`, `created_at`, `category_manual` —
    внутренние номера и признаки;
  · `ocr_fd`, `ocr_fpd` — РАСПОЗНАННЫЕ, и решением владельца это признак
    дубля, а не реквизит. Снаружи их не отличить от настоящих по имени;
  · `category`, `employee` — легаси, в них не пишут;
  · `vat_0` — двусмысленная: в неё писались два разных тега по условию;
  · `org_brand` — вывеска. Контрагента 1С заводит по ИНН и юрлицу, а они
    отданы; вывеска добавила бы третье название той же организации;
  · `payment_detail` — свободный текст с кассы («карта VISA»), рядом с
    разобранными `payment_form` и `card_last4` он только путает;
  · `source` — откуда пришли данные (руками, распознаванием, ФНС). Это наша
    внутренняя кухня, а не реквизит документа.

⚠️ ИМЕНА НАРУЖУ — ЛАТИНИЦЕЙ, И ЭТО ДОГОВОР, А НЕ ВКУС. Единственное
исключение пришло бы из общей сборки: там статья расхода зовётся `статья`
(псевдоним запроса, на нём держится выгрузка в xlsx). Переименовать её
у источника значило бы тронуть принятые заходы ① и ②, поэтому имя меняется
здесь, на выходе, — см. `СИНОНИМЫ`.
"""

import base64
import datetime as dt
from decimal import Decimal
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query

from app import receipt_photo, reports_data
from app.database import get_pool
from app.integration_keys import get_integration_principal

router = APIRouter(prefix="/api/integration", tags=["integration"])

# ⚠️ ТОЛЬКО ОДОБРЕННЫЕ. Это НОВОЕ правило, а не копия существующего: ни одна
# ручка чтения на статус сегодня не смотрит, и выгрузка в xlsx статус НЕ
# ограничивает намеренно (там он стоит колонкой в файле). Здесь приёмник —
# машина, она колонку не прочитает и проведёт документ как есть.
СТАТУС_К_ВЫДАЧЕ = "Одобрен"

# Предел страницы: умолчание и потолок. Числа взяты из чужой практики —
# у Диадока 100/100, у Контур.ОФД 1000/1000.
СТРАНИЦА_ПО_УМОЛЧАНИЮ = 100
ПОТОЛОК_СТРАНИЦЫ = 1000

# ── БЕЛЫЕ СПИСКИ ОТВЕТА ──────────────────────────────────────────────────
# Порядок значения не имеет, состав — имеет. Сторож сверяет их ПОИМЁННО.
ПОЛЯ_ОТЧЁТА = ("id", "title", "status", "total", "created")

ПОЛЯ_ЧЕКА = (
    "id",
    "date",
    "datetime",
    "org",
    "org_legal",
    "org_inn",
    "address",
    "amount",
    "currency",
    "operation_type",
    "payment",
    "payment_form",
    "card_last4",
    "tax_system",
    "kkt_fn",
    "fd_num",
    "fpd",
    "kkt_rn",
    "kkt_serial",
    "cashier",
    "vat_total",
    "sum_vat_0",
    "sum_no_vat",
    "vat_breakdown",
    "category_name",
)

# Имя наружу → имя в строке. Ровно для тех полей, где они расходятся.
# Список задуман коротким: каждая строка здесь — место, где внешний договор
# и внутреннее имя разъехались, и каждое такое расхождение надо оправдывать.
СИНОНИМЫ = {"category_name": "статья"}

# ⚠️ СНИМОК ОТДАЁТСЯ ТОЛЬКО У ЧЕКА, ЛЕЖАЩЕГО В ОДОБРЕННОМ ОТЧЁТЕ СВОЕЙ
# ОРГАНИЗАЦИИ, И ЭТО ТРЕТИЙ ЗАПРОС, А НЕ ветка человеческого. Человеку
# доступен любой чек его организации, в отчёте тот лежит или нет; ключу —
# только то, что уже прошло одобрение и уехало бы в 1С документом.
# Организация берётся ИЗ СТРОКИ КЛЮЧА, как и везде в этом файле.
#
# ⚠️ БЕЗ `LIMIT`, И ЭТО ПРОВЕРЕННОЕ ОСНОВАНИЕ, А НЕ НЕДОСМОТР. Первая редакция
# несла `LIMIT 1` с объяснением «чек бывает в нескольких отчётах»; живой прогон
# это опроверг — на связи стоит уникальность `uq_report_items_receipt_id`, один
# чек живёт не более чем в одном отчёте. Соединение множить строки не может,
# а `LIMIT` прятал бы это, если ограничение однажды снимут.
ЧЕК_ОДОБРЕННОГО_ОТЧЁТА = """SELECT %s
     FROM receipts r
     JOIN report_items ri ON ri.receipt_id = r.id
     JOIN reports rep     ON rep.id = ri.report_id
    WHERE r.id = $1 AND r.org_id = $2 AND rep.org_id = $2 AND rep.status = $3""" % ", ".join(
    "r." + имя for имя in receipt_photo.ПОЛЯ_СНИМКА.split(", ")
)


def _значение(v):
    """Типы базы → типы JSON, в форме, которую 1С читает без плясок.

    ⚠️ ДАТА И ВРЕМЯ — СТРОКОЙ БЕЗ ЗОНЫ. Ровно так их отдаёт собственный
    интерфейс 1С, и ровно так их разбирает `ПрочитатьДатуJSON`. Зоны у времени
    чека нет и быть не должно: это стенное время кассы, пояс ККТ неизвестен.

    ⚠️ ДЕНЬГИ — ЧИСЛОМ ИЗ `Decimal`. Перевод делается один раз и в самом конце,
    когда округлять больше некому.
    """
    if isinstance(v, Decimal):
        return float(v)
    if isinstance(v, dt.datetime):
        return v.strftime("%Y-%m-%dT%H:%M:%S")
    if isinstance(v, dt.date):
        return v.strftime("%Y-%m-%d")
    return v


def _по_списку(строка: dict, поля) -> dict:
    """Белый список: берём ТОЛЬКО названное, отсутствующее даём пустым.

    Отсутствующий ключ и пустое значение для приёмника разные вещи: первое
    он прочитает как «поля нет в договоре» и может упасть на разборе.
    """
    return {имя: _значение(строка.get(СИНОНИМЫ.get(имя, имя))) for имя in поля}


def _курсор(created: dt.date, id_: int) -> str:
    """Непрозрачный курсор из пары «дата, номер».

    ⚠️ ПАРА, А НЕ ОДНА ДАТА: отчётов с одной датой бывает несколько, и курсор
    по дате либо потерял бы часть, либо выдал бы её дважды. Номер разводит их
    однозначно, потому что он первичный ключ.
    """
    сырой = "%s|%d" % (created.isoformat(), id_)
    return base64.urlsafe_b64encode(сырой.encode()).decode()


def _разобрать_курсор(значение: str):
    """Курсор → (дата, номер). Негодный курсор — 400, а не тихий сброс на первую
    страницу: молча начав сначала, мы отдали бы приёмнику те же документы
    второй раз, и он задвоил бы их у себя."""
    try:
        сырой = base64.urlsafe_b64decode(значение.encode()).decode()
        дата, _, номер = сырой.partition("|")
        return dt.date.fromisoformat(дата), int(номер)
    except Exception:
        raise HTTPException(status_code=400, detail="Негодный курсор")


@router.get("/reports")
async def список_отчётов(
    # ⚠️ ОКНО ДАТ ОБЯЗАТЕЛЬНОЕ, И ЭТО НЕ УДОБСТВО. Без него первый же запрос
    # с чужой машины забирает ВСЮ историю организации разом. Обязательный
    # параметр превращает «выгрузи всё» в осознанное действие.
    date_from: dt.date = Query(..., description="начало окна, включительно"),
    date_to: dt.date = Query(..., description="конец окна, включительно"),
    limit: int = Query(СТРАНИЦА_ПО_УМОЛЧАНИЮ, ge=1, le=ПОТОЛОК_СТРАНИЦЫ),
    cursor: Optional[str] = Query(None, description="из поля next_cursor"),
    принципал: dict = Depends(get_integration_principal),
):
    """Одобренные отчёты организации ключа за окно дат, страницами.

    Порядок устойчивый — по дате и номеру, оба поля в курсоре.
    """
    if date_from > date_to:
        raise HTTPException(status_code=400, detail="Начало окна позже конца")

    условия = [
        "org_id = $1",
        "status = $2",
        "created >= $3",
        "created <= $4",
    ]
    значения = [принципал["org_id"], СТАТУС_К_ВЫДАЧЕ, date_from, date_to]
    if cursor:
        дата, номер = _разобрать_курсор(cursor)
        значения += [дата, номер]
        условия.append("(created, id) > ($5, $6)")

    p = await get_pool()
    # ⚠️ БЕРЁМ НА ОДНУ БОЛЬШЕ, ЧЕМ ПРОСИЛИ. Иначе «есть ли следующая страница»
    # пришлось бы угадывать по длине выдачи, а ровно полная страница выглядела
    # бы как последняя — и приёмник остановился бы, не забрав остаток.
    строки = await p.fetch(
        "SELECT * FROM reports WHERE %s ORDER BY created, id LIMIT %d"
        % (" AND ".join(условия), limit + 1),
        *значения,
    )
    есть_ещё = len(строки) > limit
    строки = строки[:limit]

    return {
        "reports": [_по_списку(dict(с), ПОЛЯ_ОТЧЁТА) for с in строки],
        "next_cursor": (
            _курсор(строки[-1]["created"], строки[-1]["id"])
            if есть_ещё and строки
            else None
        ),
    }


@router.get("/reports/{id}")
async def отчёт_с_чеками(id: int, принципал: dict = Depends(get_integration_principal)):
    """Один одобренный отчёт вместе с чеками состава.

    ⚠️ СБОРКА ОБЩАЯ С ВЫГРУЗКОЙ В xlsx — второй путь не пишется намеренно.
    Разошлись бы не строки (они уже общие), а соединение со справочником
    статей, фильтр организации и порядок сортировки; расхождение таких
    копий тихое: обе ручки отвечают 200 и отдают разное.
    """
    p = await get_pool()
    собранное = await reports_data.собрать(p, id, принципал)
    # Чужой отчёт неотличим от несуществующего — как во всех ручках отчётов.
    if собранное is None:
        raise HTTPException(status_code=404, detail="Not found")
    отчёт, подотчётник, чеки = собранное

    # ⚠️ ПРОВЕРКА СТАТУСА ПОСЛЕ ВЫБОРКИ, И ОТКАЗ ТОТ ЖЕ САМЫЙ 404. Отдельный
    # текст вроде «отчёт не одобрен» подтвердил бы владельцу ключа, что отчёт
    # с таким номером существует, — то есть позволил бы перебирать номера.
    if отчёт.get("status") != СТАТУС_К_ВЫДАЧЕ:
        raise HTTPException(status_code=404, detail="Not found")

    ответ = _по_списку(отчёт, ПОЛЯ_ОТЧЁТА)
    # ⚠️ `employee_name`, А НЕ `employee`. В самой строке чека есть легаси-колонка
    # с именем `employee`, и наружу она не идёт. Дать то же имя другому смыслу
    # значило бы завести ловушку: сторож запретных полей проверяет имя, а не
    # смысл, и однажды он пропустил бы именно ту колонку, ради которой заведён.
    ответ["employee_name"] = подотчётник
    ответ["receipts"] = [
        dict(
            _по_списку(ч, ПОЛЯ_ЧЕКА),
            # Признак, а не ссылка: сам снимок отдаёт отдельная ручка по ключу
            # (заход ⑥). Приёмнику нужно знать, идти ли за ним вообще.
            has_photo=bool(ч.get("photo_key") or ч.get("photo_url")),
        )
        for ч in чеки
    ]
    return ответ


@router.get("/receipts/{id}/photo")
async def снимок_чека(id: int, принципал: dict = Depends(get_integration_principal)):
    """Снимок чека БАЙТАМИ через нас, без подписанных ссылок и без 302.

    ⚠️ ПОДПИСАННОЙ ССЫЛКИ НЕТ, И ЭТО ТО ЖЕ РЕШЕНИЕ, ЧТО В ЗАХОДЕ ⑤. Ссылка
    живёт своей жизнью: отзыв ключа её не гасит, а срок протухает молча. Файл
    идёт байтами, и права проверяются НА КАЖДЫЙ запрос — тем самым запросом,
    который его и достал.

    ⚠️ ОТКАЗ ОДИН НА ВСЕ СЛУЧАИ — 404. Чужая организация, чек вне отчётов,
    чек в неодобренном отчёте, чека нет вовсе: разные ответы позволили бы
    перебирать номера и узнавать, что за ними стоит.
    """
    p = await get_pool()
    строка = await p.fetchrow(
        ЧЕК_ОДОБРЕННОГО_ОТЧЁТА, id, принципал["org_id"], СТАТУС_К_ВЫДАЧЕ
    )
    if not строка:
        raise HTTPException(status_code=404, detail="Not found")
    # ⚠️ `редиректом=False`: ключу 302 не отдаётся ни в каком виде (решение
    # владельца 13.09.2026) — адрес уехал бы на чужую машину и зажил своей
    # жизнью, а это ровно то, ради чего ссылок в машинном ответе нет вовсе.
    return await receipt_photo.отдать(строка, номер=id, редиректом=False)
