"""Ключи интеграции: выпуск, отзыв, список (шаг 3, заход ⑧).

⚠️ ЭТО РУЧКИ ДЛЯ ЧЕЛОВЕКА, А НЕ ДЛЯ МАШИНЫ. Их открывает `get_current_user`,
то есть обычная сессия сотрудника; ключом сюда не войти, и это не оговорка,
а следствие устройства: роль `integration` не входит ни в `ROLES`, ни в тип
`Role`, а привратники ниже сверяют роль по РАВЕНСТВУ с именами людей.

⚠️ ДВА КРУГА, И ОНИ РАЗНЫЕ ПО СУЩЕСТВУ (решение владельца 13.09.2026):
  · СПИСОК видят администратор и бухгалтер — тот же круг, что у справочников
    карт и категорий. Бухгалтер сводит отчёты и должен видеть, чем и когда
    забирали документы;
  · ВЫПУСК и ОТЗЫВ — только администратор. Разница ровно та, что названа
    в докстроке `app/routers/cards.py`: правка справочника не выдаёт доступ
    и откатывается заведением заново, а выпуск ключа — выдаёт, и уехавший
    секрет обратно не соберёшь.

⚠️⚠️ СЕКРЕТ ПОКАЗЫВАЕТСЯ ОДИН РАЗ, И ЭТО НЕ ДИСЦИПЛИНА ИНТЕРФЕЙСА, А
УСТРОЙСТВО. В базе лежит только `secret_hash`, односторонний; восстановить
секрет невозможно и с полным доступом к базе. Ручке списка просто неоткуда
его взять, даже если её об этом попросят.

Это НАМЕРЕННО не так, как у приглашений: там `invite_links.token` лежит
открытым текстом, и «показали один раз» верно только на вид — строку можно
прочитать из базы в любой момент. Образец для ключей — восстановление пароля
(`password_resets.token_hash`), где хранится хеш и токен не восстановим.

⚠️ БЕССРОЧНЫЙ КЛЮЧ ВЫПУСТИТЬ НЕЛЬЗЯ (решение владельца 13.09.2026). Довод
владельца дословно: вечная ссылка — это дверь, а здесь дверь лежит В ЧУЖОЙ
БАЗЕ, у клиента в настройках обработки 1С. Умолчание — год; потолок тоже год,
потому что названного основания на больший срок нет ни у кого.

⚠️ ДВА ЖИВЫХ КЛЮЧА НА ОРГАНИЗАЦИЮ — СЧЁТ В КОДЕ, А НЕ В СХЕМЕ. Частичный
уникальный индекс запер бы ровно ОДИН живой ключ, то есть выразил бы не то
правило (разбор в заходе ③). Два нужны для поворота: новый заводится, пока
старый ещё работает, иначе смена ключа останавливает интеграцию.
"""

import secrets

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, ConfigDict, Field

from app.database import get_pool
from app.integration_keys import ДЛИНА_ПРЕФИКСА, РАЗДЕЛИТЕЛЬ, хеш_секрета
from app.auth import get_current_user

router = APIRouter(prefix="/api/integration-keys", tags=["integration-keys"])

# Сколько живых ключей разрешено организации разом.
ПРЕДЕЛ_ЖИВЫХ = 2

СРОК_ПО_УМОЛЧАНИЮ_ДНЕЙ = 365
ПОТОЛОК_СРОКА_ДНЕЙ = 365

# ⚠️ ВСЁ ПОРОЖДЁННОЕ — ТОЛЬКО ASCII, И ЭТО КУПЛЕНО ЗАХОДОМ ⑤. Ключ едет
# в заголовке `Authorization`, а заголовки HTTP — ASCII: кириллица в секрете
# роняет запрос ЕЩЁ В КЛИЕНТЕ, до всякой проверки, и выглядит это как
# «интеграция не работает», а не как «ключ негодный». `token_urlsafe` берёт
# символы из алфавита base64url (латиница, цифры, `-` и `_`) — ASCII целиком.
БАЙТ_СЕКРЕТА = 32
ПРИСТАВКА_ПРЕФИКСА = "aocg"

# ── БЕЛЫЙ СПИСОК СПИСКА ──────────────────────────────────────────────────
# ⚠️ ТОТ ЖЕ ПРИЁМ, ЧТО В ЗАХОДЕ ⑤, И ПО ТОЙ ЖЕ ПРИЧИНЕ: чёрный список
# МОЛЧИТ при появлении новой колонки. `secret_hash` сюда не попадает даже
# мельком, `last_used_ip` — тоже: в списке владелец назвал префикс, имя и
# дату последнего использования, а адрес это персональные данные оператора
# на чужой стороне. Понадобится — добавляется названным решением.
ПОЛЯ_СПИСКА = (
    "id",
    "prefix",
    "name",
    "created_at",
    "expires_at",
    "last_used_at",
    "use_count",
    "revoked_at",
)

# ⚠️ ЖИВОСТЬ, ОСТАТОК И СРОК СЧИТАЕТ БАЗА, А НЕ ПРИЛОЖЕНИЕ (замечание
# владельца 13.09.2026 к первой редакции, где `is_active` и остаток считались
# по часам ПРОЦЕССА). Проверка ключа сверяет срок с NOW() базы (`найти_живой`),
# и список обязан считать ТЕМИ ЖЕ часами — иначе у порога истечения список
# скажет «живой», а проверка ответит 401. Остаток — сутками ВВЕРХ: при
# остатке в час ключ ещё работает, и «0 дней» читалось бы как «истёк».
# `expires_at` при выпуске — тоже от NOW() базы, по той же причине.
ВЫЧИСЛЯЕТ_БАЗА = """(revoked_at IS NULL AND (expires_at IS NULL OR expires_at > NOW())) AS is_active,
    CASE WHEN expires_at IS NULL THEN NULL
         ELSE GREATEST(0, CEIL(EXTRACT(EPOCH FROM (expires_at - NOW())) / 86400))::int
    END AS days_left"""

СТОЛБЦЫ = ", ".join(ПОЛЯ_СПИСКА) + ",\n    " + ВЫЧИСЛЯЕТ_БАЗА
ВЫЧИСЛЯЕМЫЕ = ("is_active", "days_left")

СПИСОК = (
    """SELECT %s FROM integration_keys
 WHERE org_id = $1
 ORDER BY revoked_at IS NOT NULL, created_at DESC"""
    % СТОЛБЦЫ
)


def _только_администратор(user: dict) -> None:
    """Выпуск и отзыв. Тот же привратник, что у приглашений (`auth.py`)."""
    if user.get("role") != "admin":
        raise HTTPException(status_code=403, detail="Только для администратора")


def _администратор_или_бухгалтер(user: dict) -> None:
    """Список. Тот же круг и тот же текст, что у карт и категорий."""
    if user.get("role") not in ("admin", "accountant"):
        raise HTTPException(
            status_code=403, detail="Только для администратора или бухгалтера"
        )


class ВыпускIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=100)
    # ⚠️ БЕЗ ВАРИАНТА «БЕССРОЧНО»: `None` сюда не принимается вовсе, и это
    # видно по типу. Значение по умолчанию подставляется, если поле не прислали.
    expires_days: int = Field(
        default=СРОК_ПО_УМОЛЧАНИЮ_ДНЕЙ, ge=1, le=ПОТОЛОК_СРОКА_ДНЕЙ
    )


def _строка_списка(строка) -> dict:
    """Строка ответа: белый список колонок плюс два числа, сосчитанных базой.

    ⚠️ НИ ОДНОГО ВЫЧИСЛЕНИЯ ЗДЕСЬ НАМЕРЕННО. «Осталось дней» — то, по чему
    человек решает, пора ли поворачивать ключ; часы у этого числа одни на
    всех — базы. Экран его тоже не пересчитывает.
    """
    return {имя: строка[имя] for имя in ПОЛЯ_СПИСКА + ВЫЧИСЛЯЕМЫЕ}


@router.get("/")
async def список_ключей(user: dict = Depends(get_current_user)):
    """Ключи организации: живые сверху, отозванные ниже.

    Секрета здесь нет и быть не может — см. докстроку модуля.
    """
    _администратор_или_бухгалтер(user)
    p = await get_pool()
    строки = await p.fetch(СПИСОК, user["org_id"])
    return [_строка_списка(с) for с in строки]


@router.post("/")
async def выпустить_ключ(body: ВыпускIn, user: dict = Depends(get_current_user)):
    """Новый ключ. Секрет возвращается ОДИН РАЗ и больше не восстанавливается.

    ⚠️ СЧЁТ ЖИВЫХ И ВСТАВКА — В ОДНОЙ СДЕЛКЕ, СО ВЗЯТИЕМ ЗАМКА НА СТРОКУ
    ОРГАНИЗАЦИИ. Без замка два одновременных выпуска прочитали бы «сейчас
    один» каждый и завели бы ТРЕТИЙ живой ключ: счёт в коде без блокировки
    гонку не закрывает. Замок берётся на строку `organizations`, потому что
    это единственная строка, общая для всех ключей организации и заведомо
    существующая; ключи ею же и ограничены, так что чужие сделки он
    не задевает.
    """
    _только_администратор(user)
    секрет = secrets.token_urlsafe(БАЙТ_СЕКРЕТА)

    p = await get_pool()
    async with p.acquire() as conn:
        async with conn.transaction():
            await conn.fetchval(
                "SELECT id FROM organizations WHERE id=$1 FOR UPDATE", user["org_id"]
            )
            живых = await conn.fetchval(
                "SELECT count(*) FROM integration_keys "
                "WHERE org_id=$1 AND revoked_at IS NULL "
                "AND (expires_at IS NULL OR expires_at > NOW())",
                user["org_id"],
            )
            if живых >= ПРЕДЕЛ_ЖИВЫХ:
                raise HTTPException(
                    status_code=409,
                    detail=(
                        "Живых ключей уже %d. Отзовите ненужный и выпустите новый."
                        % ПРЕДЕЛ_ЖИВЫХ
                    ),
                )
            # Префикс однозначен ГЛОБАЛЬНО (уникальный индекс из захода ③):
            # организацию мы узнаём из найденной строки, то есть на момент
            # поиска её ещё не знаем. Совпадение маловероятно, но повтор
            # дешевле отказа человеку.
            for попытка in range(5):
                префикс = ПРИСТАВКА_ПРЕФИКСА + secrets.token_hex(
                    (ДЛИНА_ПРЕФИКСА - len(ПРИСТАВКА_ПРЕФИКСА)) // 2
                )
                занят = await conn.fetchval(
                    "SELECT 1 FROM integration_keys WHERE prefix=$1", префикс
                )
                if not занят:
                    break
            else:
                raise HTTPException(status_code=503, detail="Попробуйте ещё раз")

            строка = await conn.fetchrow(
                "INSERT INTO integration_keys "
                "(org_id, prefix, secret_hash, name, created_by, expires_at) "
                "VALUES ($1,$2,$3,$4,$5, NOW() + make_interval(days => $6::int)) "
                "RETURNING %s" % СТОЛБЦЫ,
                user["org_id"],
                префикс,
                хеш_секрета(секрет),
                body.name.strip(),
                user["id"],
                body.expires_days,
            )

    ответ = _строка_списка(строка)
    # ⚠️ ЕДИНСТВЕННОЕ МЕСТО ВО ВСЁМ ПРИЛОЖЕНИИ, ГДЕ СЕКРЕТ ВИДЕН. Дальше он
    # существует только у того, кто его скопировал: в базе лежит хеш.
    ответ["key"] = префикс + РАЗДЕЛИТЕЛЬ + секрет
    return ответ


@router.post("/{id}/revoke")
async def отозвать_ключ(id: int, user: dict = Depends(get_current_user)):
    """Отзыв. Действует немедленно: проверка ключа смотрит `revoked_at` в SQL.

    ⚠️ ПОВТОРНЫЙ ОТЗЫВ НЕ ПЕРЕПИСЫВАЕТ ВРЕМЯ. Иначе вторым нажатием можно
    было бы затереть момент первого — а это единственная запись о том, когда
    доступ закрыли.
    """
    _только_администратор(user)
    p = await get_pool()
    строка = await p.fetchrow(
        "UPDATE integration_keys SET revoked_at = NOW(), revoked_by = $3 "
        "WHERE id = $1 AND org_id = $2 AND revoked_at IS NULL "
        "RETURNING %s" % СТОЛБЦЫ,
        id,
        user["org_id"],
        user["id"],
    )
    if строка is None:
        # Чужой ключ неотличим от несуществующего и от уже отозванного —
        # как во всех ручках, где номер можно перебрать.
        raise HTTPException(status_code=404, detail="Not found")
    return _строка_списка(строка)
