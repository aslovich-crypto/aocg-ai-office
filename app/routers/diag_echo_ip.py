"""⚠️⚠️ ВРЕМЕННАЯ РУЧКА ЗАМЕРА S-35. СТАВИТСЯ И СНИМАЕТСЯ В ОДНОМ ЗАХОДЕ.

ЗАЧЕМ ОНА ЕСТЬ. Вопрос S-35 — «доезжает ли клиентский `X-Forwarded-For`
до `_client_ip`» — до сих пор мерили КОСВЕННО, через ограничитель частоты
(`tests/tools/probe_xff.sh`): шлём запросы с подставным адресом и смотрим,
сойдутся ли корзины лимита. Такой замер отвечает «попал ли подлог в ключ»,
а не «ЧТО приложение записало как адрес клиента», и платит банами.
Эта ручка отвечает прямо и не платит ничем.

⚠️ ОНА НЕ ОСТАЁТСЯ НА ПРОДЕ. Условие владельца 21.09.2026: добавлена
и удалена в одном заходе, оба коммита показываются в отчёте. Диагностика,
прижившаяся «на всякий случай», — это поверхность, которую никто не
помнит: следующий, кто найдёт её через полгода, не будет знать, зачем
она и можно ли её снять.

⚠️ ОТДАЁТ РОВНО ТРИ ЗНАЧЕНИЯ, И СПИСОК ЗАКРЫТ. Соблазн отдать «все
заголовки» здесь смертелен: в них лежит `Authorization` с живым токеном,
и он уехал бы в вывод терминала, в историю оболочки и в отчёт. Поэтому
именно три поля, каждое названо поимённо.

⚠️ НИЧЕГО НЕ ПИШЕТ — ни в базу, ни в журнал согласий, ни в аудит.
Единственный побочный эффект — запись в ограничитель частоты, общая
для всех ручек; проба идёт четырьмя вызовами при пределе 60 в минуту.
"""

from fastapi import APIRouter, Depends, HTTPException, Request

from aocg_security.middleware import AOCGSecurityMiddleware
from app.auth import ROLE_ADMIN, get_current_user

router = APIRouter(prefix="/api/diag", tags=["diag"])


@router.get("/echo-ip")
async def зеркало_адреса(request: Request, user: dict = Depends(get_current_user)):
    """Три значения, по которым читается судьба клиентского заголовка.

    ⚠️ ТОЛЬКО АДМИНИСТРАТОР, и это не перестраховка: ручка показывает
    внутренний адрес прокси площадки. Бухгалтеру он не нужен, а лишний
    круг посвящённых — лишний.
    """
    if user["role"] != ROLE_ADMIN:
        raise HTTPException(status_code=403, detail="Только администратор")
    return {
        # Что увидят ограничитель частоты, журнал согласий и аудит.
        "client_ip": AOCGSecurityMiddleware._client_ip(request),
        # Заголовок целиком, как пришёл: по числу звеньев видно,
        # дописала площадка свой адрес или затёрла наш.
        "xff_raw": request.headers.get("x-forwarded-for"),
        # Кто реально подключился к uvicorn. Это адрес Caddy —
        # он же ответ на вопрос S-67, что ставить в FORWARDED_ALLOW_IPS.
        "peer": request.client.host if request.client else None,
    }
