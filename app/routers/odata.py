"""Проба связи с 1С организации (1C-21, заход ①). ТОЛЬКО ЧТЕНИЕ.

⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ РУЧКА РАДИ ОДНОГО ВОПРОСА. Вопрос этот — главный риск
всей ветки Ⓐ: доходит ли НАШ ПРОД до площадки 1С. Ноутбук владельца
доходит, оболочка агента доходит в обход туннеля, а про прод не известно
ничего. Узнать это иначе нельзя: у нас нет ни консоли в контейнере,
ни способа выполнить там команду. Значит спрашивает сам прод и отвечает
по HTTP.

⚠️ ЧТО ЭТА РУЧКА НЕ ДЕЛАЕТ: она НИЧЕГО НЕ СОЗДАЁТ и ничего не меняет
в 1С. Спрашивается только `$metadata` — схема. Ни одной функции записи
в заходе ① не существует вовсе.

⚠️ ГЕЙТ — ТОЛЬКО АДМИНИСТРАТОР, и это уже, чем у выгрузки в файл
(там `can_see_all`, бухгалтер и администратор). Основание: проба говорит,
настроен ли обмен и отвечает ли чужая база, — это сведения об устройстве
интеграции, а не бухгалтерский документ. Гейты соседних ручек не тронуты.
"""

import logging
import os

import asyncpg
from fastapi import APIRouter, Depends, HTTPException

from app import category_confirm, odata_body, odata_client, reports_data
from app.auth import can_see_all, get_current_user
from app.database import get_pool

router = APIRouter(prefix="/api/odata", tags=["odata"])
logger = logging.getLogger(__name__)


def _только_администратор(user: dict) -> None:
    """Тот же привратник и тот же текст, что у выпуска ключей."""
    if user.get("role") != "admin":
        raise HTTPException(status_code=403, detail="Только для администратора")


@router.get("/probe")
async def проба_связи(user: dict = Depends(get_current_user)):
    """Дошли ли мы до 1С: «дошли», версия интерфейса и время ответа.

    Ответ ВСЕГДА 200 — даже когда связи нет: это ПРИБОР, и его дело
    сообщить результат замера, а не изобразить поломку приложения.
    Разница между «не настроено» и «не дошли» видна по полю `status`,
    и она существенная: первое чинится переменными окружения, второе —
    сетью площадки.
    """
    _только_администратор(user)
    if not odata_client.настроено():
        return {
            "дошли": False,
            "status": "odata_not_configured",
            "message": "Обмен с 1С не настроен: не заданы переменные окружения",
        }
    return await odata_client.проверить_связь()


# ⚠️ ССЫЛКИ НА ЭЛЕМЕНТЫ 1С — В ПЕРЕМЕННЫХ ОКРУЖЕНИЯ, ТЕМ ЖЕ РЕШЕНИЕМ, ЧТО
# И ДОСТУПЫ (16.09.2026). Организация, склад, валюта и ответственный — это
# ЧЕТЫРЕ ссылки на справочники базы клиента, и они такие же «доступы», как
# логин: без них тело документа не собрать. Заводить под них таблицу сейчас
# значило бы завести четвёртую таблицу ради одной организации — а таблица
# соответствий людей и категорий уже есть и наполняется человеком.
# ⚠️ КОГДА ПОЯВЯТСЯ КЛИЕНТЫ, ЭТО ПЕРЕЕДЕТ В ТАБЛИЦУ вместе с доступами:
# переменные окружения — на одну организацию, и это записано в 1C-24.
ССЫЛКИ = {
    "организация": "ODATA_ORG_REF",
    "склад": "ODATA_WAREHOUSE_REF",
    "валюта": "ODATA_CURRENCY_REF",
    "ответственный": "ODATA_RESPONSIBLE_REF",
}


def _ссылки_организации() -> dict:
    return {имя: (os.getenv(пер) or "").strip() for имя, пер in ССЫЛКИ.items()}


def политика_текстом(политика: str) -> str:
    """Политика проведения человеческими словами — для ответа ручки."""
    return {
        odata_body.ПРОВОДИТЬ_КОГДА_СОПОСТАВЛЕНО: "проводить, когда всё сопоставлено",
        odata_body.ПРОВОДИТЬ_НИКОГДА: "никогда не проводить",
        odata_body.ПРОВОДИТЬ_ВСЕГДА: "проводить всегда",
    }.get(политика, политика)


def _адрес_отчёта(report_id: int) -> str:
    """Ссылка на карточку отчёта для комментария документа.

    ⚠️ БЕЗ ТОКЕНОВ. Адрес ведёт в приложение, вход обычный — документ уезжает
    в чужую бухгалтерию, и ссылка с доступом в нём означала бы выданный
    наружу ключ.

    ⚠️ ГРАНИЦА, ЗАМЕР 17.09.2026: собственного маршрута у карточки отчёта
    во фронте НЕТ — приложение читает из адреса только `token`. Значит
    ссылка открывает приложение, а не конкретный отчёт; номер отчёта стоит
    в том же комментарии рядом. Глубокая ссылка — правка фронта, отдельная
    строка.
    """
    адрес = (os.getenv("APP_URL") or "").strip().rstrip("/")
    return "%s/?report=%d" % (адрес, report_id) if адрес else ""


def _бухгалтер_или_администратор(user: dict) -> None:
    """Гейт выгрузки — тот же круг и тот же довод, что у выгрузки в файл:
    в карте ролей у бухгалтера прямо записано «Проверка, 1С выгрузка».
    Гейты соседних ручек не тронуты, здесь своя проверка."""
    if not can_see_all(user["role"]):
        raise HTTPException(
            status_code=403, detail="Выгрузка доступна бухгалтеру и администратору"
        )


async def _правила_категорий(p, org_id: int) -> dict:
    """Переопределения по категории — ИСКЛЮЧЕНИЯ, их может не быть вовсе."""
    строки = await p.fetch(
        "SELECT category_id, account_code, expense_ref, expense_name, usn_reflection"
        " FROM org_category_map WHERE org_id=$1",
        org_id,
    )
    return {с["category_id"]: dict(с) for с in строки}


async def _правила_видов(p, org_id: int) -> dict:
    """Правила по виду расхода — ОСНОВНАЯ ось сопоставления (AOCG-1C-001, § 4).

    ⚠️ ДЕВЯТЬ СТРОК ВМЕСТО СОРОКА ВОСЬМИ. У категории уже есть `tax_kind`,
    у статьи затрат клиента — то же поле `ВидРасходовНУ`; сопоставляются
    именно они, а категории цепляются к виду автоматически.
    """
    строки = await p.fetch(
        "SELECT tax_kind, account_code, expense_ref, expense_name, usn_reflection"
        " FROM org_expense_kind_map WHERE org_id=$1",
        org_id,
    )
    return {с["tax_kind"]: dict(с) for с in строки}


async def _профиль(p, org_id: int):
    """Профиль учёта организации: режимы и счёт по умолчанию (1C-22, Р5).

    ⚠️ ПРОФИЛЬ ЖИВЁТ У НАС, А НЕ В ТРАНСПОРТЕ. Выгрузка в 1С его только
    читает; следующий способ обмена прочитает тот же профиль и ничего
    своего заводить не будет.
    """
    строка = await p.fetchrow(
        "SELECT legal_form, tax_regime, vat_mode, combines_psn,"
        " default_account_code, auto_post_policy"
        " FROM org_accounting_profile WHERE org_id=$1",
        org_id,
    )
    return dict(строка) if строка else None


async def _человек(p, org_id: int, user_id: int):
    return await p.fetchval(
        "SELECT person_ref FROM odata_user_map WHERE org_id=$1 AND user_id=$2",
        org_id,
        user_id,
    )


class СбойЧтенияСправочника(RuntimeError):
    """Справочник 1С прочитать не удалось — это НЕ «элемент не найден»."""

    def __init__(self, что: str):
        super().__init__(что)
        self.что = что


async def _прочитать_справочник(путь: str, поле: str, что: str) -> dict:
    """{значение поля: [Ref_Key, …]} по ВСЕМУ справочнику. ТОЛЬКО ЧТЕНИЕ.

    ⚠️⚠️ ЧИТАЕМ ЦЕЛИКОМ, А НЕ ФИЛЬТРОМ, И ЭТО ЗАМЕР, А НЕ ВКУС (1C-21, ④).
    На площадке 1С:Фреш `$filter` не работает ВООБЩЕ: девять проб по разным
    полям и справочникам, включая голый фильтр по `Ref_Key`, дали 500 с одним
    текстом «Операция не разрешена в предложении ГДЕ». Первая редакция искала
    по одному значению через `$filter` — и приёмка упала бы на 409 «нет счёта
    20.01», хотя счёт в базе есть. Решение владельца 17.09.2026: читать
    справочник целиком и сопоставлять у нас.

    ⚠️ ОБЪЁМ ЗАМЕРЕН И ОГРАНИЧЕН `$select`: контрагенты 884 записи — 5.8 МБ
    без выбора полей и 88 КБ с тремя полями; план счетов 490 записей —
    560 КБ и 45 КБ. Продолжения страницы нет ни у одного: справочник приходит
    одним ответом.

    ⚠️ ПОМЕЧЕННЫЕ НА УДАЛЕНИЕ ОТСЕИВАЮТСЯ ЗДЕСЬ, у нас, раз фильтровать на
    стороне 1С нельзя. Без отсева удалённый контрагент с тем же ИНН дал бы
    ложное «два совпадения» или ссылку на удалённый элемент.

    ⚠️ СБОЙ ЧТЕНИЯ — ИСКЛЮЧЕНИЕ, А НЕ ПУСТОЙ СЛОВАРЬ (решение владельца
    17.09.2026). Пустой словарь превращал сбой в «элемент не найден», и человек
    читал «в плане счетов нет 20.01» там, где план просто не прочитался.
    """
    код, ответ = await odata_client.запросить(
        путь, параметры={"$select": "Ref_Key,%s,DeletionMark" % поле}
    )
    if код != 200:
        raise СбойЧтенияСправочника(что)
    строки = ((ответ or {}).get("тело") or {}).get("value")
    if not isinstance(строки, list):
        raise СбойЧтенияСправочника(что)
    индекс: dict = {}
    for строка in строки:
        if строка.get("DeletionMark"):
            continue
        значение = строка.get(поле)
        if значение:
            индекс.setdefault(str(значение).strip(), []).append(строка.get("Ref_Key"))
    return индекс


def _сопоставить(индекс: dict, значения: set) -> dict:
    """{значение: Ref_Key} только там, где совпадение РОВНО ОДНО.

    ⚠️ Два контрагента с одним ИНН в базе клиента — не редкость: замер
    17.09.2026 нашёл 9 таких ИНН среди живых. Выбор «первого попавшегося»
    и есть додумывание, поэтому такой ИНН считается не найденным.
    """
    найдено = {}
    for значение in значения:
        if not значение:
            continue
        ссылки = индекс.get(str(значение).strip()) or []
        if len(ссылки) == 1:
            найдено[значение] = ссылки[0]
    return найдено


# ⚠️ «ЖИВАЯ» ВЫГРУЗКА — ИДУЩАЯ ИЛИ ЗАКОНЧЕННАЯ С ДОКУМЕНТОМ. Тот же набор
# стоит в условии индекса `odata_exports_one_live` (app/database.py), и
# расходиться им нельзя: код и база обязаны считать живым одно и то же.
ЖИВЫЕ = ("running", "ok", "partial", "unposted")
НЕУДАЧИ = ("error", "unavailable")

# ⚠️ ЧЕРЕЗ СКОЛЬКО МИНУТ `running` СЧИТАЕТСЯ ПРЕРВАННОЙ (1C-29). Довод
# числом: между записью `running` и итогом стоят ровно два обращения к 1С —
# создание и проведение, по 20 с таймаута и без повторов, то есть меньше
# минуты даже в худшем случае. Десять минут `running` значат одно: процесс
# умер посреди отправки (перезапуск контейнера при деплое). Создан ли
# документ в 1С — неизвестно, поэтому прерванная НЕ снимается сама:
# её снимает человек отменой, посмотрев в 1С.
ПРЕРВАНА_ЧЕРЕЗ_МИНУТ = 10


async def _прошлые_выгрузки(p, report_id: int, org_id: int):
    return await p.fetch(
        "SELECT id, outcome, doc_ref, doc_number, started_at, finished_at,"
        " error_note, defaulted_categories,"
        " (outcome = 'running' AND started_at < NOW() - make_interval(mins => $3))"
        " AS прервана"
        " FROM odata_exports WHERE report_id=$1 AND org_id=$2"
        " ORDER BY started_at DESC, id DESC",
        report_id,
        org_id,
        ПРЕРВАНА_ЧЕРЕЗ_МИНУТ,
    )


@router.post("/reports/{id}/export")
async def выгрузить_отчёт(id: int, user: dict = Depends(get_current_user)):
    """Отчёт → документ в 1С. ⚠️ ТОЛЬКО ОДОБРЕННЫЙ.

    ⚠️⚠️ ОТВЕТ ОБЯЗАН СКАЗАТЬ, ЧТО СЧЕТА ПОДСТАВЛЕНЫ ПО УМОЛЧАНИЮ, и
    перечислить категории (требование владельца 16.09.2026). «Сработало»
    не должно читаться как «разнесено верно»: пока таблица соответствий
    пуста, ВСЁ ляжет на один счёт, и узнать об этом человек обязан сразу,
    а не через месяц от бухгалтера.

    ⚠️ ЧАСТИЧНЫЙ УСПЕХ — ДОКУМЕНТ СОЗДАН, ПРОВЕДЕНИЕ УПАЛО — РАЗОБРАН ЯВНО,
    см. ниже по коду: документ НЕ удаляется, его номер отдаётся человеку.
    """
    _бухгалтер_или_администратор(user)
    p = await get_pool()

    собранное = await reports_data.собрать(p, id, user)
    if собранное is None:
        raise HTTPException(status_code=404, detail="Not found")
    отчёт, подотчётник, чеки = собранное

    # ⚠️ ТОЛЬКО ОДОБРЕННЫЙ. Черновик или отклонённый в учёте клиента —
    # документ, которого там быть не должно; вернуть его оттуда дороже,
    # чем не отправить.
    if отчёт.get("status") != "Одобрен":
        raise HTTPException(
            status_code=409,
            detail="В 1С уезжают только одобренные отчёты, а этот «%s»"
            % отчёт.get("status"),
        )

    # ⚠️ ПОВТОРНАЯ ВЫГРУЗКА ОТБИВАЕТСЯ ДО ВЫЗОВА, ВНЯТНЫМ ТЕКСТОМ. База
    # запретит вторую успешную запись сама (частичный уникальный индекс),
    # но человек получил бы ошибку БАЗЫ вместо объяснения.
    for прошлая in await _прошлые_выгрузки(p, id, user["org_id"]):
        # ⚠️ ИДУЩАЯ ОТПРАВКА — ОТКАЗ ТЕКСТОМ (1C-29). Это вежливая половина
        # защиты от двойного нажатия: второй ПОСЛЕДОВАТЕЛЬНЫЙ запрос узнаёт
        # правду словами. ОДНОВРЕМЕННЫЙ сюда не попадёт — оба читают журнал
        # до записи и оба видят его пустым; его держит индекс, см. INSERT.
        if прошлая["outcome"] == "running":
            if прошлая["прервана"]:
                raise HTTPException(
                    status_code=409,
                    detail="Прошлая отправка этого отчёта в 1С прервалась, не "
                    "закончившись: создан ли документ, неизвестно. Проверьте в 1С "
                    "и отмените отправку — после этого отчёт можно отправить снова.",
                )
            raise HTTPException(
                status_code=409,
                detail="Этот отчёт уже отправляется в 1С. Дождитесь результата.",
            )
        # ⚠️ Р6 (CAT-FOOD ②): документ, который уже лежит в 1С, мог
        # разойтись с чеками. Сказать об этом обязаны там же, где отказываем
        # в повторной выгрузке, — это единственное место, где человек сегодня
        # видит состояние выгрузки (экрана выгрузок нет, строка 1C-29).
        if прошлая["outcome"] in ("ok", "partial", "unposted"):
            устарел = category_confirm.хвост_устаревшего(
                await category_confirm.изменённые_после_выгрузки(
                    p, user["org_id"], id, прошлая["started_at"]
                )
            )
        if прошлая["outcome"] == "ok":
            raise HTTPException(
                status_code=409,
                detail="Отчёт уже выгружен в 1С, документ %s. Если его удалили "
                "в 1С, отмените отправку в 1С и повторите."
                % (прошлая["doc_number"] or прошлая["doc_ref"])
                + устарел,
            )
        if прошлая["outcome"] in ("partial", "unposted"):
            # ⚠️ ЗАЩИТА ОТ ВТОРОГО ДОКУМЕНТА ПРИ ЧАСТИЧНОМ УСПЕХЕ ЖИВЁТ
            # В КОДЕ, А НЕ В БАЗЕ, и это названо честно: индекс стережёт
            # только успехи, а здесь документ создан при неуспехе.
            # ⚠️ ПО ИСХОДУ, А НЕ ПО НАЛИЧИЮ ССЫЛКИ. Первая редакция проверяла
            # `doc_ref`, и ОТМЕНЁННАЯ выгрузка — у неё ссылка остаётся ради
            # истории — навсегда запирала отчёт. Поймано живым тестом
            # «отмена выпускает из тупика»: отмена не выпускала.
            raise HTTPException(
                status_code=409,
                detail="По отчёту уже создан документ %s, но он не проведён. "
                "Проведите его в 1С или отмените отправку в 1С."
                % (прошлая["doc_number"] or прошлая["doc_ref"])
                + устарел,
            )

    ссылки = _ссылки_организации()
    нет = [ССЫЛКИ[и] for и, з in ссылки.items() if not з]
    if нет or not odata_client.настроено():
        raise HTTPException(
            status_code=503,
            detail="Обмен с 1С не настроен: не заданы %s"
            % ", ".join(нет or ["доступы ODATA_*"]),
        )

    человек = await _человек(p, user["org_id"], отчёт.get("user_id"))
    if not человек:
        # ⚠️ НЕ ДОДУМЫВАЕМ ПОДОТЧЁТНОЕ ЛИЦО. Решение 1C-08: сопоставление
        # справочником, а не автоподбором — по ИНН нечем (заполнен у одного
        # из трёх), по ФИО ненадёжно.
        raise HTTPException(
            status_code=409,
            detail="Для подотчётного лица не настроено соответствие с 1С. "
            "Заведите его в настройках обмена.",
        )

    # ⚠️ БЕЗ ПРОФИЛЯ ВЫГРУЗКИ НЕТ, И ЭТО ОТКАЗ ДО ЗАПИСИ. В профиле лежат
    # режим налогообложения, режим НДС и счёт по умолчанию: без них состав
    # документа пришлось бы додумывать, а додумывать в чужой бухгалтерии
    # нельзя. Тот же ряд, что и «не настроено соответствие человека».
    профиль = await _профиль(p, user["org_id"])
    if not профиль:
        raise HTTPException(
            status_code=409,
            detail="Профиль учёта организации не настроен: неизвестны режим "
            "налогообложения, режим НДС и счёт затрат по умолчанию.",
        )

    # ⚠️ Р5 (CAT-FOOD ②): НЕПОДТВЕРЖДЁННАЯ КАТЕГОРИЯ — ОТКАЗ ДО 1С И ДО ЖУРНАЛА.
    # Отказ обязан быть БЕСПЛАТНЫМ: ни одного запроса в чужую базу, ни строки
    # в журнале выгрузок. Первое обращение к 1С — чтение справочников ниже,
    # первая строка журнала — INSERT ещё ниже; здесь пока только наша база.
    # Довод владельца: лучше заблокировать, чем второй раз выгрузить мусор.
    не_подтверждены = category_confirm.неподтверждённые(чеки)
    if не_подтверждены:
        raise HTTPException(
            status_code=409, detail=category_confirm.текст_отказа(не_подтверждены)
        )

    правила_категорий = await _правила_категорий(p, user["org_id"])
    правила_видов = await _правила_видов(p, user["org_id"])
    коды = {профиль["default_account_code"]} | {
        п.get("account_code")
        for п in list(правила_категорий.values()) + list(правила_видов.values())
        if п.get("account_code")
    }
    # ⚠️ ОБА СПРАВОЧНИКА ЧИТАЮТСЯ ДО ЗАПИСИ В ЖУРНАЛ И ДО POST: сбой чтения
    # обязан остановить выгрузку раньше, чем в 1С или у нас что-то появится.
    инн = {ч.get("org_inn") for ч in чеки if ч.get("org_inn")}
    try:
        счета = _сопоставить(
            await _прочитать_справочник(
                "ChartOfAccounts_Хозрасчетный", "Code", "план счетов"
            ),
            коды,
        )
        # Нет ни одного ИНН — читать 88 КБ контрагентов незачем.
        контрагенты = (
            _сопоставить(
                await _прочитать_справочник(
                    "Catalog_Контрагенты", "ИНН", "справочник контрагентов"
                ),
                инн,
            )
            if инн
            else {}
        )
    except СбойЧтенияСправочника as сбой:
        # ⚠️ 503, А НЕ 409: «не прочиталось» и «не нашлось» — разные беды,
        # и чинятся они в разных местах.
        raise HTTPException(
            status_code=503,
            detail="Не удалось прочитать %s 1С. Выгрузка не выполнена, повторите позже."
            % сбой.что,
        )

    собранное_тело = odata_body.собрать(
        отчёт,
        чеки,
        {
            **ссылки,
            "человек": человек,
            "правила_категорий": правила_категорий,
            "правила_видов": правила_видов,
            "контрагенты": контрагенты,
            "счета": счета,
            "профиль": профиль,
            "автор": подотчётник,
            "адрес_отчёта": _адрес_отчёта(id),
        },
    )

    # ⚠️ СЧЁТА НЕТ В ПЛАНЕ СЧЕТОВ КЛИЕНТА — ОТКАЗ ДО ЗАПИСИ, а не документ
    # со ссылкой в никуда: такой 1С не проведёт, и мусор останется в её базе.
    if собранное_тело["нет_счёта"]:
        raise HTTPException(
            status_code=409,
            detail="В плане счетов 1С нет счетов: %s. Проверьте соответствие категорий."
            % ", ".join(собранное_тело["нет_счёта"]),
        )

    # ⚠️⚠️ ЗАПИСЬ `running` — ЗАМОК ОТ ДВОЙНОГО НАЖАТИЯ (1C-29, часть 1C-23).
    # Индекс `odata_exports_one_live` пускает у отчёта одну живую запись,
    # и второй одновременный запрос спотыкается ЗДЕСЬ — до единого обращения
    # к 1С. Замер 22.09.2026 до этой правки: два одновременных нажатия давали
    # ДВА документа в подделке 1С, а при политике «проводить, когда всё
    # сопоставлено» — ещё и 500 с записью `running`, зависшей навсегда.
    try:
        # ⚠️ СНИМКИ ОТЧЁТА ПИШУТСЯ СРАЗУ (REP-EXPDEL, 22.09.2026): отчёт можно
        # удалить, и тогда ссылка обнулится, а строка журнала обязана остаться
        # читаемой глазами. Номер — id отчёта, другого номера у отчёта нет.
        запись = await p.fetchval(
            "INSERT INTO odata_exports (org_id, report_id, report_number,"
            " report_title, user_id, outcome, defaulted_categories)"
            " VALUES ($1,$2,$3,$4,$5,'running',$6::text[]) RETURNING id",
            user["org_id"],
            id,
            id,
            отчёт.get("title"),
            user["id"],
            собранное_тело["без_соответствия"],
        )
    except asyncpg.exceptions.UniqueViolationError:
        raise HTTPException(
            status_code=409,
            detail="Этот отчёт уже отправляется в 1С или уже отправлен. "
            "Обновите карточку отчёта.",
        )

    # ⚠️ СБОЙ НА НАШЕЙ СТОРОНЕ НЕ ОСТАВЛЯЕТ `running` (1C-29). Транспортные
    # ошибки клиент превращает в код ответа сам; исключение отсюда — наша
    # поломка до или вместо отправки. Без этой ветки запись осталась бы
    # `running` и заперла отчёт на десять минут, а потом до отмены руками.
    try:
        код, ответ = await odata_client.запросить(
            "Document_АвансовыйОтчет",
            метод="POST",
            тело=собранное_тело["тело"],
        )
    except Exception as сбой:
        await p.execute(
            "UPDATE odata_exports SET outcome='error', finished_at=NOW(),"
            " error_note=$2 WHERE id=$1",
            запись,
            "сбой на нашей стороне при отправке (%s)" % type(сбой).__name__,
        )
        raise
    if код != 200:
        await p.execute(
            "UPDATE odata_exports SET outcome=$2, finished_at=NOW(), error_note=$3"
            " WHERE id=$1",
            запись,
            "unavailable" if код == 503 else "error",
            (ответ or {}).get("message") if isinstance(ответ, dict) else None,
        )
        raise HTTPException(
            status_code=502 if код != 503 else 503,
            detail="1С не приняла документ: %s"
            % ((ответ or {}).get("message") if isinstance(ответ, dict) else "отказ"),
        )

    созданный = (ответ or {}).get("тело") or {}
    ссылка, номер = созданный.get("Ref_Key"), созданный.get("Number")
    без_контрагента = собранное_тело["без_контрагента"]

    # ⚠️⚠️ ПРОВЕДЕНИЕ РЕШАЕТ ПОЛИТИКА ПРОФИЛЯ, А НЕ ЗАШИТОЕ ПРАВИЛО
    # (AOCG-1C-001, § 7). Единственный универсальный блокер — НЕПОЛНОТА
    # НАШЕЙ НАСТРОЙКИ: у чека нет ни правила по категории, ни правила
    # по виду расхода, значит неизвестны ни статья, ни признак УСН.
    #
    # ⚠️ КОНТРАГЕНТ НЕ БЛОКИРУЕТ НИ В ОДНОМ РЕЖИМЕ, и это отмена правила
    # от 16.09.2026. Довод документа (§ 2.2): контрагент нужен только чтобы
    # зарегистрировать счёт-фактуру, а по чеку ККТ счёта-фактуры нет вовсе —
    # значит вычета нет и С контрагентом. Держать из-за него весь отчёт
    # означало бы платить работой за то, что учёту не нужно.
    #
    # ⚠️ НДС И РЕЖИМ НА ПРОВЕДЕНИЕ ТОЖЕ НЕ ВЛИЯЮТ: они меняют СОСТАВ
    # документа, а не право его провести.
    без_соответствия = собранное_тело["без_соответствия"]
    политика = профиль.get("auto_post_policy") or odata_body.ПРОВОДИТЬ_НИКОГДА
    if политика == odata_body.ПРОВОДИТЬ_НИКОГДА:
        проводить = False
    elif политика == odata_body.ПРОВОДИТЬ_ВСЕГДА:
        проводить = True
    else:
        проводить = not без_соответствия
    проведён = False
    if проводить:
        # ⚠️ ПРОВЕДЕНИЕ — ОТДЕЛЬНЫЙ ВЫЗОВ, И ОН МОЖЕТ УПАСТЬ ПОСЛЕ УСПЕШНОЙ
        # ЗАПИСИ. Замер 1C-20: `Post` возвращает 200 с ПУСТЫМ телом, результат
        # читается полем `Posted`.
        # ⚠️ ДОКУМЕНТ УЖЕ СОЗДАН — ИСКЛЮЧЕНИЕ ЗДЕСЬ ЗНАЧИТ «НЕ ПРОВЕДЁН»,
        # А НЕ ПАДЕНИЕ РУЧКИ (1C-29). Иначе журнал остался бы `running` без
        # ссылки на документ, который в 1С уже лежит, — ровно тот случай,
        # когда второй документ появляется после «отмены и повтора».
        try:
            код_п, _ответ_п = await odata_client.запросить(
                "Document_АвансовыйОтчет(guid'%s')/Post" % ссылка,
                метод="POST",
                параметры={"PostingModeOperational": "false"},
            )
        except Exception as сбой:
            # В журнал — тип, а не текст: текст может нести адрес чужой базы.
            logger.warning("OData: проведение упало (%s)", type(сбой).__name__)
            код_п = None
        проведён = код_п == 200

    # ⚠️⚠️ РЕШЕНИЕ ПО ЧАСТИЧНОМУ УСПЕХУ, НАЗВАНО ЯВНО: ДОКУМЕНТ НЕ УДАЛЯЕМ.
    # Довод: удаление — ВТОРАЯ запись в чужую бухгалтерию, и делать её
    # молча, в ответ на сбой, опаснее самого сбоя: если упало проведение,
    # а не связь, документ в базе клиента уже виден его бухгалтеру.
    # Поэтому мы оставляем документ НЕПРОВЕДЁННЫМ и ОТДАЁМ ЕГО НОМЕР —
    # человек решает сам: провести руками или отменить выгрузку.
    # Мусора «молча» здесь нет: номер в ответе, номер в журнале.
    # ⚠️ ТРИ ИСХОДА, И ОНИ РАЗНЫЕ ДЛЯ РАЗБОРА ЧЕРЕЗ МЕСЯЦ: `ok` — проведён;
    # `partial` — проведение ПЫТАЛИСЬ сделать, и оно упало; `unposted` —
    # проведение НЕ ДЕЛАЛИ намеренно, потому что не у всех строк найден
    # контрагент. Слить два последних значило бы отвечать бухгалтеру
    # «что-то сломалось» там, где ничего не ломалось.
    if проведён:
        исход, заметка = "ok", None
    elif not проводить:
        исход = "unposted"
        заметка = "не проведён намеренно: " + (
            "нет соответствия у категорий %s" % ", ".join(без_соответствия)
            if без_соответствия
            else "политика проведения «%s»" % политика
        )
    else:
        исход, заметка = "partial", "документ создан, проведение не прошло"
    await p.execute(
        "UPDATE odata_exports SET outcome=$2, finished_at=NOW(), doc_ref=$3,"
        " doc_number=$4, error_note=$5 WHERE id=$1",
        запись,
        исход,
        ссылка,
        номер,
        заметка,
    )

    return {
        "выгружен": True,
        "проведён": проведён,
        "документ": номер,
        "строк": len(собранное_тело["тело"]["Прочее"]),
        # ⚠️ ДВА СПИСКА НИЖЕ — ЧАСТЬ ДОГОВОРА, А НЕ ОТЛАДКА.
        "категории_без_соответствия": без_соответствия,
        "чеки_без_контрагента": без_контрагента,
        "политика_проведения": политика,
        # ⚠️ ПОЧЕМУ НЕ ПРОВЕДЁН — СЛОВАМИ, А НЕ ФЛАГОМ.
        "почему_не_проведён": (
            "Не проведён намеренно: %s. Проверьте документ %s и проведите вручную."
            % (заметка.split(": ", 1)[-1], номер)
            if not проводить
            else ("Проведение не прошло, документ %s остался черновиком." % номер)
            if not проведён
            else None
        ),
        "предупреждение": (
            "Счёт затрат %s подставлен по умолчанию для категорий: %s. "
            "Заведите правило по виду расхода — без него документ "
            "не проводится при политике «%s»."
            % (
                профиль["default_account_code"],
                ", ".join(без_соответствия),
                политика_текстом(политика),
            )
            if без_соответствия
            else None
        ),
    }


# ⚠️ ПОМЕТКА ДОКУМЕНТА НА УДАЛЕНИЕ В 1С ПРИ ОТМЕНЕ (1C-DELMARK, решение
# владельца 23.09.2026). До этого отмена снимала только НАШУ запись, а
# документ оставался в чужой бухгалтерии, и пометку ставил бухгалтер руками —
# то есть обязательство перекладывалось на человека, который о нём мог и
# не узнать.
#
# ⚠️⚠️ ТОЛЬКО PATCH, И НИКОГДА DELETE. В стандартном интерфейсе OData метод
# DELETE удаляет объект ФИЗИЧЕСКИ и пометку НЕ ставит: документ исчезает из
# базы клиента безвозвратно, в списке помеченных не появляется, бухгалтер его
# не увидит и не проверит. Запрет держится не этим комментарием, а списком
# `ДОПУСТИМЫЕ_МЕТОДЫ` в клиенте — отказ уходит ДО сети.
#
# ⚠️⚠️ ПРОВЕДЁННЫЙ ДОКУМЕНТ ПЛАТФОРМА НЕ ТРОГАЕТ ВООБЩЕ (поправка владельца
# 23.09.2026). Первая редакция сама распроводила его через `/Unpost` и затем
# помечала. Решение отменено: проведённый документ уже вошёл в учёт клиента,
# и снимать проведение за спиной бухгалтера — не наше дело. Такой документ
# помечает человек в 1С, а мы честно говорим об этом и свою запись всё равно
# отменяем. Ни одного обращения к 1С в этой ветке не уходит — это проверяется
# тестом и мутацией, а не обещанием.
#
# ⚠️ ОТМЕНА У НАС ПРОХОДИТ В ЛЮБОМ СЛУЧАЕ (решение владельца). 1С недоступна
# или отказала — мы всё равно освобождаем отчёт, а человеку говорим, что
# пометить придётся руками. Иначе недоступность чужой системы запирала бы
# наш отчёт, и это ровно тот тупик, из которого отмена и заводилась.
ПОМЕЧЕН = "документ помечен на удаление в 1С"
НЕ_ПОМЕЧЕН = "пометка на удаление в 1С не поставлена"
# ⚠️ БЕЗ СЛОВА «БУХГАЛТЕРОМ» (поправка владельца 23.09.2026): документ
# проводит НАША выгрузка по политике учёта, а не человек, — и запись
# в журнале не должна приписывать действие тому, кто его не делал.
ПРОВЕДЁН = "документ проведён, пометка не поставлена"


async def _пометить_на_удаление(ссылка: str) -> bool:
    """`True` — 1С приняла пометку. Наружу не бросает: отмена идёт всегда."""
    try:
        код, _ответ = await odata_client.запросить(
            "Document_АвансовыйОтчет(guid'%s')" % ссылка,
            метод="PATCH",
            тело={"DeletionMark": True},
        )
        return код == 200
    except Exception as сбой:
        # В журнал — ТИП, а не текст: текст чужой ошибки несёт адрес базы
        # клиента и имя пользователя (замер 1C-21, заход ①).
        logger.warning("OData: пометка на удаление упала (%s)", type(сбой).__name__)
        return False


@router.post("/reports/{id}/cancel-export")
async def отменить_выгрузку(id: int, user: dict = Depends(get_current_user)):
    """Путь из тупика (требование 1C-23): документ в 1С удалили руками.

    ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ. Успешная выгрузка у отчёта ровно одна — так велит
    частичный уникальный индекс. Если документ в 1С удалят вручную, отчёт
    застрянет: в 1С его нет, а выгрузить заново база не даст. Выход
    правкой в базе руками — тот же тупик, что с запертым администратором.

    ⚠️ МЫ НИЧЕГО НЕ УДАЛЯЕМ В 1С. Отмена — про НАШУ запись: она помечается
    исходом `cancelled`, и индекс снова пропускает выгрузку. Что делать
    с документом в чужой базе, решает бухгалтер клиента.
    """
    _бухгалтер_или_администратор(user)
    p = await get_pool()
    строки = await _прошлые_выгрузки(p, id, user["org_id"])
    живая = next((с for с in строки if с["outcome"] in ЖИВЫЕ), None)
    if живая is None:
        raise HTTPException(
            status_code=409,
            detail="По этому отчёту нет выгрузки, которую можно отменить",
        )
    # ⚠️ ИДУЩУЮ ОТПРАВКУ НЕ ОТМЕНЯЕМ, ПРЕРВАННУЮ — ОТМЕНЯЕМ (1C-29). Отмена
    # идущей освободила бы замок, пока документ ещё едет в 1С, и следом
    # за ней прошла бы вторая отправка. Прерванная — единственный выход
    # из неё, и по той же причине, что у удалённого в 1С документа.
    if живая["outcome"] == "running" and not живая["прервана"]:
        raise HTTPException(
            status_code=409,
            detail="Отправка в 1С идёт прямо сейчас — отменять пока нечего. "
            "Дождитесь результата.",
        )
    # ⚠️ ПОМЕТКА СТАВИТСЯ ДО НАШЕЙ ЗАПИСИ, А ИСХОД ЕЁ — В ЖУРНАЛ. Ставить
    # после значило бы иметь мгновение, когда отчёт уже свободен, а документ
    # в 1С ещё жив и не помечен: повторная выгрузка в этот миг дала бы два
    # документа. Только у выгрузки, которая ДОШЛА до 1С: без ссылки помечать
    # нечего.
    # ⚠️ ИСХОД ПОМЕТКИ — ТРИ РАЗНЫХ, А НЕ «получилось / не получилось»:
    # документа нет · документ проведён и мы его не трогаем · пробовали.
    # Слить их значило бы отвечать человеку «не вышло» там, где мы даже
    # не пытались, — и он пошёл бы искать поломку вместо действия.
    помечен = None
    проведён = живая["outcome"] == "ok"
    if живая["doc_ref"] and not проведён:
        помечен = await _пометить_на_удаление(живая["doc_ref"])
    хвост = " · отменено пользователем"
    if помечен is True:
        хвост += " · " + ПОМЕЧЕН
    elif помечен is False:
        хвост += " · " + НЕ_ПОМЕЧЕН
    elif живая["doc_ref"] and проведён:
        хвост += " · " + ПРОВЕДЁН
    await p.execute(
        "UPDATE odata_exports SET outcome='cancelled', finished_at=NOW(),"
        " error_note=COALESCE(error_note,'') || $2"
        " WHERE id=$1",
        живая["id"],
        хвост,
    )
    if помечен is True:
        заметка = (
            "Запись о выгрузке отменена, документ в 1С помечен на удаление. "
            "Бухгалтер клиента удалит помеченное сам — платформа этого "
            "не делает никогда."
        )
    elif помечен is False:
        заметка = (
            "Запись о выгрузке отменена, но пометить документ в 1С не вышло: "
            "пометьте его на удаление в 1С сами, иначе после повторной "
            "выгрузки их станет два."
        )
    elif живая["doc_ref"] and проведён:
        заметка = (
            "Запись о выгрузке отменена. Документ %s в 1С уже проведён — "
            "пометьте его на удаление в 1С вручную."
            % (живая["doc_number"] or живая["doc_ref"])
        )
    else:
        заметка = (
            "Запись о выгрузке отменена. Документа в 1С по ней не было — "
            "помечать нечего."
        )
    return {
        "отменено": True,
        "документ": живая["doc_number"] or живая["doc_ref"],
        "помечен": помечен,
        "заметка": заметка,
    }


