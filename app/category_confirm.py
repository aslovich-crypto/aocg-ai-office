"""Подтверждение категории человеком (CAT-FOOD ②, решения владельца 21.09.2026).

Здесь три вещи, которым не место в роутерах:
  · порог суммы организации — чтение профиля учёта (Р3);
  · отказ выгрузки в 1С, пока категории не подтверждены, — отбор и текст (Р5);
  · «документ в 1С устарел» — какие чеки отчёта менялись после выгрузки (Р6).

Правила «нужно ли подтверждение» — чистые функции в `app/categorization.py`:
они же считают подсказку категории, и два места правил разошлись бы.
"""

from decimal import Decimal

# ⚠️ УМОЛЧАНИЕ ТО ЖЕ, ЧТО У КОЛОНКИ `confirm_amount_threshold` (init_db).
# Профиля нет вовсе — ведём себя как у профиля с умолчанием, а не как
# «по сумме не спрашивать»: NULL — это выбор клиента, его отсутствие — нет.
ПОРОГ_ПО_УМОЛЧАНИЮ = Decimal("10000")


async def порог_подтверждения(p, org_id: int):
    """Порог суммы, выше которой категорию подтверждает человек. None — не спрашивать."""
    строка = await p.fetchrow(
        "SELECT confirm_amount_threshold FROM org_accounting_profile WHERE org_id=$1",
        org_id,
    )
    if строка is None:
        return ПОРОГ_ПО_УМОЛЧАНИЮ
    return строка["confirm_amount_threshold"]


def неподтверждённые(чеки) -> list:
    """Чеки, которые держат выгрузку: правило требует подтверждения, человек не дал.

    ⚠️ ДВА ПОЛЯ, А НЕ ОДНО (решение владельца 21.09.2026). `category_manual`
    отвечает «подтвердил ли человек», `category_confirm_required` — «нужно ли
    было спрашивать». Считать «не трогал» за «требует подтверждения» нельзя:
    это верно почти для всех чеков, и выгрузка отказывала бы всегда."""
    return [
        ч
        for ч in чеки
        if ч.get("category_confirm_required") and not ч.get("category_manual")
    ]


def _рубли(сумма) -> str:
    return f"{Decimal(str(сумма or 0)):,.2f}".replace(",", " ").replace(".", ",")


# ⚠️ ПОИМЁННО — ТОЛЬКО ПЕРВЫЕ ПЯТЬ (решение владельца 21.09.2026). В отчёте 9
# под флагом 26 чеков: перечень всех не помещается на экран, а человек всё
# равно пойдёт в список. Пять самых крупных — то, с чего начинать.
ПОИМЁННО = 5


def _чек_после_числа(n: int, родительный: bool) -> str:
    """«1 чек · 2 чека · 5 чеков · 21 чек»; в родительном — «у 1 чека · у 5 чеков»."""
    if n % 10 == 1 and n % 100 != 11:
        return "чека" if родительный else "чек"
    if not родительный and n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return "чека"
    return "чеков"


def текст_отказа(чеки) -> str:
    """Текст 409: крупные первыми, поимённо и с суммой — не больше пяти.

    Без имён человек пойдёт искать чеки руками по всему отчёту; со всеми
    двадцатью шестью сообщение перестаёт помещаться на экран."""
    по_сумме = sorted(чеки, key=lambda ч: -float(ч.get("amount") or 0))
    перечень = " · ".join(
        "Чек №%s «%s» — %s ₽"
        % (
            ч.get("id"),
            ч.get("org_brand") or ч.get("org") or "без названия",
            _рубли(ч.get("amount")),
        )
        for ч in по_сумме[:ПОИМЁННО]
    )
    остаток = len(по_сумме) - ПОИМЁННО
    if остаток > 0:
        перечень += " и ещё %d %s" % (остаток, _чек_после_числа(остаток, False))
    return (
        "Подтвердите категорию у %d %s и повторите выгрузку: %s. "
        "Категорию выбрала машина, а в 1С уйдёт статья расхода — решает человек."
        % (len(по_сумме), _чек_после_числа(len(по_сумме), True), перечень)
    )


async def изменённые_после_выгрузки(p, org_id: int, report_id: int, выгружено) -> list:
    """Номера чеков отчёта, изменённых в полях документа ПОСЛЕ выгрузки (Р6).

    ⚠️ ВРЕМЯ ПРАВКИ ДВИГАЕТ ТРИГГЕР БАЗЫ, А НЕ РУЧКИ (решение владельца, Д3):
    правку прямым SQL ручка не увидит, триггер увидит. Он смотрит ровно на
    поля, из которых собирается документ, — флаг подтверждения и снимок
    время не двигают, иначе разовый проход «состарил» бы все документы."""
    строки = await p.fetch(
        "SELECT r.id FROM receipts r"
        " JOIN report_items ri ON ri.receipt_id = r.id"
        " WHERE ri.report_id = $1 AND r.org_id = $2 AND r.updated_at > $3"
        " ORDER BY r.id",
        report_id,
        org_id,
        выгружено,
    )
    return [с["id"] for с in строки]


def хвост_устаревшего(изменены) -> str:
    """Добавка к ответу о существующем документе: он разошёлся с чеками."""
    if not изменены:
        return ""
    return (
        " ⚠️ Документ в 1С устарел: после выгрузки изменены чеки %s. "
        "Отмените выгрузку и выгрузите отчёт заново."
        % ", ".join("№%s" % н for н in изменены)
    )
