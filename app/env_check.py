ЯВНОЕ_НЕТ = frozenset({"0", "false", "no", "off"})


def показать(имя: str, сырое) -> str:
    """Значение для журнала: секреты — только фактом и длиной."""
    if сырое is None:
        return "не задана"
    if имя in СЕКРЕТЫ:
        return f"задан ({len(сырое)} знаков)" if сырое else "пустая строка"
    return f"«{сырое}»" if сырое else "пустая строка"


def _сошлось(вид: str, значение: str, эталон) -> bool:
    if вид == "задан":
        return bool(значение)
    if вид == "пусто":
        return not значение
    if вид == "равно_или_пусто":
        return (not значение) or значение == эталон
    if вид == "не_больше":
        if not значение:
            return True  # умолчание кода уже безопасно
        try:
            return int(значение) <= эталон
        except ValueError:
            return False
    if вид == "не_выключено":
        return значение.lower() not in ЯВНОЕ_НЕТ
    raise ValueError(f"неизвестный вид проверки: {вид}")


def сверить(окружение=None) -> list:
    """Список расхождений: (имя, что видно, чем грозит). Пустой — сошлось."""
    среда = os.environ if окружение is None else окружение
    расхождения = []
    for имя, вид, эталон, угроза in ОЖИДАНИЯ:
        сырое = среда.get(имя)
        if not _сошлось(вид, (сырое or "").strip(), эталон):
            расхождения.append((имя, показать(имя, сырое), угроза))
    return расхождения


def сверить_и_сказать(окружение=None) -> int:
    """Сверяет и пишет в журнал. Возвращает число расхождений.

    ⚠️ УРОВЕНЬ WARNING И ПРИ УСПЕХЕ ТОЖЕ — намеренно, тот же довод, что
    у миграции NDS-CLEANUP: строка INFO при корневом уровне WARNING просто
    исчезает, и «сверка прошла» выглядит ровно как «сверка не выполнялась».
    Одна строка на старт контейнера — приемлемая цена за то, чтобы отличать
    работающий прибор от молчащего (T87).
    """
    расхождения = сверить(окружение)
    if not расхождения:
        logger.warning(
            "ENV-СВЕРКА: боевые настройки сошлись с описью (проверено %s)",
            len(ОЖИДАНИЯ),
        )
        return 0
    logger.warning(
        "ENV-СВЕРКА: РАСХОЖДЕНИЙ %s из %s — опись AOCG-ENV-001",
        len(расхождения),
        len(ОЖИДАНИЯ),
    )
    for имя, видно, угроза in расхождения:
        logger.warning("ENV-СВЕРКА: %s = %s — %s", имя, видно, угроза)
    return len(расхождения)
