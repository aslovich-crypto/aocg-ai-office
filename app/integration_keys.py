"""Ключ интеграции: принципал, который НЕ ЧЕЛОВЕК (шаг 3, заход ④).

⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИНЦИПАЛ. Ключ уезжает НА ЧУЖУЮ МАШИНУ — в базу клиента,
в настройки обработки 1С — и живёт там долго. Личный токен человека туда
отдавать нельзя: он открывает всё, что может человек, и гасится только
вместе с ним.

⚠️ КЛЮЧ ПРИТВОРЯЕТСЯ ЧЕЛОВЕКОМ ПО ФОРМЕ, НО НЕ ПО ПРАВАМ. Зависимость
возвращает словарь ТОЙ ЖЕ ФОРМЫ, что и `get_current_user`, — с `org_id`,
`id` и `role`. Благодаря этому не трогается ни одно из 82 мест фильтрации
по организации и ни одна проверка роли (замер 12.09.2026). А права ключ
не получает потому, что роль у него СВОЯ: `can_see_all` и `can_delete_any`
сравнивают роль по равенству с именами людей и для ключа возвращают ложь
по построению.

⚠️ В СЛОВАРЕ КЛЮЧА НЕТ НИ ОДНОГО СЕКРЕТНОГО ПОЛЯ, И ЭТО ТРЕБОВАНИЕ
ВЛАДЕЛЬЦА 12.09.2026, А НЕ АККУРАТНОСТЬ. `get_current_user` возвращает
СЫРУЮ строку человека целиком — 22 колонки, включая хеш пароля и токен
подтверждения почты. Повторять это для ключа нельзя: словарь уезжает
в те же ручки, а «пустое поле однажды заполнят». Здесь перечислены ровно
четыре ключа, и сторож стережёт как их состав, так и отсутствие секретных.

⚠️ КЛЮЧ ЧИТАЕТСЯ ТОЛЬКО ИЗ ЗАГОЛОВКА `Authorization`. Ни строки запроса,
ни своего имени заголовка: строка запроса оседает в журналах веб-серверов,
а своё имя ушло бы в приёмник ошибок ОТКРЫТЫМ ТЕКСТОМ — наша чистка событий
заголовки не трогает вовсе, их режет только встроенный список библиотеки
из пяти имён, и `authorization` в нём есть (замер аудита 12.09.2026).

⚠️⚠️ ЭТА ЗАВИСИМОСТЬ НАПИСАНА И ПОКА НЕ ПОДКЛЮЧЕНА НИ К ОДНОЙ РУЧКЕ —
ПОДКЛЮЧЕНИЕ ДЕЛАЕТ ЗАХОД ⑤ (ручка отчётов по ключу). НЕ СНИМАТЬ КАК
НЕИСПОЛЬЗУЕМОЕ. Это класс [[T192]]: написанное и неподключённое не ловит
ни один сторож — у сторожа достижимости обработчики исключены намеренно,
иначе он объявил бы мёртвыми все ручки до единой. Значит «ноль вызовов»
здесь — ожидаемое состояние между двумя заходами, а не признак мусора.
Проверки на эту зависимость есть и зелены: `tests/pg/test_integration_principal_live.py`
и `tests/test_integration_role_isolated.py`.

⚠️ И ПОЧЕМУ ОБЛАСТЬ ПРАВ ВЫРАЖЕНА МЕСТОМ, А НЕ РОЛЬЮ: ключ получает ровно
то, где стоит ЭТА зависимость. Пока она не стоит нигде — ключ не открывает
ничего, даже будучи верным. Права не отбираются задним числом, а выдаются
по одной ручке за раз.
"""

import hashlib
import hmac
import logging
from typing import Optional

from fastapi import Depends, HTTPException, status
from fastapi.security import OAuth2PasswordBearer

from app.auth import ROLE_INTEGRATION
from app.database import get_pool

logger = logging.getLogger(__name__)

# ⚠️ ДЛИНА ПРЕФИКСА ЗАФИКСИРОВАНА СХЕМОЙ (`VARCHAR(12)`), и это одно число
# на два места. Префикс — открытая часть: по нему ищется строка, он виден
# в списке и в журнале. Секрет в журнал не попадает никогда.
ДЛИНА_ПРЕФИКСА = 12

# Тот же разделитель, что у всех ключей такого рода: видно, где кончается
# открытая часть и начинается секрет.
РАЗДЕЛИТЕЛЬ = "."

# Читаем тот же заголовок, что и люди. `auto_error=False` — чтобы отсутствие
# заголовка давало НАШ отказ с внятным текстом, а не чужой.
ключ_из_заголовка = OAuth2PasswordBearer(tokenUrl="/api/auth/login", auto_error=False)


def хеш_секрета(секрет: str) -> str:
    """sha256 от секрета КАК ОН ЕСТЬ.

    ⚠️ ИМЕННО sha256, А НЕ bcrypt, И ЭТО НЕ ЭКОНОМИЯ. bcrypt нужен там, где
    секрет выбирает ЧЕЛОВЕК и он угадываем перебором по словарю. Ключ
    интеграции порождает машина из случайных байтов — перебирать его нечем,
    зато проверяется он на КАЖДОМ запросе обработки, и медленный хеш стал бы
    ценой на ровном месте. Тот же приём и по той же причине уже применён
    к погашенным токенам обновления (`app/routers/auth.py`).
    """
    return hashlib.sha256(секрет.encode()).hexdigest()


def разобрать(значение: str):
    """«префикс.секрет» → (префикс, секрет) либо (None, None).

    Разбор намеренно строгий: в чужой базе ключ вставляют руками, и обрезанное
    при копировании значение обязано получить внятный отказ, а не «не найдено».
    """
    if not значение or РАЗДЕЛИТЕЛЬ not in значение:
        return None, None
    префикс, _, секрет = значение.partition(РАЗДЕЛИТЕЛЬ)
    if len(префикс) != ДЛИНА_ПРЕФИКСА or not секрет:
        return None, None
    return префикс, секрет


async def найти_живой(p, префикс: str):
    """Строка ключа по префиксу, если он не отозван и не истёк.

    ⚠️ ОБЕ ПРОВЕРКИ В SQL, А НЕ В PYTHON, И ЭТО СУЩЕСТВЕННО: срок сверяется
    с часами БАЗЫ, а не приложения. Иначе расхождение часов контейнера дало бы
    ключ, который для одного инстанса ещё жив, а для другого уже мёртв.
    """
    return await p.fetchrow(
        "SELECT id, org_id, prefix, secret_hash, name FROM integration_keys "
        "WHERE prefix=$1 AND revoked_at IS NULL "
        "AND (expires_at IS NULL OR expires_at > NOW())",
        префикс,
    )


def принципал(строка) -> dict:
    """Строка ключа → словарь ТОЙ ЖЕ ФОРМЫ, что у человека.

    ⚠️ РОВНО ЧЕТЫРЕ КЛЮЧА, И НИ ОДНОГО СЕКРЕТНОГО. `secret_hash` сюда
    не попадает даже пустым: пустое поле однажды заполнят. `key_prefix` нужен
    журналу захода ⑦ — чтобы было видно, КАКОЙ ключ ходил, не раскрывая секрета.
    """
    return {
        "id": строка["id"],
        "org_id": строка["org_id"],
        "role": ROLE_INTEGRATION,
        "key_prefix": строка["prefix"],
    }


async def get_integration_principal(
    значение: Optional[str] = Depends(ключ_из_заголовка),
) -> dict:
    """Зависимость проверки ключа. 401 на любой отказ, без подробностей.

    ⚠️ ОТКАЗ ОДИН НА ВСЕ СЛУЧАИ — не найден, отозван, истёк, не сошёлся хеш.
    Разные тексты рассказали бы тому, кто подбирает ключ, на каком шаге он
    остановился: «отозван» подтверждает, что префикс существовал. Это тот же
    приём, что и единое «Неверный логин или пароль» на входе людей.
    """
    отказ = HTTPException(
        status_code=status.HTTP_401_UNAUTHORIZED,
        detail="Неверный ключ интеграции",
        headers={"WWW-Authenticate": "Bearer"},
    )
    префикс, секрет = разобрать(значение or "")
    if not префикс:
        raise отказ

    p = await get_pool()
    строка = await найти_живой(p, префикс)
    if not строка:
        raise отказ

    # ⚠️ СРАВНЕНИЕ ПОСТОЯННОГО ВРЕМЕНИ. Обычное `==` на строках выходит
    # из сравнения на первом несовпавшем знаке, и по времени ответа можно
    # добирать хеш посимвольно. Цена защиты здесь нулевая.
    if not hmac.compare_digest(хеш_секрета(секрет), строка["secret_hash"]):
        # Префикс существует, а секрет не сошёлся — это единственный случай,
        # который стоит записи: он означает либо опечатку при вставке, либо
        # подбор. Сам секрет в журнал не идёт никогда.
        logger.warning("Ключ интеграции: секрет не сошёлся, префикс %s", префикс)
        raise отказ

    return принципал(строка)
