"""Отчёт в xlsx — плоская таблица под загрузку в 1С (строка 1C, шаг 1).

ФОРМА ФАЙЛА — решение владельца 11.09.2026, вариант ⓐ: ОДНА СТРОКА НА ЧЕК,
шапка отчёта повторяется в каждой строке. Повтор не избыточность: без него
в 1С и в Excel не отфильтровать строки одного отчёта. Разбивка по позициям
чека не делается — попросит бухгалтер, добавится отдельным листом.

⚠️ СОСТАВ СТОЛБЦОВ — ДАННЫЕ, А НЕ КОД, И ЭТО ГЛАВНОЕ РЕШЕНИЕ МОДУЛЯ.
Столбцы бухгалтера нам не показаны (строка 1C требует брать их у него,
а не из документации 1С), значит первый состав — догадка. Чтобы догадка
стоила дёшево, она лежит ОДНИМ списком `ПРОФИЛЬ`: заголовок, ключ, формат.
Промах правится строкой в этом списке, а не переписыванием сборки и сторожа.
Тот же приём, что у `app/dictionaries/categories.json` — единый источник,
из которого растут и код, и проверки.

⚠️ ЧЕК БЕЗ ФИСКАЛЬНЫХ РЕКВИЗИТОВ ИДЁТ В ФАЙЛ С ПУСТЫМИ ЯЧЕЙКАМИ — решение
владельца 11.09.2026. Довод: бухгалтеру пустая ячейка и снимок понятнее,
чем отсутствие строки; чек существует, расход был, документ есть. Строка
[[31]] в трекере чинит сохранение реквизитов отдельно и выгрузку не держит.

⚠️ НДС РАЗЛОЖЕН ПО ВСЕМ СТАВКАМ ТЕГА 1199, А НЕ ПО ВСТРЕЧЕННЫМ В ДАННЫХ.
Правило репозитория «нормы РФ закладывать проактивно»: данные пользователя —
подмножество нормы, не наоборот. Список ставок берётся ИЗ ЕДИНСТВЕННОЙ карты
кодов (`app/parsers/fns_parser`), а не переписывается рядом: две карты кодов
у нас уже были, и обе врали по-своему (разбор — в шапке того же модуля).
Обороты по ставке 0% и «без НДС» стоят отдельными колонками намеренно:
это ОБОРОТЫ, а не налог, и смешивать их с суммами НДС нельзя.

⚠️ ВРЕМЯ ЧЕКА БЕРЁТСЯ КАК ЕСТЬ. С 11.09.2026 колонка `datetime` — это
`TIMESTAMP WITHOUT TIME ZONE`, наивное стенное время кассы: часовой пояс
кассы ФНС не присылает. Никакого перевода зон здесь быть не должно —
ровно это чинила строка [[20]].
"""

import datetime as _dt
import io
import json
from decimal import Decimal
from typing import Any, Optional

import xlsxwriter

from app.parsers.fns_parser import КОДЫ_С_НАЛОГОМ, СТАВКА_ПО_КОДУ

# Ставки, по которым бывает СУММА НАЛОГА. Коды 5 («0») и 6 («без НДС») сюда
# не входят: у них налога нет по определению, их обороты — отдельные колонки.
СТАВКИ_НДС = tuple(СТАВКА_ПО_КОДУ[код] for код in КОДЫ_С_НАЛОГОМ)

ШАПКА_ОТЧЁТА = (
    ("Отчёт №", "отчёт_номер", "текст"),
    ("Отчёт", "отчёт", "текст"),
    ("Статус отчёта", "статус", "текст"),
    ("Дата отчёта", "дата_отчёта", "дата"),
    ("Подотчётное лицо", "подотчётник", "текст"),
)

ТЕЛО_ЧЕКА = (
    ("Дата чека", "дата", "дата"),
    ("Время чека", "время", "время"),
    ("Продавец", "продавец", "текст"),
    ("Продавец (юрлицо)", "продавец_юрлицо", "текст"),
    ("ИНН продавца", "инн", "текст"),
    ("Сумма", "сумма", "деньги"),
    ("Валюта", "валюта", "текст"),
    ("Статья расхода", "статья", "текст"),
    ("Способ оплаты", "оплата", "текст"),
)

НДС = tuple(("НДС " + ставка, "ндс_" + ставка, "деньги") for ставка in СТАВКИ_НДС) + (
    ("Оборот 0%", "оборот_0", "деньги"),
    ("Оборот без НДС", "оборот_без_ндс", "деньги"),
)

РЕКВИЗИТЫ = (
    ("ФН", "фн", "текст"),
    ("ФД", "фд", "текст"),
    ("ФПД", "фпд", "текст"),
    ("Снимок чека", "снимок", "ссылка"),
)

ПРОФИЛЬ = ШАПКА_ОТЧЁТА + ТЕЛО_ЧЕКА + НДС + РЕКВИЗИТЫ

ЛИСТ = "Авансовый отчёт"


def _деньги(значение: Any) -> Optional[float]:
    """Decimal из базы → число для ячейки.

    ⚠️ Берём ИМЕННО `Decimal`, который отдаёт asyncpg по NUMERIC, а не
    каноническую форму чека: там суммы намеренно переведены в float ради
    JSON, и на половинке копейки это уже другое число. Здесь перевод
    делается один раз и в самом конце, когда округлять больше некому.
    """
    if значение is None:
        return None
    if isinstance(значение, Decimal):
        return float(значение)
    if isinstance(значение, (int, float)):
        return float(значение)
    return None


def _как_словарь(значение: Any) -> dict:
    """JSONB приходит от asyncpg то словарём, то строкой — принимаем оба."""
    if isinstance(значение, dict):
        return значение
    if isinstance(значение, str) and значение.strip():
        try:
            разобрано = json.loads(значение)
        except ValueError:
            return {}
        return разобрано if isinstance(разобрано, dict) else {}
    return {}


def фамилия_и_инициал(человек: Optional[dict]) -> str:
    """«Фамилия И.» — форма, выбранная владельцем 11.09.2026.

    Пустая строка, а не «—»: в файле для 1С прочерк — это значение, а нам
    нужно именно отсутствие. Отчество не берём: в авансовом отчёте лицо
    опознаётся по справочнику, а не по полноте написания.
    """
    if not человек:
        return ""
    фамилия = (человек.get("last_name") or "").strip()
    имя = (человек.get("first_name") or "").strip()
    if фамилия and имя:
        return фамилия + " " + имя[0] + "."
    return фамилия or имя


def строка_файла(отчёт: dict, подотчётник: str, чек: dict) -> dict:
    """Один чек → один словарь по ключам `ПРОФИЛЬ`.

    Все ключи профиля присутствуют всегда, даже пустые: сторож состава
    сверяет файл с профилем, и пропущенный ключ обязан быть отличим от
    пустого значения.
    """
    разбивка = _как_словарь(чек.get("vat_breakdown"))
    время = чек.get("datetime")
    ряд = {
        "отчёт_номер": отчёт.get("id"),
        "отчёт": отчёт.get("title") or "",
        "статус": отчёт.get("status") or "",
        "дата_отчёта": отчёт.get("created"),
        "подотчётник": подотчётник,
        "дата": чек.get("date"),
        "время": время,
        "продавец": чек.get("org") or "",
        "продавец_юрлицо": чек.get("org_legal") or "",
        "инн": чек.get("org_inn") or "",
        "сумма": _деньги(чек.get("amount")),
        "валюта": чек.get("currency") or "",
        "статья": чек.get("статья") or "",
        "оплата": чек.get("payment") or "",
        "оборот_0": _деньги(чек.get("sum_vat_0")),
        "оборот_без_ндс": _деньги(чек.get("sum_no_vat")),
        "фн": чек.get("kkt_fn") or "",
        "фд": чек.get("fd_num") or "",
        "фпд": чек.get("fpd") or "",
        "снимок": чек.get("снимок") or "",
    }
    for ставка in СТАВКИ_НДС:
        ряд["ндс_" + ставка] = _деньги(разбивка.get(ставка))
    return ряд


def имя_файла(отчёт: dict) -> str:
    """Имя собирается ЗДЕСЬ, а не на клиенте.

    Причина замером: `expose_headers` в CORS не выставлен, поэтому имя из
    `Content-Disposition` браузер клиенту прочитать не даст. Пусть обе
    стороны берут его из одного места — отсюда.
    """
    номер = отчёт.get("id")
    дата = отчёт.get("created")
    хвост = дата.strftime("%Y-%m-%d") if isinstance(дата, _dt.date) else "без-даты"
    return "otchet-{}-{}.xlsx".format(номер, хвост)


def собрать(отчёт: dict, подотчётник: str, чеки: list) -> bytes:
    """Готовый xlsx в память. В базу не ходит и про HTTP не знает."""
    буфер = io.BytesIO()
    книга = xlsxwriter.Workbook(
        буфер, {"in_memory": True, "default_date_format": "dd.mm.yyyy"}
    )
    лист = книга.add_worksheet(ЛИСТ)

    жирный = книга.add_format({"bold": True, "bottom": 1})
    форматы = {
        "дата": книга.add_format({"num_format": "dd.mm.yyyy"}),
        "время": книга.add_format({"num_format": "hh:mm"}),
        "деньги": книга.add_format({"num_format": "#,##0.00"}),
    }

    for столбец, (заголовок, _ключ, _вид) in enumerate(ПРОФИЛЬ):
        лист.write_string(0, столбец, заголовок, жирный)

    for номер, чек in enumerate(чеки, start=1):
        ряд = строка_файла(отчёт, подотчётник, чек)
        for столбец, (_заголовок, ключ, вид) in enumerate(ПРОФИЛЬ):
            значение = ряд.get(ключ)
            if значение is None or значение == "":
                # Пустая ячейка — это ЗНАЧЕНИЕ, а не пропуск: именно так
                # в файл попадают чеки без фискальных реквизитов.
                лист.write_blank(номер, столбец, None)
            elif вид == "дата" and isinstance(значение, _dt.date):
                лист.write_datetime(номер, столбец, значение, форматы["дата"])
            elif вид == "время" and isinstance(значение, _dt.datetime):
                лист.write_datetime(номер, столбец, значение, форматы["время"])
            elif вид == "деньги":
                лист.write_number(номер, столбец, значение, форматы["деньги"])
            elif вид == "ссылка":
                лист.write_url(номер, столбец, значение, string="снимок")
            else:
                лист.write_string(номер, столбец, str(значение))

    лист.freeze_panes(1, 0)
    лист.autofilter(0, 0, max(len(чеки), 1), len(ПРОФИЛЬ) - 1)
    книга.close()
    return буфер.getvalue()
