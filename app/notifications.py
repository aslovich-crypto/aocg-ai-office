import logging
from typing import Optional, Sequence

logger = logging.getLogger(__name__)

# Виды событий. Строкой, а не перечислением: значение уезжает в базу и живёт
# там дольше кода, а читать его будут глазами в psql.
ОТЧЁТ_ОДОБРЕН = "report_approved"
ОТЧЁТ_ОТКЛОНЁН = "report_rejected"
ОТЧЁТ_НА_ПРОВЕРКУ = "report_submitted"
ПРИГЛАШЕНИЕ_ПРИНЯТО = "invite_accepted"

# Кто считается управляющим — тот же круг, что видит отчёты и список людей.
# Ответ владельца на развилку «кому»: всем, у кого есть право видеть отчёт.
УПРАВЛЯЮЩИЕ = ("admin", "accountant")


async def кому_управляющим(p, org_id: int, кроме: Optional[int] = None) -> list:
    """Живые управляющие организации. Каждому — своя строка события."""
    строки = await p.fetch(
        "SELECT id FROM users WHERE org_id=$1 AND role = ANY($2::text[]) "
        "AND is_active = true AND id <> COALESCE($3, -1)",
        org_id,
        list(УПРАВЛЯЮЩИЕ),
        кроме,
    )
    return [с["id"] for с in строки]


async def записать(
    p,
    *,
    адресаты: Sequence[int],
    org_id: int,
    вид: str,
    заголовок: str,
    текст: Optional[str] = None,
    report_id: Optional[int] = None,
) -> int:
    """Пишет по строке на адресата. Возвращает число записанных."""
    if not адресаты:
        # Не беда и не молчание: событий без адресата не бывает по замыслу,
        # но «в организации нет активных управляющих» — законное состояние.
        logger.info("событие %s без адресатов (org=%s)", вид, org_id)
        return 0
    for кому in адресаты:
        await p.execute(
            "INSERT INTO notifications (user_id, org_id, kind, title, body, report_id) "
            "VALUES ($1,$2,$3,$4,$5,$6)",
            кому,
            org_id,
            вид,
            заголовок,
            текст,
            report_id,
        )
    return len(адресаты)


async def почты(p, ids: Sequence[int]) -> list:
    """Адреса тех, кому событие записано, — для второго канала."""
    if not ids:
        return []
    строки = await p.fetch(
        "SELECT email FROM users WHERE id = ANY($1::int[]) "
        "AND email IS NOT NULL AND email <> '' AND is_active = true",
        list(ids),
    )
    return [с["email"] for с in строки]
