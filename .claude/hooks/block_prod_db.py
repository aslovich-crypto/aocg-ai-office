#!/usr/bin/env python3
"""PreToolUse(Bash): блокирует ИСПОЛНЕНИЕ деструктивного SQL против боевой БД.

СПЕЦИФИКАЦИЯ — не этот файл, а матрица форм в `tests/tools/hook_probe.py`
(26 случаев: 13 «обязан блокировать», 13 «обязан пускать»). Код меняется
только вместе с ней: сначала строка в матрице, потом правка здесь.

ПОЧЕМУ ПЕРЕПИСАН С bash+grep (задачи S-37 и S-39, 07.08.2026). Прежняя
версия искала ПОДСТРОКИ во всей строке команды. Отсюда два дефекта,
тянувшие список признаков в разные стороны:
  • пропускала опасное — признаком боевой базы служило ИМЯ ХОСТЕРА
    (`railway`, `up.railway.app`), и та же команда со своим именем
    переменной подключения проходила насквозь (S-37);
  • останавливала безопасное — `git commit -m "…"` с описанием хука
    в сообщении блокировался, потому что в строке встретились слова
    `python` и `DELETE FROM` (S-39).
Расширять список признаков нельзя: каждое новое слово чинит первое
и ухудшает второе. Поэтому основание решения сменилось — не текст,
а разбор: ЧТО реально исполнится и КУДА оно подключится.

ДВА ПРАВИЛА:
  1. ЧТО ИСПОЛНИТСЯ. Команда разбирается на токены с учётом кавычек
     (shlex). Исполнитель — ТОКЕН (python/psql/dropdb/sqlite3/duckdb/sh),
     а не подстрока. Поэтому `python` внутри закавыченного сообщения
     коммита исполнителем не является, а `git`/`echo`/`cat`/`grep`
     исполнителями не являются вовсе.
  2. КУДА ПОДКЛЮЧИТСЯ. Явный адрес (postgres://…, -h/--host) с локальным
     хостом → локально, работать не мешаем. Внешний хост → бой.
     Признак подключения есть, а значение спрятано ($DATABASE_URL,
     $(cat dsn)) → считаем боем: недоверенный вход трактуется в сторону
     отказа. Признаков подключения нет вовсе → команда не про базу,
     пропускаем (иначе заблокируем половину безобидных строк).

НАГРУЗКА ИЩЕТСЯ ПО РОЛИ, А НЕ ПО ВИДУ СЛОВА (S-41, 10.08.2026). Читается
то, что сегмент РЕАЛЬНО ИСПОЛНИТ: скрипт-аргумент python/sh, `-f` у psql,
правый операнд `<`, тело heredoc, вывод `$(…)` и файл, влитый КОНВЕЙЕРОМ
из соседнего сегмента. Всё остальное не читается, каким бы путём оно ни
выглядело.

Через это правило прошли три подхода, и каждый следующий чинил предыдущий:
  ① список расширений (.py/.sql) — обходился выносом текста в `.txt`;
  ② любое слово, похожее на путь, — блокировал безобидное: файл, отданный
     СОСЕДНЕЙ команде (`git add app/database.py`), читался как нагрузка;
  ③ роль аргумента — проигрывает только там, где разбор флагов не знает
     формы, и трактует незнакомое как «не исполняется».

ПЕРЕНОС СТРОКИ — РАЗДЕЛИТЕЛЬ КОМАНД наравне с `;`. Без этого следующая
строка наследовала исполнителя предыдущей, и безобидный `git commit`
после проверки базы читался как продолжение питона.

ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ В ПРИНЦИПЕ (называю, чтобы не создавать ложного
спокойствия): запрос, собранный в переменную или через ORM без видимого
глагола; удаление через само приложение; ошибочный UPDATE (не в списке
глаголов); подключение, спрятанное за собственной обёрткой. Это сторож
ВИДИМОГО деструктива, а не намерений.

И ОБРАТНАЯ СТОРОНА ТОГО ЖЕ ОГРАНИЧЕНИЯ: внутри файла он не отличает
УПОМИНАНИЕ деструктива от его ИСПОЛНЕНИЯ — снимаются только комментарии
(решётка в .py, двойное тире в .sql И внутри питоновских строк, куда его
кладёт наш регламент отката). Оговорка «инструменты кода пропускаем
всегда» УБРАНА 10.08.2026: правило роли делает её работу, а мутация
показала, что оговорку больше ничто не проверяет. Замер `hook_probe.py`
собирает опасные строки на лету — иначе блокировал бы сам себя.

ЧЕГО НЕ ВИДИТ ПО РАЗМЕРУ: файл крупнее МАКС_РАЗМЕР_ФАЙЛА не читается,
и это фейл-опен — но ГРОМКИЙ, с предупреждением в stderr. Прежний предел
(256 КБ) молчал, то есть нагрузка любого объёма проезжала как «чисто».

ПРИ ЛЮБОЙ ВНУТРЕННЕЙ ОШИБКЕ — ПРОПУСКАЕМ и пишем предупреждение в stderr.
Сторож, падающий в «запрещено всё», снимают в тот же день; это ровно та
цена ложных срабатываний, из-за которой заведена S-39.
"""

# Аннотации откладываются: локальный venv — Python 3.9, а `str | None`
# в сигнатуре там падает на импорте. Хук обязан работать на том
