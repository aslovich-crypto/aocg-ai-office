МАКС_РАЗМЕР_ФАЙЛА = 4 * 1024 * 1024


def _хост(dsn: str) -> str:
    """Хост из строки подключения. Без urlparse: DSN бывает с паролем,
    в котором встречается '@', и с портом — нам нужна только часть до ':'."""
    без_схемы = re.sub(r"^postgres(?:ql)?://", "", dsn, flags=re.IGNORECASE)
    авторитет = без_схемы.split("/")[0]
    if "@" in авторитет:
        авторитет = авторитет.rsplit("@", 1)[1]
    return авторитет.split(":")[0].strip().lower()


def _вырезать_heredoc(cmd: str) -> tuple[str, list[str]]:
    """Тело heredoc — это НАГРУЗКА, а не команда. Забираем её отдельно,
    иначе shlex споткнётся о кавычки внутри и разбор потеряется целиком."""
    тела: list[str] = []

    def забрать(m: re.Match) -> str:
        тела.append(m.group("тело"))
        return " "

    cmd = re.sub(
        r"<<-?\s*['\"]?(?P<метка>[A-Za-z_][A-Za-z0-9_]*)['\"]?\n(?P<тело>.*?)\n(?P=метка)",
        забрать,
        cmd,
        flags=re.DOTALL,
    )
    # Строка-здесь: <<< 'текст'
    for m in re.finditer(r"<<<\s*(?P<тело>'[^']*'|\"[^\"]*\"|\S+)", cmd):
        тела.append(m.group("тело").strip("'\""))
    cmd = re.sub(r"<<<\s*('[^']*'|\"[^\"]*\"|\S+)", " ", cmd)
    return cmd, тела


def _подстановки(текст: str) -> list[str]:
    """Содержимое $(...) — тоже нагрузка: `python -c "$(cat запрос.txt)"`."""
    return [m.group(1) for m in re.finditer(r"\$\(([^()]*)\)", текст)]


def _py_без_комментариев(текст: str) -> str:
    """Убирает комментарии Python ТОКЕНИЗАТОРОМ, а не регуляркой.

    Регулярка «от # до конца строки» не отличает комментарий от решётки
    ВНУТРИ строкового литерала, а строка исполняется. `tokenize` знает
    разницу по построению, поэтому берётся он, а не шаблон.

    ВНУТРИ СТРОКОВЫХ ЛИТЕРАЛОВ СНИМАЕМ SQL-КОММЕНТАРИЙ (`--`), И ЭТО НЕ
    ПРОТИВОРЕЧИЕ. Решающий вопрос не «строка это или комментарий», а НАЧИНАЕТ
    ЛИ СИМВОЛ КОММЕНТАРИЙ В ТОМ ЯЗЫКЕ, НА КОТОРОМ ТЕКСТ ИСПОЛНЯТ. Строку
    отдают в execute — там её читает PostgreSQL, и `--` для него комментарий,
    который не исполнится. Решётка в той же строке комментарием НЕ является
    (опора B15), поэтому её мы не трогаем.

    Куплено дважды за два дня. T5 (09.08.2026) научил снимать решётку, и опора
    A17 это закрепила — но она написана с решёткой, а РЕПОЗИТОРИЙ пишет откат
    двойным тире внутри DDL-строки (`app/database.py`). 10.08.2026 сторож на
    этом заблокировал обычную правку трекера: проверено было не то, что мы
    делаем на самом деле (S-41, опора A19).
    """
    try:
        начала = _начала_строк(текст)
        замены: list[tuple[int, int, str]] = []
        for токен in tokenize.generate_tokens(io.StringIO(текст).readline):
            (стр1, кол1), (стр2, кол2) = токен.start, токен.end
            с, по = начала[стр1 - 1] + кол1, начала[стр2 - 1] + кол2
            if токен.type == tokenize.COMMENT:
                замены.append((с, по, " " * (по - с)))
            elif токен.type == tokenize.STRING:
                чистый = _литерал_без_sql_комментариев(токен.string)
                if чистый != токен.string:
                    замены.append((с, по, чистый))
        # С КОНЦА: замена меняет длину текста, и смещения впередистоящих
        # токенов после первой же правки перестали бы совпадать.
        for с, по, чем in reversed(замены):
            текст = текст[:с] + чем + текст[по:]
        return текст
    except (tokenize.TokenError, IndentationError, SyntaxError, ValueError, IndexError):
        # Файл не разбирается — оставляем как есть. Сторож обязан ошибаться
        # в сторону «вижу больше», а не «вижу меньше».
        return текст


def _начала_строк(текст: str) -> list[int]:
    """Смещение начала каждой строки: (строка, колонка) от tokenize → индекс."""
    начала, поз = [0], 0
    for кусок in текст.split("\n")[:-1]:
        поз += len(кусок) + 1
        начала.append(поз)
    return начала


def _литерал_без_sql_комментариев(литерал: str) -> str:
    """SQL-комментарии ВНУТРИ питоновского строкового литерала.

    Кавычки снимаются перед разбором намеренно: `_sql_без_комментариев`
    учитывает кавычки, и на литерале целиком он счёл бы ВСЁ содержимое
    строкой SQL, ничего не сняв. Разбираем нутро, кавычки возвращаем на место.
    """
    м = re.match(r"^([A-Za-z]{0,3})('''|\"\"\"|'|\")", литерал)
    if not м:
        return литерал
    префикс, кавычка = м.group(1), м.group(2)
    начало = len(префикс) + len(кавычка)
    if len(литерал) < начало + len(кавычка) or not литерал.endswith(кавычка):
        return литерал
    нутро = литерал[начало : len(литерал) - len(кавычка)]
    return префикс + кавычка + _sql_без_комментариев(нутро) + кавычка


def _sql_без_комментариев(текст: str) -> str:
    """Убирает комментарии SQL с учётом кавычек и долларовых литералов.

    `--` внутри строки комментарием НЕ является: `'см. -- откат'` это
    данные, и стоящий за ними на той же строке запрос исполнится.
    """
    вывод: list[str] = []
    i, n = 0, len(текст)
    состояние = (
        None  # None | "'" | '"' | "строка-коммент" | "блок-коммент" | ("$", тег)
    )
    while i < n:
        c = текст[i]
        if состояние is None:
            if текст.startswith("--", i):
                состояние = "строка-коммент"
                i += 2
                continue
            if текст.startswith("/*", i):
                состояние = "блок-коммент"
                i += 2
                continue
            метка = re.match(r"\$[A-Za-z_]*\$", текст[i:])
            if метка:
                состояние = ("$", метка.group(0))
                вывод.append(метка.group(0))
                i += len(метка.group(0))
                continue
            if c in "'\"":
                состояние = c
            вывод.append(c)
            i += 1
        elif состояние == "строка-коммент":
            if c == "\n":
                состояние = None
                вывод.append(c)
            i += 1
        elif состояние == "блок-коммент":
            if текст.startswith("*/", i):
                состояние = None
                i += 2
                continue
            if c == "\n":
                вывод.append(c)
            i += 1
        elif состояние in ("'", '"'):
            вывод.append(c)
            if c == состояние:
                if i + 1 < n and текст[i + 1] == состояние:  # удвоенная кавычка
                    вывод.append(текст[i + 1])
                    i += 2
                    continue
                состояние = None
            i += 1
        else:  # долларовый литерал
            тег = состояние[1]
            if текст.startswith(тег, i):
                вывод.append(тег)
                состояние = None
                i += len(тег)
                continue
            вывод.append(c)
            i += 1
    return "".join(вывод)


def _прочитать(путь: str) -> str:
    """Файл-аргумент любого расширения. Прежняя версия читала только
    .py/.sql — на этом и строился обход.

    КОММЕНТАРИИ СНИМАЮТСЯ (T5) — и только здесь, с СОДЕРЖИМОГО ФАЙЛА.
    Причина конкретная: по регламенту репозитория обратный DDL пишется
    комментарием рядом с миграцией (`# откат: DROP INDEX …`), и сторож
    блокировал правильно оформленную миграцию — то есть наказывал
    за соблюдение собственного правила. Комментарий исполнен не будет,
    значит и деструктивом считаться не должен.

    С САМОЙ КОМАНДЫ комментарии НЕ снимаются. В строке вида
    `python -c "# DELETE FROM …"` решётка может быть маскировкой: что
    стоит дальше по строке, зависит от кавычек и переносов, и разбирать
    это как исходник значит гадать. Сторож остаётся строгим там, где
    не может рассуждать точно.
    """
    try:
        if not os.path.isfile(путь):
            return ""
        размер = os.path.getsize(путь)
        if размер > МАКС_РАЗМЕР_ФАЙЛА:
            # ТИШИНА ЗДЕСЬ БЫЛА ДЫРОЙ. Прежний предел (256 КБ) отсекал файл
            # МОЛЧА и возвращал пустоту — то есть нагрузка любого размера
            # проезжала, а сторож отчитывался «чисто». Теперь предел большой
            # (файлы, которые реально исполняют, в него укладываются), а его
            # превышение — громкое: сторож обязан уметь сказать, чего он
            # НЕ проверил (S-41, опора B18).
            print(
                f"block_prod_db: файл {путь} — {размер} байт, больше предела "
                f"{МАКС_РАЗМЕР_ФАЙЛА}; НЕ ПРОВЕРЕН, пропускаю. Проверь глазами.",
                file=sys.stderr,
            )
            return ""
        with open(путь, "r", encoding="utf-8", errors="replace") as f:
            текст = f.read()
    except OSError:
        return ""
    if путь.endswith(".py"):
        return _py_без_комментариев(текст)
    if путь.endswith(".sql"):
        return _sql_без_комментариев(текст)
    return текст


def _похоже_на_путь(токен: str) -> bool:
    return ("/" in токен or "." in токен) and not токен.startswith("-")


def _переносы_как_разделители(cmd: str) -> str:
    """Перенос строки ВНЕ кавычек — такой же разделитель команд, как `;`.

    Без этого `python -c "…"` и стоящая СЛЕДУЮЩЕЙ СТРОКОЙ `git add файл.py`
    попадали в один сегмент, и безобидная вторая команда наследовала питон
    как исполнителя, а её аргументы читались как нагрузка. Именно так
    10.08.2026 заблокировалась правка трекера (S-41, опора A20).

    Кавычки учитываем: перенос ВНУТРИ сообщения коммита разделителем
    не является, и резать по нему значило бы разваливать чужой текст.
    """
    вывод: list[str] = []
    кавычка = None
    i, n = 0, len(cmd)
    while i < n:
        c = cmd[i]
        if кавычка:
            вывод.append(c)
            if c == "\\" and i + 1 < n:  # экранированный символ внутри кавычек
                вывод.append(cmd[i + 1])
                i += 2
                continue
            if c == кавычка:
                кавычка = None
        elif c in "'\"":
            кавычка = c
            вывод.append(c)
        elif c == "\n":
            вывод.append(" ; ")
        else:
            вывод.append(c)
        i += 1
    return "".join(вывод)


def _сегменты(токены: list[str]) -> list[tuple[str, list[str]]]:
    """Команда режется по операторам: каждый сегмент оценивается сам по себе,
    иначе `git show … | grep …` смешался бы с соседом.

    Возвращает пары (оператор СЛЕВА от сегмента, токены). Оператор нужен
    ровно для одного случая — конвейера: `cat запрос.sql | psql "$DSN"`
    передаёт нагрузку СПРАВА НАЛЕВО по трубе, и сегмент с psql обязан
    видеть файл соседа (опора B19)."""
    результат: list[tuple[str, list[str]]] = [("", [])]
    for т in токены:
        if т in ОПЕРАТОРЫ:
            результат.append((т, []))
        else:
            результат[-1][1].append(т)
    return [(оп, с) for оп, с in результат if с]


def _разобрать_сегмент(токены: list[str]) -> tuple[str | None, list[str], list[str]]:
    """Возвращает (исполнитель, присваивания окружения, остальные токены)."""
    окружение: list[str] = []
    i = 0
    while i < len(токены) and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", токены[i]):
        окружение.append(токены[i])
        i += 1
    хвост = токены[i:]
    исполнитель = None
    for т in хвост:
        # Токен с пробелами — это закавыченный АРГУМЕНТ (сообщение коммита,
        # текст запроса), а не имя команды. Без этой проверки сообщение,
        # кончающееся на «…/python», снова стало бы «исполнителем» — тем же
        # способом, каким прежний сторож ошибался на всей строке (S-39).
        if " " in т or "\n" in т:
            continue
        if ИСПОЛНИТЕЛИ.match(os.path.basename(т)):
            исполнитель = os.path.basename(т)
            break
    return исполнитель, окружение, хвост


def _исполняемые_файлы(исполнитель: str, хвост: list[str]) -> list[str]:
    """Пути, которые сегмент РЕАЛЬНО ИСПОЛНИТ. Не «похоже на путь», а роль.

    ЗАЧЕМ ИМЕННО РОЛЬ. Прежде читалось каждое слово, похожее на путь, — и
    сторож принимал за нагрузку файл, переданный СОСЕДНЕЙ команде (`git add
    app/database.py`) или просто упомянутый рядом. Список расширений до этого
    был ещё хуже: вынос текста в `.txt` обходил сторож целиком. Роль — третий
    подход и единственный, который не проигрывает ни в одну сторону: файл,
    который исполнят, читается независимо от расширения; файл, который никто
    не исполняет, не читается независимо от содержимого (S-41, опора A21).

    Разбор флагов узкий и намеренно неполный: `-c`/`-m` СЪЕДАЮТ значение и
    означают, что скрипта-файла дальше нет (остальные слова уходят в argv).
    Чего разбор не знает — трактует как «не исполняется»: ошибка в эту сторону
    даёт ложный пропуск, но ложный БЛОК снимают вместе со сторожем.
    """
    файлы: list[str] = []
    i = 0
    # Перенаправление входа: `psql "$DSN" < запрос.sql` — файл исполнится.
    while i < len(хвост) - 1:
        if хвост[i] == "<":
            файлы.append(хвост[i + 1])
        i += 1

    аргументы = [т for т in хвост if os.path.basename(т) != исполнитель]
    if исполнитель in ("python", "sh", "bash", "zsh", "dash") or исполнитель.startswith(
        "python"
    ):
        i = 0
        while i < len(аргументы):
            т = аргументы[i]
            if т in ("-c", "-m"):
                return файлы  # тело задано строкой, скрипта-файла не будет
            if т.startswith("-") or т == "<":
                i += 2 if т == "<" else 1
                continue
            файлы.append(т)  # первый неопционный аргумент — сам скрипт
            break
        return файлы
    if исполнитель == "psql":
        for i, т in enumerate(аргументы):
            if т in ("-f", "--file") and i + 1 < len(аргументы):
                файлы.append(аргументы[i + 1])
            elif т.startswith("--file="):
                файлы.append(т.split("=", 1)[1])
        return файлы
    # sqlite3/duckdb/dropdb: первый аргумент — это БАЗА, а не программа.
    # Читать её нечего (двоичный файл), запрос у них приходит строкой.
    return файлы


def _цель(текст: str, исполнитель: str) -> str:
    """БОЙ / ЛОКАЛЬНО / НЕТ — куда подключается сегмент."""
    хосты = [_хост(d) for d in СТРОКА_ПОДКЛЮЧЕНИЯ.findall(текст)]
    for m in re.finditer(r"(?:-h|--host)[=\s]+([^\s'\"]+)", текст):
        хосты.append(m.group(1).lower())
    if хосты:
        return "ЛОКАЛЬНО" if all(х in ЛОКАЛЬНЫЕ_ХОСТЫ for х in хосты) else "БОЙ"

    # Явного адреса нет. Есть ли вообще признак подключения?
    if исполнитель in ("psql", "dropdb", "sqlite3", "duckdb"):
        # Эти запускаются только ради базы. Адрес скрыт → считаем боем.
        # sqlite3/duckdb в проекте не используются: ложных срабатываний
        # сегодня ноль, а появятся — первый деструктивный запуск
        # заблокируется правильно. Цена ошибки несимметрична.
        return "БОЙ"
    if ПРИЗНАКИ_ПОДКЛЮЧЕНИЯ.search(текст):
        return "БОЙ"
    if any(
        ОБЁРТКИ_УДАЛЁННОГО_ЗАПУСКА.match(os.path.basename(т)) for т in текст.split()
    ):
        return "БОЙ"
    return "НЕТ"


def решение(cmd: str) -> tuple[bool, str]:
    """(блокировать, причина). Причина попадает в текст отказа —
    сторож обязан уметь сказать, ЧТО именно он увидел."""
    cmd, тела_heredoc = _вырезать_heredoc(cmd)
    cmd = _переносы_как_разделители(cmd)
    try:
        лексер = shlex.shlex(cmd, posix=True, punctuation_chars=True)
        лексер.whitespace_split = True
        токены = list(лексер)
    except ValueError:
        # Незакрытая кавычка. Разобрать нельзя — пропускаем громко.
        raise

    разбитая = _сегменты(токены)
    for номер, (оператор, сегмент) in enumerate(разбитая):
        исполнитель, окружение, хвост = _разобрать_сегмент(сегмент)
        if not исполнитель:
            continue  # git / echo / cat / grep и прочее — не исполнители SQL

        # ОГОВОРКИ ДЛЯ ИНСТРУМЕНТОВ КОДА ЗДЕСЬ БОЛЬШЕ НЕТ — И ЭТО НЕ ПОТЕРЯ.
        # Она существовала потому, что читался КАЖДЫЙ файл-аргумент: прогон
        # `pytest tests/conftest.py` натыкался на зеркало SQL приложения,
        # `ruff format` — на опоры замера, целиком состоящие из опасных строк.
        # С правилом роли (см. _исполняемые_файлы) читается только то, что
        # ИСПОЛНЯЕТСЯ, а у `python -m pytest …` исполняется модуль, не файлы
        # из хвоста — то есть повод для оговорки исчез вместе с причиной.
        # Убрана 10.08.2026 по показанию мутации M6: она перестала что-либо
        # ронять, то есть оговорку больше ничто не проверяло. Особый случай,
        # который ничем не подтверждается, — это не запас прочности, а ложная
        # уверенность и место будущего расхождения (A14, A16 держат этот вывод).
        нагрузка = [" ".join(окружение), " ".join(хвост), *тела_heredoc]
        for т in хвост:
            for подстановка in _подстановки(т):
                нагрузка.append(подстановка)
                # ВЫВОД ПОДСТАНОВКИ СТАНОВИТСЯ НАГРУЗКОЙ, значит файлы, которые
                # она читает, — тоже нагрузка: `python -c "$(cat запрос.txt)"`.
                # Роль здесь та же, что у скрипта-аргумента, поэтому читаем
                # (опора B6; на ней и поймано, что сужение до роли задело её).
                for слово in подстановка.split():
                    if _похоже_на_путь(слово):
                        нагрузка.append(_прочитать(слово))

        # ФАЙЛЫ ЧИТАЮТСЯ ПО РОЛИ, А НЕ ПО ВИДУ СЛОВА (см. _исполняемые_файлы).
        for путь in _исполняемые_файлы(исполнитель, хвост):
            нагрузка.append(_прочитать(путь))

        # КОНВЕЙЕР СЛЕВА — ЭТО ТОЖЕ ПЕРЕДАЧА НАГРУЗКИ. `cat запрос.sql | psql`
        # прежде проезжал целиком: сегменты оценивались порознь, у `cat`
        # исполнителя нет, а у `psql` нет файла. Берём файлы-аргументы левого
        # соседа — он вливает их СОДЕРЖИМОЕ нам на вход (опора B19).
        if оператор == "|" and номер > 0:
            for слово in разбитая[номер - 1][1]:
                if _похоже_на_путь(слово):
                    нагрузка.append(_прочитать(слово))
        текст = "\n".join(нагрузка)
        # ЭКРАНИРОВАННЫЕ ПЕРЕНОСЫ РАЗВОРАЧИВАЕМ В ПРОБЕЛ. В исходнике перенос
        # записан двумя символами, поэтому `…public;\nDELETE FROM…` даёт подряд
        # букву «n» и глагол: границы слова между ними нет, и шаблон деструктив
        # НЕ ВИДИТ — хотя при исполнении там настоящий перенос и настоящий
        # запрос. Найдено опорой B17 случайно, при разборе T5.
        текст = re.sub(r"\\[nrt]", " ", текст)

        деструктив = bool(ДЕСТРУКТИВ.search(текст)) or исполнитель == "dropdb"
        if not деструктив:
            continue
        цель = _цель(текст, исполнитель)
        if цель == "БОЙ":
            глагол = (
                "dropdb"
                if исполнитель == "dropdb"
                else ДЕСТРУКТИВ.search(текст).group(1)
            )
            return (
                True,
                f"исполнитель «{исполнитель}», деструктив «{глагол.strip()}», цель — боевая база",
            )
    return False, ""


def main() -> int:
    try:
        данные = json.load(sys.stdin)
        cmd = (данные.get("tool_input") or {}).get("command") or ""
    except (json.JSONDecodeError, AttributeError, ValueError):
        print("block_prod_db: не разобрал вход хука — ПРОПУСКАЮ", file=sys.stderr)
        return 0

    try:
        блокировать, причина = решение(cmd)
    except Exception as ошибка:  # noqa: BLE001 — намеренно широко, см. шапку
        print(
            f"block_prod_db: разбор команды не удался ({ошибка}) — ПРОПУСКАЮ. "
            "Проверь команду глазами.",
            file=sys.stderr,
        )
        return 0

    if блокировать:
        print(
            json.dumps(
                {
                    "hookSpecificOutput": {
                        "hookEventName": "PreToolUse",
                        "permissionDecision": "deny",
                        "permissionDecisionReason": (
                            f"Блокировано хук-защитой прод-БД: {причина}. "
                            "Если операция действительно нужна — выполни её осознанно, "
                            "временно отключив хук (см. .claude/hooks/README.md)."
                        ),
                    }
                },
                ensure_ascii=False,
            )
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
