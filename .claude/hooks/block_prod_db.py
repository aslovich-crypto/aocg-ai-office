#!/usr/bin/env python3
"""PreToolUse(Bash): блокирует ИСПОЛНЕНИЕ деструктивного SQL против боевой БД.

СПЕЦИФИКАЦИЯ — не этот файл, а матрица форм в `tests/tools/hook_probe.py`
(26 случаев: 13 «обязан блокировать», 13 «обязан пускать»). Код меняется
только вместе с ней: сначала строка в матрице, потом правка здесь.

ПОЧЕМУ ПЕРЕПИСАН С bash+grep (задачи S-37 и S-39, 07.08.2026). Прежняя
версия искала ПОДСТРОКИ во всей строке команды. Отсюда два дефекта,
тянувшие список признаков в разные стороны:
  • пропускала опасное — признаком боевой базы служило ИМЯ ХОСТЕРА
    (`railway`, `up.railway.app`), и та же команда со своим именем
    переменной подключения проходила насквозь (S-37);
  • останавливала безопасное — `git commit -m "…"` с описанием хука
    в сообщении блокировался, потому что в строке встретились слова
    `python` и `DELETE FROM` (S-39).
Расширять список признаков нельзя: каждое новое слово чинит первое
и ухудшает второе. Поэтому основание решения сменилось — не текст,
а разбор: ЧТО реально исполнится и КУДА оно подключится.

ДВА ПРАВИЛА:
  1. ЧТО ИСПОЛНИТСЯ. Команда разбирается на токены с учётом кавычек
     (shlex). Исполнитель — ТОКЕН (python/psql/dropdb/sqlite3/duckdb/sh),
     а не подстрока. Поэтому `python` внутри закавыченного сообщения
     коммита исполнителем не является, а `git`/`echo`/`cat`/`grep`
     исполнителями не являются вовсе.
  2. КУДА ПОДКЛЮЧИТСЯ. Явный адрес (postgres://…, -h/--host) с локальным
     хостом → локально, работать не мешаем. Внешний хост → бой.
     Признак подключения есть, а значение спрятано ($DATABASE_URL,
     $(cat dsn)) → считаем боем: недоверенный вход трактуется в сторону
     отказа. Признаков подключения нет вовсе → команда не про базу,
     пропускаем (иначе заблокируем половину безобидных строк).

НАГРУЗКА ИЩЕТСЯ ТАМ, КУДА ЕЁ ПЕРЕДАЛИ: -c, -f, heredoc, $(…) и файл-аргумент
ЛЮБОГО расширения. Прежняя версия читала только `.py` и `.sql`, и вынос
текста в `.txt`/`.sh` обходил её целиком — обход был найден и применён
мною же (положил сообщение коммита в файл, чтобы пройти мимо хука),
после чего замером подтвердился как рабочий приём против настоящей защиты.
Список расширений не расширяем — это гонка; смотрим на роль аргумента.

ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ В ПРИНЦИПЕ (называю, чтобы не создавать ложного
спокойствия): запрос, собранный в переменную или через ORM без видимого
глагола; удаление через само приложение; ошибочный UPDATE (не в списке
глаголов); подключение, спрятанное за собственной обёрткой. Это сторож
ВИДИМОГО деструктива, а не намерений.

И ОБРАТНАЯ СТОРОНА ТОГО ЖЕ ОГРАНИЧЕНИЯ: внутри файла он не отличает
УПОМИНАНИЕ деструктива от его ИСПОЛНЕНИЯ. В репозитории восемь файлов
содержат деструктивные строки как данные (`tests/conftest.py`, роутеры,
`app/database.py`). Отсюда две названные оговорки: прогон `pytest`
пропускается всегда, а инструменты, чьи ДАННЫЕ состоят из опасных строк
(`tests/tools/hook_probe.py`), собирают эти строки на лету, иначе
блокируют сами себя. Оговорки записаны здесь, а не разбросаны по коду.

ПРИ ЛЮБОЙ ВНУТРЕННЕЙ ОШИБКЕ — ПРОПУСКАЕМ и пишем предупреждение в stderr.
Сторож, падающий в «запрещено всё», снимают в тот же день; это ровно та
цена ложных срабатываний, из-за которой заведена S-39.
"""

# Аннотации откладываются: локальный venv — Python 3.9, а `str | None`
# в сигнатуре там падает на импорте. Хук обязан работать на том
# интерпретаторе, который есть на машине, а не на том, что в .python-version.
from __future__ import annotations

import json
import os
import re
import shlex
import sys

# ─── исполнители: токен, который реально что-то выполняет ────────────────────
ИСПОЛНИТЕЛИ = re.compile(
    r"^(python[0-9.]*|psql|dropdb|sqlite3|duckdb|sh|bash|zsh|dash)$"
)

# Обёртки удалённого запуска: сами по себе не исполняют SQL, но означают,
# что дальше команда уйдёт НЕ на эту машину. Адрес при этом не виден —
# значит цель недоверенная (см. правило 2).
ОБЁРТКИ_УДАЛЁННОГО_ЗАПУСКА = re.compile(
    r"^(railway|yc|kubectl|docker|heroku|flyctl|ssh)$"
)

# Признаки того, что команда вообще куда-то подключается. Имя хостера здесь
# ОДИН ИЗ признаков, а не единственный: его отсутствие больше не означает
# «не бой» — в этом и была дыра S-37.
ПРИЗНАКИ_ПОДКЛЮЧЕНИЯ = re.compile(
    r"(DATABASE_URL|DATABASE_PUBLIC_URL|[A-Z0-9_]*_DSN\b|PG(HOST|DATABASE|USER|PASSWORD|PORT)"
    r"|asyncpg|psycopg|sqlalchemy|create_pool|\.execute\(|\bconnect\()",
    re.IGNORECASE,
)

# Деструктив. Объект обязателен: голое слово DROP встречается в фильтрах
# и списках (`tests/tools/sql_check.py:61` — строка "DROP " в наборе правил),
# и без объекта read-only инструменты краснели бы на ровном месте.
ДЕСТРУКТИВ = re.compile(
    r"(\bDROP\s+(TABLE|INDEX|DATABASE|SCHEMA)\b|\bDELETE\s+FROM\b|\bTRUNCATE\b)",
    re.IGNORECASE,
)

СТРОКА_ПОДКЛЮЧЕНИЯ = re.compile(r"postgres(?:ql)?://[^\s'\"]+", re.IGNORECASE)
ЛОКАЛЬНЫЕ_ХОСТЫ = {"localhost", "127.0.0.1", "::1", "0.0.0.0", "host.docker.internal"}

# Инструменты, которые ходят по ФАЙЛАМ, а не по базе. Подключаться не умеют
# ни один, поэтому список закрытый и расширяется только осознанно.
ИНСТРУМЕНТЫ_КОДА = {"pytest", "ruff", "black", "mypy", "isort", "flake8", "pip"}

ОПЕРАТОРЫ = {"|", "||", "&&", ";", "&", "|&"}
МАКС_РАЗМЕР_ФАЙЛА = 256 * 1024


def _хост(dsn: str) -> str:
    """Хост из строки подключения. Без urlparse: DSN бывает с паролем,
    в котором встречается '@', и с портом — нам нужна только часть до ':'."""
    без_схемы = re.sub(r"^postgres(?:ql)?://", "", dsn, flags=re.IGNORECASE)
    авторитет = без_схемы.split("/")[0]
    if "@" in авторитет:
        авторитет = авторитет.rsplit("@", 1)[1]
    return авторитет.split(":")[0].strip().lower()


def _вырезать_heredoc(cmd: str) -> tuple[str, list[str]]:
    """Тело heredoc — это НАГРУЗКА, а не команда. Забираем её отдельно,
    иначе shlex споткнётся о кавычки внутри и разбор потеряется целиком."""
    тела: list[str] = []

    def забрать(m: re.Match) -> str:
        тела.append(m.group("тело"))
        return " "

    cmd = re.sub(
        r"<<-?\s*['\"]?(?P<метка>[A-Za-z_][A-Za-z0-9_]*)['\"]?\n(?P<тело>.*?)\n(?P=метка)",
        забрать,
        cmd,
        flags=re.DOTALL,
    )
    # Строка-здесь: <<< 'текст'
    for m in re.finditer(r"<<<\s*(?P<тело>'[^']*'|\"[^\"]*\"|\S+)", cmd):
        тела.append(m.group("тело").strip("'\""))
    cmd = re.sub(r"<<<\s*('[^']*'|\"[^\"]*\"|\S+)", " ", cmd)
    return cmd, тела


def _подстановки(текст: str) -> list[str]:
    """Содержимое $(...) — тоже нагрузка: `python -c "$(cat запрос.txt)"`."""
    return [m.group(1) for m in re.finditer(r"\$\(([^()]*)\)", текст)]


def _прочитать(путь: str) -> str:
    """Файл-аргумент любого расширения. Прежняя версия читала только
    .py/.sql — на этом и строился обход."""
    try:
        if not os.path.isfile(путь) or os.path.getsize(путь) > МАКС_РАЗМЕР_ФАЙЛА:
            return ""
        with open(путь, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _похоже_на_путь(токен: str) -> bool:
    return ("/" in токен or "." in токен) and not токен.startswith("-")


def _сегменты(токены: list[str]) -> list[list[str]]:
    """Команда режется по операторам: каждый сегмент оценивается сам по себе,
    иначе `git show … | grep …` смешался бы с соседом."""
    результат: list[list[str]] = [[]]
    for т in токены:
        if т in ОПЕРАТОРЫ:
            результат.append([])
        else:
            результат[-1].append(т)
    return [с for с in результат if с]


def _разобрать_сегмент(токены: list[str]) -> tuple[str | None, list[str], list[str]]:
    """Возвращает (исполнитель, присваивания окружения, остальные токены)."""
    окружение: list[str] = []
    i = 0
    while i < len(токены) and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", токены[i]):
        окружение.append(токены[i])
        i += 1
    хвост = токены[i:]
    исполнитель = None
    for т in хвост:
        # Токен с пробелами — это закавыченный АРГУМЕНТ (сообщение коммита,
        # текст запроса), а не имя команды. Без этой проверки сообщение,
        # кончающееся на «…/python», снова стало бы «исполнителем» — тем же
        # способом, каким прежний сторож ошибался на всей строке (S-39).
        if " " in т or "\n" in т:
            continue
        if ИСПОЛНИТЕЛИ.match(os.path.basename(т)):
            исполнитель = os.path.basename(т)
            break
    return исполнитель, окружение, хвост


def _цель(текст: str, исполнитель: str) -> str:
    """БОЙ / ЛОКАЛЬНО / НЕТ — куда подключается сегмент."""
    хосты = [_хост(d) for d in СТРОКА_ПОДКЛЮЧЕНИЯ.findall(текст)]
    for m in re.finditer(r"(?:-h|--host)[=\s]+([^\s'\"]+)", текст):
        хосты.append(m.group(1).lower())
    if хосты:
        return "ЛОКАЛЬНО" if all(х in ЛОКАЛЬНЫЕ_ХОСТЫ for х in хосты) else "БОЙ"

    # Явного адреса нет. Есть ли вообще признак подключения?
    if исполнитель in ("psql", "dropdb", "sqlite3", "duckdb"):
        # Эти запускаются только ради базы. Адрес скрыт → считаем боем.
        # sqlite3/duckdb в проекте не используются: ложных срабатываний
        # сегодня ноль, а появятся — первый деструктивный запуск
        # заблокируется правильно. Цена ошибки несимметрична.
        return "БОЙ"
    if ПРИЗНАКИ_ПОДКЛЮЧЕНИЯ.search(текст):
        return "БОЙ"
    if any(
        ОБЁРТКИ_УДАЛЁННОГО_ЗАПУСКА.match(os.path.basename(т)) for т in текст.split()
    ):
        return "БОЙ"
    return "НЕТ"


def решение(cmd: str) -> tuple[bool, str]:
    """(блокировать, причина). Причина попадает в текст отказа —
    сторож обязан уметь сказать, ЧТО именно он увидел."""
    cmd, тела_heredoc = _вырезать_heredoc(cmd)
    try:
        лексер = shlex.shlex(cmd, posix=True, punctuation_chars=True)
        лексер.whitespace_split = True
        токены = list(лексер)
    except ValueError:
        # Незакрытая кавычка. Разобрать нельзя — пропускаем громко.
        raise

    for сегмент in _сегменты(токены):
        исполнитель, окружение, хвост = _разобрать_сегмент(сегмент)
        if not исполнитель:
            continue  # git / echo / cat / grep и прочее — не исполнители SQL

        # ОГОВОРКА ДЛЯ ИНСТРУМЕНТОВ КОДА, названа явно. Тесты, форматирование
        # и проверки ходят по ФАЙЛАМ, а не по базе, но эти файлы полны
        # деструктивных строк как данных (`tests/conftest.py` зеркалит SQL
        # приложения; опоры замера состоят из них целиком). Сторож не отличает
        # упоминание от исполнения внутри файла — без оговорки он запрещал бы
        # прогон тестов и форматирование, а такой сторож снимают.
        # Список узкий и закрытый: ни один из этих инструментов не умеет
        # подключаться к базе. Куплено дважды за один вечер — сначала
        # заблокировался pytest, потом `ruff format` на собственных опорах.
        if any(os.path.basename(т) in ИНСТРУМЕНТЫ_КОДА for т in хвост):
            continue

        нагрузка = [" ".join(окружение), " ".join(хвост), *тела_heredoc]
        for т in хвост:
            нагрузка.extend(_подстановки(т))
        for кусок in list(нагрузка):
            for слово in кусок.split():
                if _похоже_на_путь(слово):
                    нагрузка.append(_прочитать(слово))
        текст = "\n".join(нагрузка)

        деструктив = bool(ДЕСТРУКТИВ.search(текст)) or исполнитель == "dropdb"
        if not деструктив:
            continue
        цель = _цель(текст, исполнитель)
        if цель == "БОЙ":
            глагол = (
                "dropdb"
                if исполнитель == "dropdb"
                else ДЕСТРУКТИВ.search(текст).group(1)
            )
            return (
                True,
                f"исполнитель «{исполнитель}», деструктив «{глагол.strip()}», цель — боевая база",
            )
    return False, ""


def main() -> int:
    try:
        данные = json.load(sys.stdin)
        cmd = (данные.get("tool_input") or {}).get("command") or ""
    except (json.JSONDecodeError, AttributeError, ValueError):
        print("block_prod_db: не разобрал вход хука — ПРОПУСКАЮ", file=sys.stderr)
        return 0

    try:
        блокировать, причина = решение(cmd)
    except Exception as ошибка:  # noqa: BLE001 — намеренно широко, см. шапку
        print(
            f"block_prod_db: разбор команды не удался ({ошибка}) — ПРОПУСКАЮ. "
            "Проверь команду глазами.",
            file=sys.stderr,
        )
        return 0

    if блокировать:
        print(
            json.dumps(
                {
                    "hookSpecificOutput": {
                        "hookEventName": "PreToolUse",
                        "permissionDecision": "deny",
                        "permissionDecisionReason": (
                            f"Блокировано хук-защитой прод-БД: {причина}. "
                            "Если операция действительно нужна — выполни её осознанно, "
                            "временно отключив хук (см. .claude/hooks/README.md)."
                        ),
                    }
                },
                ensure_ascii=False,
            )
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
