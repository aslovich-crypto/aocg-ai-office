СТРОКА_ПОДКЛЮЧЕНИЯ = re.compile(r"postgres(?:ql)?://[^\s'\"]+", re.IGNORECASE)
ЛОКАЛЬНЫЕ_ХОСТЫ = {"localhost", "127.0.0.1", "::1", "0.0.0.0", "host.docker.internal"}

ОПЕРАТОРЫ = {"|", "||", "&&", ";", "&", "|&"}
