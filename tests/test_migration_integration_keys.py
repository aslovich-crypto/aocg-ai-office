# -*- coding: utf-8 -*-
"""DDL ключей интеграции не разойдётся с `init_db` (12.09.2026, шаг 3 заход ③).

⚠️ ТОТ ЖЕ ПРИЁМ, ЧТО У `test_migration_people_fields.py` и
`test_migration_invite_columns.py`. Не копия ради копии: у каждой миграции
свой список, свой валидатор и свой предмет. Общее — правило: строки,
прогнанные на бастионе, обязаны ДОСЛОВНО лежать в `init_db`, иначе
проверяли бы одно, а применяли другое.

⚠️ ЗАЧЕМ ЭТОТ СТОРОЖ, ЕСЛИ РЕЛЬСЫ УЖЕ ЗЕЛЁНЫЕ. Рельсы валидации создают
таблицу СВОИМ списком внутри своей транзакции — и прошли бы успешно, даже
если бы в `init_db` этого блока не было ВООБЩЕ. То есть зелёная валидация
сама по себе не доказывает, что миграция вообще уедет на прод. Доказывает
это только сверка двух мест, и она здесь.

⚠️ КОММЕНТАРИИ SQL СРЕЗАЮТСЯ ПЕРЕД СВЕРКОЙ, И ЭТО НЕ МЕЛОЧЬ. Внутри
`CREATE TABLE` в `init_db` стоят пояснения (`-- Последнее использование…`),
которых в рельсах нет. Сторож, сверяющий сырой текст, краснел бы вечно
и на верном коде — класс известен своду как «текст был верным, а место нет».
"""

import importlib.util
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]


def _модуль_валидатора():
    спец = importlib.util.spec_from_file_location(
        "валидатор_ключей", КОРЕНЬ / "scripts/validate_integration_keys.py"
    )
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def _без_комментариев_sql(с: str) -> str:
    """Срезает `-- …` до конца строки. Строковых литералов в этом DDL нет."""
    return re.sub(r"(?m)--.*$", " ", с)


def _схлопнуть(с: str) -> str:
    return re.sub(r"\s+", " ", _без_комментариев_sql(с)).strip().rstrip(";")


def _исходник() -> str:
    return (КОРЕНЬ / "app/database.py").read_text(encoding="utf-8")


def test_каждая_команда_миграции_есть_в_init_db():
    """Главный сторож захода: проверенное и применяемое — один текст."""
    м = _модуль_валидатора()
    команды = м.МИГРАЦИЯ
    assert команды, "список МИГРАЦИЯ пуст — проверять нечего"
    внутри = _схлопнуть(_исходник())
    пропали = [d for d in команды if _схлопнуть(d) not in внутри]
    assert not пропали, (
        "эти команды есть в рельсах валидации, но их НЕТ в init_db — значит "
        "проверяем одно, а на прод уедет другое:\n  " + "\n  ".join(пропали)
    )


def test_обратный_ddl_назван_и_снимает_всё_созданное():
    """Точка отката обязана быть, и она обязана быть ПОЛНОЙ.

    Обратный DDL, снимающий таблицу и забывающий индекс, оставляет за собой
    имя, о которое споткнётся следующая попытка — а `IF NOT EXISTS` при
    столкновении имён молчит.
    """
    м = _модуль_валидатора()
    откат = " ".join(м.ОБРАТНЫЙ_DDL).lower()
    assert "drop table if exists integration_keys" in откат
    for индекс in ("integration_keys_prefix_unique", "idx_integration_keys_org"):
        assert индекс in откат, "обратный DDL не снимает %s" % индекс


def test_ожидаемый_состав_совпадает_с_ddl_построчно():
    """Список ожидаемых колонок — не вторая правда, а слепок ТОГО ЖЕ DDL.

    Разойдись они — рельсы проверяли бы состав, которого сами не создают,
    и обе половины были бы зелёными по отдельности.
    """
    м = _модуль_валидатора()
    создание = _схлопнуть(м.МИГРАЦИЯ[0])
    for колонка in м.ОЖИДАЕМЫЕ_КОЛОНКИ:
        assert re.search(r"\b%s\b" % re.escape(колонка), создание), (
            "колонка «%s» объявлена ожидаемой, но её нет в CREATE TABLE" % колонка
        )
    for индекс in м.ОЖИДАЕМЫЕ_ИНДЕКСЫ:
        assert индекс in " ".join(м.МИГРАЦИЯ), (
            "индекс «%s» объявлен ожидаемым, но его не создаёт ни одна команда" % индекс
        )


def test_рельсы_отдают_sql_текстом_и_он_из_того_же_списка():
    """На бастионе репозитория нет — текст обязан собираться, а не писаться рядом."""
    м = _модуль_валидатора()
    текст = м.SQL_ТЕКСТОМ()
    assert "BEGIN;" in текст and "ROLLBACK;" in текст
    # ⚠️ НИ ОДНОЙ ЗАКРЕПЛЯЮЩЕЙ КОМАНДЫ. Проверяется словом, а не доверием.
    assert "COMMIT" not in текст.upper()
    for команда in м.МИГРАЦИЯ:
        assert _схлопнуть(команда) in _схлопнуть(текст), (
            "SQL-текст собран не из списка МИГРАЦИЯ — два текста разъедутся молча"
        )
    # DDL идёт дважды: второй прогон и есть проверка идемпотентности.
    assert _схлопнуть(текст).count(_схлопнуть(м.МИГРАЦИЯ[0])) == 2
