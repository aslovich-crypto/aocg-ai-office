# -*- coding: utf-8 -*-
"""Три копии одного DDL не разойдутся молча (T104, этап ①).

⚠️ ОДИН И ТОТ ЖЕ DDL ЖИВЁТ В ТРЁХ МЕСТАХ, и это не небрежность, а
устройство: список `МИГРАЦИЯ` в `scripts/validate_invite_columns.py` —
источник; SQL, прогнанный на бастионе, — проверка на живой схеме;
`init_db` в `app/database.py` — то, что применится деплоем. Свести их
в один файл нельзя: валидатор запускается отдельно, бастионный SQL
вставляется руками, а `init_db` исполняется приложением.

⚠️ ЗАТО МОЖНО НЕ ДАТЬ ИМ РАЗОЙТИСЬ. Класс беды известен и оплачен:
T109 — код собран по двум макетам сразу, расхождение нашёл владелец
глазами через месяц. Здесь то же самое было бы дороже: колонка
с другим типом в `init_db` проехала бы валидацию (её там нет) и легла
в прод.

⚠️ СРАВНЕНИЕ ПО СХЛОПНУТЫМ ПРОБЕЛАМ, А НЕ ПОБАЙТНО. В `init_db` строки
лежат с отступом внутри тройной кавычки, в списке — без; побайтное
равенство недостижимо и требовать его значило бы держать тест,
который нельзя удовлетворить. Схлопывание пробелов оставляет то, что
и должно совпадать: таблицу, имя колонки и тип.
"""

import importlib.util
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]


def _список_миграции():
    спец = importlib.util.spec_from_file_location(
        "валидатор", КОРЕНЬ / "scripts/validate_invite_columns.py"
    )
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м.МИГРАЦИЯ


def _схлопнуть(с: str) -> str:
    return re.sub(r"\s+", " ", с).strip().rstrip(";")


def test_каждая_строка_миграции_есть_в_init_db():
    миграция = _список_миграции()
    assert миграция, "список МИГРАЦИЯ пуст — проверять нечего"

    исходник = (КОРЕНЬ / "app/database.py").read_text(encoding="utf-8")
    внутри = {_схлопнуть(с) for с in исходник.split("\n")}

    пропали = [d for d in миграция if _схлопнуть(d) not in внутри]
    assert not пропали, (
        "В app/database.py нет дословных строк из МИГРАЦИЯ "
        "(scripts/validate_invite_columns.py):\n  " + "\n  ".join(пропали)
    )


def test_в_init_db_нет_ЛИШНИХ_alter_по_этим_колонкам():
    """Обратная сторона: в init_db не должно быть ALTER по тем же колонкам
    с ДРУГИМ текстом — иначе рядом с проверенной строкой тихо ляжет вторая.
    """
    миграция = _список_миграции()
    ожидаемые = {_схлопнуть(d) for d in миграция}
    колонки = {"email", "first_name", "last_name", "sent_at"}

    исходник = (КОРЕНЬ / "app/database.py").read_text(encoding="utf-8")
    посторонние = []
    for строка in исходник.split("\n"):
        с = _схлопнуть(строка)
        if not с.startswith("ALTER TABLE invite_links ADD COLUMN"):
            continue
        if с in ожидаемые:
            continue
        if any(f" {к} " in с or с.endswith(f" {к}") for к in колонки):
            посторонние.append(с)

    assert not посторонние, (
        "В init_db есть ALTER по колонкам T104, которого нет в МИГРАЦИЯ:\n  "
        + "\n  ".join(посторонние)
    )
