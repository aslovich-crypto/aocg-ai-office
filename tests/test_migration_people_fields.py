# -*- coding: utf-8 -*-
"""DDL обязательных полей человека не разойдётся с init_db (08.09.2026).

⚠️ ТОТ ЖЕ ПРИЁМ, ЧТО У `test_migration_invite_columns.py`, и это НЕ копия
ради копии: у каждой миграции свой список, свой валидатор и свой предмет.
Общее — правило: строки, прогнанные на бастионе, обязаны дословно лежать
в `init_db`, иначе проверяли бы одно, а применяли другое.

⚠️ ЧЕМ ЭТА МИГРАЦИЯ ОПАСНЕЕ ПРЕДЫДУЩЕЙ. `ADD COLUMN IF NOT EXISTS`
безобиден: не сработал — колонка уже есть. `ALTER COLUMN SET NOT NULL`
и `ADD CONSTRAINT` МОГУТ УПАСТЬ на данных, а падение внутри `init_db`
роняет старт приложения целиком (класс T89). Поэтому здесь сверяется
не только совпадение строк, но и идемпотентность каждой из них.
"""

import importlib.util
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]


def _модуль_валидатора():
    спец = importlib.util.spec_from_file_location(
        "валидатор_полей", КОРЕНЬ / "scripts/validate_people_fields.py"
    )
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def _схлопнуть(с: str) -> str:
    return re.sub(r"\s+", " ", с).strip().rstrip(";")


def _исходник() -> str:
    return (КОРЕНЬ / "app/database.py").read_text(encoding="utf-8")


def test_каждая_строка_миграции_есть_в_init_db():
    м = _модуль_валидатора()
    строки = м.МИГРАЦИЯ + м.ИНДЕКСЫ
    assert строки, "списки МИГРАЦИЯ и ИНДЕКСЫ пусты — проверять нечего"
    внутри = {_схлопнуть(с) for с in _исходник().split("\n")}
    пропали = [d for d in строки if _схлопнуть(d) not in внутри]
    assert not пропали, (
        "В app/database.py нет дословных строк из scripts/validate_people_fields.py:\n  "
        + "\n  ".join(пропали)
    )


def test_каждая_строка_идемпотентна():
    """Ни одна строка не должна падать при ВТОРОМ запуске `init_db`.

    ⚠️ ПРОВЕРЯЕТСЯ ФОРМА, А НЕ ПОВЕДЕНИЕ, и границу надо знать: тест читает
    текст DDL, а не гоняет его дважды по базе. Он ловит `ADD CONSTRAINT` без
    предшествующего `DROP IF EXISTS` и `CREATE INDEX` без `IF NOT EXISTS` —
    то есть класс, а не конкретный случай. Настоящую повторяемость доказывает
    старт приложения, который на живой базе происходит каждый деплой.
    """
    м = _модуль_валидатора()
    небезопасные = []
    все = [_схлопнуть(с) for с in м.МИГРАЦИЯ + м.ИНДЕКСЫ]
    for с in все:
        if " ADD CONSTRAINT " in с:
            имя = с.split(" ADD CONSTRAINT ")[1].split()[0]
            снятие = f"DROP CONSTRAINT IF EXISTS {имя}"
            if not any(снятие in x for x in все):
                небезопасные.append(f"{с}  ← нет «{снятие}» перед добавлением")
        if с.startswith("CREATE UNIQUE INDEX") and "IF NOT EXISTS" not in с:
            небезопасные.append(f"{с}  ← индекс без IF NOT EXISTS")
    assert not небезопасные, (
        "DDL упадёт при втором старте (класс T89):\n  " + "\n  ".join(небезопасные)
    )


def test_обратный_DDL_записан_рядом():
    """Откат обязан быть НАПИСАН, а не восстанавливаться по памяти в аварии."""
    исходник = _исходник()
    for имя in (
        "ck_users_first_name_notblank",
        "ck_users_last_name_notblank",
        "ck_users_email_notblank",
    ):
        assert f"DROP CONSTRAINT {имя}" in исходник, (
            f"в app/database.py нет обратного DDL для {имя}"
        )
    assert "DROP NOT NULL" in исходник, "нет обратного DDL для SET NOT NULL"


def test_засев_админа_не_уронит_старт():
    """⚠️ САМАЯ ДОРОГАЯ ПРОВЕРКА ЭТОГО НАБОРА.

    Засев `BOOTSTRAP_ADMIN_*` идёт ПОСЛЕ DDL и пишет в `users`. До 08.09.2026
    он подставлял `.strip() or None` — то есть на новой площадке с заданной
    почтой, но без имени, INSERT упал бы уже под `NOT NULL`, а вместе с ним
    и `init_db`, и старт приложения. Проверяем, что засев теперь ВЫХОДИТ,
    когда имени или фамилии нет.
    """
    исходник = _исходник()
    начало = исходник.index("async def _засеять_первого_администратора")
    конец = исходник.index("async def init_db")
    тело = исходник[начало:конец]
    assert "if not имя or not фамилия:" in тело, (
        "засев не проверяет имя и фамилию — на новой базе уронит старт"
    )
    # ⚠️ ПРОВЕРЯЕМ АРГУМЕНТЫ, А НЕ ЗАПРЕЩАЕМ КОНСТРУКЦИЮ. `.strip() or None`
    # остаётся у ОТЧЕСТВА — оно необязательно по существу, и запрет «нигде
    # в теле» отверг бы верный код. Первая редакция теста делала именно так
    # и покраснела на исправном засеве.
    аргументы = тело[тело.index("WHERE NOT EXISTS") :]
    assert "\n        имя,\n        фамилия," in аргументы, (
        "в INSERT засева имя и фамилия подставляются не проверенными "
        "переменными — NULL снова возможен"
    )
