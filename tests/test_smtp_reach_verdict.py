# -*- coding: utf-8 -*-
"""Таблица решений прибора S-77 проверяется на выдуманных числах.

ПОЧЕМУ НЕ «ПОТОМ, НА БАСТИОНЕ». Самое опасное в измерителе — не сеть,
а разбор: ошибка в нём не выглядит ошибкой. Печатается уверенная фраза
на неверных числах, и по ней принимается решение переписывать отправку
почты. Сеть для проверки этого не нужна и даже мешает: сеть даёт один
исход за прогон, а проверить надо все пять.

Отдельно проверяется то, что легко потерять при правке: приоритет
сломанного прибора выше любого диагноза. Прибор, который «соединился»
с несуществующим адресом, обязан молчать, а не рассуждать.
"""

import importlib.util
import pathlib

import pytest

_путь = pathlib.Path(__file__).resolve().parent / "tools" / "smtp_reach.py"
_spec = importlib.util.spec_from_file_location("smtp_reach", _путь)
smtp_reach = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(smtp_reach)


def _и(
    прошло587=0,
    прошло465=0,
    прошло443=0,
    чужой=4,
    мёртвый=0,
    всего=4,
    таймаутов587=None,
    таймаутов465=None,
):
    """Итоги прогона. По умолчанию: SMTP молчит, сеть жива, прибор цел."""
    т587 = всего - прошло587 if таймаутов587 is None else таймаутов587
    т465 = всего - прошло465 if таймаутов465 is None else таймаутов465
    return {
        "587": {"прошло": прошло587, "всего": всего, "таймаутов": т587},
        "465": {"прошло": прошло465, "всего": всего, "таймаутов": т465},
        "443": {"прошло": прошло443, "всего": всего, "таймаутов": 0},
        "чужой443": {"прошло": чужой, "всего": всего, "таймаутов": 0},
        "мёртвый": {"прошло": мёртвый, "всего": всего, "таймаутов": всего},
    }


def test_ответил_мёртвый_адрес_вердикта_нет():
    """Главная защита: сломанный прибор молчит, а не диагностирует."""
    код, строки = smtp_reach.вердикт(_и(мёртвый=1, прошло443=4))
    assert код == 3
    assert "ПРИБОР СЛОМАН" in "\n".join(строки)


def test_сломанный_прибор_важнее_любого_другого_исхода():
    """⚠️ Числа выглядят как чистая блокировка — и всё равно вердикта нет.

    Ловит перестановку проверок: если ветку мёртвого адреса опустить ниже,
    прибор начнёт уверенно диагностировать блокировку на машине, где
    «соединяется» вообще всё.
    """
    код, строки = smtp_reach.вердикт(_и(прошло443=4, мёртвый=4))
    assert код == 3
    assert "SMTP" not in "\n".join(строки).replace("ЗАМЕР ИСХОДЯЩЕГО SMTP", "")


def test_молчат_оба_контроля_замер_ничего_не_говорит():
    код, строки = smtp_reach.вердикт(_и(прошло443=0, чужой=0))
    текст = "\n".join(строки)
    assert код == 0
    assert "СЕТИ НЕТ" in текст
    assert "НЕ ГОВОРИТ НИЧЕГО" in текст


def test_молчит_только_хост_postbox_дело_не_в_портах():
    """Отличать «режут SMTP» от «до хоста нет маршрута» — иначе уйдём

    переписывать отправку на HTTP API, который отсюда тоже не работает.
    """
    код, строки = smtp_reach.вердикт(_и(прошло443=0, чужой=4))
    текст = "\n".join(строки)
    assert код == 0
    assert "НЕ ДОСТУЧАТЬСЯ" in текст
    assert "HTTP API на 443 отсюда тоже не заработает" in текст


def test_smtp_молчит_а_443_идёт_это_блокировка():
    код, строки = smtp_reach.вердикт(_и(прошло443=4))
    текст = "\n".join(строки)
    assert код == 0
    assert "НЕ ПРОХОДИТ" in текст
    assert "НЕ РАЗОВЫЙ СБОЙ" in текст
    assert "почерк фильтра" in текст


def test_явные_отказы_отличаются_от_молчания():
    """Тот же итог «ноль из восьми», но диагноз обязан быть другим."""
    код, строки = smtp_reach.вердикт(_и(прошло443=4, таймаутов587=0, таймаутов465=0))
    текст = "\n".join(строки)
    assert код == 0
    assert "почерк фильтра" not in текст
    assert "явные отказы" in текст


def test_smtp_проходит_полностью():
    код, строки = smtp_reach.вердикт(_и(прошло587=4, прошло465=4, прошло443=4))
    текст = "\n".join(строки)
    assert код == 0
    assert "ПРОХОДИТ ПОЛНОСТЬЮ" in текст
    assert "не различить" in текст


def test_частичное_прохождение_это_нестабильность_а_не_блокировка():
    """⚠️ Разделяющий случай: 3 из 4 — повод повторить замер,

    а не переписывать отправку почты. Слить его с «блокировкой» —
    значит потратить день на починку того, что не сломано.
    """
    код, строки = smtp_reach.вердикт(_и(прошло587=3, прошло465=0, прошло443=4))
    текст = "\n".join(строки)
    assert код == 0
    assert "НЕ БЛОКИРОВКА, А НЕСТАБИЛЬНОСТЬ" in текст
    assert "Повторять замер" in текст


@pytest.mark.parametrize(
    "итоги",
    [
        _и(прошло443=4),
        _и(прошло587=4, прошло465=4, прошло443=4),
        _и(прошло587=3, прошло443=4),
        _и(прошло443=0, чужой=0),
    ],
)
def test_вердикт_всегда_что_то_печатает(итоги):
    """Пустой вердикт — тихая потеря диагноза, а выглядит как «всё хорошо»."""
    _, строки = smtp_reach.вердикт(итоги)
    assert строки and all(с.strip() for с in строки)
