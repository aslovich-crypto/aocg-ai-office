# -*- coding: utf-8 -*-
"""Тесты инварианта администраторов (T134).

⚠️ ЖИВОЙ БАЗЫ В ТЕСТАХ НЕТ (T136), поэтому под тестами — чистая функция
`вердикт` (решение по числам) и ТЕКСТ запроса (условия, без которых числа
были бы не те). Сам прогон по проду делает владелец с бастиона.
"""

import importlib.util
import pathlib

_ПУТЬ = pathlib.Path(__file__).resolve().parents[1] / "scripts/check_admin_invariant.py"
_спец = importlib.util.spec_from_file_location("check_admin_invariant", _ПУТЬ)
инв = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(инв)


def test_ноль_админов_красное_и_код_2():
    """Организация без живого админа — ровно тот тупик, из-за которого прибор
    и заведён: владелец 31.08.2026 вернул себе доступ только через базу."""
    код, вывод = инв.вердикт([(1, "АОЦГ", 0)])
    assert код == 2
    assert any("НОЛЬ" in с and "🔴" in с for с in вывод)


def test_ровно_один_жёлтое_и_код_1():
    """⚠️ ВТОРОЙ ПОРОГ — ТРЕБОВАНИЕ ВЛАДЕЛЬЦА, добавленное ДО начала работы:
    один админ — единая точка отказа, и узнать об этом надо ДО того, как он
    потеряет доступ. Без этого порога прибор молчал бы ровно в том состоянии,
    из которого владелец в тот день и выходил через базу."""
    код, вывод = инв.вердикт([(1, "АОЦГ", 1)])
    assert код == 1
    assert any("РОВНО ОДИН" in с and "🟡" in с for с in вывод)
    assert any("пригласите второго" in с for с in вывод), "нет следующего шага"


def test_два_и_больше_зелено():
    """Обратная сторона: прибор, который жёлт всегда, читается мимо (T124)."""
    код, вывод = инв.вердикт([(1, "АОЦГ", 2), (2, "Бюро", 5)])
    assert код == 0
    assert all("✓" in с for с in вывод)


def test_худшая_организация_задаёт_код_но_видны_все():
    """Код выхода — по худшей организации; отчёт печатает каждую (T89:
    красный показывает ПЕРВУЮ причину, но замер не прячет остальные)."""
    код, вывод = инв.вердикт([(1, "А", 2), (2, "Б", 1), (3, "В", 0)])
    assert код == 2
    assert len(вывод) == 3


def test_пустой_прод_это_не_порядок_а_несостоявшийся_замер():
    """T87: нет организаций — «ПРОВЕРКА НЕ ВЫПОЛНЕНА», а не зелёное."""
    код, вывод = инв.вердикт([])
    assert код == 3
    assert any("НЕ ВЫПОЛНЕНА" in с for с in вывод)


def test_запрос_считает_то_самое_и_скрипт_только_читает():
    """Текстовые условия — потому что живой базы в тестах нет (T136).

    ⚠️ БЕЗ `is_active` погашенный админ сошёл бы за живого — ровно класс
    М95/М110, уже ловленный в гейте и во фронте. Без `role = 'admin'`
    любой сотрудник считался бы админом. Слова COMMIT в скрипте нет —
    правило владельца для всего, что ходит на прод."""
    assert "is_active" in инв.ЗАПРОС
    assert "role = 'admin'" in инв.ЗАПРОС
    assert "LEFT JOIN" in инв.ЗАПРОС, "INNER потерял бы организацию без людей"
    исходник = _ПУТЬ.read_text(encoding="utf-8")
    assert "COMMIT" not in исходник
    assert "readonly=True" in исходник, "только-чтение держит база, а не дисциплина"
