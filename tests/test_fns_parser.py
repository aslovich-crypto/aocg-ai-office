# тест на смену карты не отреагировал.


def test_карта_кодов_полная_и_все_значения_различимы():
    """ГЛАВНЫЙ сторож пункта ①: одна карта, двенадцать кодов, ни одной склейки.

    ⚠️ ЛОВИТ ТРИ РАЗНЫХ ДЕФЕКТА СРАЗУ, и каждый измерен на проде 28.08.2026
    (595 позиций в `receipt_items`):
      ① ОТСУТСТВИЕ: коды 7–12 не отображались вовсе → NULL. Код 11 (22%) —
        80 позиций, и это ровно все 80 позиций без ставки среди `qr_scan`.
      ② СКЛЕЙКА 5/6: «НДС 0%» и «Без НДС» давали одно значение "0".
        Код 6 — 448 позиций, три четверти всей базы.
      ③ СКЛЕЙКА РАСЧЁТНЫХ: 3 и 4 давали "20"/"10", то есть 20/120 была
        неотличима от 20. Процент тот же, база разная: 20 начисляется СВЕРХ
        цены, 20/120 выделяется ИЗ неё.
    """
    from app.parsers.fns_parser import КОДЫ_С_НАЛОГОМ, СТАВКА_ПО_КОДУ

    assert set(СТАВКА_ПО_КОДУ) == set(range(1, 13)), "тег 1199 — ровно 12 кодов"
    assert len(set(СТАВКА_ПО_КОДУ.values())) == 12, (
        "все двенадцать значений обязаны быть РАЗНЫМИ: любое совпадение — "
        "это склейка, а склейка уже стоила 448 позиций"
    )
    assert СТАВКА_ПО_КОДУ[5] != СТАВКА_ПО_КОДУ[6], "«НДС 0%» ≠ «Без НДС»"
    assert СТАВКА_ПО_КОДУ[1] != СТАВКА_ПО_КОДУ[3], "прямая 20 ≠ расчётная 20/120"
    assert СТАВКА_ПО_КОДУ[2] != СТАВКА_ПО_КОДУ[4], "прямая 10 ≠ расчётная 10/110"
    assert 5 not in КОДЫ_С_НАЛОГОМ and 6 not in КОДЫ_С_НАЛОГОМ, (
        "ставка 0% и «без НДС» не дают сумм налога — их обороты живут "
        "в sum_vat_0 / sum_no_vat (№30), а не в разбивке"
    )
    assert max(len(v) for v in СТАВКА_ПО_КОДУ.values()) <= 10, (
        "receipt_items.vat_rate — VARCHAR(10); длиннее обрежется молча"
    )


