def test_расчётная_ставка_не_сливается_с_прямой_в_своде():
    """⚠️ ГЛАВНЫЙ по ②: в чеке бывают ОБЕ, и они обязаны стоять раздельно.

    Требование владельца 13.08.2026 дословно: «суммы НДС по ВСЕМ встретившимся
    в чеке ставкам, каждая ОТДЕЛЬНОЙ СТРОКОЙ». 20 и 20/120 — разные ставки:
    первая начисляется СВЕРХ цены, вторая выделяется ИЗ неё.
    """
    p = parse_fns_response(
        {
            "user": "X",
            "totalSum": 100000,
            "items": [
                {"name": "A", "nds": 1, "ndsSum": 20000},
                {"name": "B", "nds": 3, "ndsSum": 10000},
            ],
        }
    )
    assert p["vat_breakdown"] == {"20": 200.00, "20/120": 100.00}, (
        "две строки, не одна на 300.00"
    )


def test_ставка_ноль_и_без_ндс_не_попадают_в_свод_сумм():
    """Нулевая строка в разбивке неотличима от отсутствия строки.

    Обороты по этим кодам живут в своих колонках (`sum_vat_0`/`sum_no_vat`,
    №30) — именно затем они там и заведены.

    ⚠️ СУММЫ ЗДЕСЬ НЕНУЛЕВЫЕ, И ЭТО НЕ ОПИСКА. Первая редакция теста подавала
    `ndsSum: 0`, и мутация «пустить коды 5 и 6 в свод» её НЕ УРОНИЛА: нулевую
    сумму отсекает `if сумма:`, то есть тест проходил по причине, к проверяемому
    правилу не относящейся. Ненулевая сумма по ставке 0% — случай враждебный,
    но возможный (касса вправе прислать что угодно), и только он различает
    «код отфильтрован» от «сумма оказалась нулём».
    """
    p = parse_fns_response(
        {
            "user": "X",
            "totalSum": 100000,
            "items": [
                {"name": "A", "nds": 5, "ndsSum": 12345},
                {"name": "B", "nds": 6, "ndsSum": 67890},
            ],
        }
    )
    assert p["vat_breakdown"] is None, (
        "коды 5 и 6 не дают сумм НДС — даже когда касса прислала сумму"
    )


def test_код_ставки_строкой_принимается_и_в_контейнере():
    """⚠️ ДЫРА, НАЙДЕННАЯ МУТАЦИЕЙ: строковый код проверялся только в позициях.

    Мутация «в контейнере код не декодировать, брать только int» прошла мимо
    всех сторожей — во всех фикстурах контейнера код лежал числом. Контейнер
    приходит от стороннего сервиса проверки чека, ровно как и позиции, и
    предполагать про него больше, чем про них, оснований нет.
    """
    p = parse_fns_response(
        {
            "user": "X",
            "totalSum": 100000,
            "amountsReceiptNds": {"amountsNds": [{"nds": "11", "ndsSum": 127762}]},
        }
    )
    assert p["vat_breakdown"] == {"22": 1277.62}, "код строкой — тот же код"
