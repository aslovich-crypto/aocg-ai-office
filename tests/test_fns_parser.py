def test_контейнер_побеждает_позиции():
    """⚠️ РАЗЛИЧАЮЩИЙ ПРИОРИТЕТ: ловит «брать что нашлось» и «позиции первыми».

    Контейнер — свод САМОЙ ФНС, позиции — наш расчёт по данным чека. Когда
    есть оба, побеждает первый. Числа здесь заведомо разные, чтобы источник
    был виден по результату, а не угадывался.
    """
    p = parse_fns_response(
        {
            "user": "X",
            "totalSum": 100000,
            "amountsReceiptNds": {"amountsNds": [{"nds": 11, "ndsSum": 999900}]},
            "items": [{"name": "Y", "nds": 1, "ndsSum": 111100}],
        }
    )
    assert p["vat_breakdown"] == {"22": 9999.00}, (
        "победить обязан контейнер: 9999.00, а не 1111.00 из позиций"
    )


