# ─── J. НДС НЕ ИСЧЕЗАЕТ (NDS-CLEANUP ②) ───────────────────────────────
# Ловушка названа владельцем ДО реализации и оказалась не гипотетической:
# ровно такой ответ (суммы наверху, позиции без кодов ставок) лежал в фикстуре
# этого файла. После того как колонки vat_20/vat_10 убраны, такой чек остался
# бы без НДС вовсе — молча, потому что «пустая разбивка» и «НДС нет» выглядят
# одинаково.
def test_ндс_из_верхних_полей_когда_позиции_без_кодов():
    p = parse_fns_response(
        {
            "user": "ООО Тест",
            "totalSum": 100000,
            "nds20": 49250,  # копейки
            "nds10": 1000,
            "items": [{"name": "товар", "sum": 100000}],  # кодов ставок НЕТ
        }
    )
    assert p["vat_breakdown"] == {"20": 492.50, "10": 10.0}


def test_ндс_из_позиций_имеет_приоритет_над_верхними():
    """Позиции полнее: там ВСЕ ставки, включая 22%, которой наверху нет."""
    p = parse_fns_response(
        {
            "user": "ООО Тест",
            "nds20": 49250,
            "items": [
                {"name": "а", "nds": 11, "ndsSum": 22000},  # код 11 = 22%
                {"name": "б", "nds": 2, "ndsSum": 1000},  # код 2 = 10%
            ],
        }
    )
    assert p["vat_breakdown"] == {"22": 220.0, "10": 10.0}


def test_ндс_не_исчезает_ни_при_каком_виде_ответа():
    """ИНВАРИАНТ: если в ответе есть НДС, он обязан оказаться в разбивке.

    Проверяется не одна форма, а НАБОР форм — именно потому, что дефект
    возникает на форме, которую не предусмотрели.
    """
    формы = [
        {"nds20": 12000},
        {"nds18": 12000},  # legacy 18% → кладём как 20
        {"nds10": 5000},
        {"items": [{"nds": 1, "ndsSum": 12000}]},
        {"items": [{"nds": 11, "ndsSum": 12000}]},  # 22%
        {"nds20": 12000, "items": [{"name": "без кода", "sum": 1}]},
    ]
    for форма in формы:
        p = parse_fns_response({"user": "X", "totalSum": 1, **форма})
        сумма = sum((p["vat_breakdown"] or {}).values()) + (p["vat_total"] or 0)
        assert сумма > 0, f"НДС потерялся на форме {форма}"


def test_без_ндс_остаётся_без_ндс():
    """Обратная половина: там, где НДС нет, он не должен появляться."""
    p = parse_fns_response({"user": "X", "totalSum": 1, "ndsNo": 10000})
    assert p["vat_breakdown"] is None
    assert p["vat_total"] is None
    assert p["sum_no_vat"] == 100.0, "тег 1105 — оборот без НДС, налога в нём нет"


# ─────────────── обороты 1104 и 1105 — две величины (№30) ────────────────
#
# ⚠️ ЭТОТ БЛОК ЗАМЕНИЛ ПРЕЖНЮЮ ПРОВЕРКУ, А НЕ ДОПОЛНИЛ ЕЁ. Прежняя гласила
# `assert p["vat_0"] == 100.0  # «без НДС»` — и была ЗЕЛЁНОЙ при живой потере
# денег. Она подавала только `ndsNo`, то есть исполняла ту ветку тернарника,
# которая работает, и закрепляла комментарием ОДНО из двух несовместимых
# значений колонки как норму. Ветка `else` (`g("nds0")`) не исполнялась
# ни одним тестом репозитория.
#
# ТЕГИ РАЗНЫЕ, И ЭТО НЕ ОТТЕНОК:
#   1104 `nds0`  — оборот по ставке 0%: операция ОБЛАГАЕТСЯ, ставка нулевая
#   1105 `ndsNo` — оборот без НДС: освобождение либо продавец не плательщик
# Для покупателя это две разные причины отсутствия входящего НДС, и в
# раздельном учёте (ст. 170 НК) с выгрузкой в 1С они идут по разным аналитикам.


def test_оборот_по_ставке_ноль_не_теряется_из_за_пустого_ндсно():
    """ЭТАЛОН ЗАДАЧИ №30, чек id=61 с прода: 2670 ₽ по ставке 0%.

    ⚠️ ПРИЁМОЧНЫЙ. Ровно эта форма ответа теряла деньги: `ndsNo` присутствует
    и равен НУЛЮ, прежний тернарник брал его по `is not None` и до `nds0`
    не доходил. Чек целиком по ставке 0% выглядел как чек без сумм.
    """
    p = parse_fns_response(
        {"user": 'ООО "УСПЕХ"', "totalSum": 267000, "ndsNo": 0, "nds0": 267000}
    )
    assert p["sum_vat_0"] == 2670.00, "оборот по ставке 0% обязан сохраниться"
    assert p["sum_no_vat"] == 0.00, "и ноль без НДС — это ноль, а не отсутствие"


def test_обе_величины_независимы_и_бывают_вместе():
    """Главный: ловит ЛЮБУЮ попытку снова свести две величины в одну.

    ⚠️ На чеке id=61 коды позиций [5,5,6,5,5,6,5,5,5] — в одном чеке есть
    и ставка 0%, и «без НДС». Значит связка между полями («если одно, то
    другое», сложение, выбор большего) потеряет одну из них при любой форме.
    """
    p = parse_fns_response(
        {"user": "X", "totalSum": 300000, "nds0": 200000, "ndsNo": 100000}
    )
    assert p["sum_vat_0"] == 2000.00
    assert p["sum_no_vat"] == 1000.00
    assert p["sum_vat_0"] != p["sum_no_vat"], (
        "величины не должны совпадать по случайности"
    )


def test_только_ставка_ноль_без_поля_ндсно():
    """Вторая ветка в одиночку: `ndsNo` в ответе может отсутствовать вовсе."""
    p = parse_fns_response({"user": "X", "totalSum": 267000, "nds0": 267000})
    assert p["sum_vat_0"] == 2670.00
    assert p["sum_no_vat"] is None, "нет поля — НЕ ЗНАЕМ, а не ноль"


def test_отсутствие_обоих_полей_даёт_пусто_а_не_ноль():
    """Пусто ≠ ноль, и различие обязано доживать до колонок.

    «Ноль» значит «проверено, таких сумм нет». `None` значит «в ответе
    не было». Свести их — потерять то же различие, ради которого в №28
    заведены три явных состояния карточки.
    """
    p = parse_fns_response({"user": "X", "totalSum": 1})
    assert p["sum_vat_0"] is None
    assert p["sum_no_vat"] is None


# ─────────── ЕДИНАЯ КАРТА КОДОВ ТЕГА 1199 (№28, пункт ①) ────────────
#
# ⚠️ ЗДЕСЬ СТОЯЛ СНИМОК `test_коды_пять_и_шесть_не_склеиваются_в_позициях`,
