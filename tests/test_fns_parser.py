ЧЕК_МАКСИДОМ = {
    "user": 'ООО "МАКСИДОМ"',
    "totalSum": 708500,
    "nds0": 0,
    "amountsReceiptNds": {"amountsNds": [{"nds": 11, "ndsSum": 127762}]},
    "items": [
        {"name": "Смеситель", "nds": 11, "price": 500000, "sum": 500000},
        {"name": "Шланг", "nds": 11, "price": 208500, "sum": 208500},
    ],
}


def test_свод_из_контейнера_когда_позиции_без_сумм():
    """ЭТАЛОН ЗАДАЧИ №28, чек id=70 с прода: 1277.62 ₽ не показывались.

    ⚠️ ПРИЁМОЧНЫЙ. Ровно эта форма теряла свод: позиции несут КОД ставки
    (`nds: 11` = 22%) БЕЗ `ndsSum`, поэтому расчёт по позициям даёт пусто;
    плоские теги про 22% не знают, потому что их в формате нет. На карточке
    не рисовалось НИЧЕГО — при том что ФНС свод прислала.
    """
    p = parse_fns_response(ЧЕК_МАКСИДОМ)
    assert p["vat_breakdown"] == {"22": 1277.62}, "свод от ФНС обязан доехать"


