# ───────── СЛУЖЕБНАЯ ЗАГЛУШКА ТЕГА 1104 (№28, пункт ①) ──────────────
#
# Приказ ФНС ЕД-7-20/662@ (ред. 26.03.2025), табл. 11.2: если сведения о суммах
# НДС есть ТОЛЬКО в составе тега 1115, в чек включается тег 1104 СО ЗНАЧЕНИЕМ
# НОЛЬ и НЕ включается в печатную форму. Замер 28.08.2026: таких чеков шесть,
# и после выката №30 все шесть показывали «Оборот по ставке 0% — 0,00 ₽».


def test_служебный_ноль_тега_1104_при_контейнере_не_пишется():
    """Ноль + контейнер = заглушка формата. Не данные, показывать нечего."""
    p = parse_fns_response(
        {
            "user": "X",
            "totalSum": 100000,
            "nds0": 0,
            "amountsReceiptNds": {"amountsNds": [{"nds": 11, "ndsSum": 18033}]},
        }
    )
    assert p["sum_vat_0"] is None, "заглушка формата — не оборот, а «не знаем»"


def test_настоящий_оборот_по_ставке_ноль_при_контейнере_сохраняется():
    """⚠️ РАЗЛИЧАЮЩИЙ: ловит «выбросить nds0 всегда, если есть контейнер».

    Заглушкой тег 1104 делает ИМЕННО НОЛЬ, а не соседство с контейнером.
    Ненулевое значение — настоящий оборот и обязано дожить до колонки.
    """
    p = parse_fns_response(
        {
            "user": "X",
            "totalSum": 267000,
            "nds0": 267000,
            "amountsReceiptNds": {"amountsNds": [{"nds": 11, "ndsSum": 100}]},
        }
    )
    assert p["sum_vat_0"] == 2670.00


def test_ноль_без_контейнера_остаётся_нулём():
    """⚠️ РАЗЛИЧАЮЩИЙ: ловит «выбрасывать любой ноль».

    Без контейнера правило заглушки не применяется: ноль здесь — настоящий
    ответ ФНС «оборота по ставке 0% нет», и он отличается от «не знаем».
    """
    p = parse_fns_response({"user": "X", "totalSum": 100000, "nds0": 0})
    assert p["sum_vat_0"] == 0.00, "ноль без контейнера — проверенный ноль, не пустота"


# ══════ КАНОН СВОДА НДС: ТРИ ИСТОЧНИКА, СТРОГИЙ ПРИОРИТЕТ (№28 ②) ══════
#
# ⚠️ ДО 28.08.2026 КОНТЕЙНЕР ТЕГА 1115 (`amountsReceiptNds`) НЕ ЧИТАЛ НИКТО —
# грепом по обоим репозиториям. Замер 28.08: контейнер у 17 чеков из 71,
