def test_разбор_ключа_строгий():
    """Обрезанное при копировании значение обязано получить отказ.

    ⚠️ ЗНАЧЕНИЯ ФИКСТУР НАМЕРЕННО НЕПОХОЖИ НА НАСТОЯЩИЙ КЛЮЧ. Первая
    редакция использовала «aocg12345678», и поиск секретов в хуке коммита
    честно принял это за ключ и коммит отклонил (энтропия 3.70, правило
    generic-api-key). Чинить надо было фикстуру, а не сторожа: сторож,
    ослабленный ради удобства теста, перестаёт ловить настоящую утечку.
    """
    assert integration_keys.разобрать("aocg-proba-1.secret") == (
        "aocg-proba-1",
        "secret",
    )
    for плохое in ("", "aocg-proba-1", "короткий.secret", "aocg-proba-1.", "."):
        assert integration_keys.разобрать(плохое) == (None, None), (
            "разбор принял негодное значение: %r" % плохое
        )


def test_хеш_секрета_это_sha256_от_значения_как_оно_есть():
    import hashlib

    assert integration_keys.хеш_секрета("abc") == hashlib.sha256(b"abc").hexdigest()
