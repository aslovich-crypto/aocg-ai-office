"""Половины правки «время чека» обязаны двигаться разом (строка 20).

⚠️ ЗАЧЕМ ОБЁРТКА, А НЕ ПРОСТО СКРИПТ. Прибор, который никто не запускает,
молчит о собственной поломке ровно так же, как молчал бы исправный —
это стоило проекту недели с красным `reachable.py` (T149, замер 10.09.2026).
Парный сторож живёт в двух репозиториях сразу, то есть шансов забыть про
него больше обычного.

⚠️ ЗДЕСЬ ДВЕ РАЗНЫЕ ПРОВЕРКИ, И ИХ НЕЛЬЗЯ СЛИВАТЬ.
   ① АЛГОРИТМ — на собственных образцах, включая ловушку «искомое стоит
     в комментарии». Верен всегда, фронт для этого не нужен.
   ② ЖИВАЯ ПАРА — на настоящих файлах. Без фронта не проверяется, и тогда
     это «НЕ МЕРЕНО», а не «ок»: четвёртая графа свода (08.09.2026).
     Пропуск здесь допустим ровно потому, что алгоритм закрыт первой
     проверкой — молчаливо-зелёным остаётся только стык, не прибор.
"""

import pathlib
import subprocess
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
СТОРОЖ = КОРЕНЬ / "tests" / "tools" / "receipt_time_pair.py"


def _прогон(*аргументы):
    итог = subprocess.run(
        [sys.executable, str(СТОРОЖ), *аргументы],
        cwd=КОРЕНЬ,
        capture_output=True,
        text=True,
        timeout=120,
    )
    return итог.returncode, итог.stdout + итог.stderr


def test_парный_сторож_верен_на_своих_образцах():
    код, вывод = _прогон("--selfcheck")
    # Вердикт отличается от сбоя: упавший на импорте прибор не печатает ничего.
    assert "САМОПРОВЕРКА" in вывод, f"прибор не отработал вовсе:\n{вывод[-800:]}"
    assert код == 0, f"алгоритм парного сторожа сломан:\n{вывод}"


def test_тип_колонки_и_компенсация_во_фронте_согласованы():
    код, вывод = _прогон()
    assert "ПАРНЫЙ СТОРОЖ" in вывод, f"прибор не отработал вовсе:\n{вывод[-800:]}"
    if код == 2:
        pytest.skip("НЕ МЕРЕНО: фронт недоступен, живая пара не проверялась")
    assert код == 0, (
        "половины правки «время чека» разошлись — порядок неразделим:\n" + вывод
    )
