def test_строки_нумеруются_подряд_по_всему_документу():
    """LineNumber обязателен по схеме и обязан быть сквозным."""
    итог = об.собрать(
        ОТЧЁТ,
        [чек(vat_breakdown={"20": 5.0}), чек(id=101)],
        НАСТРОЙКИ,
    )
    номера = [с["LineNumber"] for с in итог["тело"]["Прочее"]]
    assert номера == [str(н) for н in range(1, len(номера) + 1)]


