# -*- coding: utf-8 -*-
"""Сборка тела авансового отчёта для 1С (1C-21, заход ③).

⚠️⚠️ ГРАНИЦА ПЕРВОЙ СТРОКОЙ: зелёный прогон здесь НЕ означает, что 1С
примет документ. Он означает, что мы собрали ровно то, что собирались:
раскладку чека по ставкам, подстановки счетов и списки, которые обязан
увидеть человек. Настоящая 1С в тестах не участвует никогда.

⚠️ ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ И ОТДЕЛЬНЫЙ МОДУЛЬ. Сборка тела — чистая
функция без базы и сети, и проверять её надо так же: одним вызовом,
без поднятия PostgreSQL. Ручка проверяется отдельно и другим прибором.
"""

from decimal import Decimal

from app import odata_body as об

НАСТРОЙКИ = {
    "организация": "org-guid",
    "человек": "person-guid",
    "валюта": "rub-guid",
    "склад": "sklad-guid",
    "ответственный": "user-guid",
    "правила": {},
    "счета": {"20.01": "schet-2001-guid", "26": "schet-26-guid"},
}
ОТЧЁТ = {"id": 7, "created": "2026-09-16", "status": "Одобрен", "user_id": 1}


def чек(**поля):
    основа = {
        "id": 100,
        "date": "2026-09-01",
        "amount": Decimal("120.00"),
        "org": "Кофейня",
        "org_inn": "7707083893",
        "fd_num": "4321",
        "category_id": 5,
        "статья": "Питание",
        "vat_breakdown": None,
    }
    основа.update(поля)
    return основа


# ── РАСКЛАДКА ПО СТАВКАМ ─────────────────────────────────────────────────


def test_пустой_свод_даёт_одну_строку_без_ндс():
    """⚠️ Пустой свод — это «0% и без НДС», а НЕ потеря данных: такие
    ставки в свод не кладутся намеренно (`fns_parser`)."""
    строки = об.строки_чека(чек(), None)
    assert len(строки) == 1
    assert строки[0]["СтавкаНДС"] == "БезНДС"
    assert строки[0]["Сумма"] == 120.0


def test_чек_разворачивается_в_строку_на_каждую_ставку():
    """У строки в 1С ставка ОДНА, у чека их бывает несколько."""
    строки = об.строки_чека(
        чек(amount=Decimal("100.00"), vat_breakdown={"20": 10.0, "10": 5.0}), None
    )
    ставки = [с["СтавкаНДС"] for с in строки]
    assert "НДС20" in ставки and "НДС10" in ставки


def test_остаток_чека_едет_отдельной_строкой():
    """⚠️ В своде лежат СУММЫ НДС, а не суммы строк. Всё, что не попало
    в ставки, обязано уехать отдельной строкой, иначе документ не сойдётся
    с чеком по сумме — и заметит это бухгалтер клиента, а не мы."""
    строки = об.строки_чека(
        чек(amount=Decimal("100.00"), vat_breakdown={"20": 10.0}), None
    )
    assert round(sum(с["Сумма"] for с in строки), 2) == 100.0
    assert строки[-1]["СтавкаНДС"] == "БезНДС" and строки[-1]["Сумма"] == 90.0


def test_ставки_переводятся_в_перечисление_1с():
    """Значения взяты из живого `Enum_СтавкиНДС` (замер 1C-20)."""
    for наша, ихняя in (("20/120", "НДС20_120"), ("5", "НДС5"), ("7", "НДС7")):
        строки = об.строки_чека(chek := чек(vat_breakdown={наша: 1.0}), None)
        assert строки[0]["СтавкаНДС"] == ихняя, (наша, chek)


# ── ЧЕГО НЕ ПЕРЕДАЁМ ─────────────────────────────────────────────────────


def test_номенклатура_не_передаётся():
    """Решение 1C-08, подтверждено живой записью: документ записывается
    и проводится с пустой ссылкой на номенклатуру."""
    строки = об.строки_чека(чек(), None)
    assert "Номенклатура_Key" not in строки[0]


def test_субконто_без_правила_не_передаётся():
    """Платформа подставит их сама по счёту затрат (замер 1C-20)."""
    строки = об.строки_чека(чек(), None)
    assert "Субконто2" not in строки[0]


def test_своя_статья_передаётся_явно_когда_правило_есть():
    """⚠️ ИНАЧЕ ПЛАТФОРМА СТАВИТ СВОЮ, И НЕ ТУ: в пробной записи пришла
    статья по умолчанию, отличная от той, что в документах базы."""
    строки = об.строки_чека(
        чек(),
        {"account_code": "26", "expense_ref": "статья-guid"},
        счета=НАСТРОЙКИ["счета"],
    )
    assert строки[0]["СчетЗатрат_Key"] == "schet-26-guid"
    assert строки[0]["Субконто2"] == "статья-guid"
    assert строки[0]["Субконто2_Type"].endswith("Catalog_СтатьиЗатрат")


