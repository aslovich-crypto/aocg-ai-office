def test_в_поле_счёта_едет_ссылка_а_не_код():
    """⚠️ ПЕРВАЯ РЕДАКЦИЯ КЛАЛА КОД «20.01» В `СчетЗатрат_Key`. 1С ждёт GUID
    элемента плана счетов — в пробной записи 1C-20 уходил именно GUID."""
    итог = об.собрать(ОТЧЁТ, [чек()], НАСТРОЙКИ)
