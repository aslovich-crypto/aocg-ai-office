# -*- coding: utf-8 -*-
"""Дубль по РАСПОЗНАННОМУ признаку документа (№25, мера Б) — на живой базе.

ЖИВОЙ СЛУЧАЙ, РАДИ КОТОРОГО ЭТО СДЕЛАНО (12.08.2026): один чек сохранён
ТРИЖДЫ — id 71, 72, 73, все по 3500, все `photo_ocr`, приложение промолчало.
Пары разошлись так: 71 и 72 по ДАТЕ (владелец правил её руками), 72 и 73
по ОРГАНИЗАЦИИ («РЕСТОРАН „САД"» против «Бар» — ошибка распознавания).
Мера А отвязала ключ от точной даты и закрыла первую половину. Вторая
лечится здесь: ФПД у одного документа один и тот же, как бы модель ни
прочла вывеску.

⚠️ ПОЧЕМУ НА ЖИВОЙ БАЗЕ. Ветка целиком — SQL с условием `ocr_fpd = $2
OR fpd = $2` по индексу. На двойнике проверялось бы толкование запроса,
а не сам запрос (класс T136: двойник вернее кода).
"""

from datetime import date

import pytest
import pytest_asyncio

ФПД = "3704529214"


@pytest_asyncio.fixture
async def сотрудник(db):
    await db.добавить_пользователя(id=1, first_name="Админ", role="admin")
    return db


def _чек(**поля):
    основа = {
        "date": "2026-08-12",
        "org": 'РЕСТОРАН "САД"',
        "amount": 3500,
        "source": "photo_ocr",
    }
    основа.update(поля)
    return основа


@pytest.mark.asyncio
async def test_второе_фото_того_же_чека_ловится_даже_при_другом_названии(
    client, db, сотрудник
):
    """⚠️ ГЛАВНЫЙ СЛУЧАЙ: модель прочла вывеску по-разному, документ тот же.

    Ни ИНН, ни название не совпадают — прежние мягкие ветки молчали бы,
    как промолчали 12.08.2026.
    """
    первый = await client.post("/api/receipts/", json=_чек(ocr_fpd=ФПД))
    assert первый.status_code == 200, первый.text

    # ⚠️ ДАТА И НАЗВАНИЕ РАЗНЫЕ — КАК В ЖИВОМ СЛУЧАЕ. Дату владелец правил
    # руками, вывеску по-разному прочла модель. Совпадает только ФПД.
    # Заодно это обходит ветку «двойной тап» (90 секунд, точное совпадение
    # даты и суммы): в тесте два запроса идут подряд, а в жизни между
    # снимками 12.08.2026 прошло три минуты — и та ветка тоже промолчала.
    второй = await client.post(
        "/api/receipts/",
        json=_чек(org="Бар", date="2026-08-13", ocr_fpd=ФПД),
    )
    assert второй.status_code == 200, "предупреждение, а не запрет"
    тело = второй.json()
    предупреждение = тело.get("warning") or {}
    assert предупреждение.get("confidence") == "high", тело
    assert "признак документа" in (предупреждение.get("message") or ""), тело
    assert первый.json()["id"] in [
        д["id"] for д in предупреждение.get("duplicates", [])
    ]


@pytest.mark.asyncio
async def test_разные_документы_не_дают_ВЫСОКОЙ_уверенности(client, db, сотрудник):
    """Обратная сторона: разный ФПД — не тот же документ.

    ⚠️ СЛАБОЕ предупреждение здесь ОСТАЁТСЯ, и это верно: суммы равны,
    даты рядом — прежняя мягкая ветка честно говорит «совпадает сумма».
    Первая редакция теста требовала полного молчания и краснела на
    правильном поведении: проверять надо своё утверждение, а не соседнее.
    Наше утверждение одно — по признаку документа эти чеки НЕ дубли.
    """
    await client.post("/api/receipts/", json=_чек(ocr_fpd=ФПД))
    другой = await client.post(
        "/api/receipts/",
        json=_чек(org="Бар", date="2026-08-13", ocr_fpd="1111111111"),
    )
    assert другой.status_code == 200
    предупреждение = другой.json().get("warning") or {}
    assert предупреждение.get("confidence") != "high", предупреждение
    assert "признак документа" not in (предупреждение.get("message") or "")


@pytest.mark.asyncio
async def test_фото_узнаёт_чек_заведённый_по_QR(client, db, сотрудник):
    """Чек завели сканом QR (реквизит настоящий), потом сфотографировали.

    Это тот же документ, и человеку надо про это сказать — поэтому ветка
    сравнивает распознанное И с настоящим `fpd`.
    """
    await db.добавить_чек(
        id=500,
        org='РЕСТОРАН "САД"',
        amount=3500,
        date=date(2026, 8, 12),
        user_id=1,
    )
    await db.pool.execute("UPDATE receipts SET fpd=$1 WHERE id=500", ФПД)

    фото = await client.post("/api/receipts/", json=_чек(ocr_fpd=ФПД))
    assert фото.status_code == 200
    предупреждение = фото.json().get("warning") or {}
    assert предупреждение.get("confidence") == "high", фото.json()
    assert 500 in [д["id"] for д in предупреждение.get("duplicates", [])]


@pytest.mark.asyncio
async def test_распознанное_не_попадает_в_реквизиты_карточки(client, db, сотрудник):
    """⚠️ РЕШЕНИЕ ВЛАДЕЛЬЦА: признак дубля — НЕ реквизит.

    Карточка чека показывает «ФД №» и «ФПД» как фискальные реквизиты.
    Распознанная цифра там выглядела бы как документальный факт, хотя
    она угадана — тот же класс, что подставленная карта оплаты (T153).
    """
    ответ = await client.post("/api/receipts/", json=_чек(ocr_fd="42", ocr_fpd=ФПД))
    assert ответ.status_code == 200
    строка = await db.чек(ответ.json()["id"])
    assert строка["ocr_fpd"] == ФПД, "признак дубля обязан сохраниться"
    assert строка["fpd"] is None, "в реквизиты распознанное попадать не должно"
    assert строка["fd_num"] is None
    assert строка["kkt_fn"] is None, "Вариант A: OCR не пишет ФН"


