# -*- coding: utf-8 -*-
"""Приложение поднимается БЕЗ единой ODATA-переменной — ЖИВЫМ ЗАПУСКОМ.

⚠️ ЗАЧЕМ ЭТОТ ПРИБОР, ФАКТОМ. 16.09.2026 прод отдавал 502 после выката
захода ① в момент, когда переменных ODATA_* на площадке ещё не было.
Причина НЕ установлена: совпадение с самим деплоем не исключено. Вопрос
«роняет ли отсутствие ODATA-переменных запуск приложения» — вопрос про
СТАРТ, а не про ручку, и ответить на него чтением кода нельзя: старт —
это импорт всех модулей, lifespan, сверка окружения и `init_db` вместе.

⚠️ ПОЭТОМУ НАСТОЯЩИЙ ПОДПРОЦЕСС, А НЕ ASGI-КЛИЕНТ. Тестовый клиент
`httpx` не выполняет lifespan так, как uvicorn, и не импортирует
приложение заново в чистом окружении: переменные, заданные соседними
тестами, остались бы в `os.environ`. Здесь окружение собирается с нуля,
из него вырезаются ВСЕ `ODATA_*`, и приложение стартует так, как на проде.

⚠️ ТРЕБОВАНИЕ ВЛАДЕЛЬЦА 16.09.2026: отсутствие ссылок на 1С ломает
ВЫГРУЗКУ В 1С, а не вход в приложение и не чеки. Обязательными для запуска
эти переменные не делаются.
"""

import os
import socket
import subprocess
import sys
import time

import httpx

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def _свободный_порт() -> int:
    with socket.socket() as с:
        с.bind(("127.0.0.1", 0))
        return с.getsockname()[1]


def _окружение_без_odata(адрес_базы: str) -> dict:
    """Чистое окружение: ни одной ODATA_*, только то, без чего старт
    законно отказывает (ключ подписи и адрес фронта — их проверяют
    на старте намеренно, и к 1С они отношения не имеют)."""
    среда = {к: з for к, з in os.environ.items() if not к.startswith("ODATA_")}
    среда.update(
        {
            "DATABASE_URL": адрес_базы,
            "JWT_SECRET_KEY": "проба-старта-" + "x" * 40,
            "APP_URL": "https://app.aocgai.ru",
            "ENVIRONMENT": "test",
            "SECURITY_ENFORCE_HTTPS": "false",
        }
    )
    return среда


def _поднять(среда: dict, порт: int):
    return subprocess.Popen(
        [
            sys.executable,
            "-m",
            "uvicorn",
            "app.main:app",
            "--host",
            "127.0.0.1",
            "--port",
            str(порт),
        ],
        cwd=КОРЕНЬ,
        env=среда,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )


def _дождаться(порт: int, процесс, секунд: int = 60):
    """(код /health или None, вывод процесса при раннем выходе)."""
    конец = time.monotonic() + секунд
    while time.monotonic() < конец:
        if процесс.poll() is not None:
            return None, процесс.stdout.read()
        try:
            ответ = httpx.get("http://127.0.0.1:%d/health" % порт, timeout=2)
            return ответ.status_code, ""
        except httpx.HTTPError:
            time.sleep(0.3)
    return None, "не поднялось за %d с" % секунд


def test_приложение_стартует_без_единой_odata_переменной(адрес_живой_базы):
    """⚠️ ГЛАВНЫЙ ЗАМЕР. Если это красное — отсутствие переменных роняет
    старт, и 502 на проде 16.09 объяснялся бы ими. Если зелёное — ими он
    НЕ объясняется, и причина была в другом."""
    среда = _окружение_без_odata(адрес_живой_базы)
    assert not [к for к in среда if к.startswith("ODATA_")], (
        "в окружении осталась ODATA_*"
    )
    порт = _свободный_порт()
    процесс = _поднять(среда, порт)
    try:
        код, вывод = _дождаться(порт, процесс)
        assert код == 200, (
            "ПРИЛОЖЕНИЕ НЕ ПОДНЯЛОСЬ без ODATA-переменных. Вывод:\n%s" % вывод[-2000:]
        )
        # База действительно поднята `init_db`, а не просто открыт порт.
        база = httpx.get("http://127.0.0.1:%d/health/db" % порт, timeout=5)
        assert база.status_code == 200, (
            "старт прошёл, а база не отвечает: %s" % база.text
        )
    finally:
        процесс.terminate()
        try:
            процесс.wait(timeout=10)
        except subprocess.TimeoutExpired:
            процесс.kill()


def test_без_переменных_сверка_говорит_но_не_роняет(адрес_живой_базы):
    """Прибор старта обязан ОТЛИЧАТЬ «сказал про расхождение» от «упал».
    Проверяем, что сверка действительно увидела пустые ODATA_* — иначе
    зелёный старт мог бы означать, что сверка их просто не знает."""
    среда = _окружение_без_odata(адрес_живой_базы)
    порт = _свободный_порт()
    процесс = _поднять(среда, порт)
    try:
        код, _ = _дождаться(порт, процесс)
        assert код == 200
    finally:
        процесс.terminate()
        try:
            вывод, _ = процесс.communicate(timeout=10)
        except subprocess.TimeoutExpired:
            процесс.kill()
            вывод, _ = процесс.communicate()
    assert "ODATA_URL" in вывод and "ODATA_ORG_REF" in вывод, (
        "сверка окружения не назвала пустые ODATA-переменные — она их не знает"
    )
    # И не распечатала значения секретов — их тут нет, но проверяется форма.
    assert "тайна" not in вывод
