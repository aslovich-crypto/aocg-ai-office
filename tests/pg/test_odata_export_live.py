class ПоддельнаяОдинЭс:
    """Запоминает каждый вызов и отвечает ТАК, КАК ОТВЕЧАЕТ ПЛОЩАДКА 1С:ФРЕШ.

    ⚠️ ВЕДЁТ СЕБЯ КАК ЗАМЕРЕННАЯ ПЛОЩАДКА, А НЕ КАК УДОБНО ТЕСТУ (1C-21, ④):
    на любой `$filter` отвечает 500 с тем же текстом, что настоящая база, —
    «Операция не разрешена в предложении ГДЕ». Прежняя редакция этой
    поддельной 1С охотно фильтровала — и тесты были зелёными ровно там,
    где живая приёмка упала бы. Двойник, который умеет больше оригинала,
    прячет дефект, а не ловит его.

    Справочник на GET отдаётся ЦЕЛИКОМ: записи с `Ref_Key`, полем поиска
    и `DeletionMark`. `$select` соблюдается, как на площадке: поле, которое
    не попросили, не приходит. Иначе забытый в выборе `DeletionMark`
    доезжал бы в тест и удалённые отсеивались бы только здесь.

    `нечитаемый_ответ` — 200 с телом не в JSON (страница входа, прокси):
    клиент отдаёт тогда только размер, списка записей в ответе нет.

    ⚠️ `сбой_чтения` И `падение_чтения` — РАЗНЫЕ ОТКАЗЫ, И СЛИВАТЬ ИХ НЕЛЬЗЯ
    (26.09.2026, мутант ID-06 не ловился именно из-за этого). `сбой_чтения` —
    площадка ОТВЕТИЛА отказом, код 500; `падение_чтения` — ответа не было
    вовсе, связь оборвалась, и клиент бросает исключение. В коде это две
    разные ветки: первая идёт по проверке кода, вторая — только через
    `except`. Один флаг на оба случая означает, что ветка `except` в прогонах
    не исполняется ни разу и её поломку никто не заметит.
    """

    def __init__(
        self,
        проведение_ок=True,
        запись_код=200,
        контрагенты=None,
        счета=None,
        дубли=False,
        удалённые_контрагенты=None,
        удалённые_счета=None,
        сбой_чтения=None,
        падение_чтения=None,
        нечитаемый_ответ=None,
        сбой_записи=None,
        падение_записи=None,
        ключ_свой=False,
        проведение_без_следа=False,
        отказ_на_занятый_ключ=False,
        опоздавший_ключ=None,
        сбой_чтения_после_создания=False,
    ):
        self.сбой_чтения_после_создания = сбой_чтения_после_создания
        self.вызовы = []
        self.создано = 0
        self.отказ_на_занятый_ключ = отказ_на_занятый_ключ
        # ⚠️ ОПОЗДАВШИЙ ДОКУМЕНТ — САМЫЙ ОПАСНЫЙ СЛУЧАЙ, И ИЗОБРАЗИТЬ ЕГО
        # НЕЧЕМ, КРОМЕ ЭТОГО ФЛАГА. Первый POST дошёл до 1С, но документ
        # появился ПОСЛЕ нашего поиска: поиск честно сказал «не нашли»,
        # а документ есть. Двойник проявляет его ровно после поиска —
        # иначе ветку «отказ на повторе» не пройти ни одним тестом.
        self.опоздавший_ключ = опоздавший_ключ
        self.проведение_ок = проведение_ок
        self.запись_код = запись_код
        self.сбой_чтения = set(сбой_чтения or ())
        self.падение_чтения = set(падение_чтения or ())
        self.нечитаемый_ответ = set(нечитаемый_ответ or ())
        self.сбой_записи = dict(сбой_записи or {})
        self.падение_записи = set(падение_записи or ())
        # ⚠️ ПО УМОЛЧАНИЮ ПЛОЩАДКА НАШ КЛЮЧ ИГНОРИРУЕТ, и это не
        # пессимизм, а правило двойника: он не должен уметь БОЛЬШЕ
        # оригинала. Примет ли 1С:Фреш чужой `Ref_Key`, ещё не
        # замерено — проверится первой реальной отправкой (1C-23 ②).
        # `ключ_свой=True` изображает площадку, которая принимает.
        self.ключ_свой = ключ_свой
        # ⚠️ «200, А ДОКУМЕНТ НЕ ПРОВЁЛСЯ» — ЭТО НЕ ВЫДУМКА: замер
        # площадки 1C-20 говорит, что `Post` отвечает 200 с пустым
        # телом и результат узнаётся ЧТЕНИЕМ `Posted`. Без этого
        # режима двойник не умеет изобразить единственный случай,
        # ради которого чтение и заведено.
        self.проведение_без_следа = проведение_без_следа
        # Созданные документы: ссылка → тело. Нужны затем, что
        # с 26.09.2026 мы их ЧИТАЕМ — Posted после проведения
        # и поиск после обрыва связи.
        self.документы = {}
        к = контрагенты if контрагенты is not None else {"7707083893": "k-guid"}
        с = счета if счета is not None else {"26": "s-26-guid"}
        self.записи_контрагентов = [
            {"Ref_Key": ref, "ИНН": инн, "DeletionMark": False}
            for инн, ref in к.items()
        ]
        if дубли:
            # Два живых контрагента с одним ИНН — замер нашёл 9 таких ИНН.
            self.записи_контрагентов += [
                {"Ref_Key": "второй", "ИНН": инн, "DeletionMark": False} for инн in к
            ]
        for инн in удалённые_контрагенты or ():
            self.записи_контрагентов.append(
                {"Ref_Key": "удалённый-" + инн, "ИНН": инн, "DeletionMark": True}
            )
        self.записи_счетов = [
            {"Ref_Key": ref, "Code": код, "DeletionMark": False}
            for код, ref in с.items()
        ]
        for код, ref in (удалённые_счета or {}).items():
            self.записи_счетов.append(
                {"Ref_Key": ref, "Code": код, "DeletionMark": True}
            )

    async def __call__(self, путь, *, метод="GET", параметры=None, тело=None):
        self.вызовы.append((метод, путь, параметры, тело))
        # Обрыв связи НА ЧТЕНИИ: ответа не было вовсе, клиент бросает
        # исключение. Отличие от `сбой_чтения` — в шапке класса.
        if метод == "GET" and any(путь.startswith(х) for х in self.падение_чтения):
            raise RuntimeError("1С недоступна")
        if метод == "GET" and путь.startswith("Document_"):
            # ⚠️ СБОЙ ЧТЕНИЯ ДЕЙСТВУЕТ И НА ДОКУМЕНТЫ. Без этого «1С недоступна»
            # изобразить нечем, а это ОДИН ИЗ ТРЁХ исходов проверки после
            # обрыва — и самый опасный, потому что молчание тут читается
            # как «документа нет».
            if any(путь.startswith(х) for х in self.сбой_чтения):
                return 500, {"status": "odata_error", "message": "сбой"}
            # ⚠️ ОТКАЗ ЧТЕНИЯ ТОЛЬКО ПОСЛЕ ПОЯВЛЕНИЯ ДОКУМЕНТА. Нужен ровно
            # для одного случая: первый поиск обязан УДАТЬСЯ (и не найти),
            # а второй — упасть. Глобальный `сбой_чтения` этого не изображает:
            # с ним падает и первый, и до отказа повтора тест не доходит.
            if self.сбой_чтения_после_создания and self.создано:
                return 500, {"status": "odata_error", "message": "сбой"}
            # Чтение ОДНОГО документа по ключу: «(guid'…')» в хвосте пути.
            if "(guid'" in путь:
                ссылка = путь.split("(guid'", 1)[1].split("'", 1)[0]
                док = self.документы.get(ссылка)
                if док is None:
                    return 404, {"status": "odata_error", "message": "не найден"}
                return 200, {"тело": self._поля(док, параметры)}
            # Журнал документов: `$orderby` и `$top` площадка умеет (замер
            # 26.09.2026), поэтому двойник их СОБЛЮДАЕТ — иначе проба искала бы
            # среди всего, а живая ручка среди пятидесяти.
            найдено = list(self.документы.values())
            if (параметры or {}).get("$orderby", "").startswith("Date desc"):
                найдено = найдено[::-1]
            верх = (параметры or {}).get("$top")
            if верх:
                найдено = найдено[: int(верх)]
            готово = (
                200,
                {"тело": {"value": [self._поля(д, параметры) for д in найдено]}},
            )
            # ⚠️ ОТВЕТ СОБРАН ДО ПРОЯВЛЕНИЯ ОПОЗДАВШЕГО — ПОРЯДОК ЗДЕСЬ
            # И ЕСТЬ ВЕСЬ СМЫСЛ. Поиск обязан не увидеть документа, а
            # следующий POST — увидеть. Проявить его раньше значило бы
            # изобразить другой случай, уже покрытый соседними тестами.
            if self.опоздавший_ключ and self.опоздавший_ключ not in self.документы:
                self.создано += 1
                self.документы[self.опоздавший_ключ] = {
                    "Ref_Key": self.опоздавший_ключ,
                    "Number": "0000-%06d" % (9 + self.создано),
                    "Posted": False,
                    "Комментарий": "AOCG · отчёт №1 · %s" % self.опоздавший_ключ,
                    "DeletionMark": False,
                }
            return готово
        if метод == "GET":
            if "$filter" in (параметры or {}):
                return 500, {
                    "status": "odata_error",
                    "message": "Операция не разрешена в предложении ГДЕ",
                }
            if путь in self.сбой_чтения:
                return 500, {"status": "odata_error", "message": "сбой"}
            if путь in self.нечитаемый_ответ:
                return 200, {"тело": {"размер": 5120}}
            записи = (
                self.записи_контрагентов
                if "Контрагенты" in путь
                else self.записи_счетов
            )
            выбор = (параметры or {}).get("$select")
            if выбор:
                поля = выбор.split(",")
                записи = [{п: з for п, з in р.items() if п in поля} for р in записи]
            return 200, {"тело": {"value": записи}}
        if путь.endswith("/Post"):
            if self.проведение_ок:
                ссылка = путь.split("(guid'", 1)[1].split("'", 1)[0]
                if ссылка in self.документы and not self.проведение_без_следа:
                    self.документы[ссылка]["Posted"] = True
                # ⚠️ ПУСТОЕ ТЕЛО — КАК У ПЛОЩАДКИ (замер 1C-20): результат
                # проведения по этому ответу узнать НЕЛЬЗЯ, его читают полем
                # `Posted`. Двойник, отдающий здесь результат, скрыл бы ровно
                # тот дефект, который мы чиним.
                return 200, {"тело": {}}
            return 500, {"message": "не провелось"}
        # ⚠️ ОТКАЗ ПО КОНКРЕТНОМУ ПУТИ, А НЕ ВСЕМ ЗАПИСЯМ РАЗОМ (1C-DELMARK,
        # 23.09.2026). `запись_код` глобален: поставив его, отобьёшь и
        # создание документа — до пометки тест просто не дойдёт. Пометка же
        # проверяется ровно на том, что создание УДАЛОСЬ, а пометка нет.
        for хвост, код in (self.сбой_записи or {}).items():
            if путь.endswith(хвост):
                return код, {"status": "odata_error", "message": "1С отказала"}
        for хвост in self.падение_записи or ():
            if путь.endswith(хвост):
                raise RuntimeError("1С недоступна")
        if self.запись_код != 200:
            return self.запись_код, {
                "status": "odata_error",
                "message": "1С ответила отказом",
            }
        if метод == "PATCH" and "(guid'" in путь:
            ссылка = путь.split("(guid'", 1)[1].split("'", 1)[0]
            if ссылка in self.документы and isinstance(тело, dict):
                self.документы[ссылка].update(тело)
            return 200, {"тело": {}}
        # Создание документа. Ключ — наш, если площадка его принимает.
        наш = (тело or {}).get("Ref_Key") if isinstance(тело, dict) else None
        # ⚠️ ЗАНЯТЫЙ КЛЮЧ: КАК ОТВЕЧАЕТ ЖИВАЯ 1С — НЕ ЗАМЕРЕНО, поэтому
        # по умолчанию двойник ведёт себя как площадка, которая ничего не
        # проверяет. `отказ_на_занятый_ключ=True` изображает ту, что
        # проверяет. Код и текст здесь ВЫМЫШЛЕНЫ, и ручка на них не
        # опирается: она трактует ЛЮБОЙ отказ повтора как «спроси заново».
        if self.отказ_на_занятый_ключ and наш and наш in self.документы:
            return 500, {
                "status": "odata_error",
                "message": "документ с таким ключом уже существует",
            }
        self.создано += 1
        # ⚠️ ПЛОЩАДКА, НАЗНАЧАЮЩАЯ КЛЮЧ САМА, ДАЁТ КАЖДОМУ ДОКУМЕНТУ СВОЙ
        # (26.09.2026). Раньше двойник звал их все «doc-guid» — и ВТОРОЙ
        # документ молча затирал первый: `len(документы)` оставался 1, то есть
        # прибор не мог увидеть дубль, ради которого вся строка 1C-23.
        свой = "doc-guid" if self.создано == 1 else "doc-guid-%d" % self.создано
        ссылка = наш if (self.ключ_свой and наш) else свой
        номер = "0000-%06d" % (9 + self.создано)
        self.документы[ссылка] = {
            "Ref_Key": ссылка,
            "Number": номер,
            "Posted": False,
            "Комментарий": (тело or {}).get("Комментарий", "")
            if isinstance(тело, dict)
            else "",
            "DeletionMark": False,
        }
        return 200, {"тело": {"Ref_Key": ссылка, "Number": номер}}

    @staticmethod
    def _поля(док, параметры):
        """`$select` соблюдается, как на площадке: не попросили — не пришло."""
        выбор = (параметры or {}).get("$select")
        if not выбор:
            return dict(док)
        поля = [п.strip() for п in выбор.split(",")]
        return {к: з for к, з in док.items() if к in поля}


