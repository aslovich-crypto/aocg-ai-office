# -*- coding: utf-8 -*-
"""Автодозапрос ФНС при заходе человека (T162) — на живой базе.

ЗАЧЕМ ЭТО ВООБЩЕ. Приложение ФНС на нераспознанный чек пишет: «будет
запрашиваться в течение 24 часов, при получении придёт push». У нас было
«Данные из ФНС не загрузились» и три кнопки на выбор человеку — то есть
спасение перекладывалось на него. Теперь чек, у которого есть ФН, ФД и ФПД,
но нет ответа налоговой, дозапрашивается сам, когда человек открывает
«Чеки», а результат приходит событием и письмом.

⚠️ ПОЧЕМУ ПРИ ЗАХОДЕ, А НЕ ПО РАСПИСАНИЮ: планировщика в проекте нет
(замер 04.09.2026). Обещание «мы сообщим» держится не на заходе человека,
а на ПИСЬМЕ — оно уйдёт, даже если приложение больше не открывали.
"""

from datetime import date

import pytest
import pytest_asyncio

from app.routers import receipts as модуль_чеков


@pytest_asyncio.fixture
async def человек(db):
    await db.добавить_пользователя(
        id=2, first_name="Иван", role="employee", email="ivan@example.com"
    )
    return db


async def _ждущий_чек(db, id=300, минут_назад=60):
    """Чек с реквизитами QR и без ответа ФНС — тот самый случай.

    ⚠️ ФД РАЗНЫЙ У КАЖДОГО ЧЕКА, и это не мелочь теста: пара (ФН, ФД)
    уникальна в базе — один фискальный документ не может существовать
    дважды. Первая редакция теста заводила восемь чеков с одним ФД,
    и живая база отвергла их сама; на двойнике это прошло бы молча.
    """
    await db.добавить_чек(
        id=id,
        org="Кофейня",
        amount=450,
        date=date(2026, 9, 1),
        kkt_fn="7380440700000001",
        fd_num=str(1000 + id),
        user_id=2,
    )
    await db.pool.execute(
        "UPDATE receipts SET fpd=$1, datetime=NOW(), "
        f"created_at = NOW() - INTERVAL '{минут_назад} minutes' WHERE id=$2",
        str(3704529000 + id),
        id,
    )


ОТВЕТ_ФНС = {
    "raw": {
        "operation": {"date": "2026-09-01T10:15:00", "sum": 45000, "type": 1},
        "seller": {"name": 'ООО "Кофейня"', "inn": "7707083893"},
        "items": [],
    }
}


@pytest.mark.asyncio
async def test_ответ_налоговой_ложится_в_чек_и_рождает_событие(
    client, db, человек, monkeypatch
):
    """Главный путь: чек ждал, налоговая ответила, человек об этом узнал."""
    await _ждущий_чек(db)

    async def фнс_ответила(_строка):
        return 200, ОТВЕТ_ФНС

    monkeypatch.setattr(модуль_чеков, "спросить_фнс", фнс_ответила)
    # Письмо не шлём по-настоящему: проверяем факт вызова, а не SMTP.
    ушло = []
    monkeypatch.setattr(модуль_чеков, "_фоновая_почта", lambda ф, *а: ушло.append(а[0]))

    сколько = await модуль_чеков.дозапросить_ожидающие(db.pool, 1, 2)
    assert сколько == 1, "чек обязан был дозапроситься"

    чек = await db.чек(300)
    assert чек["raw_data"] is not None, "ответ налоговой лёг в чек"

    (событие,) = [dict(с) for с in await db.pool.fetch("SELECT * FROM notifications")]
    assert событие["user_id"] == 2, "адресат — автор чека"
    assert событие["kind"] == "fns_data_received"
    assert "Кофейня" in событие["title"], "человеку нужно знать, ПО КАКОМУ чеку"
    assert ушло == ["ivan@example.com"], "письмо держит обещание «мы сообщим»"


@pytest.mark.asyncio
async def test_отказ_налоговой_ничего_не_ломает_и_молчит(
    client, db, человек, monkeypatch
):
    """⚠️ ОТКАЗ ЗДЕСЬ — ОБЫЧНОЕ СОСТОЯНИЕ, А НЕ БЕДА.

    Данные могли ещё не появиться: чек попадёт в следующий заход. Событие
    в этом случае было бы ложью, а тост — шумом на ровном месте.
    """
    await _ждущий_чек(db)

    async def фнс_молчит(_строка):
        return 404, {"message": "не найден"}

    monkeypatch.setattr(модуль_чеков, "спросить_фнс", фнс_молчит)
    сколько = await модуль_чеков.дозапросить_ожидающие(db.pool, 1, 2)
    assert сколько == 0
    assert (await db.чек(300))["raw_data"] is None, "чек остался ждать"
    assert await db.pool.fetch("SELECT * FROM notifications") == []


@pytest.mark.asyncio
async def test_свежий_чек_не_дёргает_налоговую(client, db, человек, monkeypatch):
    """Чек, заведённый минуту назад, налоговая ещё не видит — не спрашиваем."""
    await _ждущий_чек(db, id=301, минут_назад=2)
    звонки = []

    async def считалка(строка):
        звонки.append(строка)
        return 200, ОТВЕТ_ФНС

    monkeypatch.setattr(модуль_чеков, "спросить_фнс", считалка)
    assert await модуль_чеков.дозапросить_ожидающие(db.pool, 1, 2) == 0
    assert звонки == [], "по свежему чеку обращения быть не должно"


@pytest.mark.asyncio
async def test_чужие_чеки_не_дозапрашиваются(client, db, человек, monkeypatch):
    """Дозапрос идёт по СВОИМ чекам: чужой чек — не наше дело и не наш адресат."""
    await db.добавить_пользователя(id=9, first_name="Другой", role="employee")
    await _ждущий_чек(db, id=302)
    await db.pool.execute("UPDATE receipts SET user_id=9 WHERE id=302")

    async def фнс_ответила(_строка):
        return 200, ОТВЕТ_ФНС

    monkeypatch.setattr(модуль_чеков, "спросить_фнс", фнс_ответила)
    monkeypatch.setattr(модуль_чеков, "_фоновая_почта", lambda *а: None)
    assert await модуль_чеков.дозапросить_ожидающие(db.pool, 1, 2) == 0


@pytest.mark.asyncio
async def test_за_раз_не_больше_пяти(client, db, человек, monkeypatch):
    """⚠️ ПОТОЛОК НА ПРОГОН: иначе двадцать зависших чеков дали бы двадцать
    обращений к чужому сервису на каждое открытие списка."""
    for i in range(8):
        await _ждущий_чек(db, id=400 + i)

    звонки = []

    async def считалка(строка):
        звонки.append(строка)
        return 200, ОТВЕТ_ФНС

    monkeypatch.setattr(модуль_чеков, "спросить_фнс", считалка)
    monkeypatch.setattr(модуль_чеков, "_фоновая_почта", lambda *а: None)
    сколько = await модуль_чеков.дозапросить_ожидающие(db.pool, 1, 2)
    assert сколько == 5 and len(звонки) == 5
