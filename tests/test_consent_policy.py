"""Сторож пары «версия ↔ текст согласия» (задача S-34).

ЗАЧЕМ. 152-ФЗ требует связывать согласие с КОНКРЕТНОЙ редакцией текста:
каждая строка `user_consents` хранит и версию, и сам текст, чтобы старое
согласие можно было воспроизвести дословно. Значит пара «версия ↔ текст»
обязана быть взаимно однозначной, а ошибиться в ней можно ДВУМЯ способами,
и оба тихие:

  ① ТЕКСТ ПОМЕНЯЛИ, ВЕРСИЮ НЕТ — под одним номером оказываются две разные
     редакции, и по номеру уже не понять, на что человек соглашался.
     Именно это и случилось: фронт показывал 548 символов с оговоркой
     о передаче фото в США, бэкенд сохранял 450 без неё, обе — «1.0».
  ② ВЕРСИЮ ПОДНЯЛИ, ТЕКСТ НЕТ — в журнале появляется запись о согласии
     на редакцию, которой не существовало. Формально новая версия,
     фактически тот же текст: доказательство ссылается на пустоту.

Сторож ловит обе стороны. Проверяется ЭТАЛОН — записанный список пар
(версия, sha256 текста): текущая версия обязана быть в нём с совпадающим
хешем (ловит ①), а все хеши в нём обязаны быть различны (ловит ②).

КАК МЕНЯТЬ ТЕКСТ ПРАВИЛЬНО: поправить `CONSENT_TEXT`, поднять
`POLICY_VERSION`, добавить в `ЭТАЛОН` новую строку с новым хешем.
Печать нового хеша — `pytest tests/test_consent_policy.py -k хеш -s`.
Старые строки ЭТАЛОНА не удалять: они документируют, что редакций было
несколько, и позволяют опознать историческую запись.
"""

import hashlib

import pytest

from app.routers.consent import CONSENT_TEXT, POLICY_TEXT, POLICY_VERSION


def _хеш(текст: str) -> str:
    return hashlib.sha256(текст.encode("utf-8")).hexdigest()


# Пары «версия → sha256 текста». Дописывается ВРУЧНУЮ при каждой правке —
# в этом и смысл: правка текста должна требовать осознанного действия.
# Пары «версия → хеши ОБОИХ документов». Политика включена намеренно: она
# «является неотъемлемой частью Согласия» (п. 8 самого документа), значит
# подмена политики без смены версии — та же болезнь, что подмена согласия.
# Дописывается ВРУЧНУЮ: правка юридического текста должна требовать
# осознанного действия, а не проходить как побочный эффект.
#
# 2.0 — первая редакция юриста (07.08.2026). Прежние версии в журнале
# не встречаются: он очищен как тестовый.
#
# ХЕШИ ПЕРЕСЧИТАНЫ В ТОТ ЖЕ ДЕНЬ: pre-commit срезал в присланных файлах
# markdown-переносы (двойной пробел в конце строки) — 8 символов
# в согласии и 45 в политике. Смысл текста не изменился, но байты — да,
# и сторож честно покраснел. Автоправку этих файлов запретили
# (.pre-commit-config.yaml), эталон приведён к тому, что лежит в docs/.
ЭТАЛОН = {
    "2.0": {
        "согласие": "4173aa550c2f5d5114521db27aa95740422885aa2cf3eb73ae4bde71f6ba5123",
        "политика": "7abc0f6d7e07af603c4feb7520ea59ef742fc8aba666bf4cd87c9b8fda259c88",
    },
}


def test_версия_и_тексты_совпадают_с_эталоном():
    """Сторона ①: текст поменяли — версию обязаны поднять.

    Проверяются ОБА документа: согласие (уходит в журнал) и политика
    (показывается и объявлена частью согласия).
    """
    assert POLICY_VERSION in ЭТАЛОН, (
        f"Версия {POLICY_VERSION!r} не описана в ЭТАЛОНЕ. Если тексты изменились — "
        f"это правильный путь: добавьте строку с хешами\n"
        f'    "{POLICY_VERSION}": {{"согласие": "{_хеш(CONSENT_TEXT)}",\n'
        f'                          "политика": "{_хеш(POLICY_TEXT)}"}}'
    )
    эталон = ЭТАЛОН[POLICY_VERSION]
    for имя, текст in (("согласие", CONSENT_TEXT), ("политика", POLICY_TEXT)):
        assert эталон[имя] == _хеш(текст), (
            f"Документ «{имя}» изменился, а версия осталась {POLICY_VERSION!r}. "
            "Под одним номером не может быть двух редакций: по номеру потом "
            f"не понять, на что человек соглашался. Новый хеш: {_хеш(текст)}"
        )


def test_все_редакции_различны():
    """Сторона ②: версию подняли — текст обязан отличаться."""
    for имя in ("согласие", "политика"):
        хеши = [пара[имя] for пара in ЭТАЛОН.values()]
        assert len(set(хеши)) == len(хеши), (
            f"Две версии ссылаются на ОДИН И ТОТ ЖЕ документ «{имя}». Значит версию "
            "подняли, а редакцию не меняли — в журнале появится запись о согласии "
            "на текст, которого не было."
        )


def test_текст_не_выродился():
    """Охват: сторож обязан проверять НЕПУСТОЙ текст, иначе он бессмыслен."""
    assert len(CONSENT_TEXT) > 3000, (
        f"Текст согласия {len(CONSENT_TEXT)} символов — редакция юриста заметно "
        "длиннее; такая просадка означает обрезанный файл, а не новую редакцию."
    )
    assert len(POLICY_TEXT) > 3000, (
        f"Политика {len(POLICY_TEXT)} символов — то же самое"
    )
    assert "персональных данных" in CONSENT_TEXT
    # Клаузулы, ради которых редакция 2.0 и понадобилась: без них документ
    # не покрывает того, что приложение делает на самом деле.
    assert "кассире (ФИО)" in CONSENT_TEXT, "ФИО кассира обязано быть названо"
    assert "Anthropic PBC" in CONSENT_TEXT, (
        "трансграничная передача обязана быть названа"
    )
    assert "Нидерланд" in CONSENT_TEXT, "место хранения обязано быть названо"
    # Формулировки, которые мы НЕ подтвердили замером, в тексте стоять не должны.
    assert "зашифрованной базе" not in POLICY_TEXT, (
        "шифрование на стороне площадки не проверено (S-07) — утверждать нельзя"
    )
    assert "подозрительной активности" not in POLICY_TEXT, (
        "журнала аудита нет (S-08) — утверждать нельзя"
    )


def test_хеш(capsys):
    """Служебный: печатает текущий хеш для вписывания в ЭТАЛОН.

    Запуск: pytest tests/test_consent_policy.py -k хеш -s
    """
    with capsys.disabled():
        print(f"\n  версия {POLICY_VERSION}")
        print(f"    согласие: {_хеш(CONSENT_TEXT)}")
        print(f"    политика: {_хеш(POLICY_TEXT)}")


@pytest.mark.asyncio
async def test_policy_endpoint_serves_the_same_source(client):
    """Ручка отдаёт РОВНО тот текст, который сохранится в журнал.

    Без этого «один источник» остаётся намерением: фронт покажет одно,
    запись сохранит другое — ровно то, что и случилось до S-34.
    """
    r = await client.get("/api/consent/policy")
    assert r.status_code == 200, r.text
    d = r.json()
    assert d["version"] == POLICY_VERSION
    assert d["text"] == CONSENT_TEXT
    assert d["policy"] == POLICY_TEXT, (
        "политика обязана приходить той же ручкой: она объявлена неотъемлемой "
        "частью согласия, и вторая копия на фронте разошлась бы снова"
    )
    assert "Anthropic" in d["text"], (
        "в редакции обязана быть оговорка о трансграничной передаче — "
        "фото чеков уходят на распознавание в США"
    )
