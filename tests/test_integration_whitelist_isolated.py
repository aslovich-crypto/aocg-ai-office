# ⚠️ ПРОВЕРЯЕТСЯ САМА ФУНКЦИЯ, А НЕ ОТВЕТ РУЧКИ, И ЭТО РАЗНЫЕ ПРЕДМЕТЫ.
# Мутация «убрать перевод `Decimal` в число» пережила живой прогон: FastAPI
# переводит `Decimal` своим сериализатором, и по HTTP разницы не видно. Но
# опираться на чужой сериализатор в договоре с чужой машиной нельзя — сменят
# класс ответа, и деньги молча уедут строкой. Значит договор объявляет сама
# функция, и стережёт её проверка функции.


def test_деньги_переводятся_в_число():
    значение = инт._значение(Decimal("100.50"))
    assert isinstance(значение, float) and значение == 100.50


def test_дата_и_время_без_зоны_через_букву_T():
    assert инт._значение(datetime(2026, 6, 11, 11, 45)) == "2026-06-11T11:45:00"


def test_дата_без_времени():
    assert инт._значение(date(2026, 6, 11)) == "2026-06-11"


def test_остальное_проходит_как_есть():
    """Строка, число и пустое значение не трогаются: перевод — не украшение."""
    assert инт._значение("7701234567") == "7701234567"
    assert инт._значение(None) is None
    assert инт._значение(7) == 7
