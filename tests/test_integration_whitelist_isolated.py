def _разница(было, стало):
    return "лишние %s, пропали %s" % (
        sorted(было - стало),
        sorted(стало - было),
    )


def test_белый_список_отчёта_совпадает_с_писаным_договором():
    список = set(инт.ПОЛЯ_ОТЧЁТА)
    assert список == ДОГОВОР_ОТЧЁТА, _разница(список, ДОГОВОР_ОТЧЁТА)


def test_белый_список_чека_совпадает_с_писаным_договором():
    список = set(инт.ПОЛЯ_ЧЕКА)
    assert список == ДОГОВОР_ЧЕКА, _разница(список, ДОГОВОР_ЧЕКА)


def test_в_белых_списках_нет_ни_одного_запретного_имени():
    """Вторая половина того же: договор можно переписать, запрет — нет.

    Проверки выше стерегут РАВЕНСТВО списка договору, эта — что в договор
    не внесли запретное заодно с ним. Без неё правка обоих мест разом
    прошла бы молча.
    """
    весь = set(инт.ПОЛЯ_ОТЧЁТА) | set(инт.ПОЛЯ_ЧЕКА)
    просочилось = весь & ЗАПРЕТНЫЕ
    assert not просочилось, "в белый список внесли запретное: %s" % sorted(просочилось)


def test_добавочные_поля_ответа_не_совпадают_с_запретными_именами():
    """`employee_name`, а не `employee`: одно имя на два смысла — ловушка.

    Сторож запретных полей сверяет ИМЯ, а не смысл. Назвав подотчётника
    `employee`, мы научили бы его молчать ровно про ту легаси-колонку, ради
    которой он заведён.
    """
    добавочные = {"employee_name", "receipts", "has_photo", "next_cursor", "reports"}
    assert not (добавочные & ЗАПРЕТНЫЕ), "добавочное поле заняло запретное имя"


def test_синонимы_ведут_из_белого_списка_и_никуда_больше():
    """Переименование наружу — расхождение внешнего имени с внутренним.

    Каждое такое расхождение стоит оправдывать, поэтому список синонимов
    задуман коротким, а ключи его обязаны быть В белом списке: синоним
    на имя, которого наружу нет, — мёртвая строка.
    """
    assert set(инт.СИНОНИМЫ) <= set(инт.ПОЛЯ_ЧЕКА) | set(инт.ПОЛЯ_ОТЧЁТА)
    assert инт.СИНОНИМЫ == {"category_name": "статья"}


def test_наружу_не_уходит_ни_одного_кириллического_имени():
    """Договор с чужой машиной — латиницей. Единственный псевдоним со стороны
    базы (`статья`) переименован на выходе, см. `СИНОНИМЫ`."""
    весь = set(инт.ПОЛЯ_ОТЧЁТА) | set(инт.ПОЛЯ_ЧЕКА)
    нелатинские = {и for и in весь if not и.isascii()}
    assert not нелатинские, "наружу уходит имя не латиницей: %s" % sorted(нелатинские)


def test_отдаются_только_одобренные_отчёты():
    """Статус выдачи — одно слово в одном месте, и оно то самое."""
    assert инт.СТАТУС_К_ВЫДАЧЕ == "Одобрен"


def test_у_страницы_есть_потолок_и_умолчание_и_оба_те_самые():
    """Решение владельца 12.09.2026: 100 по умолчанию, 1000 потолок.

    Числа названы ЧИСЛАМИ, а не отношением «умолчание не больше потолка»:
    последнее останется верным и когда оба станут десятью тысячами.
    """
    assert инт.СТРАНИЦА_ПО_УМОЛЧАНИЮ == 100
    assert инт.ПОТОЛОК_СТРАНИЦЫ == 1000
    assert инт.СТРАНИЦА_ПО_УМОЛЧАНИЮ <= инт.ПОТОЛОК_СТРАНИЦЫ


