"""Письмо не держит цикл событий (T66).

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ЭТО НЕ ПРО СКОРОСТЬ РЕГИСТРАЦИИ.
Отправка синхронная (smtplib), обработчики — async, uvicorn поднят одним
процессом без --workers. Прямой вызов останавливал не запрос, а ВЕСЬ сервер:
на время отправки не обслуживался никто. Поэтому меряется не «быстро ли
регистрируется», а «двигаются ли ЧУЖИЕ запросы, пока уходит письмо».

⚠️ МЕРИТСЯ МОМЕНТ ЗАВЕРШЕНИЯ ОТ ОБЩЕГО НУЛЯ, А НЕ ДЛИТЕЛЬНОСТЬ ЗАПРОСА,
И ЭТО КУПЛЕНО ОШИБКОЙ. Первая проба засекала длительность постороннего
запроса, получила 0.01 с и напечатала «цикл свободен» — вывод, обратный
правде. При заблокированном цикле посторонний запрос НЕ НАЧИНАЕТСЯ вовсе:
его отсчёт стартует уже после снятия блокировки, и он честно длится
доли миллисекунды. Прибор был зелёным и неправым одновременно; различить
удалось только сменой измеряемого отрезка.

⚠️ ОСОБЕННОСТЬ ПРОГОНА, БЕЗ КОТОРОЙ ЧИСЛА ЧИТАЮТСЯ НЕВЕРНО: под
ASGITransport ожидание ответа охватывает и фоновую задачу, поэтому САМА
регистрация тут длится столько же, сколько раньше. Это не провал правки:
у настоящего клиента ответ уходит до задачи. Смысл правки — освобождённый
цикл, и именно он здесь проверяется.
"""

import asyncio
import time

import pytest

import app.routers.auth as auth

ЗАДЕРЖКА = 0.6


@pytest.fixture
def медленная_почта(monkeypatch):
    """Отправка, ведущая себя как smtplib при недоступном сервере."""
    следы = []

    def отправка(*аргументы, **_k):
        следы.append(аргументы)
        time.sleep(ЗАДЕРЖКА)
        return False

    monkeypatch.setattr(auth, "email_enabled", lambda: True)
    monkeypatch.setattr(auth, "send_verification_email", отправка)
    return следы


async def _посторонний(client, ноль, задержка=0.1):
    """Чужой запрос, не имеющий к почте отношения. Возвращает момент конца."""
    await asyncio.sleep(задержка)
    r = await client.get("/")
    return r.status_code, time.time() - ноль


async def test_чужие_запросы_идут_пока_уходит_письмо(client, медленная_почта):
    """ГЛАВНЫЙ: ловит возврат прямого вызова вместо add_task."""
    ноль = time.time()

    async def регистрация():
        return await client.post(
            "/api/auth/register",
            json={
                "email": "fon-1@example.com",
                "password": "Parol12345",
                "first_name": "Фон",
                "last_name": "Проба",
            },
        )

    ответ, (код, конец) = await asyncio.gather(
        регистрация(), _посторонний(client, ноль)
    )

    assert ответ.status_code == 200
    assert код == 200
    assert конец < ЗАДЕРЖКА * 0.8, (
        f"посторонний запрос завершился на {конец:.2f} с при задержке письма "
        f"{ЗАДЕРЖКА:.2f} с — значит он ЖДАЛ отправку, цикл заблокирован"
    )


async def test_письмо_всё_таки_уходит(client, медленная_почта):
    """Вторая половина: цикл свободен — но письмо не должно потеряться."""
    r = await client.post(
        "/api/auth/register",
        json={
            "email": "fon-2@example.com",
            "password": "Parol12345",
            "first_name": "Фон",
            "last_name": "Проба",
        },
    )
    assert r.status_code == 200
    assert r.json()["verified"] is False
    assert len(медленная_почта) == 1, "письмо не отправлялось вовсе"
    assert медленная_почта[0][0] == "fon-2@example.com"
    assert "/verify-email?token=" in медленная_почта[0][1]


async def test_ссылка_ведёт_на_адрес_фронта(client, медленная_почта, monkeypatch):
    """Ссылка строится из APP_URL и уходит в фон целиком, а не по частям.

    ⚠️ АДРЕС ЗАДАЁТСЯ ЗДЕСЬ ЯВНО, И БЕЗ ЭТОГО ТЕСТ БЫЛ ПУСТЫМ. В прогоне
    переменная APP_URL не задана, то есть константа — пустая строка, и проверка
    «ссылка начинается с APP_URL» вырождалась в «начинается с пустоты»:
    подходило что угодно. Мутант «собрать ссылку БЕЗ адреса фронта» проходил
    мимо всех четырёх тестов. Поймано мутацией, а не чтением.
    """
    monkeypatch.setattr(auth, "APP_URL", "https://app.aocgai.ru")
    await client.post(
        "/api/auth/register",
        json={
            "email": "fon-3@example.com",
            "password": "Parol12345",
            "first_name": "Фон",
            "last_name": "Проба",
        },
    )
    assert медленная_почта[0][1].startswith(
        "https://app.aocgai.ru/verify-email?token="
    ), медленная_почта[0][1]


