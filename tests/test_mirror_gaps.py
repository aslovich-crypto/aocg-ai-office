"""Сторож зеркала: двойник не должен быть позволительнее продакшена (T35).

ПОЧЕМУ СТОРОЖЕМ, А НЕ РАЗОВЫМ ЗАМЕРОМ. Пять расхождений 07.08.2026 накопились
незаметно: ветку пишут под один запрос, потом в роутере добавляют `AND org_id=$2`
— и ветка молча остаётся позволительнее. Сторож T6 такое не видит по устройству:
он сравнивает ветки МЕЖДУ СОБОЙ, а не с продакшен-SQL. Это дыра в стороже,
а не в правиле, и закрывается она здесь.

ЧТО ПРОВЕРЯЕТСЯ (три источника, каждый ломается мутацией при сдаче):
  1. РАСХОЖДЕНИЯ. Ни одна ветка FakePool не игнорирует условие доступа
     (`org_id`, `user_id`, `is_active`, `created_by`), стоящее в SQL роутера.
  2. САМОПРОВЕРКА. Замер прогоняется на ИЗВЕСТНОМ примере — заведомо дырявой
     и заведомо здоровой паре (правило T26): молчание разбора не должно
     читаться как чистое зеркало.
  3. ОХВАТ. Запросов и веток разобрано не меньше порога — иначе «расхождений
     ноль» означает «ничего не проверено».
"""

import importlib.util
import pathlib

import pytest

_ПУТЬ = pathlib.Path(__file__).with_name("tools") / "mirror_gaps.py"
_спец = importlib.util.spec_from_file_location("mirror_gaps", _ПУТЬ)
mirror_gaps = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(mirror_gaps)

# Пороги охвата — с запасом вниз от фактических на 07.08.2026 (101 запрос,
# 92 ветки). Просадка означает сломанный разбор, а не «стало чище».
МИН_ЗАПРОСОВ = 80
МИН_ВЕТОК = 70


@pytest.fixture(scope="module")
def замер():
    ветки = mirror_gaps._ветки_fakepool()
    запросы = mirror_gaps._sql_из_приложения()
    расхождения, _ = mirror_gaps.проверить(запросы, ветки)
    return ветки, запросы, расхождения


def test_selfcheck_passes(замер):
    """Источник 2: замер находит заведомо дырявую пару и не трогает здоровую."""
    ветки, _, _ = замер
    mirror_gaps._самопроверка(ветки)  # падает через SystemExit, если сломан


def test_coverage_is_real(замер):
    """Источник 3: разобрано достаточно, чтобы «ноль» что-то значил."""
    ветки, запросы, _ = замер
    всего_веток = sum(len(v) for v in ветки.values())
    assert len(запросы) >= МИН_ЗАПРОСОВ, (
        f"разобрано запросов приложения {len(запросы)} при пороге {МИН_ЗАПРОСОВ} — "
        "сломан разбор, проверка расхождений ослепла"
    )
    assert всего_веток >= МИН_ВЕТОК, (
        f"разобрано веток FakePool {всего_веток} при пороге {МИН_ВЕТОК} — то же самое"
    )


def test_no_mirror_gaps(замер):
    """Источник 1: двойник нигде не позволительнее продакшена."""
    _, _, расхождения = замер
    отчёт = "".join(
        f"\n  {файл}:{строка} ({метод}) → conftest.py:{ветка}"
        f"\n    ветка не смотрит: {', '.join(пропущены)}"
        f"\n    SQL: {sql[:110]}"
        for файл, строка, метод, sql, ветка, пропущены in расхождения
    )
    assert not расхождения, (
        "Ветка FakePool игнорирует условие доступа, которое есть в запросе "
        "роутера. Такой тест не покраснеет, если защиту снять, и не докажет, "
        "что она есть." + отчёт + "\n\n  Починка: условие БЕРЁТСЯ ИЗ ТЕКСТА "
        'запроса (`свой = "AND org_id=$2" in q`), см. правило в шапке FakePool.'
    )
