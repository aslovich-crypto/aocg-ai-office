# Ручки, защищённые НЕ пользовательской сессией, а статическим токеном
# в заголовке (`X-Relay-Token`, проверка — `_check_auth` в max_relay.py).
# Список отдельный намеренно: смешать их с ОТКРЫТЫ_НАМЕРЕННО значило бы
