def _вызывает_проверку_токена(fn) -> bool:
    """В теле обработчика есть вызов `_check_auth(...)` — защита заголовком."""
    import ast

    return any(
        isinstance(узел, ast.Call) and getattr(узел.func, "id", "") == "_check_auth"
        for узел in ast.walk(fn)
    )


def _зависимость(fn, имя: str) -> bool:
    """У обработчика есть `Depends(<имя>)` среди значений по умолчанию."""
    import ast

    return any(
        isinstance(d, ast.Call)
        and getattr(d.func, "id", "") == "Depends"
        and d.args
        and getattr(d.args[0], "id", "") == имя
        for d in list(fn.args.defaults) + list(fn.args.kw_defaults)
    )


def _открытые_ручки():
    """Четыре множества по КОДУ: открытые, по токену, по ключу и счётчик охвата.

    «Открытая» = нет ни `Depends(get_current_user)`, ни `Depends(
    get_integration_principal)`, ни `_check_auth` в теле.
    """
    import ast
    import pathlib

    корень = pathlib.Path(__file__).resolve().parents[1] / "app" / "routers"
    открытые, токеном, ключом, всего = set(), set(), set(), 0
    for файл in sorted(корень.glob("*.py")):
        tree = ast.parse(файл.read_text())
        for fn in ast.walk(tree):
            if not isinstance(fn, (ast.AsyncFunctionDef, ast.FunctionDef)):
                continue
            точка = None
            for d in fn.decorator_list:
                if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute):
                    метод = d.func.attr.upper()
                    if метод in ("GET", "POST", "PATCH", "PUT", "DELETE"):
                        путь = (
                            d.args[0].value
                            if d.args and isinstance(d.args[0], ast.Constant)
                            else ""
                        )
                        префикс = "/api"
                        for узел in ast.walk(tree):
                            if (
                                isinstance(узел, ast.Call)
                                and getattr(узел.func, "id", "") == "APIRouter"
                            ):
                                for kw in узел.keywords:
                                    if kw.arg == "prefix" and isinstance(
                                        kw.value, ast.Constant
                                    ):
                                        префикс = kw.value.value
                        точка = f"{метод} {префикс}{путь}".rstrip("/")
            if not точка:
                continue
            всего += 1
            if _зависимость(fn, "get_current_user"):
                continue
            if _зависимость(fn, "get_integration_principal"):
                ключом.add(точка)
            elif _вызывает_проверку_токена(fn):
                токеном.add(точка)
            else:
                открытые.add(точка)
    return открытые, токеном, ключом, всего


def test_open_endpoints_are_exactly_the_login_flow():
    """Источник охвата + сам список: ручек разобрано много, открыты — только эти."""
    открытые, _, _, всего = _открытые_ручки()
    assert всего >= 45, f"разобрано ручек {всего} — сломан разбор, а не «всё закрыто»"
    лишние = открытые - {p.rstrip("/") for p in ОТКРЫТЫ_НАМЕРЕННО}
    пропали = {p.rstrip("/") for p in ОТКРЫТЫ_НАМЕРЕННО} - открытые
    assert not лишние, (
        "Появилась ручка БЕЗ авторизации. Если так и задумано — добавьте её "
        f"в ОТКРЫТЫ_НАМЕРЕННО с обоснованием: {sorted(лишние)}"
    )
    assert not пропали, (
        "Ручка входа закрылась авторизацией — в неё теперь не попасть тому, "
        f"кого ещё нет в системе: {sorted(пропали)}"
    )


def test_token_protected_endpoints_are_exactly_the_declared_ones():
    """Вторая половина: защита заголовком есть ровно там, где заявлена.

    Красный в ОБЕ стороны, и это главное. Уберут `_check_auth` из обработчика —
    ручка выпадет отсюда И появится в «открытых», два сигнала сразу. Появится
    новая ручка с токенной защитой — её потребуют объявить здесь, а не
    протащат молча под видом «ну она же не совсем открытая».
    """
    _, токеном, _, _ = _открытые_ручки()
    ожидаем = {p.rstrip("/") for p in ЗАЩИЩЕНЫ_ТОКЕНОМ}
    пропали = ожидаем - токеном
    лишние = токеном - ожидаем
    assert not пропали, (
        "У ручки СНЯЛИ проверку токена (`_check_auth`) — она осталась без "
        f"защиты вовсе: {sorted(пропали)}"
    )
    assert not лишние, (
        "Появилась ручка с токенной защитой, не объявленная в "
        f"ЗАЩИЩЕНЫ_ТОКЕНОМ: {sorted(лишние)}"
    )


def test_key_protected_endpoints_are_exactly_the_declared_ones():
    """Третья половина: ключ интеграции открывает ровно то, что заявлено.

    Красный в обе стороны. Снимут зависимость — ручка выпадет отсюда И
    появится в «открытых». Повесят зависимость на новую ручку — её потребуют
    объявить здесь: права ключа выражены МЕСТОМ, и каждое новое место
    расширяет их ровно на эту ручку.
    """
    _, _, ключом, _ = _открытые_ручки()
    ожидаем = {p.rstrip("/") for p in ЗАЩИЩЕНЫ_КЛЮЧОМ}
    пропали = ожидаем - ключом
    лишние = ключом - ожидаем
    assert not пропали, (
        "У ручки СНЯЛИ проверку ключа интеграции — она осталась без защиты "
        f"вовсе: {sorted(пропали)}"
    )
    assert not лишние, (
        "Ключу интеграции открыли ручку, не объявленную в ЗАЩИЩЕНЫ_КЛЮЧОМ: "
        f"{sorted(лишние)}"
    )


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "метод,путь,тело",
    [
        ("post", "/api/receipts/ocr/", None),
        ("post", "/api/fns/check", {"qr_raw": "t=1&s=1"}),
        ("post", "/api/consent/", {"user_id": "local_user"}),
        ("get", "/api/consent/local_user", None),
    ],
)
async def test_gated_endpoints_reject_anonymous(db, метод, путь, тело):
    """Аноним получает отказ — и побочного эффекта не происходит."""
    app.dependency_overrides.clear()
    async with AsyncClient(
        transport=ASGITransport(app=app), base_url="http://test"
    ) as c:
        r = await getattr(c, метод)(путь, **({"json": тело} if тело else {}))
    assert r.status_code in (401, 403), f"{путь} → {r.status_code}: {r.text[:120]}"
    assert db.consents == [], "анонимная запись согласия не должна была появиться"


