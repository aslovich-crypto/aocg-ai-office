"""Ручка /health — та, по которой мониторинг судит, жив ли сервис.

ПОЧЕМУ ЭТИ ТЕСТЫ ПОЯВИЛИСЬ ТОЛЬКО СЕЙЧАС И ПОЧЕМУ ГЛАВНЫЙ ИЗ НИХ — ПРО HEAD.
Мониторы ходят методом HEAD: тело им не нужно, нужен код ответа. FastAPI,
в отличие от голого Starlette, НЕ добавляет HEAD к маршруту `@app.get`,
поэтому на HEAD приходил `405 Method Not Allowed`. Прибор при этом честно
измерял время ответа — сервер-то отвечал, — но статус считал падением:
UptimeRobot показывал DOWN полтора месяца подряд при доступности 0.000%
и зелёном графике скорости (замер владельца по кабинету, 12.08.2026).

Ложная тревога хуже молчащего прибора: на постоянно красный перестают
смотреть, и настоящее падение пройдёт незамеченным. Разбор — T46.
"""

import pytest

pytestmark = pytest.mark.anyio


async def test_health_get_returns_ok(client):
    resp = await client.get("/health")
    assert resp.status_code == 200
    assert resp.json() == {"status": "ok"}


async def test_health_answers_head_too(client):
    """Именно этот тест ловит полтора месяца ложной тревоги.

    Проверяем КОД, а не тело: на HEAD тела не бывает по определению,
    и монитор смотрит ровно на код.
    """
    resp = await client.head("/health")
    assert resp.status_code == 200, (
        "мониторы ходят методом HEAD; 405 здесь означает вечный DOWN при живом сервисе"
    )


