# -*- coding: utf-8 -*-
"""Отметка обращения: что она трогает и откуда берёт адрес (заход ⑦).

⚠️ ЗДЕСЬ ПРОВЕРЯЕТСЯ УСТРОЙСТВО, А НЕ ПОВЕДЕНИЕ. Что записалось в строку
ключа — предмет живых проверок (`tests/pg/test_integration_journal_live.py`).
Здесь два вопроса, на которые живой прогон не отвечает: какие колонки запрос
вообще трогает и ТЕМ ЛИ извлекателем берётся адрес.

Второй вопрос важнее, чем кажется. Своя копия извлекателя разойдётся, когда
S-35 научит брать адрес с правого конца `X-Forwarded-For`: починят одно место,
второе останется брать левый конец и продолжит верить подставленному адресу.
Живой тест этого не заметит — он проверяет результат, а результат у копии
сегодня тот же.
"""

from app import integration_keys as ик


def test_отметка_трогает_только_три_колонки_журнала():
    """Поимённо: запрос обязан менять время, адрес и счёт — и больше ничего."""
    текст = ик.ОТМЕТКА.lower()
    for колонка in ("last_used_at", "last_used_ip", "use_count"):
        assert колонка in текст, "отметка перестала писать %s" % колонка
    for запретная in ("secret_hash", "prefix", "org_id", "revoked_at", "expires_at"):
        assert запретная not in текст, "отметка трогает чужую колонку %s" % запретная
    assert текст.strip().startswith("update integration_keys")
    # Счёт наращивает БАЗА, а не приложение: иначе два параллельных запроса
    # прочитали бы одно и то же значение и записали бы одно и то же.
    assert "use_count = use_count + 1" in текст


def test_без_запроса_адрес_неизвестен_а_не_пуст():
    """Зависимость зовут напрямую из проверок — падать на этом она не должна."""
    assert ик._адрес(None) == "unknown"


def test_адрес_берётся_общим_извлекателем_а_не_своей_копией(monkeypatch):
    """⚠️ ПРОВЕРЯЕТСЯ ИМЕННО ДЕЛЕГИРОВАНИЕ. Подменяем общий извлекатель: если
    адрес всё равно вычислился сам, значит рядом завелась вторая копия —
    та самая, что разойдётся при починке S-35."""
    from aocg_security.middleware import AOCGSecurityMiddleware

    monkeypatch.setattr(
        AOCGSecurityMiddleware, "_client_ip", staticmethod(lambda request: "ПОДМЕНА")
    )
    assert ик._адрес(object()) == "ПОДМЕНА"
