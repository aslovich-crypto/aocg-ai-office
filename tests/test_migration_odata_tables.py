# -*- coding: utf-8 -*-
"""DDL таблиц обмена с 1С не разойдётся с `init_db` (1C-21, заход ②).

⚠️ ЗАЧЕМ ЭТОТ СТОРОЖ, ЕСЛИ РЕЛЬСЫ ВАЛИДАЦИИ ЗЕЛЁНЫЕ. Рельсы создают
таблицы СВОИМ списком внутри своей транзакции — и прошли бы успешно, даже
если бы в `init_db` этого блока не было ВООБЩЕ. Зелёная валидация сама
по себе не доказывает, что миграция уедет на прод. Доказывает это только
сверка двух мест, и она здесь. Приём тот же, что у ключей интеграции.

⚠️ КОММЕНТАРИИ SQL СРЕЗАЮТСЯ ПЕРЕД СВЕРКОЙ: внутри `CREATE TABLE`
в `init_db` стоят пояснения, которых в рельсах нет. Сторож, сверяющий
сырой текст, краснел бы вечно и на верном коде.
"""

import importlib.util
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]


def _модуль_валидатора():
    спец = importlib.util.spec_from_file_location(
        "валидатор_1с", КОРЕНЬ / "scripts/validate_odata_tables.py"
    )
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def _без_комментариев_sql(с: str) -> str:
    return re.sub(r"(?m)--.*$", " ", с)


def _схлопнуть(с: str) -> str:
    return re.sub(r"\s+", " ", _без_комментариев_sql(с)).strip().rstrip(";")


def _исходник() -> str:
    return (КОРЕНЬ / "app/database.py").read_text(encoding="utf-8")


def test_каждая_команда_миграции_есть_в_init_db():
    """Строки рельсов обязаны ДОСЛОВНО лежать в `init_db`."""
    м = _модуль_валидатора()
    код = _схлопнуть(_исходник())
    assert м.МИГРАЦИЯ, "список МИГРАЦИЯ пуст — проверять нечего"
    for команда in м.МИГРАЦИЯ:
        assert _схлопнуть(команда) in код, (
            "команда есть в рельсах, но её нет в init_db:\n%s" % команда.strip()[:200]
        )


def test_обратный_ddl_снимает_всё_созданное():
    """⚠️ ОБРАТНЫЙ DDL, ЗАБЫВШИЙ ИНДЕКС, ОСТАВЛЯЕТ ЗА СОБОЙ МУСОР, который
    при повторном накате даст конфликт имён — и разбираться с ним будут
    на проде."""
    м = _модуль_валидатора()
    откат = " ".join(м.ОБРАТНЫЙ_DDL).lower()
    for таблица in м.ТАБЛИЦЫ:
        assert "drop table if exists %s" % таблица in откат, (
            "обратный DDL не снимает таблицу %s" % таблица
        )
    for индекс in м.ОЖИДАЕМЫЕ_ИНДЕКСЫ:
        assert индекс.lower() in откат, "обратный DDL не снимает индекс %s" % индекс
    # Обратный DDL объявлен и в самом `init_db` — как точка отката рядом с кодом.
    исходник = _исходник()
    for таблица in м.ТАБЛИЦЫ:
        assert "DROP TABLE IF EXISTS %s" % таблица in исходник, (
            "в init_db не названа точка отката для %s" % таблица
        )


def test_ожидаемый_состав_совпадает_с_ddl_построчно():
    """Список ожидаемых колонок — слепок ТОГО ЖЕ DDL, а не вторая правда.

    Разойдись они — валидатор проверял бы состав, которого не создаёт.
    """
    м = _модуль_валидатора()
    for таблица, колонки in м.ОЖИДАЕМЫЕ_КОЛОНКИ.items():
        создание = next(
            к for к in м.МИГРАЦИЯ if "CREATE TABLE IF NOT EXISTS %s" % таблица in к
        )
        тело = _схлопнуть(создание)
        # ⚠️ КОЛОНКА, ДОБАВЛЕННАЯ ОТДЕЛЬНЫМ ALTER, ТОЖЕ «ЕСТЬ В DDL» (CAT-FOOD ②,
        # 21.09.2026). Именно так и велит 13а.24: поле существующей таблицы —
        # только отдельным ALTER, никогда строкой внутри CREATE, который на
        # проде не выполнится. Прежняя редакция сторожа искала колонку ТОЛЬКО
        # в тексте CREATE — то есть наказывала верный путь и не отличала бы
        # «поле есть в CREATE и потому есть на проде» от «поле есть в CREATE
        # и потому его на проде НЕТ».
        добавления = " ".join(
            _схлопнуть(к)
            for к in м.МИГРАЦИЯ
            if re.match(r"\s*ALTER TABLE %s\s+ADD COLUMN" % re.escape(таблица), к)
        )
        for колонка in колонки:
            в_создании = re.search(r"[(,]\s*%s\s" % re.escape(колонка), тело)
            в_добавлении = re.search(
                r"ADD COLUMN IF NOT EXISTS %s\s" % re.escape(колонка), добавления
            )
            assert в_создании or в_добавлении, (
                "колонка %s ожидается, но её нет в DDL таблицы %s" % (колонка, таблица)
            )


def test_в_валидации_нет_ни_одного_commit():
    """⚠️ ГЛАВНОЕ ТРЕБОВАНИЕ 13а.4: валидация ничего не оставляет за собой.

    Проверяется и питон рельсов, и текст, который они печатают для бастиона:
    один COMMIT в печатном SQL превратил бы проверку в тихую миграцию.
    """
    м = _модуль_валидатора()
    исходник = (КОРЕНЬ / "scripts/validate_odata_tables.py").read_text(encoding="utf-8")
    # ⚠️ ИЩЕМ КОМАНДУ, А НЕ СЛОВО. Первая редакция этого теста искала «COMMIT»
    # по всему файлу и краснела на СОБСТВЕННОЙ докстроке «закрепляющей команды
    # здесь нет ни одной» — сторож ловил объяснение вместо кода.
    команды = re.findall(r"""["']\s*COMMIT\b""", исходник, re.I)
    assert not команды, "в рельсах появилось закрепление: %s" % команды
    for список in (м.МИГРАЦИЯ, м.ОБРАТНЫЙ_DDL):
        for команда in список:
            assert "commit" not in команда.lower(), (
                "COMMIT внутри DDL: %s" % команда[:80]
            )
    assert "rollback" in исходник.lower(), "отката нет вовсе"


def test_печатный_sql_для_бастиона_содержит_откат_и_двойной_прогон(capsys):
    """Бастион получает ТЕКСТ — и в нём обязаны быть обе проверки:
    идемпотентность (DDL дважды) и откат."""
    м = _модуль_валидатора()
    м.напечатать_sql()
    напечатано = capsys.readouterr().out
    assert напечатано.count("CREATE TABLE IF NOT EXISTS org_category_map") == 2, (
        "DDL напечатан один раз — идемпотентность не проверяется"
    )
    assert напечатано.strip().splitlines()[-3].strip().startswith("ROLLBACK") or (
        "ROLLBACK;" in напечатано
    ), "в печатном SQL нет отката"
    assert "COMMIT;" not in напечатано, "в печатном SQL есть закрепление"


