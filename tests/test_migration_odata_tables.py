def test_одна_категория_одно_правило_внутри_организации():
    """Два правила на одну строку расхода означают, что проводка зависит
    от порядка выборки, а такой дефект не ловится ничем.

    ⚠️ ИЩЕМ СОЗДАНИЕ, А НЕ ПЕРВОЕ УПОМИНАНИЕ. После переименования таблицы
    (1C-22) первым в списке идёт `ALTER INDEX … RENAME TO`, и прежняя
    редакция теста проверяла на уникальность ПЕРЕИМЕНОВАНИЕ."""
    м = _модуль_валидатора()
    индекс = next(
        к
        for к in м.МИГРАЦИЯ
        if "CREATE UNIQUE INDEX IF NOT EXISTS org_category_map_unique" in к
    )
    схлопнутый = _схлопнуть(индекс).replace(" ", "")
    assert "UNIQUEINDEX" in схлопнутый.upper().replace(" ", "")
    assert "(org_id,category_id)" in схлопнутый


