"""Сторож общего сборщика SET (T38).

ПОЧЕМУ ЭТОТ ТЕСТ ВАЖНЕЕ САМОГО РЕФАКТОРА. Инъекции в четырёх местах, где
сборка была написана своими словами, не было: имена колонок всюду приходили
из белых списков (проверено по коду, S-22). Но держалось это на том, что
в каждом месте кто-то не забыл фильтр. Здесь проверяется, что теперь имя
вне белого списка НЕ МОЖЕТ доехать до текста запроса — функция откажется
его собирать, а не «просто не должна получить».

Проверяются обе стороны: и что чужое имя отвергнуто, и что своё собрано
правильно (иначе сборщик, отвергающий всё, читался бы как успешный).
"""

import pytest

from app.routers.categories import ПОЛЯ_КАТЕГОРИИ
from app.routers.receipts import ПОЛЯ_ЧЕКА
from app.routers.users import СВОЙ_ПРОФИЛЬ, UPDATABLE
from app.sql_builder import ИМЯ_КОЛОНКИ, собрать_set


def test_собирает_по_порядку_с_первого_плейсхолдера():
    sets, значения = собрать_set({"payment": "карта", "org": "ООО Ромашка"}, ПОЛЯ_ЧЕКА)
    assert sets == "payment=$1, org=$2"
    assert значения == ["карта", "ООО Ромашка"]


def test_пустой_словарь_не_ошибка():
    """Решение «нечего менять» принимает вызывающий: у каждого оно своё."""
    assert собрать_set({}, ПОЛЯ_ЧЕКА) == ("", [])


def test_чужая_колонка_отвергнута():
    with pytest.raises(ValueError, match="не в белом списке"):
        собрать_set({"role": "admin"}, СВОЙ_ПРОФИЛЬ)


def test_инъекция_в_имени_колонки_отвергнута():
    """Худший случай: имя пришло бы из тела запроса вместе с хвостом SQL."""
    with pytest.raises(ValueError):
        собрать_set({"name = 'x', role='admin' --": "что угодно"}, ПОЛЯ_КАТЕГОРИИ)


def test_белый_список_с_негодным_именем_тоже_отвергается():
    """Вторая линия: если в сам белый список попадёт мусор, сборка встанет."""
    with pytest.raises(ValueError, match="не похожа на имя колонки"):
        собрать_set({"drop table": 1}, ("drop table",))


@pytest.mark.parametrize(
    "белый_список",
    [ПОЛЯ_ЧЕКА, ПОЛЯ_КАТЕГОРИИ, СВОЙ_ПРОФИЛЬ, UPDATABLE],
    ids=["чеки", "категории", "свой профиль", "сотрудник"],
)
def test_все_белые_списки_состоят_из_имён_колонок(белый_список):
    for имя in белый_список:
        assert ИМЯ_КОЛОНКИ.match(имя), f"{имя!r} не похоже на имя колонки"


def test_роль_не_меняется_через_свой_профиль():
    """Прямая проверка политики, а не только формата: своё повышение до admin
    должно быть невозможно на уровне сборки запроса."""
    assert "role" not in СВОЙ_ПРОФИЛЬ
    assert "role" not in UPDATABLE
