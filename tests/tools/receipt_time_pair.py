#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПАРНЫЙ СТОРОЖ «время чека»: тип колонки и компенсация во фронте (строка 20).

⚠️ ЗАЧЕМ. Правка строки 20 состоит из ДВУХ ПОЛОВИН В РАЗНЫХ РЕПОЗИТОРИЯХ:
    ① `receipts.datetime` переводится в TIMESTAMP WITHOUT TIME ZONE (бэкенд);
    ② из `fmtDateTime` снимается компенсация `timeZone: "UTC"` (фронт).
Порядок неразделим, и **каждая половина по отдельности ХУЖЕ, чем ни одной** —
замер Node при поясе Europe/Moscow, чек «2026-08-11T21:34:00»:
    обе половины           → 21:34   верно
    только ① (тип сменён)  → 18:34   экран уехал на три часа назад
    только ② (снята комп.) → 00:34   экран уехал на три часа вперёд, и на сутки
Обе половины молчат: ни ошибки, ни предупреждения, только неверное время
на экране, где его никто не сверяет с бумажным чеком.

⚠️ ПОЧЕМУ СТОРОЖ ЖИВЁТ В БЭКЕНДЕ, А НЕ ВО ФРОНТЕ. Инвариант связывает DDL
и разметку; DDL знает только бэкенд. Так же устроен `dict_stamp.py` — он
тоже читает фронт через `FRONT_SRC`, и это уже проверенный стык.

⚠️ ТРЕТЬЕ МЕСТО, НАЙДЕННОЕ ПО ДОРОГЕ. Кроме `fmtDateTime` то же решение
принимает имя файла снимка (`ReceiptDetailModal.jsx`): оно собирало дату
через `getUTC*`. Пока метка лгала, это было верно; после смены типа стало
враньём на ночных чеках (замер: «2026-08-12T00:30:00» → `11-08-2026`).
Мест, значит, ТРИ, и все три обязаны двигаться разом.

⚠️ КОММЕНТАРИИ СРЕЗАЮТСЯ ПЕРЕД ПОИСКОМ, И ЭТО НЕ МЕЛОЧЬ. В обоих файлах
слова `timeZone: "UTC"` и `getUTC` стоят в объяснениях — прибор, ищущий
по сырому тексту, краснел бы вечно и на верном коде тоже. Класс известный:
«прибор отвечает про свой стык, а не про цель».

ЗАПУСК:
    ./venv/bin/python tests/tools/receipt_time_pair.py
    ./venv/bin/python tests/tools/receipt_time_pair.py --selfcheck

КОДЫ ВОЗВРАТА: 0 — половины согласованы · 1 — РАСХОЖДЕНИЕ ·
               2 — фронт недоступен, НЕ МЕРЕНО (не путать с «ок»).
"""

import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
БАЗА = os.path.join(КОРЕНЬ, "app", "database.py")
ФРОНТ_SRC = os.environ.get(
    "FRONT_SRC",
    os.path.normpath(os.path.join(КОРЕНЬ, "..", "aocg-ai-office-web", "src")),
)
ФОРМАТ = os.path.join(ФРОНТ_SRC, "lib", "format.js")
СНИМОК = os.path.join(ФРОНТ_SRC, "components", "ReceiptDetailModal.jsx")


def без_комментариев(текст: str) -> str:
    """Срезает // и /* */. Строковые литералы не трогаем намеренно: искомое
    в них не встречается, а честный разбор JS ради этого не окупается."""
    текст = re.sub(r"/\*[\s\S]*?\*/", " ", текст)
    return re.sub(r"(?m)//.*$", " ", текст)


def тип_без_зоны(текст_базы: str) -> bool:
    """Есть ли в init_db перевод колонки в тип БЕЗ зоны."""
    код = re.sub(r"(?m)^\s*#.*$", " ", текст_базы)
    return bool(
        re.search(
            r"ALTER\s+COLUMN\s+datetime\s+TYPE\s+TIMESTAMP\s+WITHOUT\s+TIME\s+ZONE",
            код,
            re.I | re.S,
        )
    )


def компенсация_во_фронте(текст_формата: str) -> bool:
    """Стоит ли `timeZone: "UTC"` в КОДЕ format.js (а не в объяснении)."""
    return bool(
        re.search(r"""timeZone\s*:\s*["']UTC["']""", без_комментариев(текст_формата))
    )


def снимок_читает_utc(текст_снимка: str) -> bool:
    """Собирает ли имя файла дату UTC-частями."""
    return bool(re.search(r"\.getUTC[A-Z]", без_комментариев(текст_снимка)))


def вердикт(без_зоны: bool, компенсация: bool, снимок_utc: bool) -> list[str]:
    """Список бед. Пусто — половины согласованы."""
    беды = []
    if без_зоны and компенсация:
        беды.append(
            'тип сменён, а компенсация timeZone:"UTC" осталась в fmtDateTime — '
            "экран уедет НАЗАД (21:34 покажется как 18:34)"
        )
    if not без_зоны and not компенсация:
        беды.append(
            "компенсация снята, а тип колонки прежний (с зоной) — "
            "экран уедет ВПЕРЁД и на сутки (21:34 покажется как 00:34 назавтра)"
        )
    if без_зоны and снимок_utc:
        беды.append(
            "тип сменён, а имя файла снимка всё ещё собирается getUTC* — "
            "ночные чеки получат дату на сутки назад"
        )
    if not без_зоны and not снимок_utc:
        беды.append(
            "имя файла снимка переведено на местные части раньше смены типа — "
            "ночные чеки получат дату на сутки вперёд"
        )
    return беды


ОБРАЗЦЫ_ЧТЕНИЯ = [
    # (что читаем, текст, ожидание) — ловушка первым номером: в объяснении
    # искомое есть, в коде нет.
    (
        "компенсация",
        '// было timeZone: "UTC", снято 11.09\nreturn d.toLocaleString("ru-RU", {day:"2-digit"});',
        False,
    ),
    ("компенсация", 'return d.toLocaleString("ru-RU", {timeZone: "UTC"});', True),
    ("снимок", "// тут стояло d.getUTCDate()\nconst x = d.getDate();", False),
    ("снимок", "const x = d.getUTCDate();", True),
    (
        "тип",
        "# ALTER COLUMN datetime TYPE TIMESTAMP WITHOUT TIME ZONE в комментарии",
        False,
    ),
    (
        "тип",
        "await conn.execute('ALTER TABLE receipts ALTER COLUMN datetime "
        "TYPE TIMESTAMP WITHOUT TIME ZONE USING datetime AT TIME ZONE ''UTC''')",
        True,
    ),
]


def самопроверка() -> int:
    print("САМОПРОВЕРКА ПАРНОГО СТОРОЖА «время чека»")
    беды = []

    читатели = {
        "компенсация": компенсация_во_фронте,
        "снимок": снимок_читает_utc,
        "тип": тип_без_зоны,
    }
    for что, текст, ждём in ОБРАЗЦЫ_ЧТЕНИЯ:
        было = читатели[что](текст)
        знак = "✓" if было == ждём else "✗"
        print(f"  {знак} чтение «{что}» на образце: {было} (ждали {ждём})")
        if было != ждём:
            беды.append(f"читатель «{что}» ошибся на образце")

    # Четыре сочетания: согласованные два и рассогласованные два.
    таблица = [
        ((False, True, True), 0, "до правки: зона есть, компенсация есть"),
        ((True, False, False), 0, "после правки: зоны нет, компенсации нет"),
        ((True, True, True), 2, "половина ①: тип сменён, фронт не тронут"),
        ((False, False, False), 2, "половина ②: фронт снят, тип прежний"),
    ]
    for (бз, к, с), сколько, метка in таблица:
        н = len(вердикт(бз, к, с))
        знак = "✓" if н == сколько else "✗"
        print(f"  {знак} вердикт на «{метка}»: бед {н} (ждали {сколько})")
        if н != сколько:
            беды.append(f"вердикт неверен на «{метка}»")

    if беды:
        print(f"ИТОГ САМОПРОВЕРКИ: ⚠️ АЛГОРИТМ СЛОМАН ({len(беды)})")
        for б in беды:
            print(f"   · {б}")
        return 1
    print("ИТОГ САМОПРОВЕРКИ: алгоритм верен")
    return 0


def main() -> int:
    if "--selfcheck" in sys.argv:
        return самопроверка()

    print("ПАРНЫЙ СТОРОЖ «время чека»: тип колонки ↔ компенсация во фронте")
    без_зоны = тип_без_зоны(open(БАЗА, encoding="utf-8").read())
    print(f"  бэкенд:  колонка {'БЕЗ зоны' if без_зоны else 'С зоной'}")

    if not (os.path.exists(ФОРМАТ) and os.path.exists(СНИМОК)):
        print(f"  фронт:   НЕДОСТУПЕН ({ФРОНТ_SRC})")
        print("ИТОГ: ⚠ НЕ МЕРЕНО — пара не проверялась (это не «ок»)")
        return 2

    компенсация = компенсация_во_фронте(open(ФОРМАТ, encoding="utf-8").read())
    снимок_utc = снимок_читает_utc(open(СНИМОК, encoding="utf-8").read())
    print(f"  фронт:   компенсация {'ЕСТЬ' if компенсация else 'снята'}")
    print(f"  снимок:  имя файла {'по UTC' if снимок_utc else 'по местным'}")

    беды = вердикт(без_зоны, компенсация, снимок_utc)
    if беды:
        print(f"ИТОГ: ⚠️ ПОЛОВИНЫ РАЗОШЛИСЬ ({len(беды)})")
        for б in беды:
            print(f"   ✗ {б}")
        print("   Порядок неразделим: сначала тип, потом компенсация, одной работой.")
        return 1
    print("ИТОГ: половины согласованы")
    return 0


if __name__ == "__main__":
    sys.exit(main())
