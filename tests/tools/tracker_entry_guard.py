def проверить(текст, живые, история, выведенные):
    """([(номер строки файла, ID, что не так)], задач, новых)."""
    беды = []
    строки = текст.split("\n")
    задачи = tracker_guard.строки_задач(текст)
    номера = [з[1] for з in задачи]
    for ид in sorted({и for и in номера if номера.count(и) > 1}):
        н = next(з[0] for з in задачи if з[1] == ид)
        беды.append((н, ид, ДВАЖДЫ))
    новых = 0
    for н, ид, *_ in задачи:
        if ид in живые and ид not in выведенные:
            continue
        новых += 1
        if ид in выведенные:
            беды.append((н, ид, ВЫВЕДЕН))
        elif ид in история:
            беды.append((н, ид, БЫЛ_В_ИСТОРИИ))
        прим = примечание(строки[н - 1])
        if прим is None:
            беды.append((н, ид, "ячеек не семь — «Примечание» не найдено"))
        elif not any(календарная for _, календарная in audit_stamps.решения(прим)):
            беды.append((н, ид, БЕЗ_РЕШЕНИЯ))
    for ид in sorted(живые - set(номера) - выведенные):
        беды.append((0, ид, ИСЧЕЗЛА))
    return беды, len(задачи), новых


def проверить_черновики(текст):
    """⑦⑧⑨ (T199 ②): ([(номер строки файла, ID, что не так)], записей в разделе)."""
    беды = []
    строки = текст.split("\n")
    # ⑦ знак черновика в «Задаче» у строки таблицы
    for н, ид, *_ in tracker_guard.строки_задач(текст):
        я = РАЗДЕЛИТЕЛЬ.split(строки[н - 1])
        if len(я) == 9 and ЗНАК_ЧЕРНОВИКА in я[2]:
            беды.append((н, ид, ЧЕРНОВИК_В_ТАБЛИЦЕ))
    # ⑧ раздел черновиков: есть, и строк таблицы в нём нет
    начало = next(
        (i for i, с in enumerate(строки) if с.startswith(РАЗДЕЛ_ЧЕРНОВИКОВ)), None
    )
    записей = 0
    if начало is None:
        беды.append((0, "—", НЕТ_РАЗДЕЛА))
    else:
        for i in range(начало + 1, len(строки)):
            с = строки[i]
            if с.startswith("## "):
                break
            if с.lstrip().startswith("|"):
                беды.append((i + 1, "—", НОМЕР_У_ЧЕРНОВИКА))
            elif ЗАПИСЬ_ЧЕРНОВИКА.match(с):
                записей += 1
    # ⑨ черновик в очереди — по первой строке И продолжению пункта: здесь
    # продолжение не довод, а место, куда черновик тоже можно вписать.
    for номер, первая, продолжение in tracker_html.пункты_блока(текст):
        if ПРИЗНАК_В_ОЧЕРЕДИ.search(первая + "\n" + продолжение):
            беды.append((0, "пункт %s" % номер, ЧЕРНОВИК_В_ОЧЕРЕДИ))
    return беды, записей


def проверить_метки(текст, закрытые_до):
    """⑩⑪⑫ (T200 ①): ([(номер строки файла, ID, что не так)], счёт).

    ⑩ у строки нет метки дорожки первым знаком «Задачи». Не проверяются ТОЛЬКО
       строки из замороженного списка закрытых до дорожек, пока они ✅ (В4):
       переоткрытая строка метку обязана нести, закрытая после — тоже;
    ⑪ после метки стоит вторая — дорожка у строки одна;
    ⑫ у записи черновика нет метки сразу после даты.
    Счёт — сколько чего ПРОВЕРЕНО: зелёный прогон без охвата не результат (T11)."""
    беды = []
    счёт = {м: 0 for м in МЕТКИ}
    счёт.update(строк=0, пропущено_закрытых=0, черновиков=0)
    строки = текст.split("\n")
    for н, ид, _, ст, _, _ in tracker_guard.строки_задач(текст):
        if ст == "✅" and ид in закрытые_до:
            счёт["пропущено_закрытых"] += 1
            continue
        счёт["строк"] += 1
        я = РАЗДЕЛИТЕЛЬ.split(строки[н - 1])
        задача = я[2].replace(ВАРИАНТ, "") if len(я) == 9 else ""
        м = МЕТКА_В_ЗАДАЧЕ.match(задача)
        if not м:
            беды.append((н, ид, БЕЗ_МЕТКИ))
            continue
        счёт[м.group(1)] += 1
        if задача[м.end() :].lstrip().startswith(МЕТКИ):
            беды.append((н, ид, ДВЕ_МЕТКИ))
    начало = next(
        (i for i, с in enumerate(строки) if с.startswith(РАЗДЕЛ_ЧЕРНОВИКОВ)), None
    )
    if начало is not None:
        for i in range(начало + 1, len(строки)):
            с = строки[i].replace(ВАРИАНТ, "")
            if с.startswith("## "):
                break
            if not ЗАПИСЬ_ЧЕРНОВИКА.match(с):
                continue
            счёт["черновиков"] += 1
            м = МЕТКА_У_ЧЕРНОВИКА.match(с)
            if not м:
                беды.append((i + 1, "черновик", ЧЕРНОВИК_БЕЗ_МЕТКИ))
            elif с[м.end() :].lstrip().startswith(МЕТКИ):
                беды.append((i + 1, "черновик", ДВЕ_МЕТКИ))
    return беды, счёт


