# ⚠️ СУММЫ ЗАПИСАНЫ ЗДЕСЬ, А НЕ РЯДОМ СО СПИСКАМИ: подменить список и его сумму
# одной правкой одного файла нельзя. Выведенных здесь нет — список растёт законно.
СУММЫ = {
    "живые": "3adc4d3209d2690c8630e8ecca9aebbe9fc1c0eea02bf34932eaacc2e03808a7",
    "история": "c6d58e8d5e3c5546a26c75ecfabca1255787004097ce10342c93d23ff249ec3a",
}
РАЗДЕЛИТЕЛЬ = re.compile(r"(?<!\\)\|")

БЕЗ_РЕШЕНИЯ = "строка без решения владельца: нет штампа решения в «Примечании»"
БЫЛ_В_ИСТОРИИ = "номер уже был в истории трекера — повторно не выдаётся"
ВЫВЕДЕН = "номер выведен из оборота — новой строке не выдаётся"
ИСЧЕЗЛА = "строка исчезла без записи в списке выведенных"
ДВАЖДЫ = "номер стоит в двух строках"


КОММЕНТАРИЙ = "# "


def прочитать_список(путь):
    """Номера из списка: первая часть строки до « · »; пустые строки и комментарии
    пропускаются.

    ⚠️ КОММЕНТАРИЙ — РЕШЁТКА И ПРОБЕЛ, А НЕ ПРОСТО РЕШЁТКА. Номер `#14` — законная
    форма ID (`tracker_id_forms.py`), и первая редакция принимала его строку за
    комментарий: список читался как 434 живых вместо 435, и сторож объявлял `#14`
    новой строкой без решения. Поймано первым прогоном на трекере 22.09.2026;
    пример с известным ответом — в самопроверке."""
    номера = set()
    with open(путь, encoding="utf-8") as ф:
        for с in ф:
            с = с.strip()
            if с and not с.startswith(КОММЕНТАРИЙ):
                номера.add(с.split(" · ")[0].strip())
    return номера


def сумма(путь):
    with open(путь, "rb") as ф:
        return hashlib.sha256(ф.read()).hexdigest()


def примечание(строка):
    я = РАЗДЕЛИТЕЛЬ.split(строка)
    return я[7] if len(я) == 9 else None


def проверить(текст, живые, история, выведенные):
    """([(номер строки файла, ID, что не так)], задач, новых)."""
    беды = []
    строки = текст.split("\n")
    задачи = tracker_guard.строки_задач(текст)
    номера = [з[1] for з in задачи]
    for ид in sorted({и for и in номера if номера.count(и) > 1}):
        н = next(з[0] for з in задачи if з[1] == ид)
        беды.append((н, ид, ДВАЖДЫ))
    новых = 0
    for н, ид, *_ in задачи:
        if ид in живые and ид not in выведенные:
            continue
        новых += 1
        if ид in выведенные:
            беды.append((н, ид, ВЫВЕДЕН))
        elif ид in история:
            беды.append((н, ид, БЫЛ_В_ИСТОРИИ))
        прим = примечание(строки[н - 1])
        if прим is None:
            беды.append((н, ид, "ячеек не семь — «Примечание» не найдено"))
        elif not any(календарная for _, календарная in audit_stamps.решения(прим)):
            беды.append((н, ид, БЕЗ_РЕШЕНИЯ))
    for ид in sorted(живые - set(номера) - выведенные):
        беды.append((0, ид, ИСЧЕЗЛА))
    return беды, len(задачи), новых


# ── САМОПРОВЕРКА: обе половины (T72). Здоровый трекер обязан пройти МОЛЧА,
# каждый дырявый — покраснеть СВОИМИ словами. Без первой половины «нашёл
# известное» ничего не говорит о ложных тревогах, а они и убивают прибор.
ШАПКА = "| ID | Задача | Пр. | Статус | План (класс) | Факт | Примечание |\n| :- | :- | :-: | :-: | :- | :- | :- |\n"
СТАР_1 = "| A-1 | старая | 🟡 | ⬜ | — | — | без штампа — законно |\n"
СТАР_2 = "| A-2 | старая | 🟡 | ✅ | — | ⏱ 5 м | без штампа — законно |\n"
НОВАЯ = "| N-1 | новая | 🟡 | ⬜ | — | — | ⟦РЕШЕНИЕ · 2026-09-22⟧ заведена по слову владельца |\n"
КОНТР_ЖИВЫЕ = {"A-1", "A-2", "A-3"}
КОНТР_ИСТОРИЯ = КОНТР_ЖИВЫЕ | {"OLD-9"}
КОНТР_ВЫВЕДЕННЫЕ = {"A-3"}
ДЫРЯВЫЕ = [
    (
        "новая без штампа",
        СТАР_1 + СТАР_2 + НОВАЯ.replace("⟦РЕШЕНИЕ · 2026-09-22⟧ ", ""),
        БЕЗ_РЕШЕНИЯ,
    ),
    (
        "некалендарная дата",
        СТАР_1 + СТАР_2 + НОВАЯ.replace("2026-09-22", "2026-13-45"),
        БЕЗ_РЕШЕНИЯ,
    ),
    (
        "номер из истории",
        СТАР_1 + СТАР_2 + НОВАЯ.replace("N-1", "OLD-9"),
        БЫЛ_В_ИСТОРИИ,
    ),
    ("номер выведен", СТАР_1 + СТАР_2 + НОВАЯ.replace("N-1", "A-3"), ВЫВЕДЕН),
    ("старая исчезла", СТАР_1 + НОВАЯ, ИСЧЕЗЛА),
    ("номер дважды", СТАР_1 + СТАР_1 + СТАР_2 + НОВАЯ, ДВАЖДЫ),
]


def самопроверка():
    print("САМОПРОВЕРКА ВХОДА")
    плохо = 0
    беды, задач, новых = проверить(
        ШАПКА + СТАР_1 + СТАР_2 + НОВАЯ, КОНТР_ЖИВЫЕ, КОНТР_ИСТОРИЯ, КОНТР_ВЫВЕДЕННЫЕ
    )
    если = not беды and задач == 3 and новых == 1
    print(
        f"  {'✓' if если else '✗'} здоровый трекер: задач {задач}, новых {новых}, нарушений {len(беды)}"
    )
    плохо += 0 if если else 1
    for имя, тело, ждём in ДЫРЯВЫЕ:
        беды, _, _ = проверить(
            ШАПКА + тело, КОНТР_ЖИВЫЕ, КОНТР_ИСТОРИЯ, КОНТР_ВЫВЕДЕННЫЕ
        )
        если = any(что == ждём for _, _, что in беды)
        print(f"  {'✓' if если else '✗'} {имя}: {'поймано' if если else 'ПРОПУЩЕНО'}")
        плохо += 0 if если else 1
    # ⚠️ ЧТЕНИЕ СПИСКА — ТОЖЕ РАЗБОР, И ОН ПРОВЕРЯЕТСЯ ИЗВЕСТНЫМ ОТВЕТОМ (T30):
    # номер с решёткой обязан прочитаться номером, комментарий — пропуститься.
    with tempfile.NamedTemporaryFile(
        "w", suffix=".txt", delete=False, encoding="utf-8"
    ) as ф:
        ф.write("# комментарий\n#7\nB-2 · 22.09.2026 · в черновики\n\n")
    прочитано = прочитать_список(ф.name)
    os.unlink(ф.name)
    если = прочитано == {"#7", "B-2"}
    print(
        f"  {'✓' if если else '✗'} чтение списка: «#7» — номер, «# …» — комментарий ({sorted(прочитано)})"
    )
    плохо += 0 if если else 1
    print(
        "  ИТОГ: самопроверка пройдена" if not плохо else f"  ИТОГ: расхождений {плохо}"
    )
    return плохо


def main():
    аргументы = sys.argv[1:]
    if самопроверка():
        print("\n⚠️ СТОРОЖ ВХОДА НЕ ПРОШЁЛ САМОПРОВЕРКУ — трекер не смотрим.")
        return 2
    if "--selfcheck" in аргументы:
        return 0
    путь = next((а for а in аргументы if not а.startswith("--")), ТРЕКЕР)
    подмены = dict(
        а[2:].split("=", 1) for а in аргументы if а.startswith("--") and "=" in а
    )

    беды_списков, списки = [], {}
    for имя, по_умолчанию in ФАЙЛЫ.items():
        файл = подмены.get(имя, по_умолчанию)
        try:
            списки[имя] = прочитать_список(файл)
        except OSError as ош:
            print(f"⚠️ СПИСОК «{имя}» НЕ ПРОЧИТАН: {ош}")
            return 2
        if имя in подмены:
            print(f"  ⚠️ список «{имя}» подменён флагом ({файл}) — сумма НЕ сверяется")
        elif имя in СУММЫ and сумма(файл) != СУММЫ[имя]:
            беды_списков.append(
                f"список «{имя}» ({os.path.basename(файл)}) изменён: сумма не та"
                f" — {сумма(файл)[:12]}… вместо {СУММЫ[имя][:12]}…"
            )

    with open(путь, encoding="utf-8") as ф:
        текст = ф.read()
    беды, задач, новых = проверить(
        текст, списки["живые"], списки["история"], списки["выведенные"]
    )

    print(f"\nВХОД В ТРЕКЕР (T199 ①) · {путь}")
    print(f"  строк-задач в файле           : {задач}")
    print(
        f"  списки: живых {len(списки['живые'])} · в истории {len(списки['история'])}"
        f" · выведенных после заморозки {len(списки['выведенные'])}"
    )
    print(f"  новых строк после заморозки   : {новых}")
    найдено = len(беды_списков) + len(беды)
    if not найдено:
        print("  ✓ нарушений 0")
        return 0
    print(
        f"\n🟥🟥🟥 ВХОД В ТРЕКЕР: НАРУШЕНИЙ {найдено} — СТРОКА БЕЗ РЕШЕНИЯ ВЛАДЕЛЬЦА НЕ ЗАВОДИТСЯ 🟥🟥🟥"
    )
    print(
        "   нет решения → находка одной фразой в «🔎 ЖУРНАЛ УЛИК»; есть → штамп решения в «Примечании»"
    )
    напечатано = 0
    for что in беды_списков:
        print(f"   {что}")
        напечатано += 1
    for н, ид, что in беды:
        print(f"   {путь}:{н or '—'}  {ид:<14} {что}")
        напечатано += 1
    # НАЙДЕНО против НАПЕЧАТАНО (T22): находка, не дошедшая до вывода, — не находка.
    if напечатано != найдено:
        print(f"⚠️ НАЙДЕНО {найдено}, НАПЕЧАТАНО {напечатано} — вывод потерял находки")
        return 2
    return 1


if __name__ == "__main__":
    sys.exit(main())
