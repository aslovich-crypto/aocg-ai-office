#!/usr/bin/env python3
"""МУТАЦИИ СТОРОЖА прод-БД — доказательство того, что матрица форм работает.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. `tests/tools/hook_probe.py` отвечает на вопрос «сходится
ли поведение хука с ожидаемым». Он НЕ отвечает на вопрос «а заметил бы он,
если бы хук сломали». Матрица без мутаций — это список, а не проверка:
зелёный прогон одинаково выглядит и когда всё цело, и когда проверять было
нечего. Здесь по очереди ломается КАЖДАЯ заявленная способность хука,
и требуется, чтобы покраснели ровно те случаи, которые за неё отвечают.

ЗАПУСК (в pytest НЕ входит — правит файл хука и возвращает его на место):
    ./venv/bin/python tests/tools/hook_mutations.py
    ./venv/bin/python tests/tools/hook_mutations.py --verbose

БАЗУ НЕ ТРОГАЕТ. Мутации применяются к `.claude/hooks/block_prod_db.py`,
файл восстанавливается в `finally` при любом исходе, включая Ctrl-C.

ПРАВИЛО, РАДИ КОТОРОГО ВСЁ НАПИСАНО (T11): мутация засчитывается, только
если она РЕАЛЬНО применилась. Скрипт замены может не найти цель — шаблон
разошёлся с кодом после чужой правки — и молча ничего не сделать. Тогда
«сторож не поймал» читается как поломка сторожа, хотя ломать было нечего.
Поэтому каждая мутация проверяет, что цель существует и текст изменился,
и отдельно проверяется, что после восстановления матрица снова зелёная.

ЕСЛИ МУТАЦИЯ ПЕРЕСТАЛА НАХОДИТЬ ЦЕЛЬ — это не повод её удалять. Значит
код хука изменился: перечитать способность, обновить шаблон, убедиться,
что краснеет то же самое.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ХУК = os.path.join(КОРЕНЬ, ".claude", "hooks", "block_prod_db.py")
ЗАМЕР = os.path.join(КОРЕНЬ, "tests", "tools", "hook_probe.py")
PYTHON = sys.executable

# Глаголы собираются на лету по той же причине, что и в hook_probe.py:
# файл с литералами хук принял бы за нагрузку и заблокировал бы собственный
# запуск. Склейка происходит в python, на выходе — точная строка.
_ОБРЕЗАНИЕ = "TRUN" + "CATE"

# (имя, что ломаем, чем заменяем, какие случаи ОБЯЗАНЫ покраснеть)
МУТАЦИИ = [
    (
        "M1 разбор кавычек: токен с пробелами снова считается командой",
        '        if " " in т or "\\n" in т:\n            continue',
        "        if False:\n            continue",
        {"A15"},
    ),
    (
        "M2 нагрузка: читаем снова только .py и .sql",
        "        if not os.path.isfile(путь) or os.path.getsize(путь) > МАКС_РАЗМЕР_ФАЙЛА:",
        '        if not os.path.isfile(путь) or not путь.endswith((".py", ".sql"))'
        " or os.path.getsize(путь) > МАКС_РАЗМЕР_ФАЙЛА:",
        {"B5", "B6", "B7"},
    ),
    (
        "M3 heredoc: тело больше не забираем",
        "    return cmd, тела",
        "    return cmd, []",
        {"B9"},
    ),
    (
        "M4 локальный хост больше не считается локальным",
        'ЛОКАЛЬНЫЕ_ХОСТЫ = {"localhost", "127.0.0.1", "::1", "0.0.0.0", "host.docker.internal"}',
        "ЛОКАЛЬНЫЕ_ХОСТЫ = set()",
        {"A7"},
    ),
    (
        "M5 недоверенная цель больше не считается боевой",
        '    if исполнитель in ("psql", "dropdb", "sqlite3", "duckdb"):',
        "    if исполнитель in ():",
        {"B11", "B12"},
    ),
    (
        "M6 оговорка для инструментов кода снята",
        "        if any(os.path.basename(т) in ИНСТРУМЕНТЫ_КОДА for т in хвост):\n            continue",
        "        if False:\n            continue",
        {"A14", "A16"},
    ),
    (
        "M7 деструктиву больше не нужен объект (голое DROP)",
        r'    r"(\bDROP\s+(TABLE|INDEX|DATABASE|SCHEMA)\b|\bDELETE\s+FROM\b|\b'
        + _ОБРЕЗАНИЕ
        + r'\b)",',
        r'    r"(\bDROP\b|\bDELETE\s+FROM\b|\b' + _ОБРЕЗАНИЕ + r'\b)",',
        {"A9"},
    ),
]


def прогон() -> set[str]:
    """Коды случаев, которые НЕ сошлись с ожиданием. Пустое множество = зелено."""
    готово = subprocess.run(
        [PYTHON, ЗАМЕР], capture_output=True, text=True, cwd=КОРЕНЬ, timeout=300
    )
    if "ЗАМЕР НЕ ГОДЕН" in готово.stdout:
        return {"<самопроверка замера не прошла>"}
    return set(re.findall(r"^\s+✗ ([AB]\d+)\s", готово.stdout, re.M))


def main() -> int:
    разбор = argparse.ArgumentParser(description="Мутации сторожа прод-БД")
    разбор.add_argument("--verbose", action="store_true", help="печатать шаблоны замен")
    аргументы = разбор.parse_args()

    with open(ХУК, encoding="utf-8") as f:
        оригинал = f.read()

    базовые = прогон()
    if базовые:
        print(
            f"База НЕ зелёная: {sorted(базовые)}. Мутации бессмысленны — сначала матрица."
        )
        return 2
    print(f"База зелёная. Мутаций к прогону: {len(МУТАЦИИ)}")

    провалы = 0
    try:
        for имя, старое, новое, ожидание in МУТАЦИИ:
            if старое not in оригинал:
                print(
                    f"  ✗ {имя}\n      ЦЕЛЬ НЕ НАЙДЕНА — мутация не применилась, "
                    f"проверять было нечего. Код хука изменился: обновить шаблон."
                )
                if аргументы.verbose:
                    print(f"      искали: {старое[:100]!r}")
                провалы += 1
                continue
            изменённый = оригинал.replace(старое, новое, 1)
            if изменённый == оригинал:
                print(f"  ✗ {имя}\n      текст не изменился после замены")
                провалы += 1
                continue

            with open(ХУК, "w", encoding="utf-8") as f:
                f.write(изменённый)
            упало = прогон()

            совпало = упало == ожидание
            провалы += 0 if совпало else 1
            print(f"  {'✓' if совпало else '✗'} {имя}")
            print(f"      ждали красными: {sorted(ожидание)}")
            print(
                f"      покраснели:     "
                f"{sorted(упало) if упало else '— НИЧЕГО (способность не покрыта матрицей)'}"
            )
    finally:
        with open(ХУК, "w", encoding="utf-8") as f:
            f.write(оригинал)

    после = прогон()
    print(f"\nПосле восстановления: расхождений {len(после)} (обязано быть 0)")
    print(
        f"Проверено способностей: {len(МУТАЦИИ)}, провалов: {провалы + (1 if после else 0)}"
    )
    return 1 if (провалы or после) else 0


if __name__ == "__main__":
    sys.exit(main())
