def путь_записи(отн: str) -> str:
    """Абсолютный путь записи белого списка.

    Фронтовые пути начинаются на `src/` и живут в ДРУГОМ репозитории. Без этого
    разбора проверка устаревания молча пропускала бы их: `os.path.exists` от
    корня бэкенда даёт False, а False читался бы как «файла нет, устареванием
    не считаем». То есть половина списка не проверялась бы вовсе.
    """
    if отн.startswith("src/"):
        return os.path.join(ФРОНТ_SRC, отн[4:])
    return os.path.join(КОРЕНЬ, отн)


МИН_ДЛИНА = 4


def словарь() -> tuple[set[str], dict[str, int]]:
    данные = json.load(open(ИСТОЧНИК, encoding="utf-8"))
    виды = set(данные["tax_kinds"])
    группы = {г["name"] for г in данные["groups"]}
    статьи = {с["name"] for г in данные["groups"] for с in г["articles"]}
    все = {и for и in (виды | группы | статьи) if len(и) >= МИН_ДЛИНА}
    return все, {"видов": len(виды), "групп": len(группы), "статей": len(статьи)}


def литералы_файла(путь: str) -> set[str]:
    """Строковые константы python (ast) + литералы внутри SQL-строк.

    Второе — потому что третья сторона словаря живёт именно там: девять видов
    расхода перечислены внутри строки DDL в `CHECK (tax_kind IN (...))`.
    Для ast это одна большая строка, и без разбора её содержимого сторож
    считал бы, что в `app/database.py` словаря нет вовсе.
    """
    найдено = set()
    for узел in ast.walk(ast.parse(open(путь, encoding="utf-8").read())):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            найдено.add(узел.value)
            if re.search(
                r"\b(CHECK|CREATE TABLE|ALTER TABLE|INSERT INTO)\b", узел.value
            ):
                найдено.update(sql_литералы(узел.value))
    return найдено


def sql_литералы(sql: str) -> set[str]:
    """Одиночные кавычки внутри SQL — ПОСТРОЧНО, а не по всей строке разом.

    Куплено ошибкой в этом же файле 10.08.2026: DDL нашей схемы — одна строка
    на 19 449 символов, и разбор `'([^']*)'` по ней целиком спарил кавычки
    ВРАЗБЕЖКУ. Апострофы в комментариях и в соседних `DEFAULT '...'` сдвигают
    разбиение, и девять видов расхода из `CHECK (tax_kind IN (...))` не нашлись
    ВООБЩЕ — сторож объявил, что словаря в `app/database.py` нет, и предложил
    убрать запись из белого списка как устаревшую. Ровно тот класс, о котором
    правило T30: разбор не падает, когда врёт, он молча отдаёт другое.
    Внутри ОДНОЙ строки SQL кавычки сбалансированы, поэтому режем построчно.
    """
    найдено = set()
    for строка in sql.split("\n"):
        найдено.update(re.findall(r"'([^'\n]*)'", строка))
    return найдено


def литералы_js(путь: str) -> set[str]:
    текст = open(путь, encoding="utf-8").read()
    пары = re.findall(r'"((?:[^"\\\n]|\\.)*)"' r"|'((?:[^'\\\n]|\\.)*)'", текст)
    ключи = re.findall(r"^[ \t]*([A-Za-zА-Яа-яЁё_$][\wЀ-ӿ$]*)[ \t]*:", текст, re.M)
    return {a or b for a, b in пары} | set(ключи)


def main() -> int:
    подробно = "--verbose" in sys.argv
    имена, состав = словарь()
    print(
        f"СЛОВАРЬ: {состав['видов']} видов · {состав['групп']} групп · "
        f"{состав['статей']} статей · имён к проверке {len(имена)}"
    )
    print()

    # ── проверка ①: штамп
    print("① ШТАМП КОПИЙ (сверка вызовом генератора)")
    готово = subprocess.run(
        [sys.executable, ГЕНЕРАТОР, "--check"],
        capture_output=True,
        text=True,
        cwd=КОРЕНЬ,
        timeout=120,
    )
    for строка in готово.stdout.strip().split("\n"):
        print(f"   {строка}")
    штамп_код = готово.returncode
    print()

    # ── проверка ②: рукописный литерал мимо генерации
    print("② РУКОПИСНЫЙ ЛИТЕРАЛ МИМО ГЕНЕРАЦИИ")
    файлы: list[tuple[str, set[str]]] = []
    for путь in sorted(
        glob.glob(os.path.join(КОРЕНЬ, "app", "**", "*.py"), recursive=True)
    ):
        файлы.append((os.path.relpath(путь, КОРЕНЬ), литералы_файла(путь)))
    фронт_доступен = os.path.isdir(ФРОНТ_SRC)
    if фронт_доступен:
        for корень_, _, имена_файлов in os.walk(ФРОНТ_SRC):
            for ф in sorted(имена_файлов):
                if ф.endswith((".js", ".jsx")):
                    полный = os.path.join(корень_, ф)
                    отн = "src/" + os.path.relpath(полный, ФРОНТ_SRC)
                    файлы.append((отн, литералы_js(полный)))

    нарушители, проверено, использован = {}, 0, set()
    for отн, литералы in файлы:
        проверено += 1
        попало = имена & литералы
        if not попало:
            continue
        ключ = отн if отн in БЕЛЫЙ_СПИСОК else None
        if ключ:
            использован.add(ключ)
            if подробно:
                print(f"   ≈ {отн}: {len(попало)} имён — в белом списке")
            continue
        нарушители[отн] = sorted(попало)

    for отн, попало in sorted(нарушители.items()):
        print(f"   ✗ {отн}: {len(попало)} имён словаря записаны литералом")
        print(f"       {попало[:6]}{' …' if len(попало) > 6 else ''}")
        print(
            "       Либо импортировать из app.dictionaries / src/lib/dictionaries.js,"
        )
        print(
            "       либо завести запись в БЕЛОМ СПИСКЕ с указанием, чем стык прикрыт."
        )
    if not нарушители:
        print(f"   ✓ рукописных литералов нет (проверено файлов: {проверено})")

    # Устаревшая запись белого списка — такой же дефект, как нарушение.
    устаревшие = [
        к
        for к in БЕЛЫЙ_СПИСОК
        if к not in использован and os.path.exists(путь_записи(к))
    ]
    for к in устаревшие:
        print(f"   ✗ БЕЛЫЙ СПИСОК УСТАРЕЛ: {к} больше не содержит имён словаря —")
        print("       убрать запись, иначе она разрешает то, чего нет")
    print()

    if подробно:
        print("БЕЛЫЙ СПИСОК — чем прикрыт каждый стык:")
        for к, почему in БЕЛЫЙ_СПИСОК.items():
            print(f"   • {к}\n       {почему}")
        print()

    if штамп_код == 2:
        print("ИТОГ: ⚠ ФРОНТ НЕДОСТУПЕН — его копия НЕ ПРОВЕРЯЛАСЬ")
        return 2 if not (нарушители or устаревшие) else 1
    if штамп_код or нарушители or устаревшие:
        print(
            f"ИТОГ: РАСХОЖДЕНИЕ (штамп: {'нет' if штамп_код else 'ок'}, "
            f"рукописных: {len(нарушители)}, устаревших записей: {len(устаревшие)})"
        )
        return 1
    print("ИТОГ: копии отвечают источнику, рукописных литералов нет")
    return 0


if __name__ == "__main__":
    sys.exit(main())
