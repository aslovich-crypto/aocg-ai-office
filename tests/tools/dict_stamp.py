#!/usr/bin/env python3
"""СТОРОЖ СЛОВАРЯ КАТЕГОРИЙ: копии не правлены руками, литералы не пишутся мимо
генерации (T39, шаг ②).

ЗАЧЕМ. У словаря появился ЕДИНЫЙ ИСТОЧНИК (`app/dictionaries/categories.json`)
и генератор (`tools/gen_dictionaries.py`). Механизм без сторожа держится
ровно до первого «да я только строчку впишу»: копия правится руками, генератор
не гоняется, и через месяц мы снова там, откуда ушли. Здесь две проверки.

  ПРОВЕРКА ① ШТАМП. Каждая копия несёт sha256 источника. Сверка — вызовом
  `tools/gen_dictionaries.py --check` (подпроцессом, чтобы коды возврата
  остались его собственными и не пересказывались).

  ПРОВЕРКА ② РУКОПИСНЫЙ ЛИТЕРАЛ МИМО ГЕНЕРАЦИИ. Имя из словаря, встреченное
  строковым литералом вне источника, копий и белого списка, — красное.
  Это то, что вернуло бы нас к исходной болезни явочным порядком.

╔══════════════════════════════════════════════════════════════════════════╗
║ ГРАНИЦА ШТАМПА — ЧИТАТЬ ОБЯЗАТЕЛЬНО, ИНАЧЕ ЕМУ ПРИПИШУТ ЛИШНЕЕ           ║
╚══════════════════════════════════════════════════════════════════════════╝

Штамп доказывает РОВНО ОДНО: копия порождена из источника с такой суммой.
Он НЕ доказывает, что:
  • источник верен по существу (что в нём те самые 9 видов и 11 групп —
    это вопрос к человеку и к нормам, а не к сумме);
  • копию перегенерировали после правки источника. Это ловит СРАВНЕНИЕ сумм
    (проверка ①), а не наличие штампа. Копия со старым штампом побайтно цела
    и при этом отстала;
  • словарь совпадает со СТОРОНАМИ, которые генерацией не покрыты, — SQL CHECK
    в `app/database.py` (пункт ③, отдельный заход) и промпт распознавания
    в `app/routers/ocr.py` (NDS-OCR22, ждёт оплаты API). За первой следит
    слой ② замера `contract_dict.py`, за второй пока НИКТО.

КЛАСС «КОПИЯ ЦЕЛА, НО ОТСТАЛА» ЗДЕСЬ НЕ ПЕРЕНОСИТСЯ, и это надо сказать явно,
потому что у нас уже есть вендорная копия дизайн-системы, которая им болеет.
Там между каноном и копией стоит ВНЕШНИЙ СЕРВИС (Claude Design): сумма сходится,
а канон тем временем уехал, и узнать об этом можно только сходив наружу
(`design/freshness.mjs`, ручной прогон). Здесь промежуточного звена нет —
источник лежит в ТОМ ЖЕ репозитории и в ТОМ ЖЕ коммите, что и копия, поэтому
«отстал» означает просто «не запустили генератор», и это видно сравнением сумм
в тот же прогон. Записано, чтобы через месяц не сочли штамп гарантией большей,
чем он даёт, и не начали городить проверку свежести, которой здесь не нужно.

ГРАНИЦА СО СТОРОНЫ ФРОНТА. Фронтовый сторож (`scripts/check-dictionaries.mjs`)
бэкенд-репозиторий не видит и проверяет только целостность своей копии
и совпадение с `GROUP_COLORS`. Вопрос «отвечает ли копия текущему источнику»
задаётся ТОЛЬКО отсюда, и если фронт недоступен — код 2, «не проверялось».

ЧЕГО ПРОВЕРКА ② НЕ ЛОВИТ: имя, собранное из частей или вычисленное; имя
в файле, которого нет в обходе (вне `app/**/*.py` и фронтового `src/`);
и имя короче 4 символов — такие в словаре не встречаются, но фильтр стоит,
чтобы не ловить служебные строки.

БЕЛЫЙ СПИСОК — НЕ ПОБЛАЖКА, А ЗАПИСАННОЕ РЕШЕНИЕ. Каждая запись обязана
назвать, ЧЕМ этот стык прикрыт вместо генерации. Запись, пережившая свою
причину (файл больше не содержит имён словаря), КРАСНЕЕТ: исключение,
переставшее быть нужным, — это ложь в документации.

КОДЫ ВОЗВРАТА:
    0 — копии отвечают источнику, рукописных литералов нет
    1 — есть расхождение либо рукописный литерал
    2 — фронт-репозиторий недоступен, ЕГО СТОРОНА НЕ ПРОВЕРЯЛАСЬ
    3 — самопроверка не пройдена

ЗАПУСК:
    ./venv/bin/python tests/tools/dict_stamp.py
    ./venv/bin/python tests/tools/dict_stamp.py --verbose
"""

