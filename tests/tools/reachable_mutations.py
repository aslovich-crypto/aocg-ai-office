import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
СТОРОЖ_ОТН = os.path.join("tests", "tools", "reachable.py")

# (имя, что заменить, на что, чего ждём в выводе, зачем)
МУТАНТЫ = [
    (
        "М1 псевдоним снова считается за одно имя",
        '                имена = {узел.name.split(".")[-1]}\n'
        "                if узел.asname:\n"
        "                    имена.add(узел.asname)",
        '                имена = {узел.asname or узел.name.split(".")[-1]}',
        "ждали {'мёртвая'}",
        "две ложные находки 10.09: `записать` и `почты` были объявлены мёртвыми",
    ),
    (
        # ⚠️ ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ МУТАЦИИ НЕ КУСАЛА, И ПРИЧИНА ПОУЧИТЕЛЬНА:
        # она снимала счёт по `ast.Name`, а ветка `ast.alias` продолжала
        # считать ИМПОРТ — переданная по ссылке функция оставалась «живой»
        # за счёт собственной строки импорта. Мутант описывал поломку,
        # которой в этом коде случиться не может. Воспроизводим НАСТОЯЩЕЕ
        # прежнее состояние: считались только вызовы, ни имён, ни импортов.
        "М2 обращения считаются только вызовами, как в первой редакции",
        "        for узел in ast.walk(дерево):",
        "        for узел in ast.walk(дерево):\n"
        "            if isinstance(узел, ast.Call) and isinstance(узел.func, ast.Name):\n"
        "                счёт[узел.func.id] = счёт.get(узел.func.id, 0) + 1\n"
        "            continue",
        "ждали {'мёртвая'}",
        "функция, ПЕРЕДАННАЯ по ссылке (add_task, Depends), объявлялась бы мёртвой",
    ),
    (
        "М3 декорированное больше не исключается",
        '            if узел.decorator_list or узел.name.startswith("_"):',
        '            if узел.name.startswith("_"):',
        "ждали {'мёртвая'}",
        "все ручки проекта попали бы в находки — сторож отбросили бы в первый запуск",
    ),
    (
        "М4 самопроверка снова смотрит на живой код, а не на образец",
        '    дырявое = на_обр == {"мёртвая"}',
        "    дырявое = True",
        "",
        "именно так поломка и пролежала: самопроверка перестаёт быть проверкой",
    ),
]


def прогнать(корень: str) -> tuple[bool, int, str]:
    """(был ли вердикт, код возврата, вывод). Вердикт ≠ исход."""
    итог = subprocess.run(
        [sys.executable, os.path.join(корень, СТОРОЖ_ОТН), "--selfcheck"],
        cwd=корень,
        capture_output=True,
        text=True,
        timeout=120,
    )
    вывод = итог.stdout + итог.stderr
    return ("САМОПРОВЕРКА" in вывод), итог.returncode, вывод


def main() -> int:
    print("\nМУТАЦИИ СТОРОЖА ДОСТИЖИМОСТИ\n")
    with tempfile.TemporaryDirectory(prefix="reach-mut-") as врем:
        копия = os.path.join(врем, "repo")
        shutil.copytree(
            КОРЕНЬ,
            копия,
            symlinks=True,
            ignore=shutil.ignore_patterns(
                ".git", "venv", "__pycache__", "node_modules", "*.pyc"
            ),
        )
        путь = os.path.join(копия, СТОРОЖ_ОТН)
        исходный = open(путь, encoding="utf-8").read()

        вердикт, код, _ = прогнать(копия)
        if not вердикт:
            print("  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ на чистой копии")
            return 1
        if код != 0:
            print("  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: самопроверка красна ДО мутаций")
            return 1
        print("  обратный ход: самопроверка зелена на нетронутой копии ✓\n")

        поставлено = поймано = 0
        непоставленные: list[str] = []
        немерено: list[str] = []
        for имя, было, стало, ждём, зачем in МУТАНТЫ:
            if исходный.count(было) != 1:
                непоставленные.append(имя)
                print(f"  ✗ НЕ ПОСТАВЛЕН  {имя}: якоря нет либо он не один")
                continue
            open(путь, "w", encoding="utf-8").write(исходный.replace(было, стало))
            поставлено += 1
            вердикт, код, вывод = прогнать(копия)
            open(путь, "w", encoding="utf-8").write(исходный)
            if not вердикт:
                немерено.append(имя)
                print(f"  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ  {имя} — исход неизвестен")
                continue
            # ⚠️ М4 ловится ИНАЧЕ: она делает самопроверку слепой, и та
            # остаётся ЗЕЛЁНОЙ. Ждём не красноты, а того, что подложенная
            # поломка разбора перестала находиться, — проверяем парой:
            # мутант «слепая самопроверка» + мутант «сломанный разбор».
            if имя.startswith("М4"):
                # ⚠️ ПАРУ БЕРЁМ С ПОЛОМКОЙ, КОТОРУЮ ЛОВИТ ТОЛЬКО ПУНКТ ①.
                # Первая редакция брала «декорированное не исключается» —
                # и слепая самопроверка всё равно краснела, но пунктом ②
                # («в находках ручки»). Мутация проверяла не то: пункт ①
                # мог быть мёртвым, а свод оставался красным за счёт соседа.
                двойной = исходный.replace(было, стало).replace(
                    '                имена = {узел.name.split(".")[-1]}\n'
                    "                if узел.asname:\n"
                    "                    имена.add(узел.asname)",
                    '                имена = {узел.asname or узел.name.split(".")[-1]}',
                )
                open(путь, "w", encoding="utf-8").write(двойной)
                _, код2, _ = прогнать(копия)
                open(путь, "w", encoding="utf-8").write(исходный)
                пойман = код2 == 0  # слепая самопроверка НЕ увидела поломку
                знак = "✓ поймана" if пойман else "✗ ПРОПУЩЕНА"
                поймано += пойман
                print(f"  {знак}  {имя}\n      — {зачем}")
                continue
            пойман = код != 0 and (not ждём or ждём in вывод)
            поймано += пойман
            print(
                f"  {'✓ поймана' if пойман else '✗ ПРОПУЩЕНА'}  {имя}\n      — {зачем}"
            )

        print(
            f"\nПОСТАВЛЕНО {поставлено} · ПОЙМАНО {поймано} · "
            f"НЕ ПОСТАВЛЕНО {len(непоставленные)} · НЕ МЕРЕНО {len(немерено)}"
        )
        if немерено:
            print(f"  ⚠️ прибор не дал вердикта: {', '.join(немерено)}")
        return 0 if поймано == поставлено and not непоставленные and not немерено else 1


if __name__ == "__main__":
    sys.exit(main())
