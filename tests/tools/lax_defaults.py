# -*- coding: utf-8 -*-
"""Замер S-49: умолчания, которые при отсутствии значения ОСЛАБЛЯЮТ защиту.

ЧТО ИЩЕТ. Класс дефекта: переменная (или ключ) не задана — код не падает
и не закрывается, а продолжает работу в БОЛЕЕ РАЗРЕШИТЕЛЬНОМ режиме.
Ошибки нет, строки в логе нет, стало хуже молча. Отличать от «отказа
закрытым» (`S3_*` не заданы → 503, `JWT_SECRET_KEY` пуст → отказ старта):
так делать правильно, и таких мест большинство.

ЧЕГО НЕ УМЕЕТ И НЕ ПРИТВОРЯЕТСЯ. Это грепом собранный СПИСОК КАНДИДАТОВ,
а не приговор: направление отката (слабее или строже) грепом не читается,
его определяет человек, открыв файл. На 13.08.2026 из 23 кандидатов
реальными оказались три — `CORS_ORIGINS`→`["*"]`, `APP_URL`→зашитый адрес,
`VITE_API_URL`→зашитый адрес. Поэтому ненулевой вывод — это «иди читай»,
а не «всё плохо».

ЗАПУСК (сначала самопроверка, потом обычный прогон):
    python3 tests/tools/lax_defaults.py --selfcheck
    python3 tests/tools/lax_defaults.py

САМОПРОВЕРКА НА ИЗВЕСТНОМ ОТВЕТЕ (правило T11/T30: новый замер сперва
гоняется там, где ответ уже знаешь). Требуем оба исхода сразу:
  · заведомо дырявое — откат CORS на `["*"]` ОБЯЗАН найтись;
  · заведомо здоровое — fail-fast `JWT_SECRET_KEY` обязан НЕ попасть
    в находки (иначе замер поднимает тревогу на правильном коде).
Без второй половины «нашёл 23 штуки» неотличимо от «ловит всё подряд».

Коды возврата: 0 — прогон состоялся; 1 — НАЙДЕНО ≠ НАПЕЧАТАНО (замер
теряет находки по дороге к выводу); 2 — самопроверка не прошла.

ПРОВЕРЕН МУТАЦИЯМИ 13.08.2026 (T11). У каждой записано не «ждём красный»,
а КОНКРЕТНАЯ строка вывода — иначе замер краснеет по неправильной причине
и проверенной считается способность, которую никто не проверял:
  M1 полоса печати уже полосы поиска (пропускать CORS/VITE при выводе)
     → код 1 и слово «РАСХОЖДЕНИЕ»;
  M2 правило «звёздочка-умолчание» перестаёт совпадать
     → код 2 и «заведомо дырявое … найдено ....... НЕТ»;
  M3 `JWT_SECRET_KEY` получает значение по умолчанию (fail-fast пропал)
     → код 2 и «заведомо здоровое … НЕ поднято ....... нет».
M2 с первого раза НЕ ЗАСЧИТАНА и переделана: подменили только первую
альтернативу регулярки, остальные (`,\\s*\\["\\*"\\]`, `"\\*"\\s*\\]`) остались
рабочими — сторож честно продолжил находить откат, а выглядело это как
его поломка. Мутация обязана убирать СПОСОБНОСТЬ целиком, а не кусок
её текста.
"""

import pathlib
import re
import sys

БЭКЕНД = pathlib.Path(__file__).resolve().parents[2]
ФРОНТ = БЭКЕНД.parent / "aocg-ai-office-web"
ПРОПУСК = ("venv/", "/tests/", "node_modules/", "/.git/", "/dist/")

# (метка, регулярка, чем подозрительно)
ШАБЛОНЫ = [
    (
        "звёздочка-умолчание",
        r'or\s*\[\s*"\*"\s*\]|,\s*\["\*"\]|"\*"\s*\]',
        "откат на «разрешить всё»",
    ),
    (
        "умолчание-окружения",
        r'os\.(getenv|environ\.get)\(\s*["\']\w+["\']\s*,\s*[^)]+\)',
        "значение по умолчанию вместо отказа",
    ),
    (
        "умолчание-сборки",
        r"import\.meta\.env\.\w+\s*(\?\?|\|\|)",
        "адрес/режим зашит на случай «не задано»",
    ),
    (
        "get-True",
        r'\.get\(\s*["\'][^"\']+["\']\s*,\s*True\s*\)',
        "по умолчанию РАЗРЕШЕНО",
    ),
    (
        "права-с-подстановкой",
        r'\.get\(\s*["\'](role|is_admin|is_active|org_id)["\']\s*,\s*[^)]+\)',
        "права/принадлежность с подстановкой",
    ),
    (
        "проверка-выключена",
        r"verify\s*=\s*False|debug\s*=\s*True",
        "проверка отключена явно",
    ),
]


def _файлы():
    for корень, маски in ((БЭКЕНД, ("*.py",)), (ФРОНТ, ("*.js", "*.jsx"))):
        if not корень.exists():
            print("  ⚠️ нет каталога %s — часть кода НЕ проверена" % корень)
            continue
        for маска in маски:
            for f in sorted(корень.rglob(маска)):
                путь = "/" + str(f.relative_to(корень))
                if any(x in путь for x in ПРОПУСК):
                    continue
                yield корень.name, f.relative_to(корень), f


def прогон(печатать=True):
    найдено, находки = 0, []
    for репо, отн, f in _файлы():
        for n, ln in enumerate(
            f.read_text(encoding="utf-8", errors="replace").split("\n"), 1
        ):
            голый = ln.strip()
            if голый.startswith(("#", "//", "*")):
                continue
            for метка, рег, почему in ШАБЛОНЫ:
                if re.search(рег, ln):
                    найдено += 1
                    находки.append((метка, репо, str(отн), n, голый[:150], почему))
                    break

    напечатано = 0
    for метка, репо, отн, n, текст, почему in находки:
        напечатано += 1
        if печатать:
            print(
                "  [%s] %s/%s:%d\n      %s\n      ← %s"
                % (метка, репо, отн, n, текст, почему)
            )

    if печатать:
        print("\nНАЙДЕНО %d · НАПЕЧАТАНО %d" % (найдено, напечатано))
    if найдено != напечатано:
        print("РАСХОЖДЕНИЕ: замер теряет находки по дороге к выводу")
        sys.exit(1)
    return находки


def самопроверка():
    находки = прогон(печатать=False)
    тексты = [т for _, _, _, _, т, _ in находки]
    дырявое = any('or ["*"]' in т for т in тексты)
    здоровое_поднято = any("JWT_SECRET" in т for т in тексты)
    print("САМОПРОВЕРКА")
    print(
        "  заведомо дырявое (откат CORS на «*») найдено ....... %s"
        % ("да" if дырявое else "НЕТ")
    )
    print(
        "  заведомо здоровое (fail-fast JWT) НЕ поднято ....... %s"
        % ("нет" if здоровое_поднято else "да")
    )
    if not дырявое or здоровое_поднято:
        print("  ИТОГ: самопроверка НЕ ПРОШЛА — обычный прогон не запускать")
        sys.exit(2)
    print("  ИТОГ: замер отвечает верно на известном примере")


if __name__ == "__main__":
    if "--selfcheck" in sys.argv:
        самопроверка()
    else:
        самопроверка()
        print()
        прогон()
