from __future__ import annotations

import collections
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ТРЕКЕР = os.path.join(КОРЕНЬ, "docs", "TASKS.md")

СЛОВАРЬ = (
    "ЖИВА",
    "СУЖЕНА",
    "ПРЕДМЕТА НЕТ",
    "МЁРТВАЯ",
    "ЖДЁТ РЕШЕНИЯ",
    "ВНЕ ДОСЯГАЕМОСТИ",
    "ПРЕДПОСЫЛКА НЕ НАСТУПИЛА",
    "БЛОКОМ",
)
# ⚠️ «БЛОКОМ» СЧИТАЕТСЯ ОТДЕЛЬНО ОТ ОСТАЛЬНЫХ. Складывать его с настоящими
# вердиктами в одно число «пройдено» — значит вернуть ту самую ошибку, ради
# которой прибор написан.
СЛАБЫЙ = "БЛОКОМ"

# ⚠️ ЗАХОД ЛОВИТСЯ ЧЕРЕЗ `*`, А НЕ `+`, НАМЕРЕННО: пустой заход обязан ПОПАСТЬ
# в разбор и покраснеть проверкой ниже. При `+` он не совпадал бы вовсе, и
# мутация «заход пустой» краснела сообщением «форма битая» — то есть прибор
# ругался не на то, что сломано. Поймано мутацией 06.09.2026.
ШТАМП = re.compile(r"⟦АУДИТ · (\d{4}-\d{2}-\d{2}) · ([^·⟧]*) · ([^·⟧]+)⟧")
# Сырой поиск скобок — ОТДЕЛЬНЫМ ходом, не через ШТАМП: иначе штамп с битой
# формой не попадёт ни в находки, ни в свод, и прибор промолчит о нём.
СЫРОЙ = re.compile(r"⟦[^⟧]*⟧")
РАЗДЕЛИТЕЛЬ = re.compile(r"(?<!\\)\|")


def строки_задач(текст):
    """(номер, ид, статус, примечание) по строкам таблиц задач."""
    для_вывода = []
    for н, с in enumerate(текст.split("\n"), 1):
        я = РАЗДЕЛИТЕЛЬ.split(с)
        if len(я) != 9:
            continue
        ид = я[1].strip()
        if not ид or ид == "ID" or ид.startswith("--") or set(ид) <= set("-: "):
            continue
        если_значок = я[4].strip()
        if если_значок in (":----:", ""):
            continue
        для_вывода.append((н, ид, если_значок, я[7]))
    return для_вывода


def разобрать(примечание):
    """[(дата, заход, вердикт)] — только штампы ВЕРНОЙ формы."""
    return [(д, з.strip(), в.strip()) for д, з, в in ШТАМП.findall(примечание)]


def проверить(задачи):
    беды = []
    свод = collections.Counter()
    без_штампа = []
    for н, ид, статус, прим in задачи:
        сырых = СЫРОЙ.findall(прим)
        штампы = разобрать(прим)
        if len(сырых) != len(штампы):
            беды.append((н, ид, "штамп есть, но форма битая — разбор его не видит"))
        for дата, заход, вердикт in штампы:
            if вердикт not in СЛОВАРЬ:
                беды.append((н, ид, f"вердикт «{вердикт}» не из словаря"))
            if not заход:
                беды.append((н, ид, "заход пустой"))
        # ④ ВЕРДИКТ ЗАКРЫТИЯ ОБЯЗАН СХОДИТЬСЯ СО СТАТУСОМ. Куплено ошибкой
        # 07.09.2026: простановка задним числом читала вердикт из ВСЕГО
        # примечания, и длинная строка T178 — живая, 🔴 — получила штамп
        # «ПРЕДМЕТА НЕТ» только потому, что эти слова встречались в её тексте
        # (она перечисляет вердикты ДРУГИХ строк). Разбор взял слово рядом
        # с предметом вместо самого предмета — тот же класс, что «прибор
        # отвечает про чужую цель».
        # ⚠️ ПРОВЕРКА ОДНОСТОРОННЯЯ, И ЭТО НЕ ПОБЛАЖКА. Первая редакция
        # сравнивала в обе стороны и тут же покраснела на T176: строку
        # аудировали как живую 06.09, а 07.09 её закрыла РАБОТА — штамп
        # «БЛОКОМ» при статусе ✅ оказался верной парой, а не ошибкой.
        # Штамп говорит, что было НА СВОЮ ДАТУ; статус живёт дальше.
        # Ошибочно только обратное: вердикт закрытия у НЕ закрытой строки —
        # так 07.09 живая T178 получила «ПРЕДМЕТА НЕТ» из-за того, что
        # перечисляет вердикты других строк.
        for _, _, вердикт in штампы:
            if вердикт in ("ПРЕДМЕТА НЕТ", "МЁРТВАЯ") and статус != "✅":
                беды.append(
                    (н, ид, f"вердикт закрытия «{вердикт}» при статусе «{статус}»")
                )
        даты = [д for д, _, _ in штампы]
        if len(даты) != len(set(даты)):
            беды.append((н, ид, "два штампа одной даты — свод по ним соврёт"))
        if штампы:
            свод[штампы[-1][2]] += 1
        elif статус != "✅":
            без_штампа.append((ид, статус))
    return беды, свод, без_штампа


КОНТРОЛЬНЫЕ = [
    (
        "| T1 | задача | 🟡 | ⬜ | — | — | текст ⟦АУДИТ · 2026-09-06 · Ⓒ · ЖИВА⟧ |",
        1,
        "ЖИВА",
    ),
    ("| T2 | задача | 🟡 | ⬜ | — | — | текст без штампа |", 0, None),
    (
        "| T3 | задача | 🟡 | ⬜ | — | — | ⟦АУДИТ · 2026-09-06 · Ⓐ · БЛОКОМ⟧ |",
        1,
        "БЛОКОМ",
    ),
]


def самопроверка():
    print("САМОПРОВЕРКА")
    плохо = 0
    for строка, сколько, вердикт in КОНТРОЛЬНЫЕ:
        задачи = строки_задач(строка)
        if len(задачи) != 1:
            print(f"  ✗ строка не разобрана как задача: {строка[:40]}")
            плохо += 1
            continue
        штампы = разобрать(задачи[0][3])
        если = len(штампы) == сколько and (not сколько or штампы[0][2] == вердикт)
        print(
            f"  {'✓' if если else '✗'} {задачи[0][1]}: штампов {len(штампы)}"
            f"{', вердикт ' + штампы[0][2] if штампы else ''}"
        )
        плохо += 0 if если else 1
    # ⚠️ ОБРАТНЫЙ СЛУЧАЙ: битая форма обязана быть ЗАМЕЧЕНА, а не пропущена.
    битая = "| T4 | задача | 🟡 | ⬜ | — | — | ⟦АУДИТ · вчера · Ⓒ · ЖИВА⟧ |"
    беды, _, _ = проверить(строки_задач(битая))
    если = any("форма битая" in б[2] for б in беды)
    print(f"  {'✓' if если else '✗'} битая дата поймана как битая форма")
    плохо += 0 if если else 1
    # ⚠️ И ВТОРОЙ ОБРАТНЫЙ: вердикт не из словаря обязан краснеть.
    чужой = "| T5 | задача | 🟡 | ⬜ | — | — | ⟦АУДИТ · 2026-09-06 · Ⓒ · ПОСМОТРЕЛ⟧ |"
    беды, _, _ = проверить(строки_задач(чужой))
    если = any("не из словаря" in б[2] for б in беды)
    print(f"  {'✓' if если else '✗'} вердикт вне словаря пойман")
    плохо += 0 if если else 1
    print(
        "  ИТОГ: самопроверка пройдена" if not плохо else f"  ИТОГ: расхождений {плохо}"
    )
    return 1 if плохо else 0


def main():
    if "--selfcheck" in sys.argv:
        return самопроверка()
    if самопроверка():
        print("\n⚠️ РАЗБОР НЕ ПРОШЁЛ САМОПРОВЕРКУ — файл не смотрим.")
        return 1
    путь = next((а for а in sys.argv[1:] if not а.startswith("--")), ТРЕКЕР)
    with open(путь, encoding="utf-8") as f:
        задачи = строки_задач(f.read())
    беды, свод, без_штампа = проверить(задачи)

    print("\nШТАМПЫ АУДИТА")
    настоящих = sum(к for в, к in свод.items() if в != СЛАБЫЙ)
    print(f"  строк задач в файле      : {len(задачи)}")
    print(f"  со штампом               : {sum(свод.values())}")
    print(f"    из них с ВЕРДИКТОМ     : {настоящих}")
    print(
        f"    из них «{СЛАБЫЙ}»        : {свод[СЛАБЫЙ]}  ← не проверка, факт членства"
    )
    for в in СЛОВАРЬ:
        if свод[в]:
            print(f"      {свод[в]:>4}  {в}")
    # ⚠️ ОСТАТОК ПЕЧАТАЕТСЯ ВСЕГДА (правило Ⓓ из T188): «ноль непройденных»
    # обязано отличаться от «не считали».
    print(f"  ОТКРЫТЫХ БЕЗ ШТАМПА      : {len(без_штампа)}")
    for ид, статус in без_штампа:
        print(f"      {ид:<12} {статус}")
    if беды:
        print(f"\n⚠️ РАСХОЖДЕНИЙ {len(беды)}")
        for н, ид, что in беды:
            print(f"   {путь}:{н}  {ид:<12} {что}")
        return 1
    print("  ✓ форма всех штампов верна")
    return 0


if __name__ == "__main__":
    sys.exit(main())
