"""Сколько проверок в тестах опираются на значение из окружения, не задавая его.

ЗАЧЕМ. Класс дефекта подтверждён трижды за три недели (S-70, сторож APP_URL
в T62, T66): проверка выглядит содержательной, а в этом прогоне не различает
ничего — пустая строка превращает сравнение в тождество. Все три найдены
мутацией, ни одна чтением.

САМОПРОВЕРКА НА ИЗВЕСТНОМ ОТВЕТЕ (правило T11/T30) — ПРОВЕДЕНА 26.08.2026.
В тест `test_ссылка_ведёт_на_адрес_фронта` временно возвращена его прежняя,
заведомо пустая форма `startswith(auth.APP_URL + ...)` — сборщик нашёл её
и напечатал «КАНДИДАТОВ: 1». На исправленном виде — ноль. То есть ноль
на рабочем дереве означает «не нашлось», а не «не умеет искать».

⚠️ ЧЕГО НЕ УМЕЕТ, И ЭТО ВАЖНЕЕ ТОГО, ЧТО УМЕЕТ:
  · видит только имена, читаемые из окружения НА УРОВНЕ МОДУЛЯ в `app/`,
    и только их прямое упоминание в строке `assert`. Значение, пришедшее
    в проверку окольным путём (через ответ ручки, через фикстуру), не видит;
  · не знает, задаёт ли значение фикстура из `conftest`, — поэтому печатает
    КАНДИДАТОВ, а не приговор.

⚠️ И ОТДЕЛЬНО ЗАМЕРЕНО, ЧТО МУТАЦИЯ ОКРУЖЕНИЯ ЭТОТ КЛАСС НЕ ЛОВИТ ВООБЩЕ.
Прогон всего набора с ПЯТЬЮ заданными переменными дал ровно те же числа,
что и с пустыми (486 прошло, 1 упал — T51). На заведомо дырявом тесте —
тоже ничего: тест, который строит ожидание ИЗ ТОЙ ЖЕ переменной, зелен
при любом её значении. Способ выглядит подходящим и бесполезен здесь.

ПЕЧАТАЕТ ТОЛЬКО ИМЕНА И ФАЙЛЫ. Значений переменных не печатает никогда:
среди них секреты, а вывод предназначен для переписки.

ЗАПУСК:
    ./venv/bin/python tests/tools/env_asserts.py
"""

import ast
import os
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path("/Users/alekseishukalovich/aocg-ai-office")

# ① имена, которые в app/ читаются из окружения на уровне модуля
имена = {}
for f in (КОРЕНЬ / "app").rglob("*.py"):
    try:
        дерево = ast.parse(f.read_text(encoding="utf-8"))
    except SyntaxError:
        continue
    for узел in дерево.body:
        if isinstance(узел, ast.Assign) and isinstance(узел.value, ast.Call):
            зов = ast.unparse(узел.value.func) if hasattr(ast, "unparse") else ""
            if "getenv" in зов or "environ.get" in зов:
                for ц in узел.targets:
                    if isinstance(ц, ast.Name):
                        имена[ц.id] = f.relative_to(КОРЕНЬ).as_posix()

# ② какие из них ПУСТЫ в тестовом окружении
os.environ.setdefault("JWT_SECRET_KEY", "проба")
sys.path.insert(0, str(КОРЕНЬ))
пустые = set()
import importlib

for имя, файл in sorted(имена.items()):
    модуль = файл[:-3].replace("/", ".")
    try:
        м = importlib.import_module(модуль)
    except Exception:
        continue
    знач = getattr(м, имя, None)
    if знач in ("", None) or (isinstance(знач, str) and not знач.strip()):
        пустые.add(имя)

print("═" * 66)
print("ИМЁН, ЧИТАЕМЫХ ИЗ ОКРУЖЕНИЯ НА УРОВНЕ МОДУЛЯ:", len(имена))
print("ИЗ НИХ ПУСТЫ В ТЕСТОВОМ ОКРУЖЕНИИ:", len(пустые))
print("  ", ", ".join(sorted(пустые)) or "—")
print("═" * 66)

# ③ проверки в тестах, упоминающие пустое имя
ЗАДАЁТ = re.compile(
    r"setenv\(\s*[\"'](\w+)|setattr\([^,]+,\s*[\"'](\w+)[\"']|environ\[\s*[\"'](\w+)"
)
находки = []
for f in sorted((КОРЕНЬ / "tests").glob("test_*.py")):
    текст = f.read_text(encoding="utf-8")
    строки = текст.split("\n")
    заданные = {g for m in ЗАДАЁТ.finditer(текст) for g in m.groups() if g}
    for н, с in enumerate(строки, 1):
        if not с.lstrip().startswith("assert"):
            continue
        for имя in пустые:
            if re.search(rf"\b{имя}\b", с) and имя not in заданные:
                находки.append((f.name, н, имя, с.strip()[:70]))

print(f"НАЙДЕНО ПРОВЕРОК-КАНДИДАТОВ: {len(находки)}")
for файл, н, имя, с in находки:
    print(f"  {файл}:{н}  [{имя}]  {с}")
print()
print("⚠️ ЭТО СПИСОК КАНДИДАТОВ, А НЕ ПРИГОВОР: грепом не видно, задаёт ли")
print("   значение фикстура из conftest. Каждую строку читает человек.")
