# -*- coding: utf-8 -*-
"""Сторож витрины трекера: до витрины доехали ВСЕ задачи.

⚠️ ЧТО СТЕРЕЖЁТСЯ — ЧИСЛО, А НЕ ВНЕШНИЙ ВИД. Витрина читается глазами, и
потерянную задачу глазами не заметить: страница на две с лишним сотни строк,
одной меньше — одной больше. Сторож сверяет НАЙДЕНО против НАПЕЧАТАНО, ровно
как требует T11: печатать оба числа и падать при расхождении.

⚠️ И ВТОРОЕ, ИЗ ТОГО ЖЕ КЛАССА, ЧТО МОЛЧАЩИЙ ПРОПУСК (T87): сборщик, который
перестал находить ЛЮБЫЕ задачи, обязан КРАСНЕТЬ, а не выдавать пустую
красивую страницу. Пустая витрина без ошибки — та же ложь.

⚠️ ТРИ ПРОВЕРКИ НИЖЕ ДОБАВЛЕНЫ ПО T100, И ДЫРУ НАЗВАЛ АГЕНТ САМ. Замер
29.08.2026: сторож считал только карточки, поэтому две мутации в разбор
разметки прошли МОЛЧА и зелёными — вырезанный разбор жирного (звёздочки
торчат по всей странице) и снятое экранирование (угловая скобка из
примечания уезжает прямо в разметку и ломает страницу). Второе хуже
косметики, потому и чинится прибором, а не обещанием.
"""

import html
import importlib.util
import pathlib
import re
import subprocess
import sys
from html.parser import HTMLParser

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ТРЕКЕР = КОРЕНЬ / "docs/TASKS.md"
СБОРЩИК = pathlib.Path(__file__).with_name("tracker_html.py")
ВЫХОД = pathlib.Path("/tmp/aocg-tracker.html")


def _модуль(имя):
    спец = importlib.util.spec_from_file_location(
        имя, pathlib.Path(__file__).with_name(f"{имя}.py")
    )
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def _целостность(страница):
    """(незакрытых, перехлёстов). Ловит и снятое экранирование: угловая
    скобка из примечания превращается в тег и разъезжается."""
    ПУСТЫЕ = {"meta", "link", "br", "img", "hr", "input", "source", "col"}

    class _Разбор(HTMLParser):
        def __init__(с):
            super().__init__()
            с.стек, с.перехлёстов = [], 0

        def handle_starttag(с, тег, атрибуты):
            if тег not in ПУСТЫЕ:
                с.стек.append(тег)

        def handle_endtag(с, тег):
            if с.стек and с.стек[-1] == тег:
                с.стек.pop()
            elif тег in с.стек:
                с.перехлёстов += 1
                с.стек.remove(тег)
            else:
                с.перехлёстов += 1

    р = _Разбор()
    р.feed(страница)
    return len(р.стек), р.перехлёстов


def main():
    беды = []
    print("\nВИТРИНА ТРЕКЕРА")

    # ⚠️ Сначала — выполнима ли проверка вообще (T87). Нет файла или нет
    # сборщика — это «НЕ ВЫПОЛНЕНА», а не «совпало».
    for имя, путь in (("трекер", ТРЕКЕР), ("сборщик", СБОРЩИК)):
        if not путь.exists():
            print(f"  ✗ НЕ НАЙДЕН {имя}: {путь}")
            return 1

    ВЫХОД.unlink(missing_ok=True)
    r = subprocess.run(
        [sys.executable, str(СБОРЩИК)], cwd=КОРЕНЬ, capture_output=True, text=True
    )
    if r.returncode != 0:
        print(f"  ✗ сборщик упал (код {r.returncode}):")
        for с in (r.stdout + r.stderr).strip().splitlines():
            print(f"      {с}")
        return 1
    if not ВЫХОД.exists():
        print(f"  ✗ сборщик отработал, но {ВЫХОД} не создан")
        return 1

    # ── НАЙДЕНО против НАПЕЧАТАНО ─────────────────────────────────────
    tracker_guard = _модуль("tracker_guard")
    найдено = len(tracker_guard.строки_задач(ТРЕКЕР.read_text(encoding="utf-8")))
    страница = ВЫХОД.read_text(encoding="utf-8")
    напечатано = len(re.findall(r"<article\b", страница))

    print(f"  НАЙДЕНО в docs/TASKS.md : {найдено}")
    print(f"  НАПЕЧАТАНО в витрине     : {напечатано}")
    if найдено != напечатано:
        беды.append(f"потеряно задач: {найдено - напечатано}")
        print(f"  ✗ РАСХОЖДЕНИЕ: {найдено - напечатано}")
    else:
        print("  ✓ совпало — ни одна задача не потерялась")

    # ── свод в шапке не расходится с содержимым ───────────────────────
    м = re.search(r"задач (\d+) ·", страница)
    if not м:
        беды.append("в шапке витрины нет числа задач")
        print("  ✗ в шапке нет числа задач — читателю не с чем сверить")
    elif int(м.group(1)) != напечатано:
        беды.append(f"шапка обещает {м.group(1)}, карточек {напечатано}")
        print(f"  ✗ шапка обещает {м.group(1)}, а карточек {напечатано}")
    else:
        print(f"  ✓ шапка обещает {м.group(1)} — столько и есть")

    # ── разметка разобрана, а не показана сырьём (T100) ───────────────
    # ⚠️ Считаем по ВИДИМОМУ тексту: вырезаем кодовые вставки (там ** и [[
    # живут законно — глобы, правила прав, JSON), потом теги, потом
    # распаковываем сущности. Сырых знаков вне кода быть не должно НИ ОДНОГО.
    вне_кода = html.unescape(
        re.sub(
            r"<[^>]+>",
            "",
            re.sub(
                r"<code>.*?</code>|<style.*?</style>|<script>.*?</script>",
                "",
                страница,
                flags=re.S,
            ),
        )
    )
    # ⚠️ ~~ ДОБАВЛЕНО ПО T101. Восемь знаков зачёркивания торчали в именах
    # четырёх задач, и прежний набор их не видел: сторож проверял ровно то,
    # что я успел разобрать, а не то, что встречается в файле.
    сырые = {з: вне_кода.count(з) for з in ("**", "[[", "`", "═══", "~~")}
    всего_сырых = sum(сырые.values())
    подпись = " · ".join(f"{з} {ч}" for з, ч in сырые.items())
    print(f"  СЫРЫХ ЗНАКОВ вне кода    : {подпись}")
    if всего_сырых:
        беды.append(f"сырых знаков разметки вне кода: {всего_сырых}")
        print(f"  ✗ разбор разметки не отработал — {всего_сырых} знаков видны глазами")
    else:
        print("  ✓ разметка разобрана — сырых знаков не осталось")

    # ── страница не разъехалась: теги закрыты и не внахлёст (T100) ─────
    незакрытых, перехлёстов = _целостность(страница)
    print(
        f"  ЦЕЛОСТНОСТЬ HTML         : незакрытых {незакрытых} · перехлёстов {перехлёстов}"
    )
    if незакрытых or перехлёстов:
        беды.append(f"HTML разъехался: {незакрытых} незакрытых, {перехлёстов} внахлёст")
        print("  ✗ разметка страницы битая — экранирование или вложенность")
    else:
        print("  ✓ теги закрыты и не внахлёст")

    # ── признаки фильтра на месте (T99) ───────────────────────────────
    # ⚠️ Фильтр обязан ПРЯТАТЬ напечатанные карточки, а не рисовать их.
    # Если признак пропал хоть у одной — фильтр её потеряет молча, и
    # счётчик на панели начнёт врать при зелёном числе карточек.
    # ⚠️ ИЩЕМ ПРИЗНАК ГДЕ УГОДНО ВНУТРИ ТЕГА, А НЕ ВПЛОТНУЮ К КЛАССУ.
    # Первая редакция требовала data-pr сразу за class — и покраснела
    # на КОНТРОЛЬНОМ прогоне, где карточкам добавили hidden. Проверка,
    # падающая от порядка атрибутов, стережёт вёрстку, а не смысл.
    с_приоритетом = len(re.findall(r"<article\b[^>]*\bdata-pr=", страница))
    со_статусом = len(re.findall(r"<article\b[^>]*\bdata-st=", страница))
    нехватка = [
        и
        for и in ('id="q"', 'id="pr"', 'id="st"', 'id="blk"', 'id="cnt"')
        if и not in страница
    ]
    print(
        f"  ПРИЗНАКИ ФИЛЬТРА         : приоритет {с_приоритетом} · статус {со_статусом}"
    )
    if с_приоритетом != напечатано or со_статусом != напечатано:
        беды.append("у части карточек нет признаков фильтра")
        print(
            f"  ✗ признаки не у всех {напечатано} карточек — фильтр потеряет их молча"
        )
    elif нехватка:
        беды.append(f"панель неполна: нет {', '.join(нехватка)}")
        print(f"  ✗ панели не хватает: {', '.join(нехватка)}")
    else:
        print("  ✓ признаки у всех карточек, панель на месте")

    # ── усечение в строке ничего не потеряло (T101) ───────────────────
    # ⚠️ «План · факт» в строке усечён многоточием, потому что у четырёх
    # задач он до 261 знака и распирал сетку. Усечение ЧИСТО ЗРИТЕЛЬНОЕ:
    # полное значение обязано лежать в примечании. Иначе «выровнялось»
    # означало бы «часть данных исчезла», а это худший исход, чем кривая
    # строка — кривую видно, а пропажу нет.
    в_строке = len(re.findall(r'<span class="fact"', страница))
    в_примечании = len(re.findall(r'<p class="сроки">', страница))
    print(f"  СРОКИ: в строке {в_строке} · полностью в примечании {в_примечании}")
    if в_строке != в_примечании:
        беды.append(f"сроки усечены без полной копии: {в_строке - в_примечании}")
        print(
            f"  ✗ у {в_строке - в_примечании} задач усечённые сроки негде прочесть целиком"
        )
    else:
        print("  ✓ усечено только на вид — полностью читается в примечании")

    if беды:
        print(f"\n  ⚠️ РАСХОЖДЕНИЙ {len(беды)}")
        return 1
    print("  ИТОГ: витрина отражает файл целиком")
    return 0


if __name__ == "__main__":
    sys.exit(main())
