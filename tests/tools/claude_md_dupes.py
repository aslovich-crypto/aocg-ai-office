#!/usr/bin/env python3
"""ЗАМЕР ДУБЛЕЙ ПРАВИЛ между CLAUDE.md двух репозиториев (T22, шаг ①).

ЗАЧЕМ. Одно правило, записанное в двух местах СВОИМИ СЛОВАМИ, расходится
молча: сверять две копии никто не будет. Прецеденты дорогие — копия скилла
task-update отставала полтора месяца и предписывала снести из трекера колонки
времени; «фирменные» цвета, которых в дизайн-системе не существовало, дважды
просочились в код. И главное: ослабление идёт не формулировкой, а ПРОПУСКОМ,
а файл, где правила нет, не отличается от файла, где правила и не должно быть.

ЧТО ДЕЛАЕТ. Режет оба файла на единицы (абзац или пункт списка — правило
у нас живёт пунктом), нормализует текст и ищет пары с высоким пересечением
СЛОВАРЕЙ, а не строк: цель — поймать пересказ, а не копипасту.

МЕРА — ДВА СИГНАЛА, кандидатом считается сработавший любой:
  ① КОЭФФИЦИЕНТ ПЕРЕКРЫТИЯ |A∩B| / min(|A|,|B|), а не Жаккар. Причина
     конкретная: выжимка со ссылкой короче источника в разы, и Жаккар её
     топит (знаменатель — объединение). Перекрытие отвечает на нужный
     вопрос: «целиком ли короткий текст лежит внутри длинного».
  ② ОБЩАЯ НЕПРЕРЫВНАЯ ЦЕПОЧКА значимых слов длиной от 4. Правило носит ИМЯ,
     и при пересказе имя переносят дословно, даже когда проза вокруг другая.

ВТОРОЙ СИГНАЛ ДОБАВЛЕН НЕ ИЗ КРАСОТЫ: на первом прогоне КОНТРОЛЬНЫЙ ПРИМЕР
УПАЛ. Известная пара «единственный / все / нигде больше» (полная версия
в бэкенде, ссылка-выжимка во фронте) дала перекрытие 0.35 при пороге 0.45 —
замер пропустил бы ровно тот случай, ради которого заводился. Порог при этом
НЕ трогали: опустить его до 0.35 значило бы подогнать ответ под известную
пару и залить прогон шумом. Контрольный пример не проходит — меняется МЕТОД,
а не порог (правило записано в T26).

ПОЛОС ВЫВОДА ТРИ, А НЕ ДВЕ, и третья заведена тоже по находке: счётчик
показал «ИТОГО 26» при 23 напечатанных. Пары, найденные ТОЛЬКО вторым
сигналом, имеют перекрытие ниже порога и не попадали ни в одну полосу —
инструмент нашёл нужный класс и молча его съел. Отсюда общее требование
ко всем нашим замерам: печатать И «сколько нашёл», И «сколько напечатал».

ЧЕГО ЭТОТ ЗАМЕР НЕ ДЕЛАЕТ, честно:
  • не понимает смысл. Правило, пересказанное ДРУГИМИ словами (синонимы,
    другой пример, другое имя), он не увидит — общего словаря нет;
  • не отличает законное повторение от вредного. Решение «свести или
    оставить» принимает человек, замер даёт СПИСОК КАНДИДАТОВ;
  • не смотрит внутрь одного файла — дубли внутри репозитория не его задача;
  • шумит на общем боилерплейте: одинаковая служебная пометка в двух разных
    правилах даёт ложную пару. Поэтому пометка временного дублирования —
    короткий тег `[ОБЩЕЕ-T22]`, а не абзац прозы.

ТРИ ИСХОДА, а не два (иначе зелёное будет означать «не проверяли»):
    0 — прогон выполнен, кандидатов нет
    1 — прогон выполнен, кандидаты есть
    2 — второй репозиторий недоступен, ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ
    3 — контрольный пример не пройден, прогон не состоялся
Прецедент различения «недоступно» и «чисто» — `design/freshness.mjs` во
фронте (код 2 «канон недоступен»). В CI второго репозитория НЕТ, поэтому
код 2 там ожидаем и означает именно «не проверяли», а не «всё хорошо».

ЗАПУСК:
    ./venv/bin/python tests/tools/claude_md_dupes.py --selfcheck
    ./venv/bin/python tests/tools/claude_md_dupes.py
    FRONT_CLAUDE_MD=/путь/CLAUDE.md ./venv/bin/python tests/tools/claude_md_dupes.py

Самопроверка идёт ПЕРЕД обычным прогоном и останавливает его: разбор,
который врёт на известном ответе, на неизвестных данных врёт тем более.
"""

from __future__ import annotations

import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
КОНТРОЛЬНЫЙ = os.path.join(КОРЕНЬ, "tests", "tools", "fixtures", "dupes_control.tsv")
БЭКЕНД = os.path.join(КОРЕНЬ, "CLAUDE.md")
# Имя переменной ЛАТИНИЦЕЙ намеренно: bash не принимает присваивание
# переменной с кириллическим именем («ФРОНТ_CLAUDE_MD=… command» падает
# с «No such file or directory»), то есть задокументированный способ
# подмены пути молча не работал бы. Поймано прогоном, а не чтением.
ФРОНТ = os.environ.get(
    "FRONT_CLAUDE_MD",
    os.path.normpath(os.path.join(КОРЕНЬ, "..", "aocg-ai-office-web", "CLAUDE.md")),
)

# Пороги назначены ПО ИЗВЕСТНЫМ ПАРАМ контрольного примера, и это оговорено
# намеренно: самопроверка подтверждает согласованность меры с известным
# ответом, а не независимую точность. Меняешь порог — гони контрольный пример.
ПОРОГ_ДУБЛЬ = 0.90
ПОРОГ_ПЕРЕФРАЗ = 0.45
МИН_ЦЕПОЧКА = 4  # общих подряд значимых слов — второй сигнал, см. шапку
МИН_СЛОВ = 10  # короткие пункты дают случайное перекрытие, их не берём

СТОП = set(
    """
и в во не на что он она они но а да за то же бы как из по о об от при для
это этот эта эти тот та те так там тут где когда чтобы если или либо ни уже
ещё еще был была были быть есть нет над под до после между через без с со
у их его её ее наш наша наши свой своя свои сам сама сами весь вся все всё
который которая которые кто чем чём том тем той тех тому этом этому
надо нужно можно нельзя только даже лишь вот здесь потому поэтому
""".split()
)


def нормализовать(текст: str) -> list[str]:
    """Значимые слова в нижнем регистре: без разметки, стоп-слов и коротышей."""
    т = текст.lower()
    т = re.sub(r"`[^`]*`", " ", т)  # код-спаны
    т = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", т)  # ссылки → текст ссылки
    т = re.sub(r"[*_>#|]", " ", т)  # разметка
    слова = re.findall(r"[a-zа-яё0-9]+", т)
    return [с for с in слова if len(с) >= 3 and с not in СТОП]


def единицы(путь: str) -> list[tuple[int, str]]:
    """(номер строки, текст) для каждого абзаца или пункта списка."""
    с_номером: list[tuple[int, str]] = []
    буфер: list[str] = []
    начало = 0
    with open(путь, encoding="utf-8") as f:
        строки = f.readlines()

    def сбросить():
        nonlocal буфер, начало
        if буфер:
            с_номером.append((начало, " ".join(x.strip() for x in буфер)))
            буфер = []

    for н, сырая in enumerate(строки, 1):
        голая = сырая.rstrip("\n").lstrip("> ").rstrip()
        пустая = not голая
        новый_пункт = bool(re.match(r"^([-*+]|\d+\.)\s", голая))
        заголовок = голая.startswith("#")
        таблица = голая.startswith("|")
        if пустая or новый_пункт or заголовок or таблица:
            сбросить()
        if пустая or заголовок or таблица:
            continue
        if not буфер:
            начало = н
        буфер.append(голая)
    сбросить()
    return с_номером


def перекрытие(a: list[str], b: list[str]) -> float:
    """|A∩B| / min(|A|,|B|) по МНОЖЕСТВАМ слов."""
    мa, мb = set(a), set(b)
    if not мa or not мb:
        return 0.0
    return len(мa & мb) / min(len(мa), len(мb))


def общая_цепочка(a: list[str], b: list[str]) -> int:
    """Длина самой длинной ОБЩЕЙ НЕПРЕРЫВНОЙ последовательности слов."""
    if not a or not b:
        return 0
    пред = [0] * (len(b) + 1)
    лучшее = 0
    for i in range(1, len(a) + 1):
        текущ = [0] * (len(b) + 1)
        for j in range(1, len(b) + 1):
            if a[i - 1] == b[j - 1]:
                текущ[j] = пред[j - 1] + 1
                лучшее = max(лучшее, текущ[j])
        пред = текущ
    return лучшее


def полоса(счёт: float, цепочка: int) -> str:
    if счёт >= ПОРОГ_ДУБЛЬ:
        return "ДУБЛЬ"
    if счёт >= ПОРОГ_ПЕРЕФРАЗ or цепочка >= МИН_ЦЕПОЧКА:
        return "ПЕРЕФРАЗ"
    return "РАЗНОЕ"


def самопроверка() -> bool:
    print("КОНТРОЛЬНЫЙ ПРИМЕР")
    if not os.path.exists(КОНТРОЛЬНЫЙ):
        print(f"  ✗ фикстуры нет: {КОНТРОЛЬНЫЙ}")
        return False
    всего = 0
    беды = []
    with open(КОНТРОЛЬНЫЙ, encoding="utf-8") as f:
        for н, сырая in enumerate(f, 1):
            строка = сырая.rstrip("\n")
            if not строка or строка.startswith("#"):
                continue
            части = строка.split("\t")
            if len(части) != 3:
                беды.append(f"строка {н}: колонок {len(части)}, ждали 3")
                continue
            ожидание, a, b = части
            всего += 1
            на, нb = нормализовать(a), нормализовать(b)
            счёт = перекрытие(на, нb)
            цепь = общая_цепочка(на, нb)
            получилось = полоса(счёт, цепь)
            метка = "✓" if получилось == ожидание else "✗"
            print(
                f"  {метка} строка {н}: ждали {ожидание:<9} получили "
                f"{получилось:<9} перекрытие {счёт:.2f}  цепочка {цепь}"
            )
            if получилось != ожидание:
                беды.append(
                    f"строка {н}: {ожидание} → {получилось} "
                    f"(перекрытие {счёт:.2f}, цепочка {цепь})"
                )
    if всего == 0:
        print("  ✗ в фикстуре ноль случаев — это поломка разбора, а не чистота")
        return False
    if беды:
        print(f"  ✗ контрольный пример НЕ пройден: {len(беды)} из {всего}")
        for б in беды:
            print("     ·", б)
        print(
            "  Порог НЕ подгонять: контрольный пример не проходит — "
            "меняется МЕТОД (см. T26)."
        )
        return False
    print(f"  ✓ контрольный пример пройден: {всего} случая, все разобраны верно")
    return True


def прогон() -> int:
    for путь, имя in ((БЭКЕНД, "бэкенд"), (ФРОНТ, "фронт")):
        if not os.path.exists(путь):
            print(f"\n⚠️  {имя}: файла нет ({путь})")
            print("ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ — код возврата 2")
            return 2

    б = [(н, т, нормализовать(т)) for н, т in единицы(БЭКЕНД)]
    ф = [(н, т, нормализовать(т)) for н, т in единицы(ФРОНТ)]
    б_годных = [x for x in б if len(set(x[2])) >= МИН_СЛОВ]
    ф_годных = [x for x in ф if len(set(x[2])) >= МИН_СЛОВ]

    print(
        f"\nЕДИНИЦ РАЗОБРАНО: бэкенд {len(б)} (годных {len(б_годных)}), "
        f"фронт {len(ф)} (годных {len(ф_годных)}); "
        f"сравнений {len(б_годных) * len(ф_годных)}"
    )
    print(
        f"ПОРОГИ: дубль ≥ {ПОРОГ_ДУБЛЬ}, перефраз ≥ {ПОРОГ_ПЕРЕФРАЗ} "
        f"ИЛИ общая цепочка ≥ {МИН_ЦЕПОЧКА}, "
        f"минимум значимых слов {МИН_СЛОВ}"
    )

    пары = []
    for бн, бт, бс in б_годных:
        for фн, фт, фс in ф_годных:
            счёт = перекрытие(бс, фс)
            цепь = общая_цепочка(бс, фс) if счёт >= 0.15 else 0
            if полоса(счёт, цепь) != "РАЗНОЕ":
                пары.append((счёт, цепь, бн, бт, фн, фт))
    пары.sort(reverse=True, key=lambda p: (p[0], p[1]))

    def срез(т: str, n: int = 96) -> str:
        т = " ".join(т.split())
        return т if len(т) <= n else т[:n] + "…"

    напечатано = 0
    for название, лоу, хай in (
        ("ДУБЛИ (почти дословно)", ПОРОГ_ДУБЛЬ, 1.01),
        ("ПЕРЕФРАЗЫ (одно правило разными словами)", ПОРОГ_ПЕРЕФРАЗ, ПОРОГ_ДУБЛЬ),
        (
            "ТОЛЬКО ПО ОБЩЕЙ ЦЕПОЧКЕ (перекрытие ниже порога — "
            "общее ИМЯ правила при разной прозе)",
            0.0,
            ПОРОГ_ПЕРЕФРАЗ,
        ),
    ):
        группа = [p for p in пары if лоу <= p[0] < хай]
        print(f"\n══ {название}: {len(группа)}")
        for счёт, цепь, бн, бт, фн, фт in группа:
            print(f"  перекр {счёт:.2f} цепь {цепь:<2} бэк:{бн:<4} {срез(бт)}")
            print(f"                       фронт:{фн:<4} {срез(фт)}")
            напечатано += 1

    # НАЙДЕНО ПРОТИВ НАПЕЧАТАНО — обязательная сверка для любого нашего
    # замера. Заведена после того, как этот же инструмент нашёл три пары
    # и не показал их: полосы вывода не покрывали найденное.
    print(f"\nНАЙДЕНО КАНДИДАТОВ: {len(пары)} · НАПЕЧАТАНО: {напечатано}")
    if напечатано != len(пары):
        print(
            "✗ ЗАМЕР ПРЯЧЕТ СВОИ ЖЕ НАХОДКИ: полосы вывода не покрывают "
            "найденное. Это поломка инструмента, а не результат."
        )
        return 3
    return 1 if пары else 0


if __name__ == "__main__":
    только_контроль = "--selfcheck" in sys.argv
    if not самопроверка():
        print(
            "\nПрогон ОСТАНОВЛЕН: разбор врёт на известном ответе, "
            "на неизвестных данных соврёт тем более."
        )
        sys.exit(3)
    sys.exit(0 if только_контроль else прогон())
