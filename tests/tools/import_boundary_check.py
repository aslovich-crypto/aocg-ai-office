#!/usr/bin/env python3
"""ПРОВЕРКА СРЕДЫ: докуда достаёт `@`-импорт в CLAUDE.md (T22, опыт Г3).

ЗАЧЕМ. На импорте держится доставка правил: `CLAUDE.md` бэкенда втягивает
`docs/RULES-FRONTEND.md` строкой `@docs/RULES-FRONTEND.md`, и если импорт
перестанет работать, 459 строк правил исчезнут из контекста МОЛЧА — ни ошибки,
ни предупреждения не будет (это установлено случаем ④ ниже). Поведение
принадлежит СРЕДЕ, а не нашему коду: со сменой версии Claude Code ответ может
измениться, а наш репозиторий об этом не узнает.

ЧТО ПРОВЕРЯЕТ — четыре случая с ИЗВЕСТНЫМИ ответами, замеренные 10.08.2026
на версии 2.1.126:

    ① метка прямо в CLAUDE.md            → ПРИШЛА  (контроль пробы)
    ② @./local-rules.md внутри проекта   → ПРИШЛА  (на этом стоим)
    ③ @../shared/... за границу каталога → НЕ пришла
    ④ @./НЕТ-ТАКОГО-ФАЙЛА.md             → НЕ пришла, и строка импорта
                                            остаётся в инструкциях обычным
                                            текстом: ни ошибки, ни кода != 0

СЛУЧАЙ ① ОБЯЗАТЕЛЕН И НЕ УДАЛЯЕТСЯ: без него «НЕ пришла» в случаях ③ и ④
неотличимо от «проба сломалась». Случай ④ обязателен по той же причине
с другой стороны: без него «всё хорошо» неотличимо от «мы не проверяли
молчаливый отказ».

ПОЧЕМУ ВОПРОС ЗАДАЁТСЯ ПРО МЕТКУ, А НЕ ПРО САМОЧУВСТВИЕ. Спрашивать модель
«видишь ли ты предупреждение» бесполезно: 10.08.2026 на этот вопрос она
ответила «да», а дословная цитата инструкций показала, что предупреждения
нет вовсе — модель его додумала. Инструмент, отвечающий о собственном
состоянии, не является замером этого состояния (T26). Поэтому спрашиваем
про НАЛИЧИЕ КОНКРЕТНОЙ СТРОКИ, которую нельзя угадать.

ЗАПУСК:
    ./venv/bin/python tests/tools/import_boundary_check.py          # разложить
    ./venv/bin/python tests/tools/import_boundary_check.py --run    # и прогнать

Без `--run` только раскладывает стенд и печатает команды: каждый прогон —
это отдельный запуск `claude -p`, он стоит времени и токенов, и он же
создаёт запись сессии в журналах (см. поправку к замеру носителей в T22).

ИСХОДЫ: 0 — среда ведёт себя как записано · 1 — поведение ИЗМЕНИЛОСЬ,
разбираться · 2 — `claude` не найден, ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile

МЕТКА = "КАНАРЕЙКА-7F3A9"
ВОПРОС = (
    f"Выведи ТОЛЬКО слово {МЕТКА}, если оно есть в твоих инструкциях. "
    "Если такого слова нет — выведи НЕТ. Ничего больше не пиши."
)

# (имя, содержимое CLAUDE.md, спутники, ожидание «метка дойдёт»)
СЛУЧАИ = [
    (
        "① метка внутри CLAUDE.md (контроль пробы)",
        f"# Правила\n\nСЛОВО-МЕТКА: {МЕТКА}\n",
        {},
        True,
    ),
    (
        "② импорт внутри каталога проекта",
        "# Правила\n\n@./local-rules.md\n",
        {"local-rules.md": f"СЛОВО-МЕТКА: {МЕТКА}\n"},
        True,
    ),
    (
        "③ импорт ЗА границу каталога проекта",
        "# Правила\n\n@../shared/RULES-SHARED.md\n",
        {},
        False,
    ),
    (
        "④ импорт несуществующего файла",
        "# Правила\n\n@./НЕТ-ТАКОГО-ФАЙЛА.md\n",
        {},
        False,
    ),
]


def разложить(корень: str) -> list[tuple[str, str, bool]]:
    общий = os.path.join(корень, "shared")
    os.makedirs(общий, exist_ok=True)
    with open(os.path.join(общий, "RULES-SHARED.md"), "w", encoding="utf-8") as f:
        f.write(f"СЛОВО-МЕТКА: {МЕТКА}\n")
    разложено = []
    for н, (имя, claude_md, спутники, ждём) in enumerate(СЛУЧАИ, 1):
        каталог = os.path.join(корень, f"proj{н}")
        os.makedirs(каталог, exist_ok=True)
        with open(os.path.join(каталог, "CLAUDE.md"), "w", encoding="utf-8") as f:
            f.write(claude_md)
        for файл, тело in спутники.items():
            with open(os.path.join(каталог, файл), "w", encoding="utf-8") as f:
                f.write(тело)
        разложено.append((имя, каталог, ждём))
    return разложено


def прогнать(каталог: str) -> bool:
    """True, если метка дошла до инструкций."""
    готово = subprocess.run(
        ["claude", "-p", ВОПРОС],
        cwd=каталог,
        capture_output=True,
        text=True,
        timeout=300,
    )
    return МЕТКА in готово.stdout


def main() -> int:
    if shutil.which("claude") is None:
        print("⚠️  `claude` не найден в PATH.")
        print("ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ — код возврата 2")
        return 2

    корень = tempfile.mkdtemp(prefix="import-boundary-")
    разложено = разложить(корень)
    print(f"СТЕНД РАЗЛОЖЕН: {корень}\n")

    if "--run" not in sys.argv:
        print("Прогон не запускался (нет --run). Команды для ручной проверки:\n")
        for имя, каталог, ждём in разложено:
            print(
                f"  # {имя} — ожидание: {'метка ПРИДЁТ' if ждём else 'метка НЕ придёт'}"
            )
            print(f"  cd {каталог} && claude -p '{ВОПРОС}'\n")
        return 0

    беды = []
    for имя, каталог, ждём in разложено:
        пришла = прогнать(каталог)
        совпало = пришла == ждём
        print(
            f"  {'✓' if совпало else '✗'} {имя}\n"
            f"      ждали: {'метка придёт' if ждём else 'метка не придёт'} · "
            f"получили: {'пришла' if пришла else 'НЕТ'}"
        )
        if not совпало:
            беды.append(имя)

    if беды:
        print(f"\n✗ ПОВЕДЕНИЕ СРЕДЫ ИЗМЕНИЛОСЬ, случаев: {len(беды)}")
        print(
            "   Импорт — несущая конструкция доставки правил "
            "(@docs/RULES-FRONTEND.md). Разбираться до того, как это "
            "заметят по пропавшим правилам."
        )
        return 1
    print("\n✓ среда ведёт себя как записано 10.08.2026")
    return 0


if __name__ == "__main__":
    sys.exit(main())
