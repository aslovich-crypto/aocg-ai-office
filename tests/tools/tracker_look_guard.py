# -*- coding: utf-8 -*-
"""Сторож РАЗМЕЩЕНИЯ витрины: страницу считает браузер, числа читает прибор.

⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИБОР. tracker_html_guard считает карточки, разбор
разметки и целостность тегов — и всё это может быть зелёным на странице,
которая выглядит сломанной. Три беды подряд (T98, T101 дважды) нашёл
ВЛАДЕЛЕЦ ГЛАЗАМИ при зелёном стороже: имя схлопывалось в букву по
вертикали, хвост уезжал за край, страница ползла вбок. Пока прибора нет,
детектором вёрстки работает владелец — худший расход из возможных.

⚠️ И ОТДЕЛЬНО: В T101 БЫЛО ЗАПИСАНО, ЧТО РАЗМЕЩЕНИЕ ЛОВИТСЯ ТОЛЬКО
ГЛАЗАМИ. Это оказалось неверно. Chrome умеет открыть страницу без окна,
дать ей посчитать раскладку и вернуть DOM уже с числами.

⚠️ ПОЧЕМУ НЕ В `tracker-check`, А ОТДЕЛЬНОЙ ЦЕЛЬЮ: нужен Chrome, это
внешняя зависимость. Но МОЛЧА ПРОПУСКАТЬ ПРОВЕРКУ ПРИ ЕГО ОТСУТСТВИИ
НЕЛЬЗЯ — печатаем «ПРОВЕРКА НЕ ВЫПОЛНЕНА» и краснеем. Тот же класс, что
М11 и М29: невыполненная проверка обязана отличаться от пройденной.
"""

import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
СБОРЩИК = pathlib.Path(__file__).with_name("tracker_html.py")
ВЫХОД = pathlib.Path("/tmp/aocg-tracker.html")
ЗАМЕРЯЕМАЯ = pathlib.Path("/tmp/aocg-tracker-замер.html")

ОКНО = (1400, 1000)

# ⚠️ ПОРОГИ ПЕРЕСТАВЛЕНЫ ПО ЗАМЕРУ, А НЕ НА ГЛАЗ — И ЭТО ВАЖНО.
# Первая редакция взяла 200px и 200px «с запасом», и прибор ПРОПУСТИЛ
# мутацию М40 — тот самый сломанный CSS, из-за которого его и ставили:
# колонка имени была 220px (порог 200 не сработал), высота строки 112px
# (порог 200 не сработал). Прибор, пропускающий свою же беду, бесполезен.
#
# Замер при окне 1400: здоровая витрина — узкая колонка имени 600px,
# самая высокая строка 67px при медиане ~46. Сломанная М40 — 220px и 112px.
# Пороги ставятся МЕЖДУ этими числами, а не «с запасом» от одного края.
МИН_ШИРИНА_ИМЕНИ = 320
# ⚠️ Высота — ОТНОСИТЕЛЬНО МЕДИАНЫ, а не в пикселях. Абсолютный порог
# протухает от смены шрифта, ширины окна и длины имён; кратность медиане
# держится. Здоровая витрина: 67/46 = 1,5. Сломанная М40: 112/46 = 2,4.
КРАТНОСТЬ_ВЫСОТЫ = 2.0

БРАУЗЕРЫ = (
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Chromium.app/Contents/MacOS/Chromium",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
)

ЗАМЕР = """
<div id="ЗАМЕР">не считано</div>
<script>
(function(){
  var строки=[].slice.call(document.querySelectorAll('summary.row'));
  var мера=[];
  for(var i=0;i<строки.length;i++){
    var р=строки[i], имя=р.querySelector('.tname');
    мера.push({
      ид:(р.querySelector('.tid')||{}).textContent||'?',
      ш:имя?имя.getBoundingClientRect().width:0,
      в:р.getBoundingClientRect().height,
      край:р.scrollWidth>р.clientWidth+1});
  }
  /* медиана высоты — опора для кратности; пикселей в пороге нет */
  var высоты=мера.map(function(м){return м.в;}).sort(function(a,b){return a-b;});
  var медиана=высоты.length?высоты[Math.floor(высоты.length/2)]:0;
  var предел=медиана*__КРАТНОСТЬ__;
  var узких=0, заКрай=0, высоких=0, минИмя=1e9, максВысота=0, примеры=[];
  for(var j=0;j<мера.length;j++){
    var м=мера[j], плохо=false;
    if(м.ш<минИмя) минИмя=м.ш;
    if(м.в>максВысота) максВысота=м.в;
    if(м.ш<__МИН_ИМЯ__){узких++; плохо=true;}
    if(медиана>0&&м.в>предел){высоких++; плохо=true;}
    if(м.край){заКрай++; плохо=true;}
    if(плохо&&примеры.length<5) примеры.push(м.ид+' (имя '+Math.round(м.ш)+'px, высота '+Math.round(м.в)+'px)');
  }
  var d=document.documentElement;
  var бок=Math.max(d.scrollWidth, document.body.scrollWidth)-d.clientWidth;
  document.getElementById('ЗАМЕР').textContent=JSON.stringify({
    строк:строки.length, узких:узких, высоких:высоких, заКрай:заКрай,
    минИмя:Math.round(минИмя), максВысота:Math.round(максВысота),
    медиана:Math.round(медиана), предел:Math.round(предел),
    бок:Math.round(бок), примеры:примеры});
})();
</script>
"""


def найти_браузер():
    for путь in БРАУЗЕРЫ:
        if pathlib.Path(путь).exists():
            return путь
    return None


def замерить(браузер):
    """DOM после подсчёта раскладки → разобранные числа. None, если не вышло."""
    страница = ВЫХОД.read_text(encoding="utf-8")
    скрипт = ЗАМЕР.replace("__МИН_ИМЯ__", str(МИН_ШИРИНА_ИМЕНИ)).replace(
        "__КРАТНОСТЬ__", str(КРАТНОСТЬ_ВЫСОТЫ)
    )
    ЗАМЕРЯЕМАЯ.write_text(
        страница.replace("</body>", скрипт + "</body>"), encoding="utf-8"
    )
    р = subprocess.run(
        [
            браузер,
            "--headless",
            "--disable-gpu",
            "--hide-scrollbars",
            "--virtual-time-budget=6000",
            f"--window-size={ОКНО[0]},{ОКНО[1]}",
            "--dump-dom",
            str(ЗАМЕРЯЕМАЯ),
        ],
        capture_output=True,
        text=True,
        timeout=120,
    )
    м = re.search(r'<div id="ЗАМЕР">(\{.*?\})</div>', р.stdout, re.S)
    if not м:
        return None, (р.stdout[-300:] + р.stderr[-300:])
    return json.loads(м.group(1)), ""


def main():
    print("\nРАЗМЕЩЕНИЕ ВИТРИНЫ")

    # ⚠️ Невыполненная проверка обязана отличаться от пройденной (М11, М29).
    браузер = найти_браузер()
    if браузер is None:
        print("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: не найден Chrome ни по одному из путей:")
        for п in БРАУЗЕРЫ:
            print(f"      {п}")
        print("    Размещение считает браузер — без него мерить нечем.")
        return 1

    р = subprocess.run(
        [sys.executable, str(СБОРЩИК)], cwd=КОРЕНЬ, capture_output=True, text=True
    )
    if р.returncode != 0 or not ВЫХОД.exists():
        print(f"  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: сборщик упал (код {р.returncode})")
        for с in (р.stdout + р.stderr).strip().splitlines():
            print(f"      {с}")
        return 1

    замер, беда = замерить(браузер)
    if замер is None:
        print("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: браузер не вернул замер")
        for с in беда.strip().splitlines()[-4:]:
            print(f"      {с}")
        return 1

    print(f"  окно {ОКНО[0]}×{ОКНО[1]} · строк измерено {замер['строк']}")
    print(
        f"  САМАЯ УЗКАЯ КОЛОНКА ИМЕНИ : {замер['минИмя']}px (порог {МИН_ШИРИНА_ИМЕНИ})"
    )
    print(
        f"  САМАЯ ВЫСОКАЯ СТРОКА      : {замер['максВысота']}px "
        f"(медиана {замер['медиана']}, предел {замер['предел']} = "
        f"{КРАТНОСТЬ_ВЫСОТЫ}× медианы)"
    )
    print(f"  ТЕКСТ ЗА КРАЙ СТРОКИ      : {замер['заКрай']}")
    print(f"  БОКОВАЯ ПРОКРУТКА         : {замер['бок']}px")

    беды = []
    if замер["строк"] == 0:
        беды.append("не измерено ни одной строки")
        print("  ✗ НИ ОДНОЙ СТРОКИ НЕ ИЗМЕРЕНО — мерить было нечего")
    if замер["узких"]:
        беды.append(f"колонка имени схлопнута у {замер['узких']} строк")
        print(
            f"  ✗ КОЛОНКА ИМЕНИ СХЛОПНУТА у {замер['узких']} строк — встанут столбиком"
        )
    if замер["высоких"]:
        беды.append(f"строк выше {КРАТНОСТЬ_ВЫСОТЫ}× медианы: {замер['высоких']}")
        print(
            f"  ✗ {замер['высоких']} строк выше {КРАТНОСТЬ_ВЫСОТЫ}× медианы — "
            "имя переносится по буквам"
        )
    if замер["заКрай"]:
        беды.append(f"текст за краем строки: {замер['заКрай']}")
        print(f"  ✗ у {замер['заКрай']} строк текст уходит за их край")
    if замер["бок"] > 1:
        беды.append(f"боковая прокрутка {замер['бок']}px")
        print(f"  ✗ СТРАНИЦА ПОЛЗЁТ ВБОК на {замер['бок']}px")

    if замер["примеры"]:
        print("  где именно:")
        for п in замер["примеры"]:
            print(f"      {п}")

    if беды:
        print(f"\n  ⚠️ РАСХОЖДЕНИЙ {len(беды)}")
        return 1
    print("  ИТОГ: строки не схлопнуты, ничего не уезжает за край")
    return 0


if __name__ == "__main__":
    sys.exit(main())
