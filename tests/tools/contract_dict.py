def sql_литералы(sql: str) -> set[str]:
    """Одиночные кавычки внутри SQL — ПОСТРОЧНО, а не по всей строке разом.

    Куплено ошибкой 10.08.2026: DDL нашей схемы — ОДНА строка на 19 449 символов,
    и разбор `'([^']*)'` по ней целиком спарил кавычки ВРАЗБЕЖКУ: апострофы
    в комментариях и в соседних `DEFAULT '...'` сдвигают разбиение, и девять
    видов расхода из `CHECK (tax_kind IN (...))` не нашлись ВООБЩЕ. Сторож
    решил, что словаря в `app/database.py` нет, и предложил убрать запись
    из белого списка как устаревшую — то есть разбор не упал, а молча отдал
    другое (правило T30). Внутри ОДНОЙ строки SQL кавычки сбалансированы,
    поэтому режем построчно.
    """
    найдено = set()
    for строка in sql.split("\n"):
        найдено.update(re.findall(r"'([^'\n]*)'", строка))
    return найдено


ПРИЗНАК_SQL = re.compile(r"\b(CHECK|CREATE TABLE|ALTER TABLE|INSERT INTO)\b")


def _sql_виды_расхода() -> set[str]:
    """Девять видов расхода из `CHECK (tax_kind IN (...))` в app/database.py.

    ТРЕТЬЯ СТОРОНА СЛОВАРЯ, и до 10.08.2026 её не видел никто: замер сверял
    python с javascript, а этот список лежит внутри строки DDL. Разойдётся —
    засев упрётся в констрейнт на живой базе.
    """
    текст = open(os.path.join(КОРЕНЬ, "app", "database.py"), encoding="utf-8").read()
    м = re.search(r"CHECK \(tax_kind IN \((.*?)\)\)", текст, re.S)
    if not м:
        raise LookupError("в app/database.py не найден CHECK (tax_kind IN (...))")
    return sql_литералы(м.group(1))


