def без_комментариев(текст: str) -> str:
    """Вырезать комментарии JS, не тронув строки.

    Зачем: в `src/lib/reports.js` в КОММЕНТАРИИ перечислены статусы
    («Источник истины по статусам — бэкенд: Literal[...]»). Без вырезания
    комментарий даёт пары, которых в коде нет, — замер сам себе рисует
    совпадение и выглядит чище, чем есть.
    """
    out = []
    i, n = 0, len(текст)
    строка = None  # активная кавычка: ' " `
    while i < n:
        c = текст[i]
        if строка:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(текст[i + 1])
                i += 2
                continue
            if c == строка:
                строка = None
            i += 1
            continue
        if c in "'\"`":
            строка = c
            out.append(c)
            i += 1
            continue
        if c == "/" and i + 1 < n and текст[i + 1] == "/":
            while i < n and текст[i] != "\n":
                i += 1
            continue
        if c == "/" and i + 1 < n and текст[i + 1] == "*":
            i += 2
            while i + 1 < n and not (текст[i] == "*" and текст[i + 1] == "/"):
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


КАВЫЧКИ = re.compile(r'"((?:[^"\\\n]|\\.)*)"' r"|'((?:[^'\\\n]|\\.)*)'")
ГОЛЫЙ_КЛЮЧ = re.compile(r"^[ \t]*([A-Za-zА-Яа-яЁё_$][\wЀ-ӿ$]*)[ \t]*:", re.M)


def литералы_js(текст: str) -> set[str]:
    """Строки в кавычках + голые ключи объектов. Второе — починка слепоты."""
    т = без_комментариев(текст)
    найдено = set()
    for m in КАВЫЧКИ.finditer(т):
        найдено.add(m.group(1) if m.group(1) is not None else m.group(2))
    найдено.update(ГОЛЫЙ_КЛЮЧ.findall(т))
    return найдено


def блок(текст: str, имя: str, открыв: str) -> str:
    """Тело именованного литерала по СЧЁТУ СКОБОК, а не регуляркой.

    Регулярка на вложенных объектах (`ROLES = [{...},{...}]`) ошибается тихо:
    берёт до первой закрывающей. Счёт скобок с пропуском строк — не ошибается.
    """
    т = без_комментариев(текст)
    m = re.search(rf"\b{re.escape(имя)}\b\s*=\s*", т)
    if not m:
        raise LookupError(f"не найдено объявление {имя}")
    i = т.index(открыв, m.end())
    закрыв = {"{": "}", "[": "]"}[открыв]
    глубина, j, строка = 0, i, None
    while j < len(т):
        c = т[j]
        if строка:
            if c == "\\":
                j += 2
                continue
            if c == строка:
                строка = None
        elif c in "'\"`":
            строка = c
        elif c == открыв:
            глубина += 1
        elif c == закрыв:
            глубина -= 1
            if глубина == 0:
                return т[i + 1 : j]
        j += 1
    raise LookupError(f"не закрыт блок {имя}")


def js_массив_строк(текст: str, имя: str) -> set[str]:
    """`const NAME = ["a", "b"]` → {"a", "b"}."""
    тело = блок(текст, имя, "[")
    return {
        (m.group(1) if m.group(1) is not None else m.group(2))
        for m in КАВЫЧКИ.finditer(тело)
    }


def js_ключи_объекта(текст: str, имя: str) -> set[str]:
    """`const NAME = {a: 1, "b c": 2}` → {"a", "b c"} — ключи ВЕРХНЕГО уровня.

    Ключи вложенных объектов (`{bg: ..., fg: ...}`) не берём: они — оформление,
    а не словарь. Отсюда счёт глубины.
    """
    тело = блок(текст, имя, "{")
    ключи, глубина, буфер, строка = set(), 0, "", None
    i = 0
    while i < len(тело):
        c = тело[i]
        if строка:
            буфер += c
            if c == "\\":
                буфер += тело[i + 1] if i + 1 < len(тело) else ""
                i += 2
                continue
            if c == строка:
                строка = None
            i += 1
            continue
        if c in "'\"`":
            строка = c
            буфер += c
        elif c in "{[(":
            глубина += 1
            буфер = ""
        elif c in "}])":
            глубина -= 1
            буфер = ""
        elif c == "," and глубина == 0:
            буфер = ""
        elif c == ":" and глубина == 0:
            ключ = буфер.strip()
            if len(ключ) >= 2 and ключ[0] in "'\"" and ключ[0] == ключ[-1]:
                ключ = ключ[1:-1]
            if ключ:
                ключи.add(ключ)
            буфер = ""
        else:
            буфер += c
        i += 1
    return ключи


def js_поле_в_массиве(текст: str, имя: str, поле: str) -> set[str]:
    """`const ROLES = [{id: "admin", ...}, ...]` → {"admin", ...}."""
    тело = блок(текст, имя, "[")
    return set(re.findall(rf'\b{re.escape(поле)}\s*:\s*["\']([^"\']+)["\']', тело))


