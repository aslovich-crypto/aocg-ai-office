# а не пропускаются молча: отсутствие источника — тоже результат замера.
БЕЗ_КАНОНА = [
    {
        "имя": "источники чека",
        "фронт_где": "src/App.jsx SRC_LABEL",
        "почему": "в бэкенде только комментарий app/routers/receipts.py:46, "
        "константы нет — сверять не с чем",
    },
]


# ─────────────────────────── сбор ───────────────────────────


def литералы_бэкенда() -> dict[str, set[str]]:
    """Строковые константы python через ast. Разбор честный, не регулярка."""
    найдено: dict[str, set[str]] = {}
    for путь in sorted(
        glob.glob(os.path.join(КОРЕНЬ, "app", "**", "*.py"), recursive=True)
    ):
        отн = os.path.relpath(путь, КОРЕНЬ)
        дерево = ast.parse(open(путь, encoding="utf-8").read())
        for узел in ast.walk(дерево):
            if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
                найдено.setdefault(узел.value, set()).add(отн)
                # Литералы ВНУТРИ SQL-строк: третья сторона словаря живёт там
                # (CHECK, DEFAULT). Для ast это одна большая строка.
                if ПРИЗНАК_SQL.search(узел.value):
                    for л in sql_литералы(узел.value):
                        найдено.setdefault(л, set()).add(отн + " (SQL)")
    return найдено


def литералы_фронта(корень: str) -> dict[str, set[str]]:
    найдено: dict[str, set[str]] = {}
    for путь, _, файлы in os.walk(корень):
        for ф in sorted(файлы):
            if not ф.endswith((".js", ".jsx")):
                continue
            полный = os.path.join(путь, ф)
            отн = os.path.relpath(полный, корень)
            for s in литералы_js(open(полный, encoding="utf-8").read()):
                найдено.setdefault(s, set()).add(отн)
    return найдено


def годен(s: str) -> bool:
    return len(s.strip()) >= МИН_ДЛИНА and not s.isspace()


# ─────────────────────────── самопроверка ───────────────────────────


def самопроверка() -> bool:
    """Известный ответ ПЕРЕД неизвестными данными. Обе половины (T30).

    Ожидания лежат В ФИКСТУРЕ рядом с образцом, а не здесь: инструмент
    переписывают, ответ должен пережить переписывание.
    """
    print("САМОПРОВЕРКА на контрольном примере из репозитория")
    print(f"  фикстура: {os.path.relpath(ФИКСТУРА, КОРЕНЬ)}")
    if not os.path.exists(ФИКСТУРА):
        print("  ✗ фикстуры нет — проверять нечем")
        return False
    текст = open(ФИКСТУРА, encoding="utf-8").read()

    ожидания = {}
    for m in re.finditer(r"^//\s*ОЖИДАНИЕ-(\S+)\s+(\S+)\s*=\s*(.*)$", текст, re.M):
        вид, имя, значения = m.group(1), m.group(2), m.group(3).strip()
        ожидания[(вид, имя)] = set(
            filter(None, (з.strip() for з in значения.split("|")))
        )
    if not ожидания:
        print("  ✗ в фикстуре нет строк ОЖИДАНИЕ- — сверять не с чем")
        return False

    разборщики = {
        "МАССИВ": js_массив_строк,
        "КЛЮЧИ": js_ключи_объекта,
        "ПОЛЕ-ID": lambda t, имя: js_поле_в_массиве(t, имя, "id"),
    }
    всё_сошлось = True
    for (вид, имя), ждём in sorted(ожидания.items()):
        if вид not in разборщики:
            print(f"  ✗ {вид} {имя}: неизвестный вид ожидания")
            всё_сошлось = False
            continue
        try:
            факт = разборщики[вид](текст, имя)
        except LookupError as e:
            print(f"  ✗ {вид} {имя}: разбор не состоялся — {e}")
            всё_сошлось = False
            continue
        if факт == ждём:
            print(f"  ✓ {вид} {имя}: {len(факт)} шт., совпало")
        else:
            print(f"  ✗ {вид} {имя}: ждали {sorted(ждём)}, получили {sorted(факт)}")
            всё_сошлось = False

    # ВТОРАЯ ПОЛОВИНА. Без неё «расхождений 0» не отличить от «проверка не
    # выполнялась»: заведомо разошедшаяся пара ОБЯЗАНА дать красный.
    здоровый = ожидания.get(("КЛЮЧИ", "КОНТРОЛЬ_ЗДОРОВЫЙ"))
    битый = ожидания.get(("КЛЮЧИ", "КОНТРОЛЬ_БИТЫЙ"))
    if здоровый is None or битый is None:
        print("  ✗ в фикстуре нет пары здоровый/битый — вторая половина не проверена")
        return False
    if здоровый != битый and (здоровый - битый or битый - здоровый):
        print(
            f"  ✓ заведомо битая пара даёт расхождение: "
            f"−{sorted(здоровый - битый)} +{sorted(битый - здоровый)}"
        )
    else:
        print("  ✗ заведомо битая пара расхождения НЕ дала — замер слеп")
        всё_сошлось = False

    print(
        "  ИТОГ:",
        "самопроверка пройдена" if всё_сошлось else "САМОПРОВЕРКА НЕ ПРОЙДЕНА",
    )
    return всё_сошлось


# ─────────────────────────── прогон ───────────────────────────


def main() -> int:
    подробно = "--verbose" in sys.argv
    принять = "--accept" in sys.argv

    if "--selfcheck" in sys.argv:
        return 0 if самопроверка() else 3

    # Самопроверка ПЕРЕД обычным прогоном и останавливает его.
    if not самопроверка():
        print("\nПРОГОН НЕ СОСТОЯЛСЯ: разбор врёт на известном ответе.")
        return 3
    print()

    if not os.path.isdir(ФРОНТ_SRC):
        print("⚠ ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ: фронт-репозиторий недоступен")
        print(f"  ждали каталог: {ФРОНТ_SRC}")
        print(
            "  (в CI бэкенда второго репозитория нет — это ожидаемо, "
            "и это НЕ означает «расхождений нет»)"
        )
        return 2

    sys.path.insert(0, КОРЕНЬ)
    бэк = литералы_бэкенда()
    фронт = литералы_фронта(ФРОНТ_SRC)
    общие = {s for s in (бэк.keys() & фронт.keys()) if годен(s)}

    # ── отпечаток читаем ДО слоя ②: в нём лежат принятые расхождения
    прошлое = None
    if os.path.exists(ОТПЕЧАТОК):
        прошлое = json.load(open(ОТПЕЧАТОК, encoding="utf-8"))
    было = set(прошлое["общие"]) if прошлое else None
    принятые = (прошлое or {}).get("принятые_расхождения", {})

    # ── слой ②: названные словари
    вердикты, расхождения_словарей, устаревшие = [], 0, 0
    кэш: dict[str, str] = {}
    for сл in СЛОВАРИ:
        путь = os.path.join(ФРОНТ_SRC, сл["фронт_файл"])
        if путь not in кэш:
            кэш[путь] = open(путь, encoding="utf-8").read()
        сторона_бэк = сл["бэк"]()
        try:
            сторона_фронт = сл["фронт"](кэш[путь])
        except LookupError as e:
            вердикты.append((сл, None, None, f"разбор не состоялся: {e}", None))
            расхождения_словарей += 1
            continue
        только_бэк = sorted(сторона_бэк - сторона_фронт)
        только_фронт = sorted(сторона_фронт - сторона_бэк)

        # ПРИНЯТОЕ РАСХОЖДЕНИЕ — не то же, что «расхождения нет».
        # Сторож, который всегда красный, перестают читать; поэтому осознанное
        # расхождение записывается в отпечаток ВМЕСТЕ С ПРИЧИНОЙ и лежит в git.
        # Но исключение, ПЕРЕЖИВШЕЕ свою причину, — это ложь в документации,
        # поэтому устаревшее исключение красит прогон так же, как расхождение.
        принято = принятые.get(сл["имя"])
        совпало_с_принятым = bool(принято) and (
            только_бэк == принято.get("только_бэк", [])
            and только_фронт == принято.get("только_фронт", [])
        )
        if принято and not (только_бэк or только_фронт):
            устаревшие += 1
        elif (только_бэк or только_фронт) and not совпало_с_принятым:
            расхождения_словарей += 1
        вердикты.append(
            (
                сл,
                только_бэк,
                только_фронт,
                None,
                принято if совпало_с_принятым else None,
            )
        )
    исчезло = sorted(было - общие) if было is not None else []
    появилось = sorted(общие - было) if было is not None else []

    # ── вывод. Расхождение — ПЕРВОЙ СТРОКОЙ СВЕРХУ, не примечанием внизу.
    if было is None:
        print("⚠ ОТПЕЧАТКА НЕТ — сравнивать не с чем, это первый прогон.")
        print("  Засеять: --accept\n")
    elif исчезло or появилось:
        print("⛔ СЛОВАРЬ ИЗМЕНИЛСЯ С ПРОШЛОГО ПРОГОНА")
        if исчезло:
            print(
                "   ИСЧЕЗЛО — пара распалась, вероятное переименование на одной стороне:"
            )
            for s in исчезло:
                где = "бэкенд" if s in бэк else ("фронт" if s in фронт else "нигде")
                print(f"     − {s!r}   (осталось только: {где})")
        if появилось:
            print("   ПОЯВИЛОСЬ — новый рукописный контракт мимо механизма:")
            for s in появилось:
                print(f"     + {s!r}   (py={len(бэк[s])} js={sorted(фронт[s])[:2]})")
        print()

    print(f"СОСТАВ: {len(общие)} общих литералов", end="")
    if было is not None:
        print(f" (было {len(было)})", end="")
    print(f" · словарей сверено {len(СЛОВАРИ)}, канона нет у {len(БЕЗ_КАНОНА)}")
    print()

    print("НАЗВАННЫЕ СЛОВАРИ (слой ②)")
    for сл, только_бэк, только_фронт, ошибка, принято in вердикты:
        if ошибка:
            print(f"  ✗ {сл['имя']}: {ошибка}")
            continue
        if принято:
            print(f"  ≈ {сл['имя']}: ПРИНЯТОЕ РАСХОЖДЕНИЕ")
            if только_бэк:
                print(f"      только в бэкенде: {только_бэк}")
            if только_фронт:
                print(f"      только во фронте: {только_фронт}")
            print(f"      почему: {принято.get('почему', 'причина не записана')}")
        elif только_бэк or только_фронт:
            print(f"  ✗ {сл['имя']}: РАСХОЖДЕНИЕ")
            print(f"      бэкенд: {сл['бэк_где']}")
            print(f"      фронт : {сл['фронт_где']}")
            if только_бэк:
                print(f"      только в бэкенде: {только_бэк}")
            if только_фронт:
                print(f"      только во фронте: {только_фронт}")
        elif сл["имя"] in принятые:
            print(f"  ✗ {сл['имя']}: ИСКЛЮЧЕНИЕ УСТАРЕЛО — расхождения больше нет,")
            print("      убрать запись из «принятые_расхождения» в отпечатке")
        else:
            print(f"  ✓ {сл['имя']}: сходятся")
    for сл in БЕЗ_КАНОНА:
        print(f"  ⚠ {сл['имя']}: КАНОНА В БЭКЕНДЕ НЕТ — {сл['почему']}")
        print(f"      фронт: {сл['фронт_где']}")
    print()

    print("ТРЕТЬИ СТОРОНЫ — словарь живёт не только в python и js")
    расхождения_сторон = 0
    for ст in СТОРОНЫ_SQL:
        try:
            факт = ст["сторона"]()
        except LookupError as e:
            print(f"  ✗ {ст['имя']}: {e}")
            расхождения_сторон += 1
            continue
        канон = ст["канон"]()
        нет = sorted(канон - факт)
        лишнее = sorted(факт - канон)
        if нет or лишнее:
            print(f"  ✗ {ст['имя']}: РАСХОЖДЕНИЕ")
            print(f"      канон:   {ст['канон_где']}")
            print(f"      сторона: {ст['сторона_где']}")
            if нет:
                print(f"      нет на стороне: {нет}")
            if лишнее:
                print(f"      лишнее на стороне: {лишнее}")
            расхождения_сторон += 1
        else:
            print(f"  ✓ {ст['имя']}: сходится ({len(факт)} значений)")
            print(f"      генерацией не покрыта: {ст['почему_не_генерируется']}")
    print()

    # ── полосы вывода слоя ①. Печатаем ВСЁ найденное: см. НАЙДЕНО/НАПЕЧАТАНО.
    в_словарях = set()
    for сл, *_ in вердикты:
        try:
            в_словарях |= сл["бэк"]()
        except Exception:  # noqa: BLE001 — сторона уже отмечена как ✗ выше
            pass
    полосы = [
        ("ЧАСТЬ НАЗВАННЫХ СЛОВАРЕЙ", sorted(общие & в_словарях)),
        ("ПРОЧИЕ ОБЩИЕ ЛИТЕРАЛЫ (кандидаты, шум заложен)", sorted(общие - в_словарях)),
    ]
    напечатано = 0
    for заголовок, состав in полосы:
        print(f"{заголовок}: {len(состав)}")
        for s in состав:
            напечатано += 1
            if подробно:
                print(f"    {s!r:44} py={sorted(бэк[s])[:2]} js={sorted(фронт[s])[:2]}")
        if not подробно and состав:
            print("    (состав — с --verbose)")
    print()

    # НАЙДЕНО против НАПЕЧАТАНО. Замер может найти нужное и не довести до
    # вывода — снаружи это выглядит как чистый результат.
    print(f"НАЙДЕНО {len(общие)} · НАПЕЧАТАНО {напечатано}")
    if напечатано != len(общие):
        print(
            "⛔ РАСХОЖДЕНИЕ НАЙДЕНО/НАПЕЧАТАНО: полосы вывода не покрывают найденное."
        )
        return 1

    if принять:
        # «принятые_расхождения» переносим как есть: их правит ЧЕЛОВЕК, вписывая
        # причину. Замер их не заводит сам — иначе исключение появлялось бы
        # молча, и сторож разрешал бы себе ровно то, что должен ловить.
        json.dump(
            {
                "пояснение": "Отпечаток прошлого прогона contract_dict.py (T39). "
                "Лежит в git намеренно: изменение контракта видно диффом в ревью.",
                "принятые_расхождения": принятые,
                "общие": sorted(общие),
            },
            open(ОТПЕЧАТОК, "w", encoding="utf-8"),
            ensure_ascii=False,
            indent=1,
        )
        print(
            f"ОТПЕЧАТОК ЗАПИСАН: {len(общие)} литералов → "
            f"{os.path.relpath(ОТПЕЧАТОК, КОРЕНЬ)}"
        )
        return 0

    итог = 0
    if расхождения_сторон:
        print(f"ИТОГ: расхождений на третьих сторонах — {расхождения_сторон}")
        итог = 1
    if расхождения_словарей:
        print(f"ИТОГ: расхождений в названных словарях — {расхождения_словарей}")
        итог = 1
    if устаревшие:
        print(
            f"ИТОГ: устаревших исключений — {устаревшие} (причина отпала, запись осталась)"
        )
        итог = 1
    if было is None or исчезло or появилось:
        итог = 1
    if итог == 0:
        print("ИТОГ: словари сходятся, состав совпал с отпечатком")
    return итог


if __name__ == "__main__":
    sys.exit(main())
