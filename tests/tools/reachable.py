    print(f"  НЕ ЗОВУТСЯ НИГДЕ (ноль и в app/, и в tests/): {len(мёртвые)}")
    for имя, файл in мёртвые:
        print(f"       {файл}: {имя}")
    print("═" * 66)
    print("⚠️ ЭТО КАНДИДАТЫ, А НЕ ПРИГОВОР. Не видит вызов через getattr,")
    print("   по строке из реестра, через importlib и из другого репозитория.")
    print("   Импорт СЧИТАЕТСЯ обращением: отличить «импортирован и передан»")
    print("   от «импортирован и забыт» на этом уровне нельзя, и ошибка выбрана")
    print("   в сторону молчания — ложная тревога отбрасывает сторожа целиком.")
    return 0


