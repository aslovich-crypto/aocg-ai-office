# -*- coding: utf-8 -*-
"""Публичные функции `app/`, которых никто не зовёт (T72).

ЗАЧЕМ. Поймано на `send_invite_notification` (T70): функция написана,
покрыта тестом, вызовов из `app/` — ноль. **Прогон такого не ловит и поймать
не может: тест проверяет, что функция РАБОТАЕТ, а не что она кому-то НУЖНА.**
Покрытие тоже бессильно — строки исполнены, процент высокий, дорога мертва.

САМЫЙ ЧЁТКИЙ ПРИЗНАК, РАДИ КОТОРОГО ВСЁ И ЗАТЕВАЛОСЬ: ноль вызовов в `app/`
ПРИ НАЛИЧИИ вызовов в `tests/`. Это код, который держится на собственном
тесте и больше ни на чём.

⚠️ ИСКЛЮЧЕНИЕ ДЕКОРИРОВАННОГО — УСЛОВИЕ РАБОТОСПОСОБНОСТИ, А НЕ ПОБЛАЖКА.
Обработчики FastAPI не зовёт по имени НИКТО: их подключает `@router.post`.
Написанный в лоб сторож объявил бы мёртвыми все 59 декорированных функций
проекта — все ручки до единой — и был бы отброшен в первый же запуск,
после чего негодной сочли бы идею, хотя негодной была бы реализация.
То же касается фикстур и всего, что подключается декоратором.

⚠️ ЧЕГО НЕ ВИДИТ — НАЗВАНО ДО НАПИСАНИЯ, А НЕ ВЫЯСНЕНО ЧЕРЕЗ ПОЛГОДА
(правило из T64 и T71):
  · вызов через `getattr(модуль, "имя")` и любое обращение по строке;
  · вызов из реестра или таблицы обработчиков;
  · `importlib` и прочий динамический импорт;
  · обращение из другого репозитория — фронт зовёт РУЧКУ, а не функцию;
  · импорт считается ОБРАЩЕНИЕМ: `from x import y` без единого `y()` уже
    выводит функцию из находок. Ошибка выбрана в сторону молчания намеренно —
    ложная тревога отбрасывает сторожа целиком, пропуск лишь откладывает
    находку.

САМОПРОВЕРКА НА ИЗВЕСТНОМ ОТВЕТЕ (правило T11/T30), обе половины сразу:
  · заведомо мёртвое — `send_invite_notification` ОБЯЗАН найтись;
  · заведомо живое — ни один обработчик ручки НЕ ДОЛЖЕН попасть в находки.
Без второй половины «нашёл N» неотличимо от «ловит всё подряд».

ЗАПУСК:
    ./venv/bin/python tests/tools/reachable.py --selfcheck
    ./venv/bin/python tests/tools/reachable.py
"""

import ast
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПРИЛОЖЕНИЕ = КОРЕНЬ / "app"
ТЕСТЫ = КОРЕНЬ / "tests"


def _функции(каталог):
    """Публичные функции уровня модуля без декораторов: имя → файл."""
    найдено = {}
    for файл in sorted(каталог.rglob("*.py")):
        дерево = ast.parse(файл.read_text(encoding="utf-8"))
        for узел in дерево.body:
            if not isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if узел.decorator_list or узел.name.startswith("_"):
                continue
            # ⚠️ ПУТЬ ОТНОСИТЕЛЬНО КОРНЯ — ТОЛЬКО КОГДА ФАЙЛ В КОРНЕ.
            # Самопроверка гоняет те же функции по временному каталогу
            # (см. ОБРАЗЕЦ ниже), и жёсткий `relative_to(КОРЕНЬ)` там падал.
            try:
                где = файл.relative_to(КОРЕНЬ).as_posix()
            except ValueError:
                где = файл.name
            найдено[узел.name] = где
    return найдено


def _обращения(каталог):
    """Сколько раз имя УПОМЯНУТО в коде — не только вызвано.

    ⚠️ ПЕРВАЯ РЕДАКЦИЯ СЧИТАЛА ТОЛЬКО ВЫЗОВЫ (ast.Call) И ДАЛА ТРИ ЛОЖНЫХ
    СРАБАТЫВАНИЯ ИЗ ПЯТИ НАХОДОК — в таком виде сторож приносил больше мусора,
    чем пользы:
      · send_verification_email     → background.add_task(ФУНКЦИЯ, ...)
      · unhandled_exception_handler → app.add_exception_handler(..., ФУНКЦИЯ)
      · get_current_user            → Depends(ФУНКЦИЯ)
    Во всех трёх функция ПЕРЕДАЁТСЯ ПО ССЫЛКЕ, а зовёт её framework — вызова
    по имени в коде нет и не будет. Это самый частый способ применения функции
    в проекте на FastAPI, и сторож, его не понимающий, объявляет мёртвым
    рабочий код.

    Поэтому считается любое упоминание идентификатора вне файла, где он
    определён. Импорт тоже считается обращением: отличить «импортирован
    и передан» от «импортирован и забыт» на этом уровне нельзя, а ошибаться
    безопаснее в сторону молчания — ложная тревога отбрасывает сторожа
    целиком, пропуск лишь оставляет находку на следующий раз.
    """
    счёт = {}
    for файл in sorted(каталог.rglob("*.py")):
        дерево = ast.parse(файл.read_text(encoding="utf-8"))
        for узел in ast.walk(дерево):
            имя = None
            if isinstance(узел, ast.Name):
                имя = узел.id
            elif isinstance(узел, ast.Attribute):
                имя = узел.attr
            elif isinstance(узел, ast.alias):
                # ⚠️ ПСЕВДОНИМ СЧИТАЕТСЯ ЗА ОБА ИМЕНИ, И ЭТО КУПЛЕНО ДВУМЯ
                # ЛОЖНЫМИ НАХОДКАМИ 10.09.2026. Стояло `asname or name`, то
                # есть при `from app.notifications import записать as
                # записать_событие` засчитывалось только `записать_событие`, —
                # и `записать` с `почты` попали в «не зовутся нигде», будучи
                # вызванными в трёх местах. Ложная тревога отбрасывает сторожа
                # целиком: два таких имени в отчёте, и следующий читатель
                # решит, что прибор врёт, — а он врал ровно здесь.
                имена = {узел.name.split(".")[-1]}
                if узел.asname:
                    имена.add(узел.asname)
                for и in имена:
                    счёт[и] = счёт.get(и, 0) + 1
                continue
            if имя:
                счёт[имя] = счёт.get(имя, 0) + 1
    return счёт


def _обработчики():
    """Имена функций, подключённых декоратором, — заведомо живые."""
    имена = set()
    for файл in ПРИЛОЖЕНИЕ.rglob("*.py"):
        дерево = ast.parse(файл.read_text(encoding="utf-8"))
        for узел in дерево.body:
            if (
                isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef))
                and узел.decorator_list
            ):
                имена.add(узел.name)
    return имена


def собрать():
    функции = _функции(ПРИЛОЖЕНИЕ)
    в_app = _обращения(ПРИЛОЖЕНИЕ)
    в_тестах = _обращения(ТЕСТЫ)
    держатся_на_тесте, просто_мёртвые = [], []
    for имя, файл in sorted(функции.items()):
        if в_app.get(имя, 0):
            continue
        (держатся_на_тесте if в_тестах.get(имя, 0) else просто_мёртвые).append(
            (имя, файл)
        )
    return функции, держатся_на_тесте, просто_мёртвые


# ⚠️ ОБРАЗЕЦ ДЛЯ САМОПРОВЕРКИ — СИНТЕТИЧЕСКИЙ, И ЭТО ГЛАВНАЯ ПРАВКА
# 10.09.2026. Раньше «заведомо мёртвым» считалась ЖИВАЯ функция проекта
# (`send_invite_notification`), и 10.09 она ОЖИЛА: её подключили работой
# по приглашениям, три обращения в `app/`. Самопроверка после этого честно
# сказала «сторож не работает» и вернула 2 — то есть **сторож класса
# «сделали и не подключили» лежал красным ровно тогда, когда этот класс
# всплыл четвёртый раз за неделю.**
#
# ⚠️ ЛЕЧИТСЯ НЕ СМЕНОЙ ИМЕНИ, А СМЕНОЙ ПРЕДМЕТА ПРОВЕРКИ. Новое имя ожило
# бы точно так же — любая функция проекта рано или поздно становится живой
# или исчезает. Самопроверка обязана мерить АЛГОРИТМ, а не состояние кода:
# алгоритм не меняется от того, что кто-то вызвал функцию.
#
# ⚠️ ЖИВЫЕ ПОЛОВИНЫ (②③④) ОСТАЮТСЯ НА НАСТОЯЩЕМ ДЕРЕВЕ: они утверждают
# «в находках НЕТ вот этого», и такое утверждение на синтетике ничего
# не стоит — оно про наш реальный `app/`.
ОБРАЗЕЦ = {
    "жильё.py": (
        "def мёртвая():\n    return 1\n\n"
        "def живая():\n    return 2\n\n"
        "def по_ссылке():\n    return 3\n\n"
        "def внутренняя():\n    return 4\n\n"
        "@router.get\n"
        "def местная():\n    return внутренняя()\n"
    ),
    # ⚠️ ЗОВУЩИЕ ФУНКЦИИ ДЕКОРИРОВАНЫ, И ЭТО НЕ УКРАШЕНИЕ ОБРАЗЦА.
    # Первая его редакция объявляла их обычными — и они честно попали
    # в находки как «никем не зовутся»: в синтетике их правда никто
    # не зовёт. В настоящем `app/` вход в цепочку — это ручка с
    # `@router.post`, и она исключается по декоратору. Образец обязан
    # повторять УСТРОЙСТВО проекта, иначе проверяет не тот случай.
    # Заодно так проверяется и само исключение декорированного.
    "звонок.py": (
        "from жильё import живая as переименованная\n"
        "from жильё import по_ссылке\n\n"
        "@router.post\n"
        "def дело():\n"
        "    переименованная()\n"
        "    return [по_ссылке, местная]\n"
    ),
}


def _на_образце():
    """Прогон тех же функций по заготовленному дереву. Возвращает находки."""
    import tempfile

    with tempfile.TemporaryDirectory(prefix="reachable-selfcheck-") as врем:
        корень = pathlib.Path(врем)
        for имя, текст in ОБРАЗЕЦ.items():
            (корень / имя).write_text(текст, encoding="utf-8")
        функции = _функции(корень)
        обращения = _обращения(корень)
        return {и for и in функции if not обращения.get(и, 0)}


def самопроверка():
    """Четыре известных ответа, и КАЖДЫЙ куплен ошибкой этого же сторожа.

    ⚠️ ПЕРВАЯ РЕДАКЦИЯ САМОПРОВЕРКИ ПРОВЕРЯЛА ДВА ПУНКТА И ПРОПУСТИЛА ОБЕ
    НАСТОЯЩИЕ ПОЛОМКИ. Сторож дважды выдавал заведомо ложные находки —
    17 вместо 2 и 5 вместо 2, — а самопроверка оба раза печатала «отвечает
    верно». Она смотрела только на то, что мёртвое НАХОДИТСЯ, и не смотрела,
    что живое НЕ находится. Пункты 3 и 4 добавлены ровно по этим двум случаям.
    """
    _, на_тесте, мёртвые = собрать()
    находки = {и for и, _ in на_тесте + мёртвые}
    на_обр = _на_образце()
    # На образце ждём РОВНО «мёртвая». Остальные четыре — по одной
    # причине каждая, и все четыре встречаются в настоящем коде:
    #   «живая»      — позвана ПОД ПСЕВДОНИМОМ (ловушка 10.09);
    #   «по_ссылке»  — ПЕРЕДАНА без вызова (add_task, Depends);
    #   «внутренняя» — позвана ВНУТРИ своего модуля;
    #   «дело», «местная» — ДЕКОРИРОВАНЫ, то есть ручки.
    # Лишнее в наборе значит «ловит подряд», недостача — «не видит мёртвого».
    дырявое = на_обр == {"мёртвая"}
    ручки = _обработчики() & находки
    по_ссылке = "send_verification_email" in находки
    внутри = "sha256_hex" in находки
    print("САМОПРОВЕРКА")
    print(
        f"  ① на образце найдено ровно мёртвое ({', '.join(sorted(на_обр)) or '—'}) "
        f"..... {'да' if дырявое else 'НЕТ'}"
    )
    print(
        f"  ② заведомо живое: обработчики ручек НЕ подняты ............ {'да' if not ручки else 'НЕТ'}"
    )
    print(
        f"  ③ живое ПО ССЫЛКЕ: send_verification_email НЕ поднят ...... {'да' if not по_ссылке else 'НЕТ'}"
    )
    print(
        f"  ④ живое ВНУТРИ МОДУЛЯ: sha256_hex НЕ поднят ............... {'да' if not внутри else 'НЕТ'}"
    )
    if not дырявое:
        print("  ИТОГ: ⚠️ на образце ответ неверен — алгоритм сломан.")
        print(f"        ждали {{'мёртвая'}}, вышло {на_обр or '{}'}")
        return 2
    if ручки:
        print(
            f"  ИТОГ: ⚠️ в находках ручки: {', '.join(sorted(ручки))} — ловит всё подряд."
        )
        return 2
    if по_ссылке:
        print("  ИТОГ: ⚠️ поднята функция, передаваемая ПО ССЫЛКЕ (add_task, Depends).")
        print("        Считаются только вызовы — так сторож объявляет мёртвым")
        print("        самый частый способ применения функции в FastAPI.")
        return 2
    if внутри:
        print("  ИТОГ: ⚠️ поднята функция, вызываемая ВНУТРИ своего же модуля.")
        print("        Обращения в файле определения не засчитываются.")
        return 2
    print("  ИТОГ: отвечает верно на всех четырёх известных примерах\n")
    return 0


def main():
    сам = "--selfcheck" in sys.argv
    код = самопроверка()
    if сам or код:
        return код

    функции, на_тесте, мёртвые = собрать()
    print("═" * 66)
    print(f"ПУБЛИЧНЫХ ФУНКЦИЙ БЕЗ ДЕКОРАТОРА В app/: {len(функции)}")
