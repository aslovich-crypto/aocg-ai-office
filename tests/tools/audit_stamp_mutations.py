#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""МУТАЦИИ ДЛЯ СТОРОЖА ШТАМПОВ (правило T11: непроверенный сторож — неработающий).

⚠️ СВОД ПЕЧАТАЕТ ТРИ ЧИСЛА: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО (правило T77).
Непойманный мутант ВИДЕН — он краснеет нулём. Непоставленный НЕ ВИДЕН вовсе:
в своде он неотличим от проверенного. Ненулевое третье число — красный итог.

Мутации ставятся на КОПИИ трекера во временном каталоге; исходный файл
не трогается ни при каком исходе.
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ТРЕКЕР = os.path.join(КОРЕНЬ, "docs", "TASKS.md")
СТОРОЖ = os.path.join(КОРЕНЬ, "tests", "tools", "audit_stamps.py")

# (имя, что заменить, на что, чего ждём в выводе сторожа)
МУТАНТЫ = [
    ("дата не ISO", "⟦АУДИТ · 2026-09-06", "⟦АУДИТ · вчера", "форма битая"),
    ("вердикт вне словаря", "· БЛОКОМ⟧", "· ПОСМОТРЕЛ⟧", "не из словаря"),
    (
        "штамп без скобок",
        "⟦АУДИТ · 2026-09-06",
        "АУДИТ · 2026-09-06",
        "ОТКРЫТЫХ БЕЗ ШТАМПА      : 2",
    ),
    ("заход пустой", "· 2026-09-06 · B ·", "· 2026-09-06 ·  ·", "заход пустой"),
]


def прогнать(путь):
    р = subprocess.run([sys.executable, СТОРОЖ, путь], capture_output=True, text=True)
    return р.stdout + р.stderr


def main():
    исходный = open(ТРЕКЕР, encoding="utf-8").read()
    чисто = прогнать(ТРЕКЕР)
    if "РАСХОЖДЕНИЙ" in чисто:
        print("⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: сторож красен ДО мутаций — мерить нечем")
        return 1
    print("обратный ход: на нетронутом файле расхождений нет ✓\n")

    поставлено = поймано = 0
    непоставленные = []
    with tempfile.TemporaryDirectory() as вр:
        for имя, было, стало, ждём in МУТАНТЫ:
            if исходный.count(было) == 0:
                непоставленные.append(имя)
                print(f"  ✗ НЕ ПОСТАВЛЕН  {имя}: якоря «{было}» в файле нет")
                continue
            # ⚠️ ТОЛЬКО ПЕРВОЕ вхождение: мутант должен быть точечным, иначе
            # «поймано» доказывает не проверку, а массовость поломки.
            текст = исходный.replace(было, стало, 1)
            путь = os.path.join(вр, "TASKS.md")
            open(путь, "w", encoding="utf-8").write(текст)
            поставлено += 1
            вывод = прогнать(путь)
            есть = ждём in вывод
            поймано += 1 if есть else 0
            print(f"  {'✓ поймана' if есть else '✗ ПРОПУЩЕНА'}  {имя}")

    print(
        f"\nПОСТАВЛЕНО {поставлено} · ПОЙМАНО {поймано} · НЕ ПОСТАВЛЕНО {len(непоставленные)}"
    )
    if исходный != open(ТРЕКЕР, encoding="utf-8").read():
        print("⚠️ ИСХОДНЫЙ ФАЙЛ ИЗМЕНИЛСЯ — этого быть не должно")
        return 1
    print("исходный трекер не тронут ✓")
    return 0 if (поймано == поставлено and not непоставленные) else 1


if __name__ == "__main__":
    sys.exit(main())
