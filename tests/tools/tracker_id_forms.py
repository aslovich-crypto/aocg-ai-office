#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""СЕМЬ ФОРМ ID В ТРЕКЕРЕ — КАЖДАЯ ОТДЕЛЬНЫМ ПРОГОНОМ (T188).

ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ОДНОЙ ПРОВЕРКОЙ ВНУТРИ СТОРОЖА. Регулярка ID —
то место, где слепота уже случилась дважды: `ЕСТЬ_ID` требовала окончания
цифрой и теряла 35 задач из 373, `ИСКОМЫЙ` требовала буквы перед цифрами и
уводила из-под надзора ещё 30. Оба фильтра выглядели разумно и молчали.

ЗДЕСЬ КАЖДАЯ ФОРМА ПРОВЕРЯЕТСЯ НА СВОЁМ КРОШЕЧНОМ ФАЙЛЕ: одна строка-задача,
и разбор обязан увидеть ровно одну задачу и ноль отброшенных. Один общий
прогон такого не даёт: в нём девять форм смешаны, и падение одной читается
как «что-то не так», а не «не видна форма с решёткой».

⚠️ ОБРАТНАЯ ПОЛОВИНА ОБЯЗАТЕЛЬНА. Проверяется и то, что НЕ задача —
разделитель, прочерк, пустая ячейка — принято за задачу быть не должно.
Без неё «принимаем всё» прошло бы как успех.

ЗАПУСК: ./venv/bin/python tests/tools/tracker_id_forms.py
"""

import importlib.util
import pathlib
import sys


def мод(и):
    п = pathlib.Path("tests/tools") / f"{и}.py"
    с = importlib.util.spec_from_file_location(и, п)
    м = importlib.util.module_from_spec(с)
    sys.modules[и] = м
    с.loader.exec_module(м)
    return м


tg = мод("tracker_guard")

ФОРМЫ = [
    ("буквы+цифры", "T180"),
    ("буквы-дефис-цифры", "S-71"),
    ("буквы-дефис-БУКВЫ", "REP-CRUD"),
    ("чистое число", "19"),
    ("только буквы", "INT"),
    ("цифра+буква", "1C"),
    ("цифра ВНУТРИ букв", "A11Y-FAB"),
    ("с решёткой", "#14"),
    ("кириллица после дефиса", "NDS-ЧП5"),
]
ШАПКА = "| ID | Задача | Пр. | Статус | План (класс) | Факт | Примечание |\n| :- | :- | :-: | :-: | :- | :- | :- |\n"
беды = 0
print(f"{'форма':26} {'ID':12} задач отброшено вердикт")
for имя, ид in ФОРМЫ:
    текст = ШАПКА + f"| {ид} | проба | 🟡 | ⬜ | — | — | проба формы |\n"
    задачи, отброшены, _ = tg.разобрать(текст)
    ок = len(задачи) == 1 and задачи[0][1] == ид and not отброшены
    беды += 0 if ок else 1
    print(
        f"{имя:26} {ид:12} {len(задачи):5} {len(отброшены):10} {'✓' if ок else '✗ НЕ ВИДЕН'}"
    )

# ⚠️ И ОБРАТНАЯ ПОЛОВИНА: то, что задачей НЕ является, приниматься не должно.
print()
НЕ_ЗАДАЧИ = [("разделитель ячеек", "---"), ("прочерк", "—"), ("пусто", "")]
for имя, ид in НЕ_ЗАДАЧИ:
    текст = ШАПКА + f"| {ид} | проба | 🟡 | ⬜ | — | — | проба |\n"
    задачи, отброшены, _ = tg.разобрать(текст)
    ок = len(задачи) == 0 and len(отброшены) == 1
    беды += 0 if ок else 1
    print(
        f"{имя:26} {ид or '«пусто»':12} {len(задачи):5} {len(отброшены):10} "
        f"{'✓ отброшено' if ок else '✗ ПРИНЯТО ЗА ЗАДАЧУ'}"
    )
print(f"\nформ проверено {len(ФОРМЫ)} + {len(НЕ_ЗАДАЧИ)} обратных · ошибок {беды}")
sys.exit(1 if беды else 0)
