# -*- coding: utf-8 -*-
"""Мутации сторожа трекера (`tracker_guard.py`). Постановка ПОДТВЕРЖДАЕТСЯ (T77).

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Сторож отвечает «сходится ли». Он НЕ отвечает, заметил бы
он поломку. Сторож, не проверенный мутацией, считается неработающим (T11).

⚠️ МУТАНТ СТАВИТСЯ ПО РАЗБОРУ AST, А НЕ ПО СОВПАДЕНИЮ ТЕКСТА, И ЭТО ЛЕКАРСТВО
ОТ ПРИЧИНЫ, А НЕ ОТ СЛУЧАЯ. 26.08.2026 на S-56 из девяти текстовых мутантов ДВА
не встали: якорь разъехался после `ruff format`. Непойманный мутант ВИДЕН —
он краснеет нулём упавших тестов. Непоставленный НЕ ВИДЕН: в своде он неотличим
от проверенного, то есть проверка, которой не было, засчитывается пройденной.
Узел AST от переноса строк не разъезжается, и форматтер перестаёт влиять вовсе.

СВОД ПЕЧАТАЕТ ТРИ ЧИСЛА: поставлено, поймано, НЕ ПОСТАВЛЕНО. Ненулевое третье
завершает прогон кодом 2 — «прогон не состоялся».

ЗАПУСК:
    ./venv/bin/python tests/tools/tracker_mutations.py
"""

import ast
import hashlib
import pathlib
import subprocess
import sys

СТОРОЖ = pathlib.Path(__file__).resolve().parent / "tracker_guard.py"


class Замена(ast.NodeTransformer):
    """Заменяет ОДИН узел, найденный по описанию, и считает попадания."""

    def __init__(self, что):
        self.что = что
        self.попаданий = 0

    def visit_Assign(self, узел):
        # мутация значения константы верхнего уровня
        if self.что[0] == "const":
            цели = [ц.id for ц in узел.targets if isinstance(ц, ast.Name)]
            if self.что[1] in цели:
                self.попаданий += 1
                узел.value = ast.Constant(value=self.что[2])
        return узел

    def visit_If(self, узел):
        self.generic_visit(узел)
        if self.что[0] == "if" and ast.unparse(узел.test).strip() == self.что[1]:
            self.попаданий += 1
            узел.test = ast.Constant(value=self.что[2])
        return узел


МУТАНТЫ = [
    (
        "M1 проверка формы ячеек отключена",
        ("if", "пр not in ПРИОРИТЕТЫ or ст not in СТАТУСЫ", False),
    ),
    (
        "M2 «закрыта без факта» не проверяется",
        ("if", "ст == '✅' and факт in ПУСТО and работали", False),
    ),
    (
        "M3 «сделана, но не отмечена» не проверяется",
        ("if", "ст in ('⬜', '🔵') and ид in свежие", False),
    ),
    (
        "M4 окно свежести распахнуто на всю историю",
        ("const", "ОКНО_СВЕЖЕСТИ", "2026-08-01"),
        "живой",
    ),
]


def прогон():
    эталон = СТОРОЖ.read_bytes()
    отпечаток = hashlib.sha256(эталон).hexdigest()
    поставлено = поймано = 0
    непоставленные = []

    # опорное состояние: сколько находок даёт целый сторож
    образец = СТОРОЖ.parent / "fixtures" / "tracker_broken.md"
    # ⚠️ У КАЖДОГО МУТАНТА СВОЯ ЦЕЛЬ, И ЭТО НЕ УДОБСТВО, А УСЛОВИЕ ПРОВЕРЯЕМОСТИ.
    # M1–M3 гоняются по ОБРАЗЦУ: рабочий трекер бывает чистым, и тогда «мутант
    # не пойман» означает лишь, что ломать было нечего. M4 (окно свежести)
    # на образце проверить нельзя — в нём нет истории коммитов, — поэтому он
    # гоняется по ЖИВОМУ трекеру.
    цели = {
        "образец": ["./venv/bin/python", str(СТОРОЖ), str(образец)],
        "живой": ["./venv/bin/python", str(СТОРОЖ)],
    }

    for мутант in МУТАНТЫ:
        имя, что = мутант[0], мутант[1]
        команда = цели[мутант[2] if len(мутант) > 2 else "образец"]
        базовые = subprocess.run(команда, capture_output=True, text=True).stdout
        дерево = ast.parse(эталон.decode("utf-8"))
        з = Замена(что)
        новое = ast.fix_missing_locations(з.visit(дерево))
        if з.попаданий != 1:
            непоставленные.append(
                f"{имя} — узел найден {з.попаданий} раз, нужен ровно 1"
            )
            print(f"  {имя:46} ⚠️ НЕ ПОСТАВЛЕН")
            continue
        поставлено += 1
        СТОРОЖ.write_text(ast.unparse(новое), encoding="utf-8")
        вывод = subprocess.run(команда, capture_output=True, text=True).stdout
        СТОРОЖ.write_bytes(эталон)
        изменилось = вывод.strip() != базовые.strip()
        поймано += 1 if изменилось else 0
        print(f"  {имя:46} {'ПОЙМАН' if изменилось else '⚠️ НЕ ПОЙМАН'}")

    вернулось = hashlib.sha256(СТОРОЖ.read_bytes()).hexdigest() == отпечаток
    print()
    print(f"  поставлено ..... {поставлено} из {len(МУТАНТЫ)}")
    print(f"  поймано ........ {поймано}")
    print(f"  НЕ ПОСТАВЛЕНО .. {len(непоставленные)}")
    print(f"  эталон восстановлен побайтно: {вернулось}")
    if непоставленные:
        print("\n⚠️ ПРОГОН НЕ СОСТОЯЛСЯ: мутант, который не встал, ничего не проверил,")
        print("   но в своде неотличим от проверенного.")
        for н in непоставленные:
            print("   ✗ " + н)
        return 2
    if not вернулось:
        print("⚠️ ФАЙЛ НЕ ВЕРНУЛСЯ В ИСХОДНОЕ СОСТОЯНИЕ")
        return 3
    return 0 if поймано == поставлено else 1


if __name__ == "__main__":
    sys.exit(прогон())
