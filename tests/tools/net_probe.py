#!/usr/bin/env python3
"""ЗАМЕР ДОСТУПНОСТИ ПРИЛОЖЕНИЯ С ТЕКУЩЕГО КАНАЛА (T43).

ЗАЧЕМ. С 10.08.2026 приложение не открывается с телефона без VPN. Версия —
фильтрация зарубежных хостингов на уровне оператора (ТСПУ): соединение рвётся
на TLS, сервер при этом жив. Пока это ВЕРСИЯ: замер с рабочей машины ничего
о ней не говорит, потому что идёт по ДРУГОМУ каналу. Прибор нужен, чтобы
прогнать одно и то же с РАЗНЫХ каналов и сравнить числа, а не ощущения.

ЧТО МЕРИТ — три вещи, и все три числом:
  ① СКОЛЬКО ORIGIN'ов трогает страница на старте. Не «много», а список
     с указанием, кто наш, а кто зарубежный, и сколько из них помечены
     `preconnect` (то есть браузер откроет их НЕМЕДЛЕННО, не дожидаясь
     надобности). Это прямой вход в описанный триггер «>3 параллельных
     TLS с интервалом <350–400 мс → заморозка».
  ② ДОХОДИТ ЛИ TLS до каждого origin'а и за сколько.
  ③ ПРОХОДИТ ЛИ ОБЪЁМ. Полная выкачка бандла (~1.5 МБ) — там, где по
     описанию рвётся после 13–16 КБ. Печатается, сколько байт дошло:
     «оборвалось на 16 КБ» и «не соединилось вовсе» — РАЗНЫЕ диагнозы,
     и по коду ошибки их не различить.

ОТПЕЧАТОК СОСТАВА (правило T25) — БЕЗ НЕГО СРАВНЕНИЕ ДО/ПОСЛЕ НЕДОКАЗУЕМО.
Мы собираемся сравнить два прогона: до правки шрифтов и после. Такое
сравнение молча опирается на «между прогонами ничего больше не менялось»,
чего никто не проверяет. Между ними будет ДЕПЛОЙ, то есть имена файлов
бандла и их размеры изменятся ЗАКОНОМЕРНО. Поэтому прогон печатает состав
(имена ассетов, их размеры, список origin'ов) и при расхождении с прошлым
прогоном говорит об этом ПЕРВОЙ СТРОКОЙ — не чтобы запретить сравнение,
а чтобы «стало 2 origin'а вместо 4» не прочиталось как сетевой эффект,
когда это эффект деплоя.

ГРАНИЦЫ — ЧИТАТЬ ОБЯЗАТЕЛЬНО:
  • Прибор НЕ ВОСПРОИЗВОДИТ БРАУЗЕР. Он открывает соединения последовательно
    и параллельно так, как задано ключами, а браузер делает это по своим
    правилам (приоритеты, preconnect, HTTP/2-мультиплексирование). Число
    origin'ов — из разметки; число РЕАЛЬНЫХ хендшейков браузера может
    отличаться. Точная величина берётся из DevTools телефона, не отсюда.
  • Прибор не знает, ГДЕ он находится. «Зелено» означает «с ЭТОГО канала
    прошло», и ничего больше. Канал называется в шапке отчёта со слов
    запускающего (`--канал`), потому что автоматически его не определить.
  • Успешный прогон НЕ ОПРОВЕРГАЕТ фильтрацию: она плавающая, а заморозка
    по описанию длится 120 с. Один зелёный прогон — не доказательство.
    Поэтому повторов несколько (`--повторов`), и печатается КАЖДЫЙ.
  • Прибор ничего не обходит и не маскирует: он только измеряет, доходит ли
    обычный запрос обычного клиента.

КОДЫ ВОЗВРАТА:
    0 — все origin'ы доступны, объём проходит
    1 — есть недоступные либо объём не проходит
    2 — не с чем сравнивать / страница не отдалась, ЗАМЕР НЕ СОСТОЯЛСЯ
    3 — самопроверка не пройдена

ЗАПУСК:
    ./venv/bin/python tests/tools/net_probe.py --selfcheck
    ./venv/bin/python tests/tools/net_probe.py --канал "wifi дом"
    ./venv/bin/python tests/tools/net_probe.py --канал "телефон LTE" --повторов 5
    ./venv/bin/python tests/tools/net_probe.py --канал "телефон LTE" --принять
"""

