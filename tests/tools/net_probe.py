КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ОТПЕЧАТОК = os.path.join(КОРЕНЬ, "tests", "tools", "net_probe_baseline.json")

# ⚠️ ПРИ СМЕНЕ ПЛОЩАДКИ АДРЕСА МЕНЯЮТСЯ ЗДЕСЬ (T53). До 27.08.2026 тут
