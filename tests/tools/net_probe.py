# ⚠️ АДРЕС ПЕРЕОПРЕДЕЛЯЕТСЯ ОКРУЖЕНИЕМ (T81, обзор 04.09.2026). Прибитое
# намертво значение — это не только «поменять при переезде»: прибор,
# прибитый к чужому адресу, отвечает про чужую площадку и выглядит
# работающим. Умолчание оставлено боевым, чтобы обычный запуск не требовал
# ничего знать, а стенд или следующая площадка задаются переменными.
# Хосты для «свой/чужой» ВЫВОДЯТСЯ из адресов, а не пишутся третьей копией:
# разойдись они — прибор считал бы свой хост чужим.
ФРОНТ = os.environ.get("AOCG_FRONT", "https://app.aocgai.ru").rstrip("/")
API = os.environ.get("AOCG_API", "https://api.aocgai.ru").rstrip("/")
НАШИ = {urlparse(ФРОНТ).hostname, urlparse(API).hostname} - {None}

# Контрольный пример для самопроверки: заведомо живой и заведомо несуществующий
# хост. Без второго «всё доступно» не отличить от «проверка не выполнялась».
#
# ⚠️ ЖИВОЙ КОНТРОЛЬ — СТОРОННИЙ ДОМЕН, А НЕ НАШ, И ЭТО НЕ МЕЛОЧЬ.
# Раньше здесь стоял наш собственный фронт. Тогда самопроверка падала
# ровно в тот момент, когда наш хост недоступен, — то есть прибор
# ОТКАЗЫВАЛСЯ МЕРИТЬ ИМЕННО ТОГДА, КОГДА ЕСТЬ ЧТО МЕРИТЬ, и печатал
# «самопроверка не пройдена» (код 3), что читается как «прибор сломан»,
# а не как «цель не отвечает». Два разных состояния под одним ответом.
# example.com — RFC 2606, зарезервирован и всегда жив; он отделяет
# «сети нет» от «наши хосты не доходят». Это третий замер из правила
# «перед выводом о сервере — замер КАНАЛА» (CLAUDE.md).
КОНТРОЛЬ_ЖИВОЙ = "example.com"
КОНТРОЛЬ_МЁРТВЫЙ = "заведомо-нет-такого-хоста.aocg-проверка.invalid"

ТАЙМАУТ = 20


def хендшейк(хост: str, порт: int = 443) -> tuple[bool, float, str]:
    """Довести TLS до конца. Возвращает (дошло, секунды, что случилось)."""
    ctx = ssl.create_default_context()
    начало = time.monotonic()
    try:
        with socket.create_connection((хост, порт), timeout=ТАЙМАУТ) as s:
            with ctx.wrap_socket(s, server_hostname=хост) as ts:
                версия = ts.version()
        return True, time.monotonic() - начало, версия or "?"
    except ssl.SSLError as e:
        return False, time.monotonic() - начало, f"TLS: {e.reason or e}"
    except socket.timeout:
        return False, time.monotonic() - начало, "таймаут"
    except OSError as e:
        return False, time.monotonic() - начало, f"{type(e).__name__}: {e}"


def выкачать(url: str) -> tuple[int, int, str]:
    """(код, сколько_байт_дошло, что случилось). Байты считаем ПОШТУЧНО:
    оборванная передача и отказ соединения — разные диагнозы, и по одному
    коду ошибки их не различить."""
    получено = 0
    try:
        с = urllib.request.urlopen(url, timeout=ТАЙМАУТ)
        while кусок := с.read(8192):
            получено += len(кусок)
        return с.status, получено, "ок"
    except urllib.error.HTTPError as e:
        return e.code, получено, f"HTTP {e.code}"
    except Exception as e:  # noqa: BLE001 — важен ЛЮБОЙ обрыв, с числом байт
        return 0, получено, f"{type(e).__name__}: {e}"


def разобрать_страницу(html: str) -> dict:
    """Origin'ы со страницы: внешние ссылки, preconnect и локальные ассеты."""
    внешние = sorted(set(re.findall(r"https?://([a-z0-9.-]+)", html)))
    preconnect = sorted(
        set(re.findall(r'rel="preconnect"[^>]*href="https?://([a-z0-9.-]+)"', html))
        | set(re.findall(r'href="https?://([a-z0-9.-]+)"[^>]*rel="preconnect"', html))
    )
    ассеты = sorted(set(re.findall(r'(?:src|href)="(/assets/[^"]+)"', html)))
    return {"внешние": внешние, "preconnect": preconnect, "ассеты": ассеты}


def самопроверка() -> bool:
    """Известный ответ ПЕРЕД неизвестными данными, обе половины (T30)."""
    print("САМОПРОВЕРКА на известном примере")
    дошло, сек, что = хендшейк(КОНТРОЛЬ_ЖИВОЙ)
    ок1 = дошло
    print(
        f"  {'✓' if ок1 else '✗'} заведомо ЖИВОЙ хост: "
        f"{'дошёл' if дошло else 'НЕ дошёл'} за {сек:.2f}с ({что})"
    )
    дошло2, сек2, что2 = хендшейк(КОНТРОЛЬ_МЁРТВЫЙ)
    ок2 = not дошло2
    print(
        f"  {'✓' if ок2 else '✗'} заведомо МЁРТВЫЙ хост: "
        f"{'верно не дошёл' if ок2 else 'ДОШЁЛ — прибор врёт'} ({что2})"
    )
    # Разбор страницы — на известном куске, а не на живой выдаче.
    образец = (
        '<link rel="preconnect" href="https://fonts.googleapis.com">'
        '<link href="https://fonts.googleapis.com/css2?x" rel="stylesheet">'
        '<script src="/assets/index-AAA.js"></script>'
    )
    р = разобрать_страницу(образец)
    ок3 = (
        р["внешние"] == ["fonts.googleapis.com"]
        and р["preconnect"] == ["fonts.googleapis.com"]
        and р["ассеты"] == ["/assets/index-AAA.js"]
    )
    print(f"  {'✓' if ок3 else '✗'} разбор страницы на контрольном куске: {р}")
    итог = ок1 and ок2 and ок3
    print("  ИТОГ:", "самопроверка пройдена" if итог else "САМОПРОВЕРКА НЕ ПРОЙДЕНА")
    if not ок1:
        print(
            "  (если ЖИВОЙ хост не дошёл — возможно, канал и правда режет; "
            "тогда это не поломка прибора, а результат. Смотри отчёт ниже.)"
        )
    return итог


def main() -> int:
    р = argparse.ArgumentParser(description="Замер доступности с текущего канала")
    р.add_argument(
        "--канал",
        default="не указан",
        help="как называется канал: «wifi дом», «телефон LTE»",
    )
    р.add_argument("--повторов", type=int, default=3)
    р.add_argument("--принять", action="store_true", help="записать отпечаток состава")
    р.add_argument("--selfcheck", action="store_true")
    а = р.parse_args()

    if а.selfcheck:
        return 0 if самопроверка() else 3
    прошла = самопроверка()
    print()

    # ── страница и её состав
    код, байт, что = выкачать(ФРОНТ + "/")
    if код != 200:
        print(f"⚠ ЗАМЕР НЕ СОСТОЯЛСЯ: страница не отдалась ({что}, дошло {байт} Б).")
        print(f"  Канал: {а.канал}. Это САМО ПО СЕБЕ результат — но состав")
        print("  origin'ов взять неоткуда, поэтому сравнивать нечего.")
        return 2
    html = urllib.request.urlopen(ФРОНТ + "/", timeout=ТАЙМАУТ).read().decode()
    состав = разобрать_страницу(html)
    origins = sorted(
        {ФРОНТ.split("//")[1], API.split("//")[1]} | set(состав["внешние"])
    )
    зарубежные = [o for o in origins if o not in НАШИ]

    # ── отпечаток состава (T25)
    прошлое = (
        json.load(open(ОТПЕЧАТОК, encoding="utf-8"))
        if os.path.exists(ОТПЕЧАТОК)
        else None
    )
    текущий = {
        "origins": origins,
        "preconnect": состав["preconnect"],
        "ассеты": состав["ассеты"],
    }
    if прошлое is None:
        print("⚠ ОТПЕЧАТКА СОСТАВА НЕТ — сравнивать не с чем, это первый прогон.\n")
    elif прошлое["состав"] != текущий:
        print("⛔ СОСТАВ СТРАНИЦЫ ИЗМЕНИЛСЯ С ПРОШЛОГО ПРОГОНА")
        for поле in ("origins", "preconnect", "ассеты"):
            было, стало = прошлое["состав"][поле], текущий[поле]
            if было != стало:
                print(f"   {поле}: было {len(было)} → стало {len(стало)}")
                if ушли := [x for x in было if x not in стало]:
                    print(f"      ушло:    {ушли}")
                if пришли := [x for x in стало if x not in было]:
                    print(f"      пришло:  {пришли}")
        print(
            "   Разница в доступности ниже может быть эффектом ДЕПЛОЯ, а не канала.\n"
        )

    print(
        f"КАНАЛ: {а.канал}   (называется со слов запускающего — автоматически не определить)"
    )
    print(
        f"ORIGIN'ов на старте страницы: {len(origins)}, из них ЗАРУБЕЖНЫХ: {len(зарубежные)}"
    )
    for o in origins:
        метки = []
        if o in НАШИ:
            метки.append("наш")
        else:
            метки.append("ЗАРУБЕЖНЫЙ")
        if o in состав["preconnect"]:
            метки.append("PRECONNECT — хендшейк уйдёт немедленно")
        print(f"   • {o}  [{', '.join(метки)}]")
    print(
        f"PRECONNECT-хостов: {len(состав['preconnect'])} "
        f"(каждый — принудительный TLS в первые миллисекунды)"
    )
    print()

    # ── ② хендшейк до каждого origin'а, повторами
    print(
        f"TLS-ХЕНДШЕЙКИ ({а.повторов} повтора на origin; печатается КАЖДЫЙ — "
        f"фильтрация плавающая, один зелёный прогон ничего не доказывает)"
    )
    недоступны = 0
    for o in origins:
        строки = []
        for _ in range(а.повторов):
            дошло, сек, что = хендшейк(o)
            строки.append(
                f"{'✓' if дошло else '✗'}{сек:.2f}с" + ("" if дошло else f"({что})")
            )
            if not дошло:
                недоступны += 1
        print(f"   {o:45} {'  '.join(строки)}")
    print()

    # ── ③ проходит ли объём
    print("ПРОХОДИТ ЛИ ОБЪЁМ (там, где по описанию рвётся после 13–16 КБ)")
    объём_ок = True
    for имя, url in [("страница", ФРОНТ + "/"), ("API /health", API + "/health")] + [
        (f"бандл {a}", ФРОНТ + a) for a in состав["ассеты"]
    ]:
        код, байт, что = выкачать(url)
        полностью = код == 200
        объём_ок &= полностью
        пометка = ""
        if not полностью and 8_000 < байт < 40_000:
            пометка = "  ⚠ ОБРЫВ В ПОЛОСЕ 8–40 КБ — совпадает с описанным порогом"
        print(
            f"   {'✓' if полностью else '✗'} {имя:38} дошло {байт:>9} Б  {что}{пометка}"
        )
    print()

    if а.принять:
        json.dump(
            {
                "пояснение": "Отпечаток состава страницы для сравнения ДО/ПОСЛЕ (T43).",
                "состав": текущий,
            },
            open(ОТПЕЧАТОК, "w", encoding="utf-8"),
            ensure_ascii=False,
            indent=1,
        )
        print(
            f"ОТПЕЧАТОК СОСТАВА ЗАПИСАН: {len(origins)} origin'ов, "
            f"{len(состав['preconnect'])} preconnect"
        )

    print(
        f"ИТОГ по каналу «{а.канал}»: origin'ов {len(origins)} "
        f"(зарубежных {len(зарубежные)}), preconnect {len(состав['preconnect'])}, "
        f"неудачных хендшейков {недоступны}, объём {'проходит' if объём_ок else 'НЕ проходит'}"
    )
    if not прошла:
        print("⚠ САМОПРОВЕРКА НЕ ПРОШЛА — числа выше читать с осторожностью.")
        return 3
    return 0 if (недоступны == 0 and объём_ок) else 1


if __name__ == "__main__":
    sys.exit(main())
