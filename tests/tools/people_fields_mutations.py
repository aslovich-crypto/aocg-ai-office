def прогнать() -> str:
    р = subprocess.run(
        [
            PYTEST,
            "tests/pg/test_invite_email_match.py",
            "tests/pg/test_users_payload_whitelist.py",
            "-q",
        ],
        cwd=КОРЕНЬ,
        capture_output=True,
        text=True,
        timeout=600,
    )
    return р.stdout + р.stderr


