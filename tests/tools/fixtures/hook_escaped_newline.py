"""ОПОРА ДЛЯ ЗАМЕРА hook_probe.py. НЕ ЗАПУСКАТЬ — это данные.

Случай B17, найден случайно при разборе T5 и оказался НАСТОЯЩЕЙ дырой.
В исходнике перенос строки записан как escape-последовательность, поэтому
подряд идут буква «n» и слово «DELETE»: `…public;\nDELETE FROM…`. Граница
слова между двумя буквами не срабатывает, и шаблон деструктива глагол
НЕ ВИДИТ — хотя в момент исполнения там настоящий перенос и настоящий
запрос, который удалит записи.

Лечится не шаблоном глагола, а нормализацией: перед поиском `\\n`, `\\r`
и `\\t` в тексте заменяются на пробел.
"""

import os

import asyncpg

ЗАПРОС = "SET search_path = public;\nDELETE FROM user_consents"


async def применить() -> None:
    conn = await asyncpg.connect(os.environ["DATABASE_URL"])
    await conn.execute(ЗАПРОС)
    await conn.close()
