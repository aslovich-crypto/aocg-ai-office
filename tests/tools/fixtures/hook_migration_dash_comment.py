import os

import asyncpg


async def применить() -> None:
    conn = await asyncpg.connect(os.environ["DATABASE_URL"])
    await conn.execute(
        """
        CREATE INDEX IF NOT EXISTS idx_receipts_org ON receipts(org_id);
        -- Откат: DROP INDEX IF EXISTS idx_receipts_org;
        """
    )
    await conn.close()
