def прогнать(корень: str, тест: str) -> tuple[bool, str]:
    """Прогон одного теста. Возвращает (был ли вердикт, вывод)."""
    итог = subprocess.run(
        [sys.executable, "-m", "pytest", f"{ТЕСТ}::{тест}", "-q", "--no-header"],
        cwd=корень,
        capture_output=True,
        text=True,
        timeout=300,
    )
    вывод = итог.stdout + итог.stderr
    # ⚠️ ВЕРДИКТ ОТЛИЧАЕТСЯ ОТ СБОЯ: pytest, не сумевший собраться, печатает
    # «error», а не «passed/failed». Без этой проверки «прибор не отработал»
    # засчиталось бы как «мутант не пойман».
    есть_вердикт = " passed" in вывод or " failed" in вывод
    прошёл = " failed" not in вывод and " error" not in вывод
    return есть_вердикт, ("прошёл" if прошёл else "упал"), вывод


