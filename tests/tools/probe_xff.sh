#!/bin/bash
# ПРОБА: подделывается ли клиентский адрес через X-Forwarded-For (S-35, T53).
#
# НЕ ЧАСТЬ pytest — ходит в ЖИВОЙ прод, поэтому запускается руками и только
# осознанно. Лежит рядом с замерами, чтобы повторить одной командой, а не
# собирать заново: повтор обязателен после ЛЮБОЙ смены периметра (см. ниже).
#
# ЗАЧЕМ. `aocg_security/middleware.py:103` берёт ЛЕВЫЙ элемент X-Forwarded-For
# (проверено по коду 27.08.2026). В общем случае это то, что прислал клиент,
# то есть подделываемое значение: им ключуются ограничитель частоты, авто-бан
# и адрес в журнале согласий 152-ФЗ. Журнал согласий показывают проверяющим.
#
# ═══ ИСТОРИЯ ЗАМЕРОВ ═══
#
# 07.08.2026, RAILWAY: подделка НЕ РАБОТАЕТ. Шесть входов с шестью РАЗНЫМИ
# подставными адресами дали 401×5 и 429 на шестом — ровно как без заголовка.
# Railway перезаписывал входящий XFF, приложение видело настоящий адрес.
#
# 27.08.2026, TIMEWEB: подделка НЕ РАБОТАЕТ — так же, как на Railway.
# Эталон без заголовка и опыт с шестью РАЗНЫМИ подставными адресами дали
# одинаковую картину: 401×5 и 429 на шестом. Площадка перезаписывает
# входящий X-Forwarded-For, приложение видит настоящий адрес.
#
# ⚠️ ПОЧЕМУ ЭТОТ ЗАМЕР ЖДАЛ ДЕВЯТЬ ДНЕЙ. Переезд был 18.08.2026 (S-06) —
# первый пункт списка «повторить обязательно» ниже. Всё это время скрипт
# опрашивал мёртвый адрес Railway и вернул бы зелёный отчёт про чужую
# площадку: прибор был сломан ровно тем событием, ради которого нужен.
#
# ⚠️ И ПЕРВЫЙ ПРОГОН 27.08 ОТВЕТА НЕ ДАЛ, ХОТЯ ВЫГЛЯДЕЛ ЗАКОНЧЕННЫМ:
# шесть 401 подряд в ОБЕИХ фазах. Вердикт «замер не состоялся» оказался
# верным — в панели площадки стояло SECURITY_AUTH_RATE_LIMIT=50 при
# умолчании кода 5, и шесть входов не могли упереться в предел.
# Отсюда правило ниже: порог НЕ зашивать в скрипт, а находить замером.
#
# ПОВТОРИТЬ ОБЯЗАТЕЛЬНО, если меняется что-либо из списка — каждое включает
# дыру в тот же день и молча:
#   • смена площадки (было: Railway → Timeweb, 18.08.2026);
#   • CDN перед приложением (Cloudflare и любой другой);
#   • собственный обратный прокси (nginx/Traefik) перед бэкендом;
#   • смена тарифа/региона площадки, если меняется входной прокси;
#   • появление второго домена или балансировщика.
#
# ═══ ЧТО ОТПРАВЛЯЕТСЯ И ЧЕМ ЭТО БЕЗОПАСНО ═══
#
# До 2×CAP запросов входа (по умолчанию CAP=15, с остановкой на первом 429)
# плюс служебные проверки. Логин НЕСУЩЕСТВУЮЩИЙ
# (`probe-not-a-user@example.invalid`), поэтому ничьи счётчики неудачных
# попыток и блокировки не растут — ни один живой пользователь не задет.
#
# ⚠️ ПОРОГ НЕ ЗАШИТ. Обе фазы шлют запросы ДО ПЕРВОГО 429 и сравнивают
# ПОЗИЦИИ срабатывания между собой. Зашитое ожидание «429 на шестом»
# сломалось бы от любой правки предела в панели, и выглядело бы это
# как находка, а не как поломка прибора.
#
# ⚠️ НЕ ЗАПУСКАТЬ ЧАЩЕ ЧЕТЫРЁХ РАЗ ПОДРЯД. Каждый прогон даёт до ДВУХ
# превышений лимита, а `_violations` в middleware НЕ УБЫВАЕТ со временем —
# обнуляется только по истечении бана. На десятом превышении адрес получает
# бан на 5 минут (BAN_SECONDS=300), и следующий прогон измерит бан, а не XFF.
#
# ═══ ЗАПУСК ═══
#
#   bash tests/tools/probe_xff.sh
#
# Идёт ~2.5 минуты (пауза 70 с, чтобы окно лимита в 60 с истекло).
# Другая цель:  AOCG_API=https://... bash tests/tools/probe_xff.sh
# Другой потолок: AOCG_CAP=25 bash tests/tools/probe_xff.sh — поднимать,
# если предел в панели выше 14, иначе фаза упрётся в потолок раньше предела.
#
# Имена переменных латиницей — правило CLAUDE.md, «Конвенции кода».

set -u

BASE="${AOCG_API:-https://api.aocgai.ru}"
BODY='{"phone_or_email":"probe-not-a-user@example.invalid","password":"neverusedpassword"}'
DEAD="https://203.0.113.1/"   # RFC 5737, зарезервирован для документации
CAP="${AOCG_CAP:-15}"         # потолок запросов в фазе: ищем предел, но не бьём вслепую

echo "═══ ① МЕТКА ПРОГОНА ═══"
echo "   МСК: $(TZ=Europe/Moscow date '+%d.%m.%Y %H:%M:%S')"
echo "   цель: $BASE"
echo "   ⚠️ Нет свежей метки в выводе — значит вывод СТАРЫЙ, а не «прежний результат»."

echo
echo "═══ ② КОНТРОЛЬ КАНАЛА — без него весь прогон недействителен ═══"

IFACE=$(route get 8.8.8.8 2>/dev/null | awk '/interface:/{print $2}')
echo "   трафик уходит через: ${IFACE:-не определён}"
case "$IFACE" in
  utun*|ppp*|ipsec*)
    echo "   ✗ ЭТО VPN. Дальше мерить бессмысленно — выключить и повторить."
    echo "     (куплено 27.08.2026: VPN дал картину «инфраструктура лежит»)"
    exit 1;;
esac

# Заведомо МЁРТВАЯ цель обязана НЕ соединиться. Если соединилась — локальный
# слой принимает каждое соединение сам, и любые «дошло/не дошло» ниже — мусор.
if curl -s -o /dev/null --max-time 6 "$DEAD" 2>/dev/null; then
  echo "   ✗ ЗАВЕДОМО МЁРТВЫЙ АДРЕС 203.0.113.1 ОТВЕТИЛ. Прибор сломан:"
  echo "     соединения перехватывает что-то локальное. Прогон остановлен."
  exit 1
fi
echo "   ✓ заведомо мёртвый 203.0.113.1 не соединился — как и должен"

HEALTH=$(curl -s -o /dev/null -w "%{http_code}" --max-time 15 "$BASE/health")
if [ "$HEALTH" != "200" ]; then
  echo "   ✗ $BASE/health вернул $HEALTH вместо 200 — цель не отвечает,"
  echo "     замер про XFF не начинаем."
  exit 1
fi
echo "   ✓ $BASE/health → 200"
echo "   ⚠️ /health в middleware исключён из ВСЕХ ограничений (LIVENESS_EXEMPT),"
echo "      поэтому он доказывает достижимость и НИЧЕГО не говорит о лимите."

echo
echo "═══ ③ ЭТАЛОН: входы БЕЗ заголовка, до первого 429 ═══"
echo "   ⚠️ Порог НЕ зашит в скрипт — он находится замером. Иначе правка"
echo "      предела в панели ломала бы прибор, а выглядело бы как находка."
REF=""
POS_REF=0
for I in $(seq 1 "$CAP"); do
  if [ "$I" = "1" ]; then
    # ПЕРВЫЙ ответ печатается ЦЕЛИКОМ — контроль жанра отказа.
    # 422 значит «тело не прошло разбор, проверяемая логика НЕ РАБОТАЛА»,
    # и считать такие отказы нельзя. Куплено дважды на поле phone_or_email.
    OUT=$(curl -s -w "\n%{http_code}" --max-time 15 -X POST "$BASE/api/auth/login" \
      -H "Content-Type: application/json" -d "$BODY")
    CODE=$(echo "$OUT" | tail -1)
    echo "  #1 -> $CODE   тело: $(echo "$OUT" | sed '$d' | head -c 200)"
  else
    CODE=$(curl -s -o /dev/null -w "%{http_code}" --max-time 15 -X POST "$BASE/api/auth/login" \
      -H "Content-Type: application/json" -d "$BODY")
    echo "  #$I -> $CODE"
  fi
  REF="$REF$CODE "
  if [ "$CODE" = "429" ]; then POS_REF=$I; break; fi
done

echo
echo "═══ ④ пауза 70 с, чтобы окно лимита (60 с) истекло ═══"
sleep 70

echo
echo "═══ ⑤ ОПЫТ: входы, у каждого СВОЙ подставной X-Forwarded-For ═══"
TEST=""
POS_TEST=0
for I in $(seq 1 "$CAP"); do
  CODE=$(curl -s -o /dev/null -w "%{http_code}" --max-time 15 -X POST "$BASE/api/auth/login" \
    -H "Content-Type: application/json" \
    -H "X-Forwarded-For: 203.0.113.$I" -d "$BODY")
  echo "  #$I (XFF 203.0.113.$I) -> $CODE"
  TEST="$TEST$CODE "
  if [ "$CODE" = "429" ]; then POS_TEST=$I; break; fi
done

echo
echo "═══ ⑥ ВЕРДИКТ ═══"
echo "   эталон: $REF"
echo "   опыт:   $TEST"
echo

echo "   429 в эталоне на позиции: ${POS_REF} (0 = не было)"
echo "   429 в опыте   на позиции: ${POS_TEST} (0 = не было)"
echo

if [ "$POS_REF" -eq 0 ]; then
  echo "   ⚠️ ЗАМЕР НЕ СОСТОЯЛСЯ, И ЭТО НЕ ОТВЕТ ПРО XFF."
  echo "   За ${CAP} входов подряд ограничитель не сработал ни разу."
  echo "   Значит мерили не его:"
  echo "     • сплошь 422 — тело не прошло разбор, логика не работала;"
  echo "     • сплошь 401 — предел выше ${CAP}. Посмотреть"
  echo "       SECURITY_AUTH_RATE_LIMIT в панели: 27.08.2026 там стояло 50"
  echo "       при умолчании кода 5, и шесть входов ничего не показывали;"
  echo "     • 403 — принуждение HTTPS или запрет по CORS."
  echo "   Про подделку XFF по этому прогону сказать НЕЛЬЗЯ ничего."
  exit 2
fi

echo "   → действующий предел по замеру: $((POS_REF - 1)) входов в минуту"
echo

if [ "$POS_TEST" -eq "$POS_REF" ]; then
  echo "   ✓ ПОДДЕЛКА НЕ РАБОТАЕТ. Опыт сработал на той же позиции, что эталон:"
  echo "     подставной адрес в ключ ограничителя НЕ попадает — площадка"
  echo "     перезаписывает X-Forwarded-For. Дыры нет, чинить нечего."
  exit 0
fi

if [ "$POS_TEST" -eq 0 ]; then
  echo "   ✗ ПОДДЕЛКА РАБОТАЕТ — ДЫРА ОТКРЫТА."
  echo "     Эталон упёрся в предел на #${POS_REF}, а с РАЗНЫМИ подставными"
  echo "     адресами предела нет вовсе: каждый запрос учтён как новый клиент."
  echo "     Следствия сразу три:"
  echo "       ① ограничитель частоты обходится — перебор пароля свободен;"
  echo "       ② авто-бан обходится тем же приёмом;"
  echo "       ③ в журнал согласий 152-ФЗ пишется ЛОЖНЫЙ адрес субъекта,"
  echo "          а этот журнал показывают проверяющим."
  echo "     Чинить _client_ip (aocg_security/middleware.py:103): доверять"
  echo "     заголовку только от известного прокси площадки, иначе брать"
  echo "     request.client.host."
  exit 1
fi

echo "   ⚠️ ТРЕТИЙ ИСХОД, НЕ ОПИСАННЫЙ ЗАРАНЕЕ: предел сработал в обеих фазах,"
echo "     но на РАЗНЫХ позициях (${POS_REF} против ${POS_TEST}). Возможен"
echo "     недоистёкший счётчик от прошлой фазы. Разбирать вручную, вывод выше —"
echo "     не выносить вердикт по половине картины."
exit 3
