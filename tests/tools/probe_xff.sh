#!/bin/bash
# ПРОБА: подделывается ли клиентский адрес через X-Forwarded-For (S-35).
#
# НЕ ЧАСТЬ pytest — ходит в ЖИВОЙ прод, поэтому запускается руками и только
# осознанно. Лежит рядом с замерами, чтобы повторить одной командой, а не
# собирать заново: повтор обязателен после ЛЮБОЙ смены периметра (см. ниже).
#
# ЗАЧЕМ. `aocg_security/middleware.py` берёт ЛЕВЫЙ элемент X-Forwarded-For.
# В общем случае это то, что прислал клиент, то есть подделываемое значение:
# им ключуются ограничитель частоты, авто-бан и (после строки 9) адрес
# в журнале согласий 152-ФЗ.
#
# РЕЗУЛЬТАТ 07.08.2026 (Railway): подделка НЕ РАБОТАЕТ. Шесть входов
# с шестью РАЗНЫМИ подставными адресами дали 401×5 и 429 на шестом — ровно
# как без заголовка. Railway перезаписывает входящий XFF, приложение видит
# настоящий адрес.
#
# ПОВТОРИТЬ ОБЯЗАТЕЛЬНО, если меняется что-либо из списка — каждое включает
# дыру в тот же день и молча:
#   • переезд на Yandex Cloud (S-06);
#   • CDN перед приложением (Cloudflare и любой другой);
#   • собственный обратный прокси (nginx/Traefik) перед бэкендом;
#   • смена плана/региона Railway, если меняется входной прокси;
#   • появление второго домена или балансировщика.
#
# ЧТО ОТПРАВЛЯЕТСЯ. 8 запросов + 6 после паузы. Логин НЕСУЩЕСТВУЮЩИЙ, поэтому
# ничьи счётчики неудачных попыток и блокировки не растут. Одно-два превышения
# лимита; авто-бан наступает после десяти.
#
# ЧТЕНИЕ РЕЗУЛЬТАТА:
#   шаг 3 «401×5 + 429» → подставной адрес в ключ НЕ попадает, платформа
#                          перезаписывает XFF: сегодня безопасно;
#   шаг 3 «401×6»       → ключ берётся из заголовка: ПОДДЕЛКА РАБОТАЕТ,
#                          ограничитель обходится, адрес в журнале ложный.
#
# ЗАПУСК:  bash tests/tools/probe_xff.sh
set -u
BASE="${AOCG_API:-https://aocg-ai-office-production.up.railway.app}"
BODY='{"phone_or_email":"probe-not-a-user@example.invalid","password":"neverusedpassword"}'

echo "== цель: $BASE"

echo "== шаг 1: шесть входов БЕЗ заголовка (эталон: лимит 5/мин на IP)"
for i in $(seq 1 6); do
  code=$(curl -s -o /dev/null -w "%{http_code}" -X POST "$BASE/api/auth/login" \
    -H "Content-Type: application/json" -d "$BODY")
  echo "  #$i -> $code"
done

echo "== шаг 2: пауза 70 с, чтобы окно лимита истекло"
sleep 70

echo "== шаг 3: шесть входов, у каждого СВОЙ подставной X-Forwarded-For"
for i in $(seq 1 6); do
  code=$(curl -s -o /dev/null -w "%{http_code}" -X POST "$BASE/api/auth/login" \
    -H "Content-Type: application/json" \
    -H "X-Forwarded-For: 203.0.113.$i" -d "$BODY")
  echo "  #$i (XFF 203.0.113.$i) -> $code"
done

echo
echo "429 на шестом = подделка НЕ работает (как 07.08.2026)."
echo "401 на всех шести = ПОДДЕЛКА РАБОТАЕТ, чинить _client_ip немедленно."
