"""Очистка тестовых записей журнала согласий (строка 9, решение владельца).

ЕДИНСТВЕННЫЙ СКРИПТ РЕПОЗИТОРИЯ, КОТОРЫЙ ПИШЕТ В ПРОД. Основание: 07.08.2026
приложение не запущено, клиентов нет, шестеро пользователей — свои, а 19 строк
журнала это следы периода разработки: `user_id='local_user'`, адрес пуст,
текст-черновик. Юридическими документами они не являются, поэтому чистая
таблица лучше помеченной маркерами.

ЧТО УДАЛЯЕТ: строки `user_consents` с `user_id = 'local_user'` — ровно тот
набор, который печатает показ перед удалением. Ничего больше.

ТРИ ПРЕДОХРАНИТЕЛЯ, и все три обязательны:
  • печатает состояние ДО (сколько всего, сколько под условием, сколько чужих);
  • ОТКАЗЫВАЕТСЯ работать, если в таблице есть запись с другим субъектом —
    значит набор изменился с момента показа;
  • ОТКАЗЫВАЕТСЯ работать, если под условием не ровно 19 строк.
Отказ — это `SystemExit` до удаления, а не «пропустим и продолжим».

ПОВТОРНЫЙ ЗАПУСК безопасен ровно один раз: после успешной чистки строк
не останется, и второй прогон упадёт на проверке «не 19», ничего не тронув.

ЗАПУСК: DATABASE_URL=<внешняя строка подключения из панели Timeweb> \
            ./venv/bin/python tests/tools/purge_consents.py
"""

import asyncio
import os

import asyncpg

МАРКЕР = "local_user"
ОЖИДАЕМО = 19


async def main():
    url = os.environ.get("DATABASE_PUBLIC_URL") or os.environ.get("DATABASE_URL")
    if not url:
        raise SystemExit("нет DATABASE_PUBLIC_URL / DATABASE_URL в окружении")
    conn = await asyncpg.connect(url)
    try:
        всего = await conn.fetchval("SELECT COUNT(*) FROM user_consents")
        свои = await conn.fetchval(
            "SELECT COUNT(*) FROM user_consents WHERE user_id = $1", МАРКЕР
        )
        чужие = всего - свои
        print(f"до: всего {всего}, под условием {свои}, с другим субъектом {чужие}")

        if чужие:
            raise SystemExit(
                f"ОТКАЗ: в таблице {чужие} записей с другим субъектом. Набор изменился "
                "с момента показа — удаление не выполняется."
            )
        if свои != ОЖИДАЕМО:
            raise SystemExit(
                f"ОТКАЗ: под условием {свои} записей, а ожидалось {ОЖИДАЕМО}. "
                "Набор изменился — удаление не выполняется."
            )

        итог = await conn.execute(
            "DELETE FROM user_consents WHERE user_id = $1", МАРКЕР
        )
        осталось = await conn.fetchval("SELECT COUNT(*) FROM user_consents")
        print(f"результат: {итог}; осталось записей: {осталось}")
        if осталось:
            print("ВНИМАНИЕ: таблица не пуста — проверьте, что это ожидалось")
    finally:
        await conn.close()


asyncio.run(main())
