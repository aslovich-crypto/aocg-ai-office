#!/bin/bash
# ПРОБА: доезжает ли схема соединения до приложения за прокси (S-67),
#        и ушла ли с прода временная ручка-зеркало замера S-35.
#
# НЕ ЧАСТЬ pytest — ходит в ЖИВОЙ прод, поэтому запускается руками. Лежит
# рядом с probe_xff.sh и probe_ratelimit.sh по той же причине: повтор нужен
# после ЛЮБОЙ смены периметра, и собирать замер заново каждый раз — способ
# его не делать.
#
# ═══ ПОЧЕМУ ПО ПРОДУ, А НЕ ПО ДВОЙНИКУ — ТРЕБОВАНИЕ ВЛАДЕЛЬЦА 21.09.2026 ═══
#
# Двойник схему прокси НЕ ВОСПРОИЗВОДИТ: в тестах нет ни Caddy, ни заголовка
# `X-Forwarded-Proto`, ни uvicorn с его `forwarded_allow_ips`. Сторож на
# двойнике был бы зелёным при полностью сломанном проде — то есть учил бы
# на себя не смотреть. Единственное место, где этот дефект вообще существует,
# — живой контур.
#
# ═══ ЧТО ЛОВИТ ПРОВЕРКА ① ═══
#
# Без `FORWARDED_ALLOW_IPS` uvicorn не верит заголовку прокси (умолчание —
# `127.0.0.1`, а Caddy приходит из сети контейнеров). Тогда Starlette строит
# редирект по слэшу из `scope["scheme"]`, куда схема не попала, и отдаёт
# `location: http://…`. Браузер такой редирект с https-страницы БЛОКИРУЕТ:
# «Mixed Content». Приложение при этом отвечает, тесты зелены, в логах тихо —
# дефект провисел месяц, до 21.09.2026, когда владелец упёрся в него руками.
#
# ═══ ЧТО ЛОВИТ ПРОВЕРКА ② ═══
#
# Ручка-зеркало `/api/diag/echo-ip` заводилась НА ОДИН ЗАМЕР (S-35, 2c57ca3)
# и снята тем же заходом (739a50b). Удаление из репозитория НЕ ДОКАЗЫВАЕТ,
# что она ушла с прода: между коммитом и контейнером стоит деплой, и он
# может не доехать. Диагностическая ручка, пережившая свой замер, — это
# открытая наружу справка о внутреннем устройстве.
#
# ⚠️ КОНТРОЛЬ ОБЯЗАТЕЛЕН, И ВОТ ПОЧЕМУ. Ответ 404 сам по себе не значит
# «ручки нет»: 404 даёт и лежащий сервис, и чужой домен, и прокси, который
# глотает всё подряд. Поэтому рядом опрашивается ЗАВЕДОМО ЖИВАЯ ручка под
# авторизацией — она обязана дать 401. Пара «404 на зеркале + 401 на живой»
# различает «ручка снята» и «сервер не отвечает»; одиночное 404 — не различает.
#
# ═══ ИСТОРИЯ ЗАМЕРОВ ═══
#
# 21.09.2026, до лечения (владелец, руками): `curl -I https://api.aocgai.ru/
# api/reports` → `HTTP/2 307`, `location: http://api.aocgai.ru/api/reports/`.
# Тот же отказ в браузере на проде — Mixed Content с app.aocgai.ru.
#
# 21.09.2026, после лечения (этот скрипт, первый прогон): `location:
# https://api.aocgai.ru/api/reports/`. Зеркало — 404 при 401 на живой ручке.
# Лечение в панели: `FORWARDED_ALLOW_IPS=172.18.0.0/16` — ПОДСЕТЬ, не адрес:
# при пересоздании контейнера адрес Caddy сменится внутри неё (c723766).
#
# ═══ ПОВТОРЯТЬ ОБЯЗАТЕЛЬНО ═══
#
#   • после любого переезда площадки и смены входного прокси;
#   • после пересоздания стека контейнеров — префикс сети может смениться,
#     и тогда вернётся `location: http`. Это отказ в безопасную сторону:
#     он ловится ровно здесь, но САМ О СЕБЕ не сообщает;
#   • после появления второго домена или балансировщика;
#   • после любого захода, который заводил временную диагностическую ручку.
#
# ═══ ЧТО ОТПРАВЛЯЕТСЯ И ЧЕМ ЭТО БЕЗОПАСНО ═══
#
# Три запроса GET без тела и без токена. Ничьи счётчики не растут, ничего
# не создаётся и не меняется: две ручки отвечают отказом, третья — редиректом.
#
# ═══ ЗАПУСК ═══
#
#   bash tests/tools/probe_proxy_scheme.sh
#
# Идёт несколько секунд. Другая цель: AOCG_API=https://... bash ...
#
# Имена переменных латиницей — правило CLAUDE.md, «Конвенции кода».

set -u

BASE="${AOCG_API:-https://api.aocgai.ru}"
REDIRECT_PATH="/api/reports"        # без слэша — тот самый случай редиректа
MIRROR_PATH="/api/diag/echo-ip"     # снятая ручка-зеркало замера S-35
ALIVE_PATH="/api/reports/"          # заведомо живая, под авторизацией → 401
TIMEOUT=12

# Разбор ОДНИМ местом: и самопроверка, и живой прогон зовут эту функцию.
# Разведи их — и самопроверка начнёт подтверждать не тот разборщик.
# ⚠️ БЕЗ ВЛОЖЕННЫХ ТЕРНАРНЫХ ВЫРАЖЕНИЙ: awk на macOS (BSD) их в `print` не
# принимает и падает синтаксической ошибкой. Поймала это самопроверка ③
# на первом же прогоне 21.09.2026 — до того, как прибор отчитался о проде.
scheme_from_headers() {
  awk 'tolower($1) == "location:" {
         found = 1
         v = tolower($2)
         if (v ~ /^https:\/\//)     { print "https" }
         else if (v ~ /^http:\/\//) { print "http" }
         else                       { print "inoe" }
       }
       END { if (!found) print "net" }'
}

echo "═══ ① МЕТКА ПРОГОНА ═══"
echo "   МСК: $(TZ=Europe/Moscow date '+%d.%m.%Y %H:%M:%S')"
echo "   цель: $BASE"
echo "   ⚠️ Нет свежей метки в выводе — значит вывод СТАРЫЙ, а не «прежний результат»."
echo

echo "═══ ② КОНТРОЛЬ КАНАЛА — без него весь прогон недействителен ═══"
IFACE=$(route get 8.8.8.8 2>/dev/null | awk '/interface:/{print $2}')
echo "   трафик уходит через: ${IFACE:-не определён}"
case "$IFACE" in
  utun*|ppp*|ipsec*)
    echo "   ✗ ЭТО ТУННЕЛЬ. Российские хосты он рвёт, и отказ будет похож"
    echo "     на поломку прода. Выключить VPN либо запускать так:"
    echo "     AOCG_CURL_IFACE=en0 bash tests/tools/probe_proxy_scheme.sh"
    ;;
  *)
    echo "   ✓ не туннель"
    ;;
esac
CURL_IFACE="${AOCG_CURL_IFACE:-}"
CURL_BIND=()
if [ -n "$CURL_IFACE" ]; then
  CURL_BIND=(--interface "$CURL_IFACE")
  echo "   привязка curl к интерфейсу: $CURL_IFACE"
fi
echo

echo "═══ ③ САМОПРОВЕРКА РАЗБОРЩИКА — до всякого обращения к проду ═══"
echo "   ⚠️ Без неё «схема https ✓» неотличимо от «прибор ничего не разбирал»."
echo "   ⚠️ И это ЗАМЕНА живой мутации, а не она сама: снять переменную"
echo "      в панели может только владелец. Здесь разборщику подаётся ровно"
echo "      тот ответ, который прод отдавал БЕЗ лечения 21.09.2026."
SELF_FAIL=0

GOT=$(printf 'HTTP/2 307\nlocation: https://api.aocgai.ru/api/reports/\n' | scheme_from_headers)
if [ "$GOT" = "https" ]; then
  echo "   ✓ вылеченный ответ разобран как https"
else
  echo "   ✗ вылеченный ответ разобран как «$GOT» — разборщик сломан"
  SELF_FAIL=1
fi

GOT=$(printf 'HTTP/2 307\nlocation: http://api.aocgai.ru/api/reports/\n' | scheme_from_headers)
if [ "$GOT" = "http" ]; then
  echo "   ✓ больной ответ (мутация «нет FORWARDED_ALLOW_IPS») разобран как http"
else
  echo "   ✗ больной ответ разобран как «$GOT» — прибор НЕ ПОКРАСНЕЕТ на дефекте"
  SELF_FAIL=1
fi

GOT=$(printf 'HTTP/2 200\ncontent-length: 0\n' | scheme_from_headers)
if [ "$GOT" = "net" ]; then
  echo "   ✓ ответ без location назван отсутствием, а не схемой"
else
  echo "   ✗ ответ без location разобран как «$GOT» — молчание сойдёт за успех"
  SELF_FAIL=1
fi

if [ "$SELF_FAIL" -ne 0 ]; then
  echo
  echo "   ✗ САМОПРОВЕРКА НЕ ПРОШЛА. Прогон остановлен: чинить прибор,"
  echo "     а не читать его вывод про прод."
  exit 4
fi
echo

echo "═══ ④ СХЕМА В РЕДИРЕКТЕ (S-67) ═══"
HEADERS=$(curl -sSI "${CURL_BIND[@]+"${CURL_BIND[@]}"}" --max-time "$TIMEOUT" "$BASE$REDIRECT_PATH" 2>&1)
CURL_RC=$?
if [ "$CURL_RC" -ne 0 ]; then
  echo "   ✗ ЗАПРОС НЕ СОСТОЯЛСЯ (curl $CURL_RC). Про схему сказать нельзя ничего."
  echo "$HEADERS" | sed 's/^/     /'
  exit 2
fi
CODE=$(echo "$HEADERS" | awk 'toupper($1) ~ /^HTTP/ {print $2}' | tail -1)
SCHEME=$(echo "$HEADERS" | scheme_from_headers)
LOCATION=$(echo "$HEADERS" | awk 'tolower($1) == "location:" {print $2}')
echo "   $REDIRECT_PATH → код $CODE"
echo "   location: ${LOCATION:-«нет»}"

case "$SCHEME" in
  https)
    echo "   ✓ СХЕМА ДОЕХАЛА. uvicorn верит X-Forwarded-Proto от Caddy,"
    echo "     редирект остаётся на https — браузер его не заблокирует."
    SCHEME_OK=1
    ;;
  http)
    echo "   ✗ ДЕФЕКТ S-67 ЖИВ. Редирект уходит на http, и браузер"
    echo "     заблокирует его как Mixed Content со страницы https."
    echo "     Чинить переменной площадки: FORWARDED_ALLOW_IPS=172.18.0.0/16"
    echo "     (подсеть, не адрес — при пересоздании контейнера адрес сменится)."
    SCHEME_OK=0
    ;;
  net)
    echo "   ⚠️ ИСХОД, НЕ ОПИСАННЫЙ ЗАРАНЕЕ: ответ без location вовсе."
    echo "     Возможно, поведение редиректа по слэшу изменилось — разбирать"
    echo "     руками, вердикт по этой проверке НЕ выносить."
    SCHEME_OK=2
    ;;
  *)
    echo "   ⚠️ location с неизвестной схемой — разбирать руками."
    SCHEME_OK=2
    ;;
esac
echo

echo "═══ ⑤ УШЛА ЛИ ВРЕМЕННАЯ РУЧКА-ЗЕРКАЛО (S-35) ═══"
MIRROR_CODE=$(curl -sS -o /dev/null -w '%{http_code}' \
  "${CURL_BIND[@]+"${CURL_BIND[@]}"}" --max-time "$TIMEOUT" "$BASE$MIRROR_PATH" 2>/dev/null)
ALIVE_CODE=$(curl -sS -o /dev/null -w '%{http_code}' \
  "${CURL_BIND[@]+"${CURL_BIND[@]}"}" --max-time "$TIMEOUT" "$BASE$ALIVE_PATH" 2>/dev/null)
echo "   $MIRROR_PATH → $MIRROR_CODE   (ожидается 404 — ручки нет)"
echo "   $ALIVE_PATH → $ALIVE_CODE   (контроль: ожидается 401 — сервер жив)"

if [ "$ALIVE_CODE" != "401" ]; then
  echo "   ⚠️ КОНТРОЛЬ НЕ СОШЁЛСЯ. Живая ручка ответила не 401, значит про"
  echo "     404 на зеркале сказать нельзя ничего: сервер может быть просто"
  echo "     недоступен. Разбирать руками."
  MIRROR_OK=2
elif [ "$MIRROR_CODE" = "404" ]; then
  echo "   ✓ РУЧКИ НА ПРОДЕ НЕТ. Удаление доехало до контейнера, а не только"
  echo "     до репозитория — это разные вещи, и здесь проверена вторая."
  MIRROR_OK=1
elif [ "$MIRROR_CODE" = "401" ] || [ "$MIRROR_CODE" = "403" ]; then
  echo "   ✗ РУЧКА ЖИВА НА ПРОДЕ. Отказ по авторизации означает, что маршрут"
  echo "     СУЩЕСТВУЕТ: удаление в репозитории есть, деплой не доехал."
  MIRROR_OK=0
else
  echo "   ⚠️ Неожиданный код $MIRROR_CODE — разбирать руками."
  MIRROR_OK=2
fi
echo

echo "═══ ⑥ ИТОГ ═══"
if [ "$SCHEME_OK" = "1" ] && [ "$MIRROR_OK" = "1" ]; then
  echo "   ✓ ОБЕ ПРОВЕРКИ ЗЕЛЁНЫЕ: схема доезжает, временной диагностики"
  echo "     на проде не осталось."
  exit 0
fi
if [ "$SCHEME_OK" = "0" ] || [ "$MIRROR_OK" = "0" ]; then
  echo "   ✗ ЕСТЬ КРАСНОЕ — смотреть разделы ④ и ⑤ выше."
  exit 1
fi
echo "   ⚠️ ВЕРДИКТ НЕ ВЫНЕСЕН: хотя бы одна проверка дала исход, не описанный"
echo "     заранее. Это не «почти зелёный» — это «прибор не ответил»."
exit 3
