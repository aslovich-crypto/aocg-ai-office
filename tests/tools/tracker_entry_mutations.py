def вставить_после(якорь_строки, новая):
    """Мутация «вставить строку после строки, начинающейся с якоря»."""

    def м(текст):
        строки = текст.split("\n")
        н = [i for i, с in enumerate(строки) if с.startswith(якорь_строки)]
        if len(н) != 1:
            return None
        строки.insert(н[0] + 1, новая)
        return "\n".join(строки)

    return м


def заменить(было, стало):
    def м(текст):
        if текст.count(было) != 1:
            return None
        return текст.replace(было, стало)

    return м


def удалить_строку(якорь_строки):
    def м(текст):
        строки = текст.split("\n")
        н = [i for i, с in enumerate(строки) if с.startswith(якорь_строки)]
        if len(н) != 1:
            return None
        del строки[н[0]]
        return "\n".join(строки)

    return м


def удвоить_строку(якорь_строки):
    def м(текст):
        строки = текст.split("\n")
        н = [i for i, с in enumerate(строки) if с.startswith(якорь_строки)]
        if len(н) != 1:
            return None
        строки.insert(н[0] + 1, строки[н[0]])
        return "\n".join(строки)

    return м


def дописать(хвост):
    def м(текст):
        return текст + хвост

    return м


def правка_строки_cat_confirm(текст):
    """Обратный мутант: старая строка меняет статус и текст, штампа у неё нет."""
    строки = текст.split("\n")
    н = [i for i, с in enumerate(строки) if с.startswith("| CAT-CONFIRM |")]
    if len(н) != 1:
        return None
    я = строки[н[0]].split(" | ")
    if я[3] != "⬜":
        return None
    я[3] = "🔵"
    строки[н[0]] = " | ".join(я).rstrip(" |") + " мутант: взята в работу |"
    return "\n".join(строки)


