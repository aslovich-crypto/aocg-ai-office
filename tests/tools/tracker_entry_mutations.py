def зачеркнуть_последний_живой(текст):
    """Мутация владельца: последний живой пункт блока — зачеркнуть."""
    строки = текст.split("\n")
    живые = [
        i
        for i, с in enumerate(строки)
        if re.match(r"^\d+\. ", с) and not re.match(r"^\d+\. ~~", с)
    ]
    if not живые:
        return None
    i = живые[-1]
    номер, пункт = строки[i].split(" ", 1)
    строки[i] = "%s ~~%s~~" % (номер, пункт)
    return "\n".join(строки)


