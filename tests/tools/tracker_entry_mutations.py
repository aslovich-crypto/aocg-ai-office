def прогнать(каталог, сторож, аргументы):
    """(код, вывод) либо None, если прибор не дал вердикта трижды подряд."""
    for _ in range(3):
        р = subprocess.run(
            [
                sys.executable,
                "-B",
                os.path.join(каталог, сторож),
                *[os.path.join(каталог, а) if а == ТРЕКЕР else а for а in аргументы],
            ],
            capture_output=True,
            text=True,
            cwd=каталог,
        )
        вывод = р.stdout + р.stderr
        if р.returncode in (0, 1, 2) and вывод.strip() and "Traceback" not in вывод:
            return р.returncode, вывод
    return None


def копия(куда):
    for путь in КОПИРОВАТЬ:
        цель = os.path.join(куда, путь)
        os.makedirs(os.path.dirname(цель), exist_ok=True)
        shutil.copy2(os.path.join(КОРЕНЬ, путь), цель)


def main():
    исходные = {п: open(os.path.join(КОРЕНЬ, п), "rb").read() for п in КОПИРОВАТЬ}
    поставлено = поймано = 0
    не_поставлено, не_мерено, пропущено = [], [], []
    with tempfile.TemporaryDirectory() as вр:
        # ── ОБРАТНЫЙ ХОД: на нетронутой копии оба сторожа зелёные, иначе мерить нечем
        копия(вр)
        чисто = [прогнать(вр, ВХОД, []), прогнать(вр, ШТАМПЫ, [ТРЕКЕР])]
        if any(р is None or р[0] != 0 for р in чисто):
            print("⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: сторож красен ДО мутаций — мерить нечем")
            for р in чисто:
                print(р[1] if р else "  (вердикта нет)")
            return 1
        print("обратный ход: на нетронутой копии оба сторожа зелёные ✓\n")

        for номер_м, имя, правки, ожидания in МУТАНТЫ:
            каталог = os.path.join(вр, номер_м)
            копия(каталог)
            встал = True
            for файл, мутация in правки:
                путь = os.path.join(каталог, файл)
                было = open(путь, encoding="utf-8").read()
                стало = мутация(было)
                if стало is None or стало == было:
                    встал = False
                    break
                open(путь, "w", encoding="utf-8").write(стало)
            if not встал:
                не_поставлено.append(номер_м)
                print(
                    f"  ✗ НЕ ПОСТАВЛЕН  {номер_м} {имя}: якорь не найден ровно один раз"
                )
                continue
            поставлено += 1
            итог, почему = True, ""
            for сторож, аргументы, код, тексты in ожидания:
                р = прогнать(каталог, сторож, аргументы)
                if р is None:
                    итог = None
                    break
                if р[0] != код:
                    итог, почему = (
                        False,
                        f"{os.path.basename(сторож)}: код {р[0]}, ждали {код}",
                    )
                    break
                for т in тексты:
                    if т.startswith("НЕ ждём: "):
                        if т[len("НЕ ждём: ") :] in р[1]:
                            итог, почему = (
                                False,
                                f"{os.path.basename(сторож)}: есть «{т[9:]}»",
                            )
                    elif т not in р[1]:
                        итог, почему = False, f"{os.path.basename(сторож)}: нет «{т}»"
            if итог is None:
                не_мерено.append(номер_м)
                print(
                    f"  ? НЕ МЕРЕНО     {номер_м} {имя}: прибор не дал вердикта трижды"
                )
            elif итог:
                поймано += 1
                print(f"  ✓ ПОЙМАН        {номер_м} {имя}")
            else:
                пропущено.append(номер_м)
                print(f"  ✗ ПРОПУЩЕН      {номер_м} {имя} — {почему}")

    print(
        f"\nПОСТАВЛЕНО {поставлено} · ПОЙМАНО {поймано} · НЕ ПОСТАВЛЕНО {len(не_поставлено)}"
        f" · НЕ МЕРЕНО {len(не_мерено)}"
    )
    тронуто = [
        п
        for п in КОПИРОВАТЬ
        if open(os.path.join(КОРЕНЬ, п), "rb").read() != исходные[п]
    ]
    if тронуто:
        print("⚠️ РАБОЧИЕ ФАЙЛЫ ИЗМЕНИЛИСЬ — этого быть не должно:", тронуто)
        return 1
    print("рабочие файлы не тронуты ✓")
    return 0 if (поймано == поставлено and not не_поставлено and not не_мерено) else 1


if __name__ == "__main__":
    sys.exit(main())
