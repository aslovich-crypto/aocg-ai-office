КОДОВЫЕ = re.compile(r"^(app|scripts|tests)/")


class ОчередьНеПрочитана(Exception):
    pass


def разобрать(текст):
    """{'пункты': [...], 'следующая': пункт|None, 'в_работе': [пункты], 'записи': [...]}.

    Пункт — {'номер', 'первая', 'живой', 'синий', 'ид'}; ид — номера из ПРЕДМЕТА
    пункта (часть первой строки до « — »), как у сверки блока с фактом."""
    сырые = tracker_html.пункты_блока(текст)
    if not сырые:
        raise ОчередьНеПрочитана("блок «▶ ПОРЯДОК ВЫПОЛНЕНИЯ» не найден или пуст")
    пункты = []
    for номер, первая, _ in сырые:
        начало = первая.lstrip()
        пункты.append(
            {
                "номер": номер,
                "первая": первая,
                "живой": not начало.startswith("~~"),
                "синий": начало.startswith("🔵"),
                "ид": ССЫЛКА.findall(первая.split(" — ")[0]),
            }
        )
    живые = [п for п in пункты if п["живой"]]
    строки = текст.split("\n")
    начало = next(
        (i for i, с in enumerate(строки) if с.startswith(РАЗДЕЛ_ЖУРНАЛА)), None
    )
    записи = None
    if начало is not None:
        записи = []
        for i in range(начало + 1, len(строки)):
            с = строки[i]
            if с.startswith("## "):
                break
            if ЗАПИСЬ.match(с):
                записи.append((i + 1, с))
    return {
        "пункты": пункты,
        "следующая": живые[0] if живые else None,
        "в_работе": [п for п in пункты if п["синий"]],
        "записи": записи,
        "дорожки": tracker_entry_guard.дорожки(текст),
    }


def проверить(очередь):
    """[(номер строки или 0, что не так)] по ⑩ ⑪ ⑫ ⑬."""
    беды = []
    синие = очередь["в_работе"]
    if len(синие) > 1:
        беды.append(
            (0, "%s: пункты %s" % (БОЛЬШЕ_ОДНОЙ, ", ".join(п["номер"] for п in синие)))
        )
    записи = очередь["записи"]
    if записи is None:
        беды.append((0, НЕТ_ЖУРНАЛА))
        записи = []
    взяли = set()
    for н, с in записи:
        м = ФОРМА_ЗАПИСИ.match(с)
        if not м:
            беды.append((н, ФОРМА))
            continue
        взяли.update(ССЫЛКА.findall(м.group("взяли")))
    следующая = очередь["следующая"]
    if len(синие) == 1 and следующая and синие[0] is not следующая:
        п = синие[0]
        if not (set(п["ид"]) & взяли):
            беды.append(
                (
                    0,
                    "%s: в работе пункт %s %s, а следующий — пункт %s %s"
                    % (
                        БЕЗ_ЗАПИСИ,
                        п["номер"],
                        "+".join(п["ид"]) or "(без номера в предмете)",
                        следующая["номер"],
                        "+".join(следующая["ид"]),
                    ),
                )
            )
    # ⑬ (T200 ②): каждый живой пункт, не только 🔵 (В3) — иначе ✨ на третьем
    # месте сидел бы незамеченным, пока до него не дойдёт очередь.
    дор = очередь["дорожки"]
    открытые = sorted(
        ид
        for ид, (метка, ст) in дор.items()
        if метка == "🚀" and ст in ОТКРЫТОЕ_КОРОТКОЕ
    )
    if открытые:
        for п in очередь["пункты"]:
            if not п["живой"]:
                continue
            # 🚀 в ⏸ внутри предмета — тоже 🚀 пункта (В2); закрытая — нет.
            if any(
                дор.get(ид, (None, None))[0] == "🚀" and дор[ид][1] != "✅"
                for ид in п["ид"]
            ):
                continue
            if set(п["ид"]) & взяли:
                continue
            беды.append(
                (
                    0,
                    "%s: пункт %s %s, а открытых 🚀 %d (%s)"
                    % (
                        НЕ_КОРОТКОЕ,
                        п["номер"],
                        " + ".join(
                            "%s %s" % (ид, дор.get(ид, (None,))[0] or "без метки")
                            for ид in п["ид"]
                        )
                        or "(без номера в предмете)",
                        len(открытые),
                        ", ".join(открытые),
                    ),
                )
            )
    return беды


def счёт_дорожек(дор, закрытые_до=frozenset()):
    """{метка: (открыто, в ⏸, закрыто после дорожек)} — T200 ③.

    ⚠️ ОДНА ФУНКЦИЯ НА ХУК И ВИТРИНУ: «короткая: открыто 5 (⏸ 1)» в первой строке
    ответа и на плитке витрины считаются здесь, и разойтись им нечем. Открыто —
    ⬜, 🔵, 👀; ⏸ отдельно (В5); закрыто — ✅ с меткой, кроме строк, закрытых до
    введения дорожек (у них метки нет, а список их заморожен)."""
    итог = {м: [0, 0, 0] for м in tracker_entry_guard.МЕТКИ}
    for ид, (метка, ст) in дор.items():
        if метка is None:
            continue
        if ст in ОТКРЫТОЕ_КОРОТКОЕ:
            итог[метка][0] += 1
        elif ст == "⏸":
            итог[метка][1] += 1
        elif ст == "✅" and ид not in закрытые_до:
            итог[метка][2] += 1
    return {м: tuple(в) for м, в in итог.items()}


def короткая(дор):
    """(открыто, в ⏸) — строки 🚀, кроме закрытых. Правилу ② нужно первое,
    витрине — сумма; в строке хука видны оба (решение владельца, В1)."""
    открыто, ждёт, _ = счёт_дорожек(дор)["🚀"]
    return открыто, ждёт


def сигнал_разбора(текст):
    """Причины «пора разбирать черновики»; пусто — не пора (T200 ⑤, правило ④).

    Причин две, календарной среди них нет (решение владельца 22.09.2026): все
    пункты блока зачёркнуты — очередь исчерпана, следующую собираем из
    черновиков; черновиков больше пяти. ⚠️ ОДНА ФУНКЦИЯ НА ХУК И ВИТРИНУ
    (заход ③): вторая копия правила разошлась бы с этой молча."""
    причины = []
    if not any(
        not первая.lstrip().startswith("~~")
        for _, первая, _ in tracker_html.пункты_блока(текст)
    ):
        причины.append("очередь исчерпана")
    черновиков = tracker_entry_guard.проверить_черновики(текст)[1]
    if черновиков > tracker_entry_guard.ПОРОГ_ЧЕРНОВИКОВ:
        причины.append(
            "черновиков %d, больше %d"
            % (черновиков, tracker_entry_guard.ПОРОГ_ЧЕРНОВИКОВ)
        )
    return причины


def кратко(п):
    return "пункт %s · %s" % (п["номер"], "+".join(п["ид"]) or п["первая"][:40])


def вывод_хука(текст):
    """(systemMessage, additionalContext)."""
    try:
        очередь = разобрать(текст)
        беды = проверить(очередь)
    except Exception as ош:  # хук не вправе молчать и не вправе ронять сессию
        причина = "%s: %s" % (НЕ_ПРОЧИТАНА, ош)
        return причина, (
            причина
            + ". Скажи владельцу об этом ПЕРВОЙ строкой ответа и не работай молча:"
            " без очереди нельзя проверить, та ли задача берётся. " + ПРАВИЛО
        )
    след = очередь["следующая"]
    синие = очередь["в_работе"]
    черновиков = tracker_entry_guard.проверить_черновики(текст)[1]
    отступлений = len(очередь["записи"] or [])
    открыто, ждёт = короткая(очередь["дорожки"])
    причины = сигнал_разбора(текст)
    строка = (
        "▶ следующая: %s · в работе: %s · короткая: открыто %d (⏸ %d)"
        " · черновиков %d · отступлений %d"
        % (
            кратко(след) if след else "очередь пуста",
            ", ".join(кратко(п) for п in синие) if синие else "ничего не отмечено",
            открыто,
            ждёт,
            черновиков,
            отступлений,
        )
    )
    if причины:
        строка += " · ⚠️ пора разбирать черновики — " + "; ".join(причины)
    if беды:
        строка += " · ⚠️ нарушений очереди %d" % len(беды)
    # ⚠️ СТРОКА — ПЕРВОЙ, СЛОВО В СЛОВО (решение владельца 22.09.2026, В6): до
    # этого модель собирала первую строку ответа из частей ниже, и дословной
    # копии у неё не было (улика 22.09.2026).
    контекст = [
        строка,
        "ОЧЕРЕДЬ из блока «▶ ПОРЯДОК ВЫПОЛНЕНИЯ» (docs/TASKS.md).",
        "Следующая по очереди: %s — %s" % (кратко(след), след["первая"])
        if след
        else "Очередь пуста.",
        "В работе (🔵): %s"
        % ("; ".join(кратко(п) for п in синие) if синие else "ничего не отмечено"),
        "Черновиков в разделе: %d. Записей в журнале отступлений: %d."
        % (черновиков, отступлений),
        ПРАВИЛО,
    ]
    if причины:
        контекст.append(
            "⚠️ ПОРА РАЗБИРАТЬ ЧЕРНОВИКИ: %s. Процедура — скилл task-update, раздел "
            "«Черновик»." % "; ".join(причины)
        )
    for _, что in беды:
        контекст.append("⚠️ НАРУШЕНИЕ ОЧЕРЕДИ: " + что)
    return строка, "\n".join(контекст)


def метка(источник, строка):
    """Метка прогона для замера О7: время старта, источник, что показано."""
    try:
        with open(МЕТКА, "a", encoding="utf-8") as ф:
            ф.write(
                "%s · %s · %s\n"
                % (
                    datetime.datetime.now().isoformat(timespec="seconds"),
                    источник,
                    строка,
                )
            )
    except OSError:
        pass


def режим_хука(путь):
    источник = "?"
    try:
        if not sys.stdin.isatty():
            источник = json.loads(sys.stdin.read() or "{}").get("source", "?")
    except (ValueError, OSError):
        pass
    try:
        with open(путь, encoding="utf-8") as ф:
            текст = ф.read()
        строка, контекст = вывод_хука(текст)
    except OSError as ош:
        строка = "%s: трекер не открыт (%s)" % (НЕ_ПРОЧИТАНА, ош)
        контекст = (
            строка + ". Скажи владельцу об этом ПЕРВОЙ строкой ответа. " + ПРАВИЛО
        )
    метка(источник, строка)
    print(
        json.dumps(
            {
                "systemMessage": строка,
                "hookSpecificOutput": {
                    "hookEventName": "SessionStart",
                    "additionalContext": контекст,
                },
            },
            ensure_ascii=False,
        )
    )
    return 0


def режим_pre_commit(путь, файлы):
    """О6: кодовый коммит, а в блоке ни одной 🔵 — предупреждение, код 0."""
    кодовые = [ф for ф in файлы if КОДОВЫЕ.match(ф)]
    if not кодовые:
        print("очередь: в коммите нет кода — проверка «работа без 🔵» не нужна")
        return 0
    try:
        with open(путь, encoding="utf-8") as ф:
            очередь = разобрать(ф.read())
    except (OSError, ОчередьНеПрочитана) as ош:
        print("%s: %s — проверка «работа без 🔵» не выполнена" % (НЕ_ПРОЧИТАНА, ош))
        return 0
    if очередь["в_работе"]:
        print(
            "очередь: в работе %s ✓" % ", ".join(кратко(п) for п in очередь["в_работе"])
        )
        return 0
    print(
        "🟨🟨🟨 КОДОВЫЙ КОММИТ, А В БЛОКЕ «▶ ПОРЯДОК» НИ ОДНОЙ 🔵 — работа идёт"
        " мимо очереди 🟨🟨🟨"
    )
    print(
        "   кодовых файлов в коммите: %d (%s)" % (len(кодовые), ", ".join(кодовые[:3]))
    )
    print(
        "   отметь 🔵 пункт, по которому работа, либо заведи отступление по «ок» владельца"
    )
    return 0


# ── САМОПРОВЕРКА: обе половины. Известные ответы на крошечных трекерах.
def _трекер(блок, журнал=None):
    т = "## ▶ ПОРЯДОК ВЫПОЛНЕНИЯ\n\n" + блок + "\n\n## Блок\n\n"
    if журнал is not None:
        т += "## ↪ ЖУРНАЛ ОТСТУПЛЕНИЙ\n\n> правило\n\n" + журнал + "\n\n"
    return т + "## 🔎 ЖУРНАЛ УЛИК\n"


БЛОК = (
    "1. ~~**[[A-0]]** — закрыт~~\n"
    "2. 🔵 **[[A-1]]** — в работе\n"
    "   довод\n"
    "3. **[[A-2]]** — следующий после\n"
    "4. **[[A-3]]** — последний живой"
)
ЗАПИСЬ_ЗДОРОВАЯ = (
    "**22.09.2026** · взяли [[A-2]] вместо [[A-1]] (пункт 2) · слово владельца: «так»"
)


ШАПКА = (
    "| ID | Задача | Пр. | Статус | План (класс) | Факт | Примечание |\n"
    "| :- | :- | :-: | :-: | :- | :- | :- |\n"
)


def _трекер_дорожек(блок, строки, журнал="", черновиков=0):
    """Трекер с таблицей строк (ид, метка, статус) и разделом черновиков (T200 ②⑤)."""
    т = "## ▶ ПОРЯДОК ВЫПОЛНЕНИЯ\n\n" + блок + "\n\n## Блок\n\n" + ШАПКА
    т += "".join("| %s | %s · задача | 🟡 | %s | — | — | — |\n" % с for с in строки)
    т += "\n## ↪ ЖУРНАЛ ОТСТУПЛЕНИЙ\n\n> правило\n\n" + журнал + "\n\n"
    т += "## ✏️ ЧЕРНОВИКИ — без номера\n\n"
    т += "".join(
        "**22.09.2026** · ✨ · черновик %d · опора: улика\n\n" % к
        for к in range(черновиков)
    )
    return т + "## 🔎 ЖУРНАЛ УЛИК\n"


Д_БЛОК = "1. 🔵 **[[S-1]]** — короткая в работе\n2. **[[L-1]]** — длинная"
