# -*- coding: utf-8 -*-
"""ОЧЕРЕДЬ: следующая задача, одна в работе, отступления — только в журнал (T199, часть ③).

ЗАЧЕМ. Правило «в работе держать одну задачу, брать следующую по очереди»
держалось на доброй воле. Замер 22.09.2026 по 139 версиям трекера с 06.09:
🔵 стоял не на первом живом пункте блока 7 раз — и ни разу это не было
записано; ни одной 🔵 — 68 раз (это нормальное состояние между заходами).
Решения владельца 22.09.2026 — О1–О8 захода ③ строки T199.

ИСТОЧНИК ОЧЕРЕДИ — ТОЛЬКО блок «▶ ПОРЯДОК ВЫПОЛНЕНИЯ» в docs/TASKS.md (Р6).
Разбор блока — тот же, что у витрины (`tracker_html.пункты_блока`): другой
разбор дал бы другую «следующую», и прибор с витриной разошлись бы.
  СЛЕДУЮЩАЯ — первый незачёркнутый пункт блока;
  В РАБОТЕ  — пункт с 🔵 в начале первой строки; их не больше одного.

ЧТО ПРОВЕРЯЕТСЯ (CI, код 1):
  ⑩ 🔵 больше чем у одного пункта — «в работе больше одного пункта»;
  ⑪ 🔵 не на первом живом пункте, а в «↪ ЖУРНАЛ ОТСТУПЛЕНИЙ» нет записи,
     где этот пункт назван во «взяли» — «отступление без записи»;
  ⑫ запись журнала не той формы — «запись журнала отступлений: форма»;
     нет самого раздела журнала — тоже красное: проверка ⑪ не выполнена.
  «Ни одной 🔵» — НЕ нарушение, только печать (О5): на истории это половина
  версий, и красное там приучило бы не смотреть на красное.

РЕЖИМЫ:
  (без флага)    сторож для CI: печать и коды 0 / 1 / 2;
  --hook         вывод хука начала сессии (О2, О3): JSON, где systemMessage —
                 владельцу одной строкой, additionalContext — модели с правилом
                 «не следующая — стоп». Код ВСЕГДА 0: хук не вправе мешать сессии.
                 Сбой разбора — «⚠️ ОЧЕРЕДЬ НЕ ПРОЧИТАНА» В ОБА КАНАЛА, и модели
                 велено сказать об этом первой строкой ответа (уточнение владельца
                 22.09.2026). Пишет метку прогона в МЕТКА — для замера О7.
  --pre-commit   предупреждение О6: кодовый коммит, а в блоке ни одной 🔵.
                 Код ВСЕГДА 0 — предупреждение, не блокировка.
  --selfcheck    самопроверка на известных ответах, обе половины.

⚠️ НАЗВАННАЯ СЛЕПОТА. CI видит только объявленную работу: пункт с 🔵. Работа,
которую никто не объявил, для него не существует. Предупреждение pre-commit
(О6) закрывает это наполовину — оно видит кодовый коммит без 🔵, но не видит,
что коммит про другую задачу, чем та, что с 🔵.

КОДЫ (без флага): 0 — чисто; 1 — нарушения; 2 — самопроверка не прошла.
"""

from __future__ import annotations

import datetime
import json
import os
import re
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)
import tracker_entry_guard  # noqa: E402
import tracker_html  # noqa: E402

КОРЕНЬ = os.path.dirname(os.path.dirname(ЗДЕСЬ))
ТРЕКЕР = os.path.join(КОРЕНЬ, "docs", "TASKS.md")
# ⚠️ МЕТКА ВНЕ РЕПОЗИТОРИЯ: файл в дереве виден `git status` и полез бы в коммит.
# ⚠️ И ПУТЬ ЗАДАЁТСЯ СНАРУЖИ: тесты и мутации пишут свою метку во временный файл.
# Иначе их строки легли бы в ту же метку, что и настоящий запуск хука, и замер
# «хук сработал в VS Code» (О7) принял бы прогон теста за прогон хука.
МЕТКА = os.environ.get("AOCG_QUEUE_MARK", "/tmp/aocg-session-queue.log")

РАЗДЕЛ_ЖУРНАЛА = "## ↪ ЖУРНАЛ ОТСТУПЛЕНИЙ"
ЗАПИСЬ = re.compile(r"^\*\*\d{2}\.\d{2}\.\d{4}\*\* · ")
ФОРМА_ЗАПИСИ = re.compile(
    r"^\*\*(\d{2}\.\d{2}\.\d{4})\*\* · взяли (?P<взяли>.*?\[\[[^\]]+\]\].*?)"
    r" вместо (?P<вместо>.*?\[\[[^\]]+\]\].*?) · слово владельца"
)
ССЫЛКА = re.compile(r"\[\[([^\]]+)\]\]")

БОЛЬШЕ_ОДНОЙ = "в работе больше одного пункта"
БЕЗ_ЗАПИСИ = "отступление без записи в журнале отступлений"
ФОРМА = "запись журнала отступлений: форма"
НЕТ_ЖУРНАЛА = "раздел «↪ ЖУРНАЛ ОТСТУПЛЕНИЙ» не найден — проверка ⑪ не выполнена"
НЕ_ПРОЧИТАНА = "⚠️ ОЧЕРЕДЬ НЕ ПРОЧИТАНА"
ПРАВИЛО = (
    "ПРАВИЛО ОЧЕРЕДИ (T199 ③, решение владельца 22.09.2026): бери СЛЕДУЮЩУЮ задачу. "
    "Если владелец просит другую — СТОП: нужно его явное «ок» с названием, от чего "
    "отступаем; тогда пункт в блок с 🔵 и запись в «↪ ЖУРНАЛ ОТСТУПЛЕНИЙ» — одним "
    "коммитом. 🔵 в блоке — ровно у одного пункта."
)
# Кодовый коммит для О6: правка кода приложения, скриптов или тестов.
КОДОВЫЕ = re.compile(r"^(app|scripts|tests)/")


class ОчередьНеПрочитана(Exception):
    pass


def разобрать(текст):
    """{'пункты': [...], 'следующая': пункт|None, 'в_работе': [пункты], 'записи': [...]}.

    Пункт — {'номер', 'первая', 'живой', 'синий', 'ид'}; ид — номера из ПРЕДМЕТА
    пункта (часть первой строки до « — »), как у сверки блока с фактом."""
    сырые = tracker_html.пункты_блока(текст)
    if not сырые:
        raise ОчередьНеПрочитана("блок «▶ ПОРЯДОК ВЫПОЛНЕНИЯ» не найден или пуст")
    пункты = []
    for номер, первая, _ in сырые:
        начало = первая.lstrip()
        пункты.append(
            {
                "номер": номер,
                "первая": первая,
                "живой": not начало.startswith("~~"),
                "синий": начало.startswith("🔵"),
                "ид": ССЫЛКА.findall(первая.split(" — ")[0]),
            }
        )
    живые = [п for п in пункты if п["живой"]]
    строки = текст.split("\n")
    начало = next(
        (i for i, с in enumerate(строки) if с.startswith(РАЗДЕЛ_ЖУРНАЛА)), None
    )
    записи = None
    if начало is not None:
        записи = []
        for i in range(начало + 1, len(строки)):
            с = строки[i]
            if с.startswith("## "):
                break
            if ЗАПИСЬ.match(с):
                записи.append((i + 1, с))
    return {
        "пункты": пункты,
        "следующая": живые[0] if живые else None,
        "в_работе": [п for п in пункты if п["синий"]],
        "записи": записи,
    }


def проверить(очередь):
    """[(номер строки или 0, что не так)] по ⑩ ⑪ ⑫."""
    беды = []
    синие = очередь["в_работе"]
    if len(синие) > 1:
        беды.append(
            (0, "%s: пункты %s" % (БОЛЬШЕ_ОДНОЙ, ", ".join(п["номер"] for п in синие)))
        )
    записи = очередь["записи"]
    if записи is None:
        беды.append((0, НЕТ_ЖУРНАЛА))
        записи = []
    взяли = set()
    for н, с in записи:
        м = ФОРМА_ЗАПИСИ.match(с)
        if not м:
            беды.append((н, ФОРМА))
            continue
        взяли.update(ССЫЛКА.findall(м.group("взяли")))
    следующая = очередь["следующая"]
    if len(синие) == 1 and следующая and синие[0] is not следующая:
        п = синие[0]
        if not (set(п["ид"]) & взяли):
            беды.append(
                (
                    0,
                    "%s: в работе пункт %s %s, а следующий — пункт %s %s"
                    % (
                        БЕЗ_ЗАПИСИ,
                        п["номер"],
                        "+".join(п["ид"]) or "(без номера в предмете)",
                        следующая["номер"],
                        "+".join(следующая["ид"]),
                    ),
                )
            )
    return беды


def кратко(п):
    return "пункт %s · %s" % (п["номер"], "+".join(п["ид"]) or п["первая"][:40])


def вывод_хука(текст):
    """(systemMessage, additionalContext)."""
    try:
        очередь = разобрать(текст)
        беды = проверить(очередь)
    except Exception as ош:  # хук не вправе молчать и не вправе ронять сессию
        причина = "%s: %s" % (НЕ_ПРОЧИТАНА, ош)
        return причина, (
            причина
            + ". Скажи владельцу об этом ПЕРВОЙ строкой ответа и не работай молча:"
            " без очереди нельзя проверить, та ли задача берётся. " + ПРАВИЛО
        )
    след = очередь["следующая"]
    синие = очередь["в_работе"]
    черновиков = tracker_entry_guard.проверить_черновики(текст)[1]
    отступлений = len(очередь["записи"] or [])
    строка = "▶ следующая: %s · в работе: %s · черновиков %d · отступлений %d" % (
        кратко(след) if след else "очередь пуста",
        ", ".join(кратко(п) for п in синие) if синие else "ничего не отмечено",
        черновиков,
        отступлений,
    )
    if беды:
        строка += " · ⚠️ нарушений очереди %d" % len(беды)
    контекст = [
        "ОЧЕРЕДЬ из блока «▶ ПОРЯДОК ВЫПОЛНЕНИЯ» (docs/TASKS.md).",
        "Следующая по очереди: %s — %s" % (кратко(след), след["первая"])
        if след
        else "Очередь пуста.",
        "В работе (🔵): %s"
        % ("; ".join(кратко(п) for п in синие) if синие else "ничего не отмечено"),
        "Черновиков в разделе: %d. Записей в журнале отступлений: %d."
        % (черновиков, отступлений),
        ПРАВИЛО,
    ]
    for _, что in беды:
        контекст.append("⚠️ НАРУШЕНИЕ ОЧЕРЕДИ: " + что)
    return строка, "\n".join(контекст)


def метка(источник, строка):
    """Метка прогона для замера О7: время старта, источник, что показано."""
    try:
        with open(МЕТКА, "a", encoding="utf-8") as ф:
            ф.write(
                "%s · %s · %s\n"
                % (
                    datetime.datetime.now().isoformat(timespec="seconds"),
                    источник,
                    строка,
                )
            )
    except OSError:
        pass


def режим_хука(путь):
    источник = "?"
    try:
        if not sys.stdin.isatty():
            источник = json.loads(sys.stdin.read() or "{}").get("source", "?")
    except (ValueError, OSError):
        pass
    try:
        with open(путь, encoding="utf-8") as ф:
            текст = ф.read()
        строка, контекст = вывод_хука(текст)
    except OSError as ош:
        строка = "%s: трекер не открыт (%s)" % (НЕ_ПРОЧИТАНА, ош)
        контекст = (
            строка + ". Скажи владельцу об этом ПЕРВОЙ строкой ответа. " + ПРАВИЛО
        )
    метка(источник, строка)
    print(
        json.dumps(
            {
                "systemMessage": строка,
                "hookSpecificOutput": {
                    "hookEventName": "SessionStart",
                    "additionalContext": контекст,
                },
            },
            ensure_ascii=False,
        )
    )
    return 0


def режим_pre_commit(путь, файлы):
    """О6: кодовый коммит, а в блоке ни одной 🔵 — предупреждение, код 0."""
    кодовые = [ф for ф in файлы if КОДОВЫЕ.match(ф)]
    if not кодовые:
        print("очередь: в коммите нет кода — проверка «работа без 🔵» не нужна")
        return 0
    try:
        with open(путь, encoding="utf-8") as ф:
            очередь = разобрать(ф.read())
    except (OSError, ОчередьНеПрочитана) as ош:
        print("%s: %s — проверка «работа без 🔵» не выполнена" % (НЕ_ПРОЧИТАНА, ош))
        return 0
    if очередь["в_работе"]:
        print(
            "очередь: в работе %s ✓" % ", ".join(кратко(п) for п in очередь["в_работе"])
        )
        return 0
    print(
        "🟨🟨🟨 КОДОВЫЙ КОММИТ, А В БЛОКЕ «▶ ПОРЯДОК» НИ ОДНОЙ 🔵 — работа идёт"
        " мимо очереди 🟨🟨🟨"
    )
    print(
        "   кодовых файлов в коммите: %d (%s)" % (len(кодовые), ", ".join(кодовые[:3]))
    )
    print(
        "   отметь 🔵 пункт, по которому работа, либо заведи отступление по «ок» владельца"
    )
    return 0


# ── САМОПРОВЕРКА: обе половины. Известные ответы на крошечных трекерах.
def _трекер(блок, журнал=None):
    т = "## ▶ ПОРЯДОК ВЫПОЛНЕНИЯ\n\n" + блок + "\n\n## Блок\n\n"
    if журнал is not None:
        т += "## ↪ ЖУРНАЛ ОТСТУПЛЕНИЙ\n\n> правило\n\n" + журнал + "\n\n"
    return т + "## 🔎 ЖУРНАЛ УЛИК\n"


БЛОК = (
    "1. ~~**[[A-0]]** — закрыт~~\n"
    "2. 🔵 **[[A-1]]** — в работе\n"
    "   довод\n"
    "3. **[[A-2]]** — следующий после\n"
    "4. **[[A-3]]** — последний живой"
)
ЗАПИСЬ_ЗДОРОВАЯ = (
    "**22.09.2026** · взяли [[A-2]] вместо [[A-1]] (пункт 2) · слово владельца: «так»"
)


def самопроверка():
    print("САМОПРОВЕРКА ОЧЕРЕДИ")
    плохо = 0

    def отметить(имя, если):
        nonlocal плохо
        print("  %s %s" % ("✓" if если else "✗", имя))
        плохо += 0 if если else 1

    о = разобрать(_трекер(БЛОК, ""))
    отметить(
        "следующая — первый живой пункт (2, а не последний 4)",
        о["следующая"]["номер"] == "2",
    )
    отметить("здоровая очередь молчит", not проверить(о))
    случаи = [
        ("две 🔵", БЛОК.replace("3. **", "3. 🔵 **"), "", БОЛЬШЕ_ОДНОЙ),
        (
            "🔵 не на следующем, записи нет",
            БЛОК.replace("2. 🔵 **", "2. **").replace("3. **", "3. 🔵 **"),
            "",
            БЕЗ_ЗАПИСИ,
        ),
        ("запись битой формы", БЛОК, "**22.09.2026** · взял что-то сам", ФОРМА),
        ("журнала нет", БЛОК, None, НЕТ_ЖУРНАЛА),
    ]
    for имя, блок, журнал, ждём in случаи:
        беды = проверить(разобрать(_трекер(блок, журнал)))
        отметить("%s: поймано" % имя, any(что.startswith(ждём) for _, что in беды))
    # обратная половина: то же отступление, но с записью — молчит
    с_записью = БЛОК.replace("2. 🔵 **", "2. **").replace("3. **", "3. 🔵 **")
    отметить(
        "отступление с записью молчит",
        not проверить(разобрать(_трекер(с_записью, ЗАПИСЬ_ЗДОРОВАЯ))),
    )
    # сбой разбора — в ОБА канала, со словами «первой строкой»
    вм, вк = вывод_хука("# трекер без блока\n")
    отметить(
        "сбой разбора — в оба канала",
        вм.startswith(НЕ_ПРОЧИТАНА)
        and вк.startswith(НЕ_ПРОЧИТАНА)
        and "ПЕРВОЙ строкой" in вк,
    )
    print(
        "  ИТОГ: самопроверка пройдена"
        if not плохо
        else "  ИТОГ: расхождений %d" % плохо
    )
    return плохо


def main():
    аргументы = sys.argv[1:]
    путь = next(
        (а for а in аргументы if not а.startswith("--") and а.endswith(".md")), ТРЕКЕР
    )
    if "--hook" in аргументы:
        return режим_хука(путь)
    if "--pre-commit" in аргументы:
        return режим_pre_commit(путь, [а for а in аргументы if not а.startswith("--")])
    if самопроверка():
        print("\n⚠️ СТОРОЖ ОЧЕРЕДИ НЕ ПРОШЁЛ САМОПРОВЕРКУ — трекер не смотрим.")
        return 2
    if "--selfcheck" in аргументы:
        return 0
    with open(путь, encoding="utf-8") as ф:
        текст = ф.read()
    try:
        очередь = разобрать(текст)
    except ОчередьНеПрочитана as ош:
        print("\n%s: %s" % (НЕ_ПРОЧИТАНА, ош))
        return 1
    беды = проверить(очередь)
    след = очередь["следующая"]
    print("\nОЧЕРЕДЬ (T199 ③) · %s" % путь)
    print("  пунктов в блоке               : %d" % len(очередь["пункты"]))
    print(
        "  следующая                     : %s"
        % (кратко(след) if след else "очередь пуста")
    )
    print(
        "  в работе (🔵)                 : %s"
        % (
            ", ".join(кратко(п) for п in очередь["в_работе"])
            or "ничего не отмечено — не нарушение"
        )
    )
    print("  записей в журнале отступлений : %d" % len(очередь["записи"] or []))
    if not беды:
        print("  ✓ нарушений 0")
        return 0
    print("\n🟥🟥🟥 ОЧЕРЕДЬ: НАРУШЕНИЙ %d 🟥🟥🟥" % len(беды))
    for н, что in беды:
        print("   %s:%s  %s" % (путь, н or "—", что))
    return 1


if __name__ == "__main__":
    sys.exit(main())
