#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПАРНЫЙ СТОРОЖ «канал реквизитов ФНС»: бэкенд принимает ↔ фронт шлёт (строка 31).

⚠️ ЗАЧЕМ. Этот сторож заведён по случаю, который приборы НЕ ВИДЕЛИ ВОВСЕ.
Бэкенд принимал `fd_num` и `fpd` от клиента с 31.08.2026 (T132, шаг ⓪ — поля
добавлены ровно под случай «ФНС промолчала»), а фронт не слал их НИ РАЗУ.
Канал открыли и не подключили; замер владельца на проде 11.09.2026 показал
цену: фискальные реквизиты есть у 22 чеков из 98.

⚠️ ПОЧЕМУ ЭТОГО НЕ ЛОВИЛО НИЧТО. Обе половины по отдельности ЗДОРОВЫ:
у бэкенда поле объявлено и покрыто тестами, у фронта разбор QR эти значения
честно возвращает. Красным не становится ни один прогон — ломается только
ДОРОГА между ними, а дорогу не проверяет ни pytest (он не видит фронт),
ни eslint (он не видит договор ручки). Класс известен как «сделали
и не подключили» (T149), и его признак: у всех приборов зелено.

⚠️ ПЯТЬ ЗНАЧЕНИЙ, А НЕ ТРИ. Право на дозапрос (`_можно_дозапросить`) требует
ФН, ФД, ФПД, ВРЕМЯ и сумму: запрос к ФНС — это строка QR, и в ней `t=` дата
и время до минуты. Поэтому сторож проверяет и `datetime`: без него четыре
остальные правки не дают результата, и чек залипает без права на дозапрос
навсегда. Нашёл это не основной разбор, а адвокат дьявола.

⚠️ КОММЕНТАРИИ СРЕЗАЮТСЯ ПЕРЕД ПОИСКОМ. Имена `fd_num`, `fpd` и `datetime`
стоят в обоих репозиториях в пояснениях — в том числе в этом самом файле.
Прибор, ищущий по сырому тексту, нашёл бы СВОИ ЖЕ объяснения и зеленел бы
на мёртвом коде. Куплено четыре раза за два дня 28–29.08.2026, свод
называет это «текст был верным, а место — нет».

ЗАПУСК:
    ./venv/bin/python tests/tools/fns_requisites_pair.py
    ./venv/bin/python tests/tools/fns_requisites_pair.py --selfcheck

КОДЫ ВОЗВРАТА: 0 — обе половины на месте · 1 — РАСХОЖДЕНИЕ ·
               2 — фронт недоступен, НЕ МЕРЕНО (не путать с «ок»).
"""

import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ЧЕКИ = os.path.join(КОРЕНЬ, "app", "routers", "receipts.py")
ФРОНТ_SRC = os.environ.get(
    "FRONT_SRC",
    os.path.normpath(os.path.join(КОРЕНЬ, "..", "aocg-ai-office-web", "src")),
)
ПРИЛОЖЕНИЕ = os.path.join(ФРОНТ_SRC, "App.jsx")
КОДЕК_QR = os.path.join(ФРОНТ_SRC, "lib", "qr.js")


def без_комментариев(текст: str) -> str:
    """Срезает // и /* */ и питоновские #.

    Строковые литералы не трогаем намеренно: искомое в них не встречается,
    а честный разбор двух языков ради этого не окупается.
    """
    текст = re.sub(r"/\*[\s\S]*?\*/", " ", текст)
    текст = re.sub(r"(?m)//.*$", " ", текст)
    return re.sub(r"(?m)#.*$", " ", текст)


# ── половина ① БЭКЕНД: договор входа объявляет все три поля ──────────────
ПОЛЯ_ДОГОВОРА = (
    ("fd_num", r"\bfd_num\s*:\s*Optional\["),
    ("fpd", r"\bfpd\s*:\s*Optional\["),
    ("datetime", r"\bdatetime\s*:\s*Optional\["),
)

# ⚠️ ОБЪЯВИТЬ МАЛО — ЗНАЧЕНИЕ ОБЯЗАНО ДОЙТИ ДО INSERT. Поле, принятое
# договором и потерянное по дороге, снаружи неотличимо от непринятого:
# ручка отвечает 200 в обоих случаях.
ДОХОДИТ_ДО_ВСТАВКИ = (
    ("fd_num", r"r\.fd_num"),
    ("fpd", r"r\.fpd"),
    ("datetime", r"r\.datetime"),
)

# ── половина ② ФРОНТ: значения кладутся в тело запроса ───────────────────
ШЛЁТ_ФРОНТ = (
    ("fd_num", r"payload\.fd_num\s*="),
    ("fpd", r"payload\.fpd\s*="),
    ("datetime", r"payload\.datetime\s*="),
)

# ⚠️ И ИСТОЧНИК ЭТИХ ЗНАЧЕНИЙ. Разбор QR обязан ОТДАВАТЬ время: оно лежит
# в строке всегда, и ровно его здесь однажды и выбросили.
КОДЕК_ОТДАЁТ_ВРЕМЯ = r"time\s*:"


def проверить(чеки: str, приложение: str, кодек: str):
    """Возвращает список расхождений. Пустой список — обе половины на месте."""
    беды = []
    for имя, образец in ПОЛЯ_ДОГОВОРА:
        if not re.search(образец, чеки):
            беды.append("бэкенд: договор входа не объявляет поле «%s»" % имя)
    for имя, образец in ДОХОДИТ_ДО_ВСТАВКИ:
        if not re.search(образец, чеки):
            беды.append(
                "бэкенд: поле «%s» объявлено, но до вставки не доходит — "
                "ручка ответит 200 и промолчит" % имя
            )
    for имя, образец in ШЛЁТ_ФРОНТ:
        if not re.search(образец, приложение):
            беды.append(
                "фронт: «%s» не кладётся в тело запроса — канал открыт "
                "и не подключён" % имя
            )
    if not re.search(КОДЕК_ОТДАЁТ_ВРЕМЯ, кодек):
        беды.append("фронт: разбор QR не отдаёт время — слать будет нечего")
    return беды


ЗДОРОВЫЙ_БЭК = (
    "class ReceiptIn(BaseModel):\n"
    "    fd_num: Optional[str] = None\n"
    "    fpd: Optional[str] = None\n"
    "    datetime: Optional[_dt] = None\n"
    "VALUES (r.fd_num, r.fpd, parsed.get('datetime') or r.datetime)\n"
)
ЗДОРОВЫЙ_ФРОНТ = (
    "if (form.fd) payload.fd_num = form.fd;\n"
    "if (form.fpd) payload.fpd = form.fpd;\n"
    "payload.datetime = `${form.date}T${form.time}:00`;\n"
)
ЗДОРОВЫЙ_КОДЕК = "return { date, time: время, fn: p.fn };\n"


def самопроверка() -> int:
    """ОБЕ ПОЛОВИНЫ, И ВТОРАЯ ВАЖНЕЕ ПЕРВОЙ.

    ① заведомо дырявое обязано найтись; ② заведомо ЗДОРОВОЕ обязано пройти.
    Без второй половины «расхождений 0» неотличимо от «прибор слеп», а сторож
    с ложными находками отбрасывают в первый же день — вместе с идеей.
    """
    ошибки = []

    # ② здоровое — молчит
    беды = проверить(ЗДОРОВЫЙ_БЭК, ЗДОРОВЫЙ_ФРОНТ, ЗДОРОВЫЙ_КОДЕК)
    if беды:
        ошибки.append("ЛОЖНАЯ ТРЕВОГА на заведомо здоровом образце: %s" % беды)

    # ① дырявое — ловится, и каждая дыра ОТДЕЛЬНО: одна успешная проверка
    # подтверждает одну ветку, а не сторож целиком.
    дыры = (
        (
            "фронт не шлёт ФД",
            ЗДОРОВЫЙ_БЭК,
            ЗДОРОВЫЙ_ФРОНТ.replace("payload.fd_num =", "// нет"),
            ЗДОРОВЫЙ_КОДЕК,
        ),
        (
            "фронт не шлёт ФПД",
            ЗДОРОВЫЙ_БЭК,
            ЗДОРОВЫЙ_ФРОНТ.replace("payload.fpd =", "// нет"),
            ЗДОРОВЫЙ_КОДЕК,
        ),
        (
            "фронт не шлёт время",
            ЗДОРОВЫЙ_БЭК,
            ЗДОРОВЫЙ_ФРОНТ.replace("payload.datetime =", "// нет"),
            ЗДОРОВЫЙ_КОДЕК,
        ),
        (
            "договор не принимает время",
            ЗДОРОВЫЙ_БЭК.replace("datetime: Optional[_dt]", "нет"),
            ЗДОРОВЫЙ_ФРОНТ,
            ЗДОРОВЫЙ_КОДЕК,
        ),
        (
            "значение не доходит до вставки",
            ЗДОРОВЫЙ_БЭК.replace("r.fd_num", "нет"),
            ЗДОРОВЫЙ_ФРОНТ,
            ЗДОРОВЫЙ_КОДЕК,
        ),
        (
            "кодек не отдаёт время",
            ЗДОРОВЫЙ_БЭК,
            ЗДОРОВЫЙ_ФРОНТ,
            "return { date, fn: p.fn };\n",
        ),
    )
    for имя, б, ф, к in дыры:
        if not проверить(б, ф, к):
            ошибки.append("НЕ ПОЙМАНА заведомая дыра: %s" % имя)

    # ⑤ ЛОЖНАЯ НАХОДКА, КОТОРУЮ УЖЕ ЗНАЕМ, — ОТДЕЛЬНЫМ ПУНКТОМ САМОПРОВЕРКИ,
    # а не строчкой в оговорках: оговорку через полгода прочитают как описание,
    # пункт самопроверки покраснеет. Имена полей стоят в комментариях обоих
    # репозиториев; прибор, не срезающий комментарии, зеленел бы на мёртвом коде.
    только_комментарии_бэк = (
        "# fd_num: Optional[str] = None\n"
        "# fpd: Optional[str] = None\n"
        "# datetime: Optional[_dt] = None\n"
        "# r.fd_num r.fpd r.datetime\n"
    )
    только_комментарии_фронт = (
        "// payload.fd_num = form.fd;\n"
        "// payload.fpd = form.fpd;\n"
        "// payload.datetime = x;\n"
    )
    if not проверить(
        без_комментариев(только_комментарии_бэк),
        без_комментариев(только_комментарии_фронт),
        без_комментариев("// time:"),
    ):
        ошибки.append(
            "НЕ ПОЙМАНО: искомое стоит ТОЛЬКО в комментариях, а сторож счёл "
            "это рабочим кодом"
        )

    if ошибки:
        print("⚠️ САМОПРОВЕРКА НЕ ПРОШЛА:")
        for э in ошибки:
            print("   ·", э)
        return 1
    print("✓ самопроверка: здоровое проходит, шесть заведомых дыр ловятся,")
    print("  искомое в комментариях за рабочий код не считается")
    return 0


def main() -> int:
    if "--selfcheck" in sys.argv:
        return самопроверка()

    if not os.path.exists(ПРИЛОЖЕНИЕ) or not os.path.exists(КОДЕК_QR):
        # ⚠️ НЕ «ок» И НЕ «плохо», А «НЕ МЕРЕНО». Отдельный код возврата,
        # потому что молчание недоступного фронта неотличимо от согласия.
        print("⚠️ ФРОНТ НЕДОСТУПЕН, СТЫК НЕ ПРОВЕРЕН: %s" % ФРОНТ_SRC)
        print("   задайте FRONT_SRC, если репозиторий лежит в другом месте")
        return 2

    чеки = без_комментариев(open(ЧЕКИ, encoding="utf-8").read())
    приложение = без_комментариев(open(ПРИЛОЖЕНИЕ, encoding="utf-8").read())
    кодек = без_комментариев(open(КОДЕК_QR, encoding="utf-8").read())

    print("КАНАЛ РЕКВИЗИТОВ ФНС · парный сторож (строка 31)")
    print("  бэкенд: %s" % os.path.relpath(ЧЕКИ, КОРЕНЬ))
    print("  фронт : %s" % ФРОНТ_SRC)
    print("  проверено полей: %d (ФД, ФПД, время) по трём признакам каждое" % 3)

    беды = проверить(чеки, приложение, кодек)
    if беды:
        print("\n⚠️ РАСХОЖДЕНИЙ %d:" % len(беды))
        for б in беды:
            print("   ·", б)
        print("\n  Канал считается рабочим, только когда обе половины на месте:")
        print("  принять и не прислать — то же самое, что не принимать.")
        return 1
    print("\n✓ обе половины на месте: бэкенд принимает и доводит до вставки,")
    print("  фронт шлёт, разбор QR отдаёт время")
    return 0


if __name__ == "__main__":
    sys.exit(main())
