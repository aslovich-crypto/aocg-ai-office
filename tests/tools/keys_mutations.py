def прогнать(ловцы, копия: str):
    """(есть ли вердикт, «прошёл»/«упал», вывод). Все ловцы — одним прогоном."""
    итог = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            ПРОВЕРКИ,
            "-q",
            "--no-header",
            "-k",
            " or ".join(ловцы),
        ],
        cwd=копия,
        capture_output=True,
        text=True,
        timeout=900,
    )
    вывод = итог.stdout + итог.stderr
    # ⚠️ РАЗЛИЧАЕМ «ПРИБОР НЕ ОТРАБОТАЛ» И «ПРИБОР ПРОМОЛЧАЛ». Без живого
    # PostgreSQL фикстура валится, и её падение засчиталось бы за поимку
    # мутанта — прибор показал бы работу там, где её не было.
    есть = " passed" in вывод or " failed" in вывод
    прошёл = " failed" not in вывод and " error" not in вывод
    return есть, ("прошёл" if прошёл else "упал"), вывод


def main() -> int:
    print("\nМУТАЦИИ КЛЮЧЕЙ ИНТЕГРАЦИИ: круг · срок · секрет · замок · список\n")

    with tempfile.TemporaryDirectory(prefix="keys-mut-") as врем:
        копия = os.path.join(врем, "back")
        shutil.copytree(
            КОРЕНЬ,
            копия,
            symlinks=True,
            ignore=shutil.ignore_patterns(
                ".git", "venv", "__pycache__", "node_modules", "*.pyc", "dist"
            ),
        )
        исходники = {
            ф: open(os.path.join(копия, ф), encoding="utf-8").read()
            for _, ф, *_ in МУТАНТЫ
        }

        # ОБРАТНЫЙ ХОД: на нетронутой копии все ловцы зелены. Здесь же
        # отсеивается «нет базы» — иначе каждая мутация читалась бы пойманной.
        все_ловцы = sorted({л for м in МУТАНТЫ for л in м[4]})
        есть, исход, вывод = прогнать(все_ловцы, копия)
        if not есть:
            print("  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ на чистом дереве — мерить нечем")
            print("     " + (вывод.strip().splitlines() or ["пусто"])[-1][:300])
            return 1
        if исход != "прошёл":
            print("  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: ловцы красны ДО мутаций")
            print(вывод[-1500:])
            return 1
        print(f"  обратный ход: {len(все_ловцы)} ловцов зелены на чистой копии ✓\n")

        поставлено = поймано = 0
        непоставленные: list[str] = []
        немерено: list[str] = []
        for имя, файл, было, стало, ловцы, зачем in МУТАНТЫ:
            путь = os.path.join(копия, файл)
            исходный = исходники[файл]
            if исходный.count(было) != 1:
                непоставленные.append(имя)
                print(f"  ✗ НЕ ПОСТАВЛЕН  {имя}")
                print(f"      якорь встречается {исходный.count(было)} раз, нужен один")
                continue
            open(путь, "w", encoding="utf-8").write(исходный.replace(было, стало))
            поставлено += 1
            есть, исход, _ = прогнать(ловцы, копия)
            open(путь, "w", encoding="utf-8").write(исходный)

            если_ловцы = " · ".join(л.replace("test_", "") for л in ловцы)
            if not есть:
                немерено.append(имя)
                print(f"  ⚠ НЕ МЕРЕНО     {имя}")
            elif исход == "упал":
                поймано += 1
                print(f"  ✓ ПОЙМАН        {имя}")
            else:
                print(f"  ✗ НЕ ПОЙМАН     {имя}")
            print(f"      ловцы: {если_ловцы}")
            print(f"      зачем: {зачем}")

        print(
            f"\nПОСТАВЛЕНО {поставлено} · ПОЙМАНО {поймано} · "
            f"НЕ ПОСТАВЛЕНО {len(непоставленные)} · НЕ МЕРЕНО {len(немерено)}"
        )
        целы = all(
            open(os.path.join(копия, ф), encoding="utf-8").read() == т
            for ф, т in исходники.items()
        )
        print("копия возвращена в исходное" + (" ✓" if целы else " ✗ НЕТ"))
        плохо = len(непоставленные) + len(немерено) + (поставлено - поймано)
        return 0 if плохо == 0 and целы else 1


if __name__ == "__main__":
    sys.exit(main())
