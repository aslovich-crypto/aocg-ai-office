#!/usr/bin/env python3
"""РАЗБОР MARKDOWN-ТАБЛИЦ с контрольным примером (T30).

ЗАЧЕМ. Разбор текста выглядит работающим, пока не встретит экранирование,
кавычки или неразрывный пробел. 06.08.2026 это стоило двух ошибок за день:
сводка трекера резала строку по КАЖДОМУ символу `|`, включая экранированный
внутри текста задачи, и объявила целую строку побитой; в тот же день правка
ячейки с `Number(n \\|\\| 0)` разъехала таблицу на девять столбцов.
Ни линтер, ни тесты этого не видят: разбор не падает, он врёт.

Класс шире markdown — сюда же CSV, строка QR, JSON из ответа. Общее одно:
у разбора обязан быть КОНТРОЛЬНЫЙ ПРИМЕР С ИЗВЕСТНЫМ ОТВЕТОМ, и проверяться
он должен при каждом прогоне, а не однажды при написании.

КОНТРОЛЬНЫЙ ПРИМЕР ЛЕЖИТ В РЕПОЗИТОРИИ — `tests/tools/fixtures/md_control.tsv`,
не внутри этого файла. Причина: ответ должен пережить переписывание
инструмента. Инструмент меняют, фикстуру — только осознанно, отдельной
правкой, которую видно в диффе.

ЗАПУСК:
    ./venv/bin/python tests/tools/md_table.py                 # проверить docs/TASKS.md
    ./venv/bin/python tests/tools/md_table.py путь.md ...     # свои файлы
    ./venv/bin/python tests/tools/md_table.py --selfcheck     # только контрольный пример

Самопроверка идёт ПЕРЕД любой проверкой файлов и при расхождении
останавливает прогон: разбор, который врёт на известном ответе, на
неизвестных данных врёт тем более.
"""

from __future__ import annotations

import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
КОНТРОЛЬНЫЙ = os.path.join(КОРЕНЬ, "tests", "tools", "fixtures", "md_control.tsv")
ПО_УМОЛЧАНИЮ = os.path.join(КОРЕНЬ, "docs", "TASKS.md")

# Столб-разделитель — это `|`, перед которым НЕТ обратной косой черты.
# Экранированный `\|` markdown показывает как обычный символ внутри ячейки.
РАЗДЕЛИТЕЛЬ = re.compile(r"(?<!\\)\|")


def ячейки(строка: str) -> list[str]:
    """Ячейки строки markdown-таблицы. Экранированный столб НЕ делит."""
    куски = РАЗДЕЛИТЕЛЬ.split(строка.rstrip())
    if куски and куски[0].strip() == "":
        куски = куски[1:]
    if куски and куски[-1].strip() == "":
        куски = куски[:-1]
    return куски


def _строки_контрольного() -> list[tuple[int, int, str]]:
    """(номер строки файла, ожидание, строка) — комментарии пропускаются."""
    результат = []
    with open(КОНТРОЛЬНЫЙ, encoding="utf-8") as f:
        for номер, сырая in enumerate(f, 1):
            if sr := сырая.rstrip("\n"):
                if sr.startswith("#"):
                    continue
                ожидание, _, строка = sr.partition("\t")
                результат.append((номер, int(ожидание), строка))
    return результат


def самопроверка(подробно: bool = False) -> bool:
    """Разбор против контрольного примера. False — разбор не годен."""
    случаи = _строки_контрольного()
    if not случаи:
        print("  ✗ контрольный пример пуст — проверять нечем")
        return False
    сбои = 0
    for номер, ожидание, строка in случаи:
        факт = len(ячейки(строка))
        if факт != ожидание:
            сбои += 1
            print(f"  ✗ {КОНТРОЛЬНЫЙ}:{номер} ждали {ожидание} ячеек, разобрали {факт}")
            print(f"      {строка[:110]}")
        elif подробно:
            print(f"  ✓ строка {номер}: {факт} ячеек")
    if not сбои:
        print(
            f"  ✓ контрольный пример пройден: {len(случаи)} строк, все разобраны верно"
        )
    return сбои == 0


def проверить_файл(путь: str) -> list[str]:
    """Расхождения числа ячеек внутри каждой таблицы файла.

    Проверяется НЕ «ровно семь столбцов» (в документах таблицы разные),
    а согласованность: каждая строка тела совпадает со своим заголовком.
    """
    беды: list[str] = []
    with open(путь, encoding="utf-8") as f:
        строки = f.read().split("\n")

    заголовок_ячеек = None
    номер_заголовка = 0
    for номер, строка in enumerate(строки, 1):
        если_таблица = строка.lstrip().startswith("|")
        if not если_таблица:
            заголовок_ячеек = None
            continue
        счёт = len(ячейки(строка))
        if заголовок_ячеек is None:
            заголовок_ячеек, номер_заголовка = счёт, номер
            continue
        if set(строка.replace("|", "").replace(" ", "")) <= set("-:"):
            continue  # разделительная строка таблицы
        if счёт != заголовок_ячеек:
            беды.append(
                f"{os.path.relpath(путь, КОРЕНЬ)}:{номер}: ячеек {счёт}, "
                f"а в заголовке (строка {номер_заголовка}) — {заголовок_ячеек}. "
                f"Лишнее markdown НЕ покажет: текст станет невидимым."
            )
    return беды


def main() -> int:
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    подробно = "--verbose" in sys.argv

    print("КОНТРОЛЬНЫЙ ПРИМЕР")
    if not самопроверка(подробно):
        print("\nРАЗБОР НЕ ГОДЕН — файлы не проверялись. Чинить разбор, а не файлы.")
        return 2
    if "--selfcheck" in sys.argv:
        return 0

    файлы = аргументы or [ПО_УМОЛЧАНИЮ]
    всего_бед = 0
    for путь in файлы:
        беды = проверить_файл(путь)
        всего_бед += len(беды)
        print(f"\n{os.path.relpath(путь, КОРЕНЬ)}: расхождений {len(беды)}")
        for беда in беды:
            print(f"  ✗ {беда}")
    return 1 if всего_бед else 0


if __name__ == "__main__":
    sys.exit(main())
