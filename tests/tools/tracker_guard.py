# -*- coding: utf-8 -*-
"""Сторож трекера: отметка в строке расходится с тем, что было сделано.

ЗАЧЕМ. 26.08.2026 замер показал: за три дня ТРИ задачи (T61, T62, T66) стояли
⬜, будучи сделанными и закоммиченными. Правило журнала времени «факт вписывается
при закрытии задачи ТЕМ ЖЕ коммитом» существует и не исполнено НИ РАЗУ.
**Чинить надо не дисциплину, а отсутствие проверки: добавить «не забывай»
к правилу, которое уже не сработало, — значит получить второе несработавшее.**

⚠️ РЕЖИМ ПРЕДУПРЕЖДЕНИЯ, КОД ВОЗВРАТА ВСЕГДА 0. Блокировка на трекере учит
обходить хук через `--no-verify`, и тогда теряется сторож ЦЕЛИКОМ, а не одна
проверка. Предупреждение видно и не мешает.

ЧТО ПРОВЕРЯЕТСЯ:
  ① ⬜/🔵, а номер стоит в заголовке СВЕЖЕГО кодового коммита (окно 5 дней)
     → сделана, не отмечена;
  ② ✅ без вписанного факта, при наличии кодового коммита → закрыта неполно;
  ③ ячейки «Пр.» и «Статус» содержат посторонний текст → строка разобрана
     неверно всем, что её читает.

⚠️ ПОЧЕМУ ТОЛЬКО КОДОВЫЕ КОММИТЫ — ЭТО СУЖЕНИЕ КУПЛЕНО ПЕРВЫМ ЖЕ ПРОГОНОМ.
Проверка «номер встречается в истории» дала 143 находки из 219 строк, то есть
объявила расхождением каждую вторую задачу и стала нечитаемой. Причина
в здешнем обычае: строки ЗАВОДЯТСЯ коммитами `docs(tasks)`, и там номер значит
«строку создали», а не «задачу сделали». Замер по истории с 01.08.2026:
212 коммитов `docs` против 55 кодовых (`fix`, `feat`, `test`, `refactor`).
**Работой считается только кодовый коммит — иначе сторож принимает
собственную бухгалтерию за выполненную работу.**

⚠️ И ВТОРОЕ СУЖЕНИЕ, ТОЖЕ КУПЛЕННОЕ ПРОГОНОМ: ① СМОТРИТ ТОЛЬКО СВЕЖУЮ ИСТОРИЮ.
По всей истории с 01.08 она дала 18 находок, и из них ВЕРНЫХ ОКАЗАЛОСЬ ДВЕ.
Пять — ложные: заголовок кодового коммита перечисляет строки, которые в нём
ЗАВЕДЕНЫ («…(T62); заведены T65, LEGAL-006, UX-23»), а не сделаны. Остальные
одиннадцать — многошаговые задачи, где кодовый коммит закрыл ОДИН шаг
(«S-54, шаг 1», «T36, пункт 1»), и строка законно осталась открытой.
**Значит «есть кодовый коммит» НЕ значит «сделана» — ни в одном, ни в другом
случае.** Что сторож действительно может — напомнить о СВЕЖЕМ расхождении:
код закоммичен сегодня, а строка так и стоит ⬜. Ровно тот случай, ради
которого сторож и заводился (T61, T62, T66 в один день). За пределами окна
это уже не напоминание, а ревизия трекера — работа человека, не прибора.

⚠️ ЧЕГО СТОРОЖ НЕ УМЕЕТ — НАЗВАНО ДО НАПИСАНИЯ (правило T64/T71/T72):
  · номер в сообщении пишется РУКАМИ: опечатка или пропуск обманут сторожа —
    он видит совпадение строки, а не смысл работы;
  · «см. T62» в заголовке кодового коммита о другой задаче будет засчитано
    как работа над T62;
  · ГОЛЫЕ ЧИСЛА ИСКАТЬ НЕЛЬЗЯ: в трекере есть задачи с ID «1», «10», «20» —
    историческая нумерация. Любое число в сообщении (дата, количество) с ними
    совпадёт, и первый прогон дал по ним десятки ложных находок. Такие строки
    проверяются ТОЛЬКО на форму ячеек (③);
  · ③ ловит форму, а не смысл: правильные значки в неправильных ячейках
    он пропустит.

САМОПРОВЕРКА (обе половины, правило T72):
  · заведомо расходящееся — строка ⬜ при наличии кодового коммита ОБЯЗАНА
    найтись; берётся из реального дерева, а не подделывается;
  · заведомо здоровое — закрытая строка с фактом ОБЯЗАНА не найтись.
Без второй половины «ноль расхождений» неотличим от неработающего прибора.

ЗАПУСК:
    ./venv/bin/python tests/tools/tracker_guard.py
    ./venv/bin/python tests/tools/tracker_guard.py --selfcheck
"""

import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ТРЕКЕР = КОРЕНЬ / "docs" / "TASKS.md"
С_ДАТЫ = "2026-08-01"  # для ② — вся история соглашения об именовании
ОКНО_СВЕЖЕСТИ = "5.days"  # для ① — только свежее: сторож напоминает, а не ревизует
КОДОВЫЕ = ("feat", "fix", "refactor", "perf", "test")
ПРИОРИТЕТЫ = {"🔴", "🟡", "🟢"}
СТАТУСЫ = {"⬜", "✅", "👀", "🔵", "⏸"}
# ⚠️ ID — ЭТО НЕ «БУКВЫ, ПОТОМ ЦИФРЫ». Замер 06.09.2026 нашёл в трекере СЕМЬ
# форм, и прежняя пара регулярок теряла две трети из них молча (T188):
#   буквы+цифры 307 (T180, S-71, NDS-ЧП5) · буквы-БУКВЫ 32 (REP-CRUD, Cat-E)
#   чистое число 25 (1, 12, 19) · только буквы 5 (INT, MONO, TAX, UX, OCR)
#   цифра+буква 1 (1C) · цифра ВНУТРИ буквенной части 1 (A11Y-FAB) · с решёткой 1 (#14)
# Прежняя `ЕСТЬ_ID` требовала окончания цифрой и выбрасывала 35 задач из 372,
# из них 24 ОТКРЫТЫЕ; прежняя `ИСКОМЫЙ` требовала буквы перед цифрами и уводила
# из-под проверок ①② все продуктовые задачи с числовым ID — ещё 30.
ЕСТЬ_ID = re.compile(r"^#?[A-Za-zА-Яа-я0-9]+(?:-[A-Za-zА-Яа-я0-9]+)*$")
# ⚠️ ВТОРОГО СИТА БОЛЬШЕ НЕТ. Раньше `ИСКОМЫЙ` решал, стоит ли искать строку в
# коммитах, и решал по ФОРМЕ ID — то есть повторял ту же ошибку вторым слоем.
# Теперь ищутся ВСЕ известные ID, а безопасность поиска обеспечивает `_шаблон`
# ниже: он знает, как каждая форма выглядит в заголовке коммита.
ПУСТО = ("", "—", "-")


def _строки_таблиц(текст):
    """Все строки, похожие на строку задачи, ДО всякого разбора ячеек.

    ⚠️ СЫРОЙ СЧЁТ НУЖЕН РАДИ ПОТЕРЬ ДО ФИЛЬТРА. Проверка `len(я) < 8` ниже
    молча выбрасывает строку, у которой разъехались ячейки (неэкранированный
    `|` в тексте). Такая потеря происходит РАНЬШЕ фильтра по ID, и печать
    остатка её не увидит: строка до остатка не доходит.
    """
    return [
        (н, с)
        for н, с in enumerate(текст.split("\n"), 1)
        if с.startswith("| ")
        and not с.startswith("| ID |")
        and not set(с) <= set("| -:")
    ]


def сырой_счёт(текст):
    """Сколько строк таблиц в файле — СЧИТАЕТСЯ ОТДЕЛЬНО ОТ РАЗБОРА.

    ⚠️ ПОЧЕМУ НЕ `len(_строки_таблиц(...))`. Тогда число бралось бы из той же
    функции, что и разбор, и совпало бы ВСЕГДА — включая случай, когда в
    `_строки_таблиц` однажды добавят ещё одно исключение и потеряют строки
    молча. Прибор, считающий обе стороны одним ходом, согласен сам с собой:
    ровно так витрина и её сторож месяц сходились на 337 задачах из 373 (T188).
    Здесь счёт нарочно тупой и НЕ ЗНАЕТ ни про ячейки, ни про ID.
    """
    return sum(
        1
        for с in текст.split("\n")
        if с.startswith("| ")
        and not с.startswith("| ID |")
        and not set(с) <= set("| -:")
    )


def разобрать(текст):
    """(задачи, отброшенные, сырых). Задача — кортеж из шести полей.

    ⚠️ ОТБРОШЕННЫЕ ВОЗВРАЩАЮТСЯ НАРАВНЕ С ПРИНЯТЫМИ, И ЭТО ГЛАВНОЕ В ПРАВКЕ.
    До 06.09.2026 разбор молча терял всё, что не подошло под форму ID, и
    узнать об этом было неоткуда: и витрина, и её сторож считали ОДНИМ И ТЕМ
    ЖЕ разбором, поэтому сходились всегда — даже потеряв 35 задач (T188).
    """
    задачи, отброшены = [], []
    сырые = _строки_таблиц(текст)
    for н, с in сырые:
        я = с.split("|")
        if len(я) < 8:
            отброшены.append((н, с[:60].strip(), "ячеек меньше восьми"))
            continue
        ид = я[1].strip()
        if not ЕСТЬ_ID.match(ид):
            отброшены.append((н, ид or "«пусто»", "ID не похож на ID"))
            continue
        задачи.append((н, ид, я[3].strip(), я[4].strip(), я[5].strip(), я[6].strip()))
    return задачи, отброшены, len(сырые)


def строки_задач(текст):
    """(номер строки, ID, приоритет, статус, план, факт) для каждой задачи."""
    return разобрать(текст)[0]


def _шаблон(ид):
    """Как этот ID выглядит в заголовке коммита.

    ⚠️ ГОЛОЕ ЧИСЛО НЕ СЧИТАЕТСЯ УПОМИНАНИЕМ. «12 полей» — не задача 12, и
    поиск по цифрам дал бы ложные находки чаще верных. Продуктовые задачи
    здесь называют «№25», «строка 24» — эти формы и ищем.
    ⚠️ Прежний разбор искал по ФОРМЕ (`[A-Za-zА-Яа-я]{1,6}-?\d+`) и не видел
    ни `REP-CRUD`, ни `1C`, ни `INT` — третья половина той же слепоты (T188).
    """
    if ид.isdigit():
        return re.compile(rf"(?:№\s*{ид}|строк[аи]\s+{ид})(?!\d)")
    return re.compile(rf"(?<![\w-]){re.escape(ид)}(?![\w-])")


def номера_в_коде(с_какого=None, известные=None):
    """ID из заголовков КОДОВЫХ коммитов за указанный период.

    `известные` — множество ID из трекера. Ищем ИХ, а не угадываем по форме:
    угадывание и было третьим местом слепоты."""
    r = subprocess.run(
        ["git", "log", f"--since={с_какого or С_ДАТЫ}", "--pretty=format:%s"],
        cwd=КОРЕНЬ,
        capture_output=True,
        text=True,
    )
    найдено = set()
    for строка in r.stdout.split("\n"):
        тип = строка.split("(")[0].split(":")[0].strip()
        if тип not in КОДОВЫЕ:
            continue
        # ⚠️ ХВОСТ ПОСЛЕ СЛОВА «ЗАВЕДЕН…» ОТРЕЗАЕТСЯ, И ЭТО НЕ ПРИДИРКА.
        # Здешний обычай — перечислять в заголовке кодового коммита строки,
        # которые этим же коммитом ЗАВЕДЕНЫ: «…(T62); заведены T65, LEGAL-006,
        # UX-23». Без отрезания сторож считал их сделанными и давал пять
        # ложных находок из десяти — то есть половину.
        видимая = re.split(r"заведен[аоы]?|заведён", строка)[0]
        for ид in известные or ():
            if _шаблон(ид).search(видимая):
                найдено.add(ид)
    return найдено


def проверить(задачи, в_коде, свежие):
    находки = []
    for н, ид, пр, ст, _план, факт in задачи:
        if пр not in ПРИОРИТЕТЫ or ст not in СТАТУСЫ:
            находки.append(
                (н, ид, "③ ячейки разъехались: «Пр.» или «Статус» — не значок")
            )
            continue
        работали = ид in в_коде
        if ст in ("⬜", "🔵") and ид in свежие:
            находки.append((н, ид, f"① есть кодовый коммит, а стоит {ст}"))
        if ст == "✅" and факт in ПУСТО and работали:
            находки.append((н, ид, "② закрыта, а факт времени не вписан"))
    return находки


def самопроверка():
    задачи = строки_задач(ТРЕКЕР.read_text(encoding="utf-8"))
    в_коде = номера_в_коде(известные={и for _, и, _, _, _, _ in задачи})
    дырявые = [и for _, и, _, с, _, _ in задачи if с in ("⬜", "🔵") and и in в_коде]
    здоровые = [и for _, и, _, с, _, ф in задачи if с == "✅" and ф not in ПУСТО]
    поднято = {и for _, и, _ in проверить(задачи, в_коде, в_коде)}
    print("САМОПРОВЕРКА")
    ок1 = bool(дырявые) and дырявые[0] in поднято
    ок2 = bool(здоровые) and здоровые[0] not in поднято
    print(
        f"  заведомо расходящееся ({дырявые[0] if дырявые else '—'}) найдено ...... "
        f"{'да' if ок1 else 'НЕТ'}"
    )
    print(
        f"  заведомо здоровое ({здоровые[0] if здоровые else '—'}) НЕ поднято ...... "
        f"{'да' if ок2 else 'НЕТ'}"
    )
    if not дырявые or not здоровые:
        print("  ИТОГ: ⚠️ в дереве нет примера для одной из половин — проверить нечем")
        return 2
    if not (ок1 and ок2):
        print("  ИТОГ: ⚠️ сторож отвечает неверно на известном примере")
        return 2
    print("  ИТОГ: отвечает верно на обоих известных примерах\n")
    return 0


def main():
    if "--selfcheck" in sys.argv:
        return самопроверка()
    # ⚠️ ПУТЬ ПАРАМЕТРОМ — РАДИ ПРОВЕРЯЕМОСТИ САМОГО СТОРОЖА. Мутация «проверка
    # формы ячеек отключена» не ловится на ЧИСТОМ трекере: убирать нечего,
    # вывод не меняется, и мутант выглядит непойманным по причине, не имеющей
    # к нему отношения. Прогон по образцу с заведомо сломанной строкой эту
    # способность проверяет прямо.
    файлы = [а for а in sys.argv[1:] if not а.startswith("--")]
    путь = pathlib.Path(файлы[0]) if файлы else ТРЕКЕР
    текст = путь.read_text(encoding="utf-8")
    задачи, отброшены, _ = разобрать(текст)
    сырых = сырой_счёт(текст)  # ⚠️ ОТДЕЛЬНЫМ ХОДОМ, см. довод у функции
    известные = {и for _, и, _, _, _, _ in задачи}
    находки = проверить(
        задачи,
        номера_в_коде(известные=известные),
        номера_в_коде(ОКНО_СВЕЖЕСТИ, известные=известные),
    )

    # ⚠️ ОСТАТОК ПЕЧАТАЕТСЯ ВСЕГДА, ДАЖЕ КОГДА ОН НУЛЕВОЙ. Прибор, который
    # молчит при нуле, ничем не отличается от прибора, который молчит всегда —
    # ровно из этого выросла слепота T188: разбор терял 35 задач и не говорил
    # об этом ни строчкой, а сторож витрины сверял своё число со СВОИМ ЖЕ.
    print(
        f"   разбор: строк таблиц {сырых} · задач {len(задачи)} · отброшено {len(отброшены)}"
    )
    for н, что, почему in отброшены[:12]:
        print(f"      отброшено docs/TASKS.md:{н}  {что:14} — {почему}")
    if len(отброшены) > 12:
        print(f"      … и ещё {len(отброшены) - 12}")

    # ⚠️ СЫРОЙ СЧЁТ — ВТОРОЕ МНЕНИЕ, ПОСЧИТАННОЕ ДРУГИМ СПОСОБОМ. Он не знает
    # ни про ID, ни про ячейки: считает строки таблиц как таковые. Расхождение
    # означает потерю ДО фильтра — строку, которая до разбора не дошла.
    if сырых != len(задачи) + len(отброшены):
        print(
            f"   ⚠️ СЫРОЙ СЧЁТ НЕ СХОДИТСЯ: строк {сырых}, "
            f"а разобрано {len(задачи)} + {len(отброшены)} = "
            f"{len(задачи) + len(отброшены)} — потеря ДО фильтра"
        )

    if not находки:
        print(f"трекер: расхождений 0 (задач {len(задачи)})")
        return 0
    print(f"⚠️ ТРЕКЕР: РАСХОЖДЕНИЙ {len(находки)} (задач {len(задачи)})")
    for н, ид, что in находки:
        print(f"   docs/TASKS.md:{н}  {ид:10} {что}")
    print("   ПРЕДУПРЕЖДЕНИЕ, коммит не блокируется: блокировка на трекере учит")
    print("   обходить хук, и тогда теряется весь сторож, а не одна проверка.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
