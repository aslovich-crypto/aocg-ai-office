#!/usr/bin/env python3
"""МУТАЦИИ МЕХАНИЗМА СЛОВАРЯ — доказательство, что сторожа вообще смотрят.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Генератор и два сторожа отвечают на вопрос «сходится ли
словарь сегодня». Они НЕ отвечают на вопрос «а заметили бы, если бы разошёлся».
Зелёный прогон одинаково выглядит и когда всё цело, и когда проверять было
нечем. Здесь по очереди ломается КАЖДАЯ заявленная способность механизма.

ПРАВИЛО, ПО КОТОРОМУ НАПИСАНЫ ОЖИДАНИЯ (T11, уточнение от 10.08.2026):
мутация требует не только КРАСНЫЙ, но и КОНКРЕТНУЮ строку в выводе. Иначе
она подтверждает не ту ветку — сторож краснеет «правильно» по неправильной
причине. Куплено на M7 замера контракта в тот же день.

И вторая половина того же правила: мутация засчитывается, только если она
РЕАЛЬНО применилась. Каждая замена проверяет, что цель существует и текст
изменился.

ЧТО ПРОВЕРЯЕТСЯ:
    M1  копия python правлена руками        → штамп разошёлся
    M2  копия js правлена руками            → штамп разошёлся
    M3  источник правлен без перегенерации  → обе копии отстали
    M4  ключ GROUP_COLORS переименован      → разошёлся со списком GROUPS
    M5  имя словаря вписано литералом       → сторож рукописных красный
    M6  SQL CHECK разошёлся с TAX_KINDS     → третья сторона замера красная
    M7  запись белого списка устарела       → красный (образец M7 контракта)

ЧУЖОЙ РЕПОЗИТОРИЙ. Фронтовые мутации правят файл В РАБОЧЕМ ДЕРЕВЕ фронта:
сторож `check-dictionaries.mjs` читает пути от своего корня, подменить их
нечем. Файл восстанавливается в `finally` при любом исходе, а в конце прогон
СВЕРЯЕТ список изменённых файлов фронта с тем, что был до начала, и падает
при расхождении — обещание «я всё вернул» проверяется, а не даётся.

ЗАПУСК (в pytest НЕ входит — правит файлы и возвращает их на место):
    ./venv/bin/python tests/tools/dict_mutations.py
    ./venv/bin/python tests/tools/dict_mutations.py --verbose
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ФРОНТ = os.path.normpath(os.path.join(КОРЕНЬ, "..", "aocg-ai-office-web"))
PYTHON = sys.executable

ФАЙЛЫ = {
    "источник": os.path.join(КОРЕНЬ, "app", "dictionaries", "categories.json"),
    "копия-py": os.path.join(КОРЕНЬ, "app", "dictionaries", "__init__.py"),
    "копия-js": os.path.join(ФРОНТ, "src", "lib", "dictionaries.js"),
    "схема": os.path.join(КОРЕНЬ, "app", "database.py"),
    "цвета": os.path.join(ФРОНТ, "src", "lib", "categories.js"),
    "сторож": os.path.join(КОРЕНЬ, "tests", "tools", "dict_stamp.py"),
    "новый-файл": os.path.join(КОРЕНЬ, "app", "мутация_временный.py"),
}

# Чем гоняем. Ключ — как назовём в отчёте.
ПРОГОНЫ = {
    "генератор": [
        PYTHON,
        os.path.join(КОРЕНЬ, "tools", "gen_dictionaries.py"),
        "--check",
    ],
    "сторож-бэк": [PYTHON, os.path.join(КОРЕНЬ, "tests", "tools", "dict_stamp.py")],
    "сторож-фронт": ["npm", "run", "--silent", "lint"],
    "замер": [PYTHON, os.path.join(КОРЕНЬ, "tests", "tools", "contract_dict.py")],
}

# (имя, файл, что ломаем, чем заменяем, чем гоняем, ожидаемый текст в выводе)
МУТАЦИИ = [
    (
        "M1 копия python правлена руками",
        "копия-py",
        '"Материальные расходы",',
        '"Материальные расходики",',  # двойные кавычки: копия нормализована ruff
        "генератор",
        ["РАЗОШЛАСЬ С ИСТОЧНИКОМ"],
    ),
    (
        "M2 копия js правлена руками",
        "копия-js",
        '  "Оплата труда",',
        '  "Оплата трудов",',
        "генератор",
        ["js-копия", "РАЗОШЛАСЬ С ИСТОЧНИКОМ"],
    ),
    (
        "M3 источник правлен БЕЗ перегенерации",
        "источник",
        '"Транспортные расходы"',
        '"Транспортныe расходы"',  # латинская e — опечатка того же вида, что в жизни
        "генератор",
        ["ШТАМП НЕ СОВПАЛ"],
    ),
    (
        # Мутируем ИМЕННО ту связь, которую сторож стережёт: ключ GROUP_COLORS
        # против списка GROUPS в копии. Первая попытка правила ИСТОЧНИК — и
        # сторож честно молчал, потому что копию при этом никто не перегенерировал,
        # а он читает копию. Ошибка была в мутации, не в стороже; поймала её
        # проверка на конкретный текст, код возврата совпал бы.
        "M4 ключ GROUP_COLORS разошёлся со списком групп",
        "цвета",
        '"IT и софт": { bg: "#F5F3FF", fg: "#6D28D9" },',
        '"IT и софтина": { bg: "#F5F3FF", fg: "#6D28D9" },',
        "сторож-фронт",
        ["GROUP_COLORS РАЗОШЁЛСЯ", "IT и софт"],
    ),
    (
        "M5 имя словаря вписано литералом в новый файл",
        "новый-файл",
        "",  # файла нет — создаётся целиком, см. main()
        'СТАТЬЯ = "Канцелярские товары"\n',
        "сторож-бэк",
        ["имён словаря записаны литералом"],
    ),
    (
        "M6 SQL CHECK разошёлся с TAX_KINDS (третья сторона)",
        "схема",
        "'Материальные расходы','Прочие расходы','Командировочные расходы',",
        "'Прочие расходы','Командировочные расходы',",
        "замер",
        ["виды расхода — SQL CHECK: РАСХОЖДЕНИЕ", "Материальные расходы"],
    ),
    (
        "M7 запись белого списка устарела",
        "сторож",
        '"app/categorization.py": (',
        '"app/main.py": "заведомо ложная запись — в main.py имён словаря нет",\n    "app/categorization.py": (',
        "сторож-бэк",
        ["БЕЛЫЙ СПИСОК УСТАРЕЛ", "app/main.py"],
    ),
]


def прогон(ключ: str) -> tuple[int, str]:
    команда = ПРОГОНЫ[ключ]
    рабочий = ФРОНТ if ключ == "сторож-фронт" else КОРЕНЬ
    готово = subprocess.run(
        команда, capture_output=True, text=True, cwd=рабочий, timeout=600
    )
    return готово.returncode, готово.stdout + готово.stderr


def грязные_файлы_фронта() -> set[str]:
    готово = subprocess.run(
        ["git", "status", "--porcelain"],
        capture_output=True,
        text=True,
        cwd=ФРОНТ,
        timeout=60,
    )
    return {с[3:] for с in готово.stdout.strip().split("\n") if с}


def main() -> int:
    разбор = argparse.ArgumentParser(description="Мутации механизма словаря")
    разбор.add_argument("--verbose", action="store_true")
    аргументы = разбор.parse_args()

    if not os.path.isdir(ФРОНТ):
        print(f"ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ: нет фронт-репозитория {ФРОНТ}")
        return 2

    фронт_до = грязные_файлы_фронта()
    оригиналы = {
        к: open(п, encoding="utf-8").read()
        for к, п in ФАЙЛЫ.items()
        if os.path.exists(п)
    }

    # База обязана быть зелёной, иначе мутации ничего не значат.
    for ключ in ("генератор", "сторож-бэк", "замер", "сторож-фронт"):
        код, вывод = прогон(ключ)
        if код != 0:
            print(f"База НЕ зелёная: {ключ} даёт {код}. Мутации бессмысленны.")
            print(вывод[-1500:])
            return 2
    print(f"База зелёная по всем четырём прогонам. Мутаций: {len(МУТАЦИИ)}\n")

    провалы = 0
    try:
        for имя, ключ, старое, новое, чем, ждём_текст in МУТАЦИИ:
            путь = ФАЙЛЫ[ключ]
            if ключ == "новый-файл":
                open(путь, "w", encoding="utf-8").write(новое)
                применилась = True
            else:
                оригинал = оригиналы[ключ]
                if старое not in оригинал:
                    print(
                        f"  ✗ {имя}\n      ЦЕЛЬ НЕ НАЙДЕНА — мутация не применилась, "
                        f"проверять было нечего. Код изменился: обновить шаблон."
                    )
                    if аргументы.verbose:
                        print(f"      искали: {старое[:70]!r}")
                    провалы += 1
                    continue
                изменённый = оригинал.replace(старое, новое, 1)
                применилась = изменённый != оригинал
                if применилась:
                    open(путь, "w", encoding="utf-8").write(изменённый)
            if not применилась:
                print(f"  ✗ {имя}\n      текст не изменился после замены")
                провалы += 1
                continue

            try:
                код, вывод = прогон(чем)
            finally:
                if ключ == "новый-файл":
                    os.remove(путь)
                else:
                    open(путь, "w", encoding="utf-8").write(оригиналы[ключ])

            нет_текста = [т for т in ждём_текст if т not in вывод]
            сошлось = код != 0 and not нет_текста
            провалы += 0 if сошлось else 1
            print(f"  {'✓' if сошлось else '✗'} {имя}")
            print(f"      гнали: {чем} · код {код} (ждали не 0)")
            if нет_текста:
                print(f"      НЕ НАШЛОСЬ В ВЫВОДЕ: {нет_текста}")
            else:
                print(f"      в выводе нашлось: {ждём_текст}")
            if аргументы.verbose:
                for с in вывод.splitlines():
                    print(f"      {с}")
    finally:
        for к, п in ФАЙЛЫ.items():
            if к == "новый-файл":
                if os.path.exists(п):
                    os.remove(п)
            elif к in оригиналы:
                open(п, "w", encoding="utf-8").write(оригиналы[к])

    # Обещание «я всё вернул» ПРОВЕРЯЕТСЯ, а не даётся.
    фронт_после = грязные_файлы_фронта()
    if фронт_после != фронт_до:
        print(
            f"\n✗ ДЕРЕВО ФРОНТА ИЗМЕНИЛОСЬ: было {sorted(фронт_до)}, "
            f"стало {sorted(фронт_после)}"
        )
        провалы += 1
    else:
        print(
            f"\nДерево фронта то же, что до прогона ({len(фронт_до)} изменённых файлов)"
        )

    итоги = {
        к: прогон(к)[0] for к in ("генератор", "сторож-бэк", "замер", "сторож-фронт")
    }
    print(f"После восстановления: {итоги} (все обязаны быть 0)")
    провалы += sum(1 for к in итоги.values() if к != 0)
    print(f"Проверено способностей: {len(МУТАЦИИ)}, провалов: {провалы}")
    return 1 if провалы else 0


if __name__ == "__main__":
    sys.exit(main())
