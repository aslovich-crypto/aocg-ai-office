#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПРОХОДИТ ЛИ ИСХОДЯЩИЙ SMTP С ЭТОЙ МАШИНЫ (S-77).

ЗАЧЕМ. 25.08.2026 прод дал `[EMAIL] send failed: TimeoutError: timed out`
на портах 587 И 465, при верно заданных переменных (иначе была бы строка
`[EMAIL:disabled]` со списком недостающих имён). Один такой замер НЕ РАЗЛИЧАЕТ
два случая: площадка режет исходящий SMTP — или это был разовый сетевой сбой.
Лечение у них разное: первое требует ухода на HTTP API, второе — повтора.

ЧТО ДЕЛАЕТ. Открывает TCP-соединение и закрывает. НИЧЕГО НЕ ОТПРАВЛЯЕТ,
не логинится, не читает ни логин, ни пароль — их здесь нет вовсе, и добавлять
нельзя: прибор должен быть безопасен для запуска где угодно и для вставки
его вывода в переписку.

ТРИ КОНТРОЛЯ, БЕЗ КОТОРЫХ ЧИСЛА НИЧЕГО НЕ ЗНАЧАТ:
  ① ТОТ ЖЕ ХОСТ, ПОРТ 443. Разделяет «режут порты SMTP» и «до Postbox
     не достучаться вовсе». Без него закрытые 587/465 неотличимы
     от недоступного хоста.
  ② ЗАВЕДОМО ЖИВОЙ ЧУЖОЙ ХОСТ, 443. Разделяет «режут SMTP» и «сети нет».
     Взят `proverkacheka.com` намеренно: на него приложение ходит каждый
     день, то есть его достижимость с прода — не предположение.
  ③ ЗАВЕДОМО МЁРТВЫЙ АДРЕС (203.0.113.1, RFC 5737, TEST-NET-3).
     Если он «соединился» — врёт прибор, а не сеть, и вердикт не выдаётся.
     Правило CLAUDE.md, вид контроля №2.

ЧЕМ ОТЛИЧАЕТСЯ ТАЙМАУТ ОТ ОТКАЗА, И ПОЧЕМУ ЭТО ПЕЧАТАЕТСЯ ОТДЕЛЬНО:
  · отказ (Connection refused) — хост ответил «порт закрыт». Он жив,
    маршрут есть, диалог состоялся;
  · таймаут — пакет пропал молча. Это почерк фильтра: тот, кто режет,
    обычно не отвечает, чтобы не подтверждать факт фильтрации.
Смешивать их в «не соединилось» — терять половину диагноза.

ПОЧЕМУ ПОПЫТОК НЕСКОЛЬКО. Одна попытка не отличает постоянную блокировку
от мигающей сети. Печатается доля прошедших: «0 из 5» и «3 из 5» —
разные диагнозы, и второй означает НЕ блокировку.

ЗАПУСК:
    python3 tests/tools/smtp_reach.py --selfcheck   # сначала: прибор исправен?
    python3 tests/tools/smtp_reach.py               # затем: сам замер
    python3 tests/tools/smtp_reach.py --host <хост> --attempts 5

ГДЕ ЗАПУСКАТЬ И ЧТО ЭТО ДОКАЗЫВАЕТ:
  · с бастиона (VPS Timeweb, Москва) — доказывает политику ПЛОЩАДКИ VPS;
  · с машины владельца — не доказывает о проде НИЧЕГО (другой канал,
    другой оператор), годится только как проверка самого прибора;
  · из прод-контейнера (App Platform) — ЗАПУСТИТЬ НЕГДЕ: консоли у площадки
    нет. Это ограничение, а не недосмотр; см. S-77.

Коды возврата: 0 — прогон состоялся; 2 — самопроверка не прошла;
3 — прибор сломан (ответил заведомо мёртвый адрес), вердикта нет.
"""

import argparse
import os
import socket
import sys
import time

ХОСТ_ПО_УМОЛЧАНИЮ = "postbox.cloud.yandex.net"
ЖИВОЙ_ЧУЖОЙ = "proverkacheka.com"
МЁРТВЫЙ = "203.0.113.1"  # RFC 5737 TEST-NET-3: маршрутизации нет ни у кого

ОТКАЗ = "отказ"
ТАЙМАУТ = "таймаут"
ОК = "ок"


def _попытка(хост, порт, предел):
    """Один TCP-коннект. Возвращает (исход, миллисекунды, пояснение)."""
    начало = time.time()
    try:
        s = socket.create_connection((хост, порт), timeout=предел)
        s.close()
        return ОК, (time.time() - начало) * 1000, ""
    except socket.timeout:
        return ТАЙМАУТ, (time.time() - начало) * 1000, "молчание"
    except ConnectionRefusedError:
        return ОТКАЗ, (time.time() - начало) * 1000, "порт закрыт, хост жив"
    except OSError as e:
        return ОТКАЗ, (time.time() - начало) * 1000, f"{type(e).__name__}: {e}"


def _замерить(метка, хост, порт, попыток, предел, пауза, тихо=False):
    исходы = []
    for н in range(попыток):
        исход, мс, почему = _попытка(хост, порт, предел)
        исходы.append((исход, мс, почему))
        if not тихо:
            хвост = f" · {почему}" if почему else ""
            print(f"    {н + 1}/{попыток}  {исход:8} {мс:7.0f} мс{хвост}", flush=True)
        if н + 1 < попыток:
            time.sleep(пауза)
    прошло = sum(1 for и, _, _ in исходы if и == ОК)
    таймаутов = sum(1 for и, _, _ in исходы if и == ТАЙМАУТ)
    if not тихо:
        print(
            f"    ИТОГ {метка}: прошло {прошло} из {попыток}, "
            f"молчаливых таймаутов {таймаутов}\n",
            flush=True,
        )
    return {"метка": метка, "прошло": прошло, "всего": попыток, "таймаутов": таймаутов}


def самопроверка(предел):
    """Обе половины сразу: мёртвый обязан молчать, живой обязан отвечать."""
    print("САМОПРОВЕРКА ПРИБОРА")
    мёртвый, _, _ = _попытка(МЁРТВЫЙ, 443, min(предел, 5))
    живой, _, _ = _попытка(ЖИВОЙ_ЧУЖОЙ, 443, предел)
    print(
        f"  заведомо мёртвый {МЁРТВЫЙ}:443 НЕ соединился ... "
        f"{'да' if мёртвый != ОК else 'НЕТ'}"
    )
    print(
        f"  заведомо живой {ЖИВОЙ_ЧУЖОЙ}:443 соединился ..... "
        f"{'да' if живой == ОК else 'НЕТ'}"
    )
    if мёртвый == ОК:
        print("  ИТОГ: ⚠️ прибор врёт — «соединился» с адресом, которого нет.")
        return 2
    if живой != ОК:
        print("  ИТОГ: ⚠️ самопроверка НЕ СОСТОЯЛАСЬ — сети нет с этой машины.")
        print("        Это не поломка прибора, но и замер отсюда бессмыслен.")
        return 2
    print("  ИТОГ: прибор отвечает верно на обоих известных примерах\n")
    return 0


def вердикт(и):
    """Разбор чисел в диагноз. ЧИСТАЯ ФУНКЦИЯ: ни сети, ни времени, ни печати.

    ⚠️ ВЫНЕСЕНА ИЗ main ИМЕННО РАДИ ПРОВЕРЯЕМОСТИ. Это самое опасное место
    прибора: ошибка здесь не выглядит ошибкой — печатается уверенная фраза
    на неверных числах, и по ней принимается решение переписывать отправку
    почты. Сеть для проверки такой ошибки не нужна и даже мешает, поэтому
    таблица решений проверяется тестами на выдуманных числах
    (tests/test_smtp_reach_verdict.py), а не «когда-нибудь на бастионе».

    Принимает словарь итогов с ключами 587, 465, 443, чужой443, мёртвый;
    каждый — {"прошло": n, "всего": n, "таймаутов": n}.
    Возвращает (код возврата, список строк вывода).
    """
    строки = []
    if и["мёртвый"]["прошло"]:
        строки.append("⚠️ ПРИБОР СЛОМАН: ответил заведомо мёртвый адрес.")
        строки.append("   Вердикта нет. Так выглядит машина, где соединения")
        строки.append("   перехватывает прокси: «соединилось» отвечает ВСЁ,")
        строки.append("   включая адреса, которых не существует.")
        return 3, строки

    if not и["чужой443"]["прошло"] and not и["443"]["прошло"]:
        строки.append("СЕТИ НЕТ С ЭТОЙ МАШИНЫ: молчат оба контроля на 443.")
        строки.append("⚠️ О БЛОКИРОВКЕ SMTP ЗАМЕР НЕ ГОВОРИТ НИЧЕГО.")
        return 0, строки

    прошло = и["587"]["прошло"] + и["465"]["прошло"]
    всего = и["587"]["всего"] + и["465"]["всего"]

    if прошло == 0:
        if not и["443"]["прошло"]:
            строки.append("ДО ХОСТА POSTBOX НЕ ДОСТУЧАТЬСЯ ВООБЩЕ: молчит и 443.")
            строки.append("⚠️ ЭТО НЕ ПРО ПОРТЫ SMTP. Дело в маршруте до хоста,")
            строки.append("   и HTTP API на 443 отсюда тоже не заработает.")
            return 0, строки
        молча = и["587"]["таймаутов"] + и["465"]["таймаутов"]
        строки.append("ИСХОДЯЩИЙ SMTP НЕ ПРОХОДИТ, А 443 К ТОМУ ЖЕ ХОСТУ ПРОХОДИТ.")
        строки.append(f"587 и 465: 0 из {всего}; молчаливых таймаутов {молча}.")
        if молча == всего:
            строки.append("Молчание на ВСЕХ попытках — почерк фильтра: режущий")
            строки.append("обычно не отвечает, чтобы не подтверждать фильтрацию.")
        else:
            строки.append("Есть явные отказы, а не только молчание — хост жив")
            строки.append("и отвечает «порт закрыт». Это тоже блокировка, но")
            строки.append("не скрытая, и в поддержке её признать легче.")
        строки.append("⚠️ ЭТО НЕ РАЗОВЫЙ СБОЙ. Запасной путь — HTTP API на 443.")
        return 0, строки

    if прошло == всего:
        строки.append("SMTP ПРОХОДИТ ПОЛНОСТЬЮ с этой машины.")
        строки.append("⚠️ Значит отказ на проде — не свойство площадки целиком.")
        строки.append("   Либо сбой был разовым, либо режут именно ту площадку,")
        строки.append("   где крутится приложение. Отсюда этого не различить.")
        return 0, строки

    строки.append(
        f"SMTP ПРОХОДИТ ЧАСТИЧНО: 587 — {и['587']['прошло']}/{и['587']['всего']}, "
        f"465 — {и['465']['прошло']}/{и['465']['всего']}."
    )
    строки.append("⚠️ ЭТО НЕ БЛОКИРОВКА, А НЕСТАБИЛЬНОСТЬ. Блокировка не мигает.")
    строки.append("   Повторять замер, а не переписывать отправку.")
    return 0, строки


def main():
    p = argparse.ArgumentParser(add_help=True)
    p.add_argument(
        "--host", default=os.getenv("POSTBOX_SMTP_HOST") or ХОСТ_ПО_УМОЛЧАНИЮ
    )
    p.add_argument("--attempts", type=int, default=4)
    p.add_argument("--timeout", type=float, default=6.0)
    p.add_argument("--pause", type=float, default=1.0)
    p.add_argument("--selfcheck", action="store_true")
    a = p.parse_args()

    # МЕТКА ПРОГОНА (вид контроля №5): вывод без неё через день неотличим
    # от вчерашнего и от чужого.
    print("═" * 62)
    print("ЗАМЕР ИСХОДЯЩЕГО SMTP · S-77")
    print(f"  где .... {socket.gethostname()}")
    print(f"  когда .. {time.strftime('%d.%m.%Y %H:%M:%S')} местного")
    print(f"  хост ... {a.host}")
    print(f"  попыток {a.attempts}, предел {a.timeout} с, пауза {a.pause} с")
    print("═" * 62)

    if a.selfcheck:
        return самопроверка(a.timeout)

    код = самопроверка(a.timeout)
    if код:
        return код

    цели = [
        ("587", "SMTP 587  ПРЕДМЕТ", a.host, 587),
        ("465", "SMTP 465  ПРЕДМЕТ", a.host, 465),
        ("443", "443 тот же хост  КОНТРОЛЬ", a.host, 443),
        ("чужой443", f"443 {ЖИВОЙ_ЧУЖОЙ}  КОНТРОЛЬ", ЖИВОЙ_ЧУЖОЙ, 443),
        ("мёртвый", f"443 {МЁРТВЫЙ}  КОНТРОЛЬ", МЁРТВЫЙ, 443),
    ]
    итоги = {}
    for ключ, метка, хост, порт in цели:
        print(f"  {метка}  ({хост}:{порт})")
        итоги[ключ] = _замерить(метка, хост, порт, a.attempts, a.timeout, a.pause)

    код, строки = вердикт(итоги)
    print("═" * 62)
    print("ВЕРДИКТ")
    for с in строки:
        print("  " + с)
    return код


if __name__ == "__main__":
    sys.exit(main())
