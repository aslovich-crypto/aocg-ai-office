def вердикт(команда: str) -> str:
    """БЛОК или ПУСК — что ответил хук на эту команду."""
    вход = json.dumps({"tool_input": {"command": команда}}, ensure_ascii=False)
    готово = subprocess.run(
        ["bash", ХУК],
        input=вход,
        capture_output=True,
        text=True,
        cwd=КОРЕНЬ,
        timeout=30,
    )
    return БЛОК if '"deny"' in готово.stdout else ПУСК


def самопроверка() -> bool:
    """Проверяет ЗАМЕР, а не хук. Гоняется перед каждым обычным прогоном.

    Три вопроса, на которые обязан быть известен ответ заранее:
      1. хук вообще доступен и отвечает отказом на заведомо опасное;
      2. хук не «запрещает всё» — заведомо чистое проходит;
      3. данные матрицы НЕ РАСПАЛИСЬ: в каждом случае «обязан блокировать»
         действительно есть деструктивный глагол, а опоры на диске на месте
         и непусты. Ровно этого не хватило первой версии замера.
    """
    ошибки = []

    if not os.path.isfile(ХУК):
        print(f"  ✗ хук не найден: {ХУК}")
        return False

    if вердикт(f'railway run ./venv/bin/python -c "{ТЕЛО_УДАЛЕНИЯ}"') != БЛОК:
        ошибки.append(
            "заведомо опасная команда НЕ заблокирована — хук молчит или сломан"
        )
    if вердикт("git status --short") != ПУСК:
        ошибки.append("заведомо чистая команда заблокирована — хук запрещает всё")

    # Шаблон тоже собирается из кусков: иначе сам файл замера станет носителем
    # деструктивной строки и снова заблокирует собственный запуск.
    глагол = re.compile(
        r"(DR"
        + r"OP\s+(TABLE|INDEX|DATABASE|SCHEMA)|"
        + УДАЛЕНИЕ.replace(" ", r"\s+")
        + r"|"
        + ОБРЕЗАНИЕ
        + r")",
        re.I,
    )
    for код, ожидание, _, команда in МАТРИЦА:
        if ожидание != БЛОК or код == "B8":  # B8 деструктивен самой командой dropdb
            continue
        текст = команда
        for слово in команда.split():
            путь = os.path.join(КОРЕНЬ, слово.strip("\"'()$"))
            if os.path.isfile(путь):
                with open(путь, encoding="utf-8", errors="replace") as f:
                    текст += "\n" + f.read()
        if not глагол.search(текст):
            ошибки.append(
                f"{код}: в данных случая НЕТ деструктивного глагола — проверять нечего"
            )

    for опора in (
        "hook_cleanup.sh",
        "hook_payload_body.txt",
        "hook_query.txt",
        "hook_destructive.py",
        "hook_readonly.py",
    ):
        путь = os.path.join(КОРЕНЬ, ОПОРЫ, опора)
        if not os.path.isfile(путь) or os.path.getsize(путь) == 0:
            ошибки.append(f"опора {опора} отсутствует или пуста")

    for сбой in ошибки:
        print(f"  ✗ {сбой}")
    if not ошибки:
        print(
            f"  ✓ самопроверка пройдена: хук отвечает, данные матрицы целы "
            f"({len(МАТРИЦА)} случаев)"
        )
    return not ошибки


def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument(
        "--selfcheck", action="store_true", help="только самопроверка замера"
    )
    разбор.add_argument("--verbose", action="store_true", help="печатать сами команды")
    аргументы = разбор.parse_args()

    print("САМОПРОВЕРКА ЗАМЕРА")
    if not самопроверка():
        print("\nЗАМЕР НЕ ГОДЕН — матрица не гонялась. Чинить замер, а не хук.")
        return 2
    if аргументы.selfcheck:
        return 0

    print(
        f"\nМАТРИЦА ФОРМ — {len(МАТРИЦА)} случаев "
        f"({sum(1 for c in МАТРИЦА if c[1] == БЛОК)} блокировать / "
        f"{sum(1 for c in МАТРИЦА if c[1] == ПУСК)} пускать)"
    )
    расхождения = []
    for код, ожидание, зачем, команда in МАТРИЦА:
        факт = вердикт(команда)
        знак = "✓" if факт == ожидание else "✗"
        if факт != ожидание:
            расхождения.append((код, ожидание, факт, зачем))
        print(f"  {знак} {код:<4} надо:{ожидание}  факт:{факт}  — {зачем}")
        if аргументы.verbose:
            print(f"       {команда.splitlines()[0][:120]}")

    print(f"\nПроверено {len(МАТРИЦА)}, расхождений {len(расхождения)}")
    for код, ожидание, факт, зачем in расхождения:
        print(f"  ✗ {код}: надо {ожидание}, получено {факт} — {зачем}")
    return 1 if расхождения else 0


if __name__ == "__main__":
    sys.exit(main())
