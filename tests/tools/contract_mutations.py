#!/usr/bin/env python3
"""МУТАЦИИ ЗАМЕРА СЛОВАРЯ КОНТРАКТА — доказательство, что он вообще смотрит.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. `tests/tools/contract_dict.py` отвечает на вопрос
«сходятся ли словари сегодня». Он НЕ отвечает на вопрос «а заметил бы он,
если бы они разошлись». Зелёный прогон одинаково выглядит и когда всё цело,
и когда проверять было нечем. Здесь по очереди ломается КАЖДАЯ заявленная
способность замера, и требуется, чтобы он покраснел.

ЧТО ПРОВЕРЯЕТСЯ (по одной мутации на заявленную способность, T11):
    M1  расхождение на стороне БЭКЕНДА       — переименована группа справочника
    M2  расхождение на стороне ФРОНТА        — выброшено значение из TAX_KINDS
    M3  СЛЕПОЕ МЕСТО наивного разбора        — переименован ГОЛЫЙ ключ объекта
    M4  полосы вывода не покрывают найденное — НАЙДЕНО против НАПЕЧАТАНО
    M5  отпечаток прошлого прогона           — состав изменился, баннер ⛔
    M6  фронт недоступен                     — код 2, а не «расхождений нет»
    M7  принятое расхождение устарело        — причина отпала, запись осталась
M3 — главная: ради неё замер и читает голые ключи. Наши словари живут именно
в них (4 группы из 11, все 6 систем налогообложения), и разбор по одним
кавычкам молчал бы о переименовании ровно там.

ЧУЖОЙ РЕПОЗИТОРИЙ НЕ ТРОГАЕТСЯ ДАЖЕ ВРЕМЕННО. Фронтовые мутации идут на
КОПИИ `src` во временном каталоге, замер направляется туда через FRONT_SRC.
Причина не в аккуратности, а в правиле про одно русло: правка в рабочем
дереве соседнего репозитория переживёт падение скрипта и попадёт в чужой
коммит. Своё дерево (`app/`, сам замер, отпечаток) восстанавливается
в `finally` при любом исходе, включая Ctrl-C.

ПРАВИЛО, РАДИ КОТОРОГО ВСЁ НАПИСАНО (T11): мутация засчитывается, только
если она РЕАЛЬНО применилась. Скрипт замены может не найти цель — шаблон
разошёлся с кодом после чужой правки — и молча ничего не сделать. Тогда
«замер не поймал» читается как поломка замера, хотя ломать было нечего.
Поэтому каждая мутация проверяет, что цель существует и текст изменился.

ЕСЛИ МУТАЦИЯ ПЕРЕСТАЛА НАХОДИТЬ ЦЕЛЬ — это не повод её удалять. Значит код
изменился: перечитать способность, обновить шаблон, убедиться, что краснеет
то же самое.

ЗАПУСК (в pytest НЕ входит — правит файлы и возвращает их на место):
    ./venv/bin/python tests/tools/contract_mutations.py
    ./venv/bin/python tests/tools/contract_mutations.py --verbose
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ЗАМЕР = os.path.join(КОРЕНЬ, "tests", "tools", "contract_dict.py")
СЕМЕНА = os.path.join(КОРЕНЬ, "app", "categories_seed.py")
ОТПЕЧАТОК = os.path.join(КОРЕНЬ, "tests", "tools", "contract_dict_baseline.json")
PYTHON = sys.executable

# (имя, файл, что ломаем, чем заменяем, ожидаемый код, что ОБЯЗАНО быть в выводе)
# Файл «фронт» подставляется на копию, см. main().
МУТАЦИИ = [
    (
        "M1 расхождение на стороне БЭКЕНДА: группа справочника переименована",
        "бэк",
        '        "Материалы и расходники",',
        '        "Материалы и расходнички",',
        1,
        ["группы справочника: РАСХОЖДЕНИЕ", "Материалы и расходники"],
    ),
    (
        "M2 расхождение на стороне ФРОНТА: из TAX_KINDS выброшено значение",
        "фронт/App.jsx",
        '  "Транспортные расходы",\n',
        "",
        1,
        ["виды расхода (tax_kind): РАСХОЖДЕНИЕ", "Транспортные расходы"],
    ),
    (
        "M3 СЛЕПОЕ МЕСТО: переименован ГОЛЫЙ ключ объекта (разбор по кавычкам слеп)",
        "фронт/lib/tax.js",
        "  psn: ",
        "  patent: ",
        1,
        ["системы налогообложения: РАСХОЖДЕНИЕ", "psn"],
    ),
    (
        "M4 полосы вывода не покрывают найденное (НАЙДЕНО против НАПЕЧАТАНО)",
        "замер",
        '("ПРОЧИЕ ОБЩИЕ ЛИТЕРАЛЫ (кандидаты, шум заложен)", sorted(общие - в_словарях)),',
        '("ПРОЧИЕ ОБЩИЕ ЛИТЕРАЛЫ (кандидаты, шум заложен)", sorted(общие - в_словарях)[:5]),',
        1,
        ["РАСХОЖДЕНИЕ НАЙДЕНО/НАПЕЧАТАНО"],
    ),
    (
        "M5 отпечаток: состав разошёлся с прошлым прогоном",
        "отпечаток",
        '  "access_token",',
        '  "access_token_переименованный",',
        1,
        ["СЛОВАРЬ ИЗМЕНИЛСЯ С ПРОШЛОГО ПРОГОНА", "ИСЧЕЗЛО", "ПОЯВИЛОСЬ"],
    ),
    (
        # Устаревание изображается СОГЛАСИЕМ словарей, а не правкой отпечатка:
        # если убрать значение из исключения, расхождение станет обычным — это
        # другая ветка. Здесь бэкенд «дорастает» до фронта (как будет при FIN-01),
        # причина исключения отпадает, а запись остаётся.
        "M7 принятое расхождение устарело: причина отпала, запись осталась",
        "роли",
        'Role = Literal["admin", "accountant", "employee"]',
        'Role = Literal["admin", "accountant", "employee", "manager"]',
        1,
        ["ИСКЛЮЧЕНИЕ УСТАРЕЛО"],
    ),
]


def прогон(фронт: str, окружение_замера: str | None = None) -> tuple[int, str]:
    среда = dict(os.environ, FRONT_SRC=окружение_замера or фронт)
    готово = subprocess.run(
        [PYTHON, ЗАМЕР],
        capture_output=True,
        text=True,
        cwd=КОРЕНЬ,
        env=среда,
        timeout=300,
    )
    return готово.returncode, готово.stdout + готово.stderr


def main() -> int:
    разбор = argparse.ArgumentParser(description="Мутации замера словаря контракта")
    разбор.add_argument("--verbose", action="store_true", help="печатать вывод замера")
    аргументы = разбор.parse_args()

    настоящий_фронт = os.environ.get(
        "FRONT_SRC",
        os.path.normpath(os.path.join(КОРЕНЬ, "..", "aocg-ai-office-web", "src")),
    )
    if not os.path.isdir(настоящий_фронт):
        print(f"ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ: нет каталога {настоящий_фронт}")
        return 2

    времянка = tempfile.mkdtemp(prefix="contract-mut-")
    копия = os.path.join(времянка, "src")
    shutil.copytree(настоящий_фронт, копия)
    print(f"Копия фронта для мутаций: {копия}")

    файлы = {
        "бэк": СЕМЕНА,
        "роли": os.path.join(КОРЕНЬ, "app", "auth.py"),
        "замер": ЗАМЕР,
        "отпечаток": ОТПЕЧАТОК,
        "фронт/App.jsx": os.path.join(копия, "App.jsx"),
        "фронт/lib/tax.js": os.path.join(копия, "lib", "tax.js"),
    }
    оригиналы = {к: open(п, encoding="utf-8").read() for к, п in файлы.items()}

    код, вывод = прогон(копия)
    if код != 0:
        print(f"База НЕ зелёная (код {код}). Мутации бессмысленны — сначала замер.")
        print(вывод)
        shutil.rmtree(времянка, ignore_errors=True)
        return 2
    print(f"База зелёная. Мутаций к прогону: {len(МУТАЦИИ)} + M6 (недоступный фронт)\n")

    провалы = 0
    try:
        for имя, ключ, старое, новое, ждём_код, ждём_текст in МУТАЦИИ:
            путь, оригинал = файлы[ключ], оригиналы[ключ]
            if старое not in оригинал:
                print(
                    f"  ✗ {имя}\n      ЦЕЛЬ НЕ НАЙДЕНА — мутация не применилась, "
                    f"проверять было нечего. Код изменился: обновить шаблон."
                )
                if аргументы.verbose:
                    print(f"      искали: {старое[:80]!r}")
                провалы += 1
                continue
            изменённый = оригинал.replace(старое, новое, 1)
            if изменённый == оригинал:
                print(f"  ✗ {имя}\n      текст не изменился после замены")
                провалы += 1
                continue

            open(путь, "w", encoding="utf-8").write(изменённый)
            try:
                код, вывод = прогон(копия)
            finally:
                open(путь, "w", encoding="utf-8").write(оригинал)

            нет_текста = [т for т in ждём_текст if т not in вывод]
            сошлось = код == ждём_код and not нет_текста
            провалы += 0 if сошлось else 1
            print(f"  {'✓' if сошлось else '✗'} {имя}")
            print(f"      ждали код {ждём_код}, получили {код}")
            if нет_текста:
                print(f"      НЕ НАШЛОСЬ В ВЫВОДЕ: {нет_текста}")
            else:
                print(f"      в выводе нашлось: {ждём_текст}")
            if аргументы.verbose:
                print("      ── вывод замера ──")
                for с in вывод.splitlines():
                    print(f"      {с}")

        # M6 отдельно: ломается не файл, а доступность каталога.
        код, вывод = прогон(
            копия, окружение_замера=os.path.join(времянка, "нет-такого")
        )
        сошлось = код == 2 and "ПРОВЕРКА НЕ ВЫПОЛНЯЛАСЬ" in вывод
        провалы += 0 if сошлось else 1
        print(
            f"  {'✓' if сошлось else '✗'} M6 фронт недоступен: код 2, а не «расхождений нет»"
        )
        print(f"      ждали код 2, получили {код}")
    finally:
        for ключ, путь in файлы.items():
            open(путь, "w", encoding="utf-8").write(оригиналы[ключ])
        shutil.rmtree(времянка, ignore_errors=True)

    код, _ = прогон(настоящий_фронт)
    print(f"\nПосле восстановления: код {код} (обязано быть 0)")
    всего = len(МУТАЦИИ) + 1
    провалы += 1 if код != 0 else 0
    print(f"Проверено способностей: {всего}, провалов: {провалы}")
    return 1 if провалы else 0


if __name__ == "__main__":
    sys.exit(main())
