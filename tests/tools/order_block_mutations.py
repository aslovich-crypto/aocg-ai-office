# -*- coding: utf-8 -*-
"""МУТАЦИИ СВЕРКИ «БЛОК ПОРЯДКА ↔ ФАКТ» (правило T11).

Свод четырёхграфный: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО · НЕ МЕРЕНО.
Четвёртая графа заведена 08.09.2026 и здесь применяется впервые: «прибор
не отработал» и «мутант не пойман» давали один и тот же ответ, и второе
засчитывалось за первое — свод врал в опасную сторону, показывая проверку
там, где её не было.

⚠️ ТРЕТЬЯ МУТАЦИЯ ДРУГОЙ ПРИРОДЫ, И ЭТО НАМЕРЕННО. М1 и М2 портят ДАННЫЕ и
ждут, что сторож покраснеет. М3 портит САМ СТОРОЖ — переводит признак
зачёркивания с первой строки на весь пункт — и ждёт, что тот СОВРЁТ на
верном файле. «Поймана» здесь значит «соврал», и это единственный способ
доказать, что первая строка выбрана не по вкусу.

⚠️ М3 САЖАЕТ И ПРОДОЛЖЕНИЕ. Замер 08.09.2026: ни одно продолжение пунктов
блока сегодня не несёт ни `~~`, ни ID, которого нет в первой строке, —
то есть кусать мутации нечего. Мутация, которой нечего кусать, проверяет
удачу подбора данных, а не правило (тот же урок, что М3/М4 в UX-26).
Поэтому она добавляет реалистичный довод со ссылкой на зачёркнутую строку —
ровно то, что человек однажды и напишет.

ЗАПУСК: ./venv/bin/python tests/tools/order_block_mutations.py
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ТРЕКЕР = КОРЕНЬ / "docs" / "TASKS.md"
СТОРОЖ = КОРЕНЬ / "tests" / "tools" / "tracker_html_guard.py"
ФАЙЛЫ = {"трекер": ТРЕКЕР, "сторож": СТОРОЖ}

# Вердикт прибора отличается от его сбоя: без этого «не мерено» неотличимо
# от «не поймано» (правило четвёртой графы, 08.09.2026).
ВЕРДИКТ = re.compile(r"ПОРЯДОК ПРОТИВ ФАКТА")

# ⚠️ ЯКОРЯ ВЫЧИСЛЯЮТСЯ ИЗ ТЕКУЩЕГО БЛОКА, А НЕ ЗАПИСАНЫ ТЕКСТОМ. Первая
# редакция целилась в «1. ~~**[[T39]]**» и «3. **[[S-79]]**» — и в день
# пересборки блока под цель Ⓐ (09.09.2026) пять мутаций из шести стали
# «НЕ ПОСТАВЛЕНЫ» разом: сторож остался без единой живой мутации, то есть
# по правилу T11 — неработающим, и никто бы этого не заметил до следующего
# прогона. Блок — данные, которые меняются каждый день; мутация обязана
# находить свой материал в том блоке, который есть, а не в том, который был.
import importlib.util as _iu


def _модуль(имя):
    спец = _iu.spec_from_file_location(имя, КОРЕНЬ / "tests" / "tools" / f"{имя}.py")
    м = _iu.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def _первый_живой(текст):
    """(первая строка пункта, единственный ID его предмета) — первый пункт с одним ID."""
    th = _модуль("tracker_html")
    for _, первая, _ in th.пункты_блока(текст):
        if первая.lstrip().startswith("~~"):
            continue
        иды = re.findall(r"\[\[([^\]]+)\]\]", первая.split(" — ")[0])
        if len(иды) == 1:
            return первая, иды[0]
    raise SystemExit("в блоке нет живого пункта с одним ID — мутациям нечего кусать")


def _со_статусом(текст, ид, статус):
    """Тот же файл, у строки `ид` статус заменён — ПО ИНДЕКСУ ЯЧЕЙКИ."""
    строки = текст.split("\n")
    for i, с in enumerate(строки):
        if re.match(rf"^\| {re.escape(ид)} \|", с):
            я = re.split(r"(?<!\\)\|", с)
            assert len(я) == 9, (ид, len(я))
            я[4] = f" {статус} "
            строки[i] = "|".join(я)
            return "\n".join(строки)
    raise SystemExit(f"строки {ид} нет в трекере")


def мутанты(исходники):
    """Список мутаций, собранный по ТЕКУЩЕМУ блоку."""
    трекер = исходники["трекер"]
    первая, ид = _первый_живой(трекер)
    зачёркнутая = "~~" + первая + "~~"
    пункт = "1. " + первая  # нумерация сплошная, живой пункт с одним ID — первый
    assert трекер.count(пункт) == 1, "первый живой пункт не найден дословно"
    return [
        {
            "имя": f"М1 строка {ид} закрыта, а пункт не зачёркнут",
            "трекер": _со_статусом(трекер, ид, "✅"),
            "сторож": None,
            "ждём": rf"пункт \d+ НЕ зачёркнут, а все его строки закрыты: {re.escape(ид)}",
            "почему": "ровно то, что случилось 08.09 дважды и заметил человек глазами",
        },
        {
            "имя": f"М2 пункт зачёркнут, а строка {ид} открыта",
            "трекер": трекер.replace(пункт, "1. " + зачёркнутая),
            "сторож": None,
            "ждём": rf"пункт \d+ зачёркнут, а строки открыты: {re.escape(ид)}",
            "почему": "поспешное зачёркивание прячет работу — вторая сторона правила",
        },
        {
            "имя": "М3 признак ищется по всему пункту, а не в первой строке",
            "трекер": трекер.replace(
                пункт,
                пункт
                + "\n   Порядок тот же, что был у ~~**[[T39]]**~~: сперва правило, потом прибор.",
            ),
            "сторож": (
                'зачёркнут = первая.lstrip().startswith("~~")',
                'зачёркнут = "~~" in (первая + _продолжение)',
            ),
            "ждём": rf"пункт \d+ зачёркнут, а строки открыты: {re.escape(ид)}",
            "почему": "цитата в доводе не должна выглядеть состоянием пункта",
        },
        {
            # предмет берётся из всей строки: за тире сажаем ссылку на ОТКРЫТУЮ
            # строку, сам пункт зачёркиваем, а его строку закрываем — верный
            # сторож зелёный (предмет ✅), испорченный видит T159 за тире.
            "имя": "М4 предмет берётся из всей строки, а не до тире",
            "трекер": _со_статусом(
                трекер.replace(
                    пункт, "1. " + зачёркнутая[:-2] + "; блокирует [[T159]]~~"
                ),
                ид,
                "✅",
            ),
            "сторож": ('предмет = первая.split(" — ")[0]', "предмет = первая"),
            "ждём": r"пункт \d+ зачёркнут, а строки открыты: .*T159",
            "почему": "ссылка в пояснении — не работа пункта, а то, что она разблокирует",
        },
        {
            "имя": "М5 отложенная строка считается очередью",
            "трекер": _со_статусом(трекер.replace(пункт, "1. " + зачёркнутая), ид, "⏸"),
            "сторож": (
                'В_ОЧЕРЕДИ = ("⬜", "🔵", "👀")',
                'В_ОЧЕРЕДИ = ("⬜", "🔵", "👀", "⏸")',
            ),
            "ждём": rf"пункт \d+ зачёркнут, а строки открыты: {re.escape(ид)}",
            "почему": "⏸ снята с очереди решением владельца, а не забыта",
        },
        {
            "имя": "М6 требование «хоть одна ✅» снято",
            "трекер": _со_статусом(трекер, ид, "⏸"),
            "сторож": (
                'elif not зачёркнут and not живые and any(ст == "✅" for _, ст in свои):',
                "elif not зачёркнут and not живые:",
            ),
            "ждём": rf"пункт \d+ НЕ зачёркнут, а все его строки закрыты: {re.escape(ид)}",
            "почему": "пункт, где всё лишь отложено, ещё не сделан — вычёркивать нечего",
        },
    ]


def прогнать() -> str | None:
    """Трижды, потому что молчание прибора — не вердикт."""
    for _ in range(3):
        итог = subprocess.run(
            [sys.executable, str(СТОРОЖ)],
            capture_output=True,
            text=True,
            cwd=КОРЕНЬ,
        )
        вывод = итог.stdout + итог.stderr
        if ВЕРДИКТ.search(вывод):
            return вывод
    return None


def main() -> int:
    print("\nМУТАЦИИ СВЕРКИ «БЛОК ПОРЯДКА ↔ ФАКТ»")
    исходники = {к: п.read_text(encoding="utf-8") for к, п in ФАЙЛЫ.items()}

    чисто = прогнать()
    if чисто is None:
        print("  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ трижды — мутации не мерились")
        return 1
    if "✗ пункт" in чисто:
        print("  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: сторож красен ДО мутаций")
        return 1
    print("  обратный ход: на нетронутом файле расхождений нет ✓\n")

    поставлено = поймано = 0
    непоставленные: list[str] = []
    немерено: list[str] = []
    for м in мутанты(исходники):
        сторож = исходники["сторож"]
        if м["сторож"]:
            было, стало = м["сторож"]
            if сторож.count(было) != 1:
                непоставленные.append(м["имя"])
                print(
                    f"  ✗ НЕ ПОСТАВЛЕН  {м['имя']}: якоря в стороже нет либо он не один"
                )
                continue
            сторож = сторож.replace(было, стало)
        if м["трекер"] == исходники["трекер"] and not м["сторож"]:
            непоставленные.append(м["имя"])
            print(f"  ✗ НЕ ПОСТАВЛЕН  {м['имя']}: трекер не изменился")
            continue
        ФАЙЛЫ["трекер"].write_text(м["трекер"], encoding="utf-8")
        ФАЙЛЫ["сторож"].write_text(сторож, encoding="utf-8")
        поставлено += 1
        вывод = прогнать()
        for к, п in ФАЙЛЫ.items():
            п.write_text(исходники[к], encoding="utf-8")
        if вывод is None:
            немерено.append(м["имя"])
            print(f"  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ  {м['имя']} — исход неизвестен")
            continue
        есть = re.search(м["ждём"], вывод) is not None
        поймано += есть
        print(f"  {'✓ поймана' if есть else '✗ ПРОПУЩЕНА'}  {м['имя']} — {м['почему']}")

    print(
        f"\nПОСТАВЛЕНО {поставлено} · ПОЙМАНО {поймано} · "
        f"НЕ ПОСТАВЛЕНО {len(непоставленные)} · НЕ МЕРЕНО {len(немерено)}"
    )
    if немерено:
        print(f"  ⚠️ прибор не дал вердикта: {', '.join(немерено)}")
    for к, п in ФАЙЛЫ.items():
        if п.read_text(encoding="utf-8") != исходники[к]:
            print(f"  ⚠️ ФАЙЛ {к} НЕ ВОССТАНОВЛЕН")
            return 1
    print("исходные файлы не тронуты ✓")
    return 0 if поймано == поставлено and not непоставленные and not немерено else 1


if __name__ == "__main__":
    sys.exit(main())
