# -*- coding: utf-8 -*-
"""МУТАЦИИ СВЕРКИ «БЛОК ПОРЯДКА ↔ ФАКТ» (правило T11).

Свод четырёхграфный: ПОСТАВЛЕНО · ПОЙМАНО · НЕ ПОСТАВЛЕНО · НЕ МЕРЕНО.
Четвёртая графа заведена 08.09.2026 и здесь применяется впервые: «прибор
не отработал» и «мутант не пойман» давали один и тот же ответ, и второе
засчитывалось за первое — свод врал в опасную сторону, показывая проверку
там, где её не было.

⚠️ ТРЕТЬЯ МУТАЦИЯ ДРУГОЙ ПРИРОДЫ, И ЭТО НАМЕРЕННО. М1 и М2 портят ДАННЫЕ и
ждут, что сторож покраснеет. М3 портит САМ СТОРОЖ — переводит признак
зачёркивания с первой строки на весь пункт — и ждёт, что тот СОВРЁТ на
верном файле. «Поймана» здесь значит «соврал», и это единственный способ
доказать, что первая строка выбрана не по вкусу.

⚠️ М3 САЖАЕТ И ПРОДОЛЖЕНИЕ. Замер 08.09.2026: ни одно продолжение пунктов
блока сегодня не несёт ни `~~`, ни ID, которого нет в первой строке, —
то есть кусать мутации нечего. Мутация, которой нечего кусать, проверяет
удачу подбора данных, а не правило (тот же урок, что М3/М4 в UX-26).
Поэтому она добавляет реалистичный довод со ссылкой на зачёркнутую строку —
ровно то, что человек однажды и напишет.

ЗАПУСК: ./venv/bin/python tests/tools/order_block_mutations.py
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ТРЕКЕР = КОРЕНЬ / "docs" / "TASKS.md"
СТОРОЖ = КОРЕНЬ / "tests" / "tools" / "tracker_html_guard.py"
ФАЙЛЫ = {"трекер": ТРЕКЕР, "сторож": СТОРОЖ}

# Вердикт прибора отличается от его сбоя: без этого «не мерено» неотличимо
# от «не поймано» (правило четвёртой графы, 08.09.2026).
ВЕРДИКТ = re.compile(r"ПОРЯДОК ПРОТИВ ФАКТА")

МУТАНТЫ = [
    {
        "имя": "М1 строка закрыта, а пункт не зачёркнут",
        "правки": [("трекер", "1. ~~**[[T39]]**", "1. **[[T39]]**")],
        "ждём": r"пункт 1 НЕ зачёркнут, а все его строки закрыты",
        "почему": "ровно то, что случилось 08.09 дважды и заметил человек глазами",
    },
    {
        "имя": "М2 пункт зачёркнут, а строка открыта",
        "правки": [
            (
                "трекер",
                "3. **[[S-79]]",
                "3. ~~**[[S-79]]",
            )
        ],
        "ждём": r"пункт 3 зачёркнут, а строки открыты",
        "почему": "поспешное зачёркивание прячет работу — вторая сторона правила",
    },
    {
        "имя": "М3 признак ищется по всему пункту, а не в первой строке",
        "правки": [
            (
                "сторож",
                'зачёркнут = первая.lstrip().startswith("~~")',
                'зачёркнут = "~~" in (первая + _продолжение)',
            ),
            (
                "трекер",
                "3. **[[S-79]] + [[S-80]] + [[S-81]]**"
                " — доставляемость писем: блокируют [[T159]],"
                " а недошедшее уведомление мы не заметим",
                "3. **[[S-79]] + [[S-80]] + [[S-81]]**"
                " — доставляемость писем: блокируют [[T159]],"
                " а недошедшее уведомление мы не заметим\n"
                "   Порядок здесь тот же, что был у ~~**[[T39]]**~~:"
                " сперва канал, потом то, что по нему пойдёт.",
            ),
        ],
        "ждём": r"пункт 3 зачёркнут, а строки открыты",
        "почему": "цитата в доводе не должна выглядеть состоянием пункта",
    },
]


def прогнать() -> str | None:
    """Трижды, потому что молчание прибора — не вердикт."""
    for _ in range(3):
        итог = subprocess.run(
            [sys.executable, str(СТОРОЖ)],
            capture_output=True,
            text=True,
            cwd=КОРЕНЬ,
        )
        вывод = итог.stdout + итог.stderr
        if ВЕРДИКТ.search(вывод):
            return вывод
    return None


def main() -> int:
    print("\nМУТАЦИИ СВЕРКИ «БЛОК ПОРЯДКА ↔ ФАКТ»")
    исходники = {к: п.read_text(encoding="utf-8") for к, п in ФАЙЛЫ.items()}

    чисто = прогнать()
    if чисто is None:
        print("  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ трижды — мутации не мерились")
        return 1
    if "✗ пункт" in чисто:
        print("  ⚠️ ОБРАТНЫЙ ХОД НЕ ПРОЙДЕН: сторож красен ДО мутаций")
        return 1
    print("  обратный ход: на нетронутом файле расхождений нет ✓\n")

    поставлено = поймано = 0
    непоставленные: list[str] = []
    немерено: list[str] = []
    for м in МУТАНТЫ:
        цели_есть = all(исходники[к].count(было) == 1 for к, было, _ in м["правки"])
        if not цели_есть:
            непоставленные.append(м["имя"])
            print(f"  ✗ НЕ ПОСТАВЛЕН  {м['имя']}: якоря в файле нет либо он не один")
            continue
        for к, было, стало in м["правки"]:
            ФАЙЛЫ[к].write_text(исходники[к].replace(было, стало), encoding="utf-8")
        поставлено += 1
        вывод = прогнать()
        for к, п in ФАЙЛЫ.items():
            п.write_text(исходники[к], encoding="utf-8")
        if вывод is None:
            немерено.append(м["имя"])
            print(f"  ⚠️ ПРИБОР НЕ ОТРАБОТАЛ  {м['имя']} — исход неизвестен")
            continue
        есть = re.search(м["ждём"], вывод) is not None
        поймано += есть
        print(f"  {'✓ поймана' if есть else '✗ ПРОПУЩЕНА'}  {м['имя']} — {м['почему']}")

    print(
        f"\nПОСТАВЛЕНО {поставлено} · ПОЙМАНО {поймано} · "
        f"НЕ ПОСТАВЛЕНО {len(непоставленные)} · НЕ МЕРЕНО {len(немерено)}"
    )
    if немерено:
        print(f"  ⚠️ прибор не дал вердикта: {', '.join(немерено)}")
    for к, п in ФАЙЛЫ.items():
        if п.read_text(encoding="utf-8") != исходники[к]:
            print(f"  ⚠️ ФАЙЛ {к} НЕ ВОССТАНОВЛЕН")
            return 1
    print("исходные файлы не тронуты ✓")
    return 0 if поймано == поставлено and not непоставленные and not немерено else 1


if __name__ == "__main__":
    sys.exit(main())
