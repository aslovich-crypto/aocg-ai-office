"""Сборщик xlsx: проверяем СОДЕРЖИМОЕ файла, а не факт его появления.

⚠️ ЧИТАЕМ ФАЙЛ ОБРАТНО, А НЕ ДОВЕРЯЕМ СБОРЩИКУ. xlsx — это zip с XML, и
стандартной библиотеки хватает, чтобы распаковать и посмотреть, что реально
легло в ячейки. Проверка «байты вернулись и они непустые» не отличила бы
рабочий файл от файла с пустым листом.
"""

import datetime as dt
import zipfile
from decimal import Decimal
from xml.etree import ElementTree

import pytest

from app.exports import report_xlsx as rx

ПРОСТРАНСТВО = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"


def прочитать(байты):
    """xlsx → список строк, каждая строка — список значений ячеек как строк.

    Пустая ячейка отдаётся как None, чтобы отличать её от строки «».
    """
    with zipfile.ZipFile(__import__("io").BytesIO(байты)) as архив:
        общие = []
        if "xl/sharedStrings.xml" in архив.namelist():
            корень = ElementTree.fromstring(архив.read("xl/sharedStrings.xml"))
            for si in корень.findall(ПРОСТРАНСТВО + "si"):
                общие.append("".join(t.text or "" for t in si.iter(ПРОСТРАНСТВО + "t")))
        лист = ElementTree.fromstring(архив.read("xl/worksheets/sheet1.xml"))
    строки = []
    for row in лист.iter(ПРОСТРАНСТВО + "row"):
        ячейки = {}
        for c in row.findall(ПРОСТРАНСТВО + "c"):
            # ⚠️ КЛАДЁМ ПО НОМЕРУ КОЛОНКИ ИЗ АТРИБУТА `r`, А НЕ ПО ПОРЯДКУ
            # В XML. Пустую ячейку xlsx вправе не записывать вовсе, и чтение
            # «подряд» тогда молча сдвигает ВСЕ последующие колонки — ошибка
            # не падает, а выдаёт другое число. Поймано этим же тестом.
            ячейки[_номер_колонки(c.get("r"))] = _значение(c, общие)
        ширина = max(ячейки) + 1 if ячейки else 0
        строки.append([ячейки.get(i) for i in range(ширина)])
    # ⚠️ ДОБИВАЕМ СТРОКИ ДО ШИРИНЫ ШАПКИ. Пустые ячейки В КОНЦЕ строки xlsx
    # вправе не записывать вовсе — это свойство формата, а не потеря данных.
    # Без добивки строка чека без реквизитов и снимка оказывается короче
    # заголовка, и проверка падает по длине вместо того, чтобы смотреть
    # в ячейку.
    ширина_шапки = len(строки[0]) if строки else 0
    return [ряд + [None] * (ширина_шапки - len(ряд)) for ряд in строки]


def _номер_колонки(адрес):
    """«AB12» → 27. Буквы — это число в системе счисления по основанию 26."""
    номер = 0
    for знак in адрес or "":
        if знак.isalpha():
            номер = номер * 26 + (ord(знак.upper()) - ord("A") + 1)
    return номер - 1


def типы_ячеек(байты):
    """Строки листа, где вместо значения стоит ПРИЗНАК ТИПА ячейки.

    ⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ ЧИТАЛКА. Значение «907» выглядит одинаково и в числовой
    ячейке, и в текстовой, поэтому проверка по значению НЕ РАЗЛИЧАЕТ их вовсе —
    это поймано мутацией М23, которая перевела номер чека в текст и осталась
    незамеченной. А разница настоящая: текстовую ячейку приёмная сторона
    прочитает строкой, и ключ идемпотентности перестанет быть числом.
    """
    with zipfile.ZipFile(__import__("io").BytesIO(байты)) as архив:
        лист = ElementTree.fromstring(архив.read("xl/worksheets/sheet1.xml"))
    строки = []
    for row in лист.iter(ПРОСТРАНСТВО + "row"):
        ячейки = {}
        for c in row.findall(ПРОСТРАНСТВО + "c"):
            ячейки[_номер_колонки(c.get("r"))] = c.get("t") or "число"
        ширина = max(ячейки) + 1 if ячейки else 0
        строки.append([ячейки.get(i) for i in range(ширина)])
    return строки


def _значение(c, общие):
    v = c.find(ПРОСТРАНСТВО + "v")
    if v is None or v.text is None:
        return None
    if c.get("t") == "s":
        return общие[int(v.text)]
    return v.text


# ⚠️ МОМЕНТ ВЫГРУЗКИ НАМЕРЕННО ДАЛЁК ОТ СЕГОДНЯШНЕГО ДНЯ. Куплено мутацией
# М6: когда здесь стояла сегодняшняя дата, подмена `выгружено` на
# `datetime.now()` внутри сборщика тестом НЕ ЛОВИЛАСЬ — обе ветки давали один
# и тот же день. Проверка зеленела по совпадению, а не по существу.
ВЫГРУЖЕНО = dt.datetime(2020, 3, 4, 20, 30)

ОТЧЁТ = {
    "id": 42,
    "title": "Командировка в Тверь",
    "status": "Одобрен",
    "created": dt.date(2026, 9, 11),
    "user_id": 7,
}


def собрать_в(отчёт, подотчётник, чеки):
    """Обёртка над сборщиком с ФИКСИРОВАННЫМ моментом выгрузки.

    Время приходит параметром именно ради этого: файл, собранный дважды,
    обязан быть одинаковым, иначе тест проверяет часы, а не сборку.
    """
    return rx.собрать(отчёт, подотчётник, чеки, ВЫГРУЖЕНО)


def чек(**поправки):
    основа = {
        "id": 1,
        "date": dt.date(2026, 9, 10),
        "datetime": dt.datetime(2026, 9, 10, 13, 34),
        "org": "МЕРКА",
        "org_legal": 'ООО "МЕРКА"',
        "org_inn": "7701234567",
        "amount": Decimal("100.50"),
        "currency": "RUB",
        "статья": "Питание в командировке",
        "payment": "Карта",
        "vat_breakdown": {"20": 16.75},
        "sum_vat_0": None,
        "sum_no_vat": None,
        "kkt_fn": "7380440700123456",
        "fd_num": "49526",
        "fpd": "1234567890",
        "снимок": "",
    }
    основа.update(поправки)
    return основа


def test_заголовки_совпадают_с_профилем():
    """Файл обязан повторять профиль столбец в столбец, без сдвига."""
    строки = прочитать(собрать_в(ОТЧЁТ, "Шукалович А.", [чек()]))
    assert строки[0] == [заголовок for заголовок, _, _ in rx.ПРОФИЛЬ]


def test_чек_без_реквизитов_даёт_пустые_ячейки_а_не_пропадает():
    """Решение владельца 11.09.2026: строка есть, ячейки пустые."""
    строки = прочитать(
        собрать_в(ОТЧЁТ, "Шукалович А.", [чек(kkt_fn=None, fd_num=None, fpd=None)])
    )
    # Строка чека на месте — не исчезла.
    assert len(строки) == 2
    ключи = [ключ for _, ключ, _ in rx.ПРОФИЛЬ]
    for ключ in ("фн", "фд", "фпд"):
        assert строки[1][ключи.index(ключ)] is None
    # И при этом остальное заполнено — иначе пустота была бы не там.
    assert строки[1][ключи.index("продавец")] == "МЕРКА"


def test_ндс_ложится_в_колонку_своей_ставки():
    """20 и 20/120 — РАЗНЫЕ колонки: разная база, и путать их нельзя."""
    строки = прочитать(
        собрать_в(ОТЧЁТ, "Ш. А.", [чек(vat_breakdown={"20/120": 8.4, "22": 1.5})])
    )
    ключи = [ключ for _, ключ, _ in rx.ПРОФИЛЬ]
    assert строки[1][ключи.index("ндс_20/120")] == "8.4"
    assert строки[1][ключи.index("ндс_22")] == "1.5"
    assert строки[1][ключи.index("ндс_20")] is None


def test_все_двенадцать_значений_тега_1199_представлены():
    """Норма, а не встреченные данные: десять ставок с налогом плюс два оборота."""
