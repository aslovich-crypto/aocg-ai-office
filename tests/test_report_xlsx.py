def test_дата_выгрузки_и_срок_ссылок_стоят_в_каждой_строке():
    """Требование владельца 11.09.2026: без даты бухгалтер не поймёт,
    когда протухнут ссылки на снимки, а протухшая молча выглядит как
    «снимка не было»."""
    строки = прочитать(собрать_в(ОТЧЁТ, "Ш. А.", [чек(), чек(id=2)]))
    ключи = [ключ for _, ключ, _ in rx.ПРОФИЛЬ]
