"""ГИГИЕНА МОДЕЛИ 1С: СПИСКИ НЕ РАСХОДЯТСЯ (1C-22, AOCG-1C-001 v0.1).

⚠️ ЗАЧЕМ. Один и тот же набор значений записан в проекте несколько раз:
виды расхода — в словаре категорий, в CHECK у `categories` и в CHECK
у правила по виду; режимы НДС и налогообложения — в CHECK профиля и
константами в сборке тела. Разойтись они могут молча, и первым это увидит
бухгалтер клиента на неверной проводке, а не мы.

⚠️ ЭТО СВЕРКА ТЕКСТА, А НЕ ПОВЕДЕНИЯ. Она не отвечает, верны ли сами
значения; она отвечает ровно на один вопрос — одинаковы ли копии.
"""

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))


def _схема() -> str:
    return (КОРЕНЬ / "app/database.py").read_text(encoding="utf-8")


def _виды_из_check(кусок: str) -> set:
    return set(re.findall(r"'([^']+)'", кусок))


def _check_по_якорю(якорь: str) -> str:
    текст = _схема()
    н = текст.index(якорь)
    открытая = текст.index("(", текст.index("CHECK", н))
    глубина, к = 0, открытая
    while к < len(текст):
        if текст[к] == "(":
            глубина += 1
        elif текст[к] == ")":
            глубина -= 1
            if глубина == 0:
                return текст[открытая : к + 1]
        к += 1
    raise AssertionError("не нашёл закрывающую скобку у %s" % якорь)


def test_оба_check_на_вид_расхода_совпадают_со_словарём():
    """⚠️ ТРИ КОПИИ ОДНОГО НАБОРА: словарь категорий, CHECK у `categories`
    и CHECK у правила по виду расхода. Новый вид, добавленный в словарь
    и забытый в правиле, оставил бы категории этого вида без соответствия —
    молча, до первого непроведённого документа."""
    from app.dictionaries import TAX_KINDS

    у_категорий = _виды_из_check(_check_по_якорю("tax_kind    TEXT NOT NULL"))
    у_правила = _виды_из_check(_check_по_якорю("tax_kind       TEXT NOT NULL"))
    assert у_категорий == set(TAX_KINDS), (
        "CHECK у categories разошёлся со словарём: %s"
        % sorted(у_категорий ^ set(TAX_KINDS))
    )
    assert у_правила == set(TAX_KINDS), (
        "CHECK у правила по виду расхода разошёлся со словарём: %s"
        % sorted(у_правила ^ set(TAX_KINDS))
    )


def test_режимы_ндс_в_сборке_совпадают_с_check_профиля():
    """Константы сборки тела — зеркало ограничения базы. Разойдись они,
    режим из базы просто не совпал бы ни с одной веткой, и чек поехал бы
    по чужому правилу дробления."""
    from app import odata_body

    из_базы = _виды_из_check(_check_по_якорю("vat_mode             TEXT NOT NULL"))
    из_кода = {
        odata_body.НДС_НЕ_ПЛАТЕЛЬЩИК,
        odata_body.НДС_В_СТОИМОСТИ,
        odata_body.НДС_К_ВЫЧЕТУ,
    }
    assert из_базы == из_кода, sorted(из_базы ^ из_кода)


def test_режимы_налогообложения_разобраны_кодом_полностью():
    """⚠️ КАЖДЫЙ режим профиля обязан попасть ровно в одну ветку признака
    УСН: «из правила», «всегда НеПринимаются» или ОСНО, где поля нет вовсе.
    Режим, не попавший никуда, означал бы документ без признака там, где
    он обязателен."""
    from app import odata_body

    из_базы = _виды_из_check(_check_по_якорю("tax_regime           TEXT NOT NULL"))
    из_правила = set(odata_body.РЕЖИМЫ_ПРИЗНАК_ИЗ_ПРАВИЛА)
    без_признака = set(odata_body.РЕЖИМЫ_ПРИЗНАК_ВСЕГДА_НЕТ)
    assert not (из_правила & без_признака), "режим попал в обе ветки"
    неразобранные = из_базы - из_правила - без_признака - {"osno"}
    assert not неразобранные, "режимы не разобраны кодом: %s" % sorted(неразобранные)
    assert из_правила | без_признака | {"osno"} == из_базы, (
        "код знает режимы, которых нет в базе: %s"
        % sorted((из_правила | без_признака | {"osno"}) - из_базы)
    )


