@pytest.mark.parametrize(
    "вывеска, юрлицо",
    [
        ("Торговый зал", 'ООО "Максидом"'),
        ("АЗС 11117 Ждановская", 'ООО "ТЕБОЙЛ РУС"'),
        ("B41D Балтийский", "АО ТД Перекресток"),
    ],
)
def test_вывеска_не_общепит_и_не_розница_считается_как_сегодня(вывеска, юрлицо):
    """Находка владельца ②: стройматериалы, топливо, магазин с немой вывеской —
    не опознаны и идут прежним путём, слово в слово."""
    assert тип_продавца(вывеска, юрлицо) == НЕ_ОПОЗНАН
    прежний = categorize_items(МЕНЮ) or auto_categorize_v2(юрлицо, вывеска)
    assert categorize(юрлицо, МЕНЮ, brand=вывеска) == прежний


def test_опечатка_кассира_в_вывеске_известный_промах():
    """Находка владельца ①: «Рестран» без «о» словарь НЕ ловит (id 97, 27 380 ₽).
    Закреплено как известное: закроют промах — тест покраснеет и потребует
    пересмотра, а не промолчит. До тех пор такой чек спрашивает человека
    только порогом."""
    assert тип_продавца('Рестран "Шушу"') == НЕ_ОПОЗНАН
    assert нужно_подтверждение('ООО "ШУШУ"', 'Рестран "Шушу"', 27380, 10000) is True


# ── СЕТИ ОБЩЕПИТА БЕРУТСЯ ИЗ TRIGGERS, А НЕ КОПИЕЙ ─────────────────────────


def test_исключённые_слова_закупки_живут_в_своих_статьях():
    """Вычитаемое слово обязано существовать там, откуда вычитается: иначе
    исключение устарело, а сторож молчит."""
    источник = {с for статья in СТАТЬИ_СЕТЕЙ_ОБЩЕПИТА for с in TRIGGERS[статья]}
    assert НЕ_ЗАВЕДЕНИЯ <= источник, НЕ_ЗАВЕДЕНИЯ - источник


def test_сети_взяты_из_статей_без_слов_закупки():
    источник = [с for статья in СТАТЬИ_СЕТЕЙ_ОБЩЕПИТА for с in TRIGGERS[статья]]
    assert list(СЕТИ_ОБЩЕПИТА) == [с for с in источник if с not in НЕ_ЗАВЕДЕНИЯ]
    assert "макдоналдс" in СЕТИ_ОБЩЕПИТА and "чай" not in СЕТИ_ОБЩЕПИТА


def test_чай_не_делает_продавца_общепитом():
    """«чай» подстрокой сидит в «случайный» — слово закупки, а не заведения."""
    assert тип_продавца("ООО Случайный выбор") == НЕ_ОПОЗНАН


