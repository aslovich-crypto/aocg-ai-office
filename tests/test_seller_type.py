def test_общепит_требует_подтверждения_при_любой_сумме():
    assert нужно_подтверждение("ООО Бар", "Паб Арден", 100, 10000) is True
    assert нужно_подтверждение("ООО Бар", "Паб Арден", 100, None) is True


