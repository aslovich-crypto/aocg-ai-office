"""CAT-FOOD ②: отбор чеков, держащих выгрузку, и текст отказа Р5 — без базы.

⚠️ ТЕКСТ ОБЯЗАН ПОМЕЩАТЬСЯ НА ЭКРАН (решение владельца 21.09.2026): в отчёте 9
под флагом 26 чеков, поимённо — только пять самых крупных, остальное числом.
"""

import pytest

from app.category_confirm import неподтверждённые, текст_отказа

ФРАЗА = "Категорию выбрала машина, а в 1С уйдёт статья расхода — решает человек."


def _чеки(n):
    return [
        {"id": 100 + i, "org_brand": "Заведение %d" % i, "amount": 1000 + i}
        for i in range(n)
    ]


def test_при_двадцати_шести_поимённо_только_пять_крупнейших():
    текст = текст_отказа(_чеки(26))
    assert текст.count("Чек №") == 5
    for номер in (125, 124, 123, 122, 121):
        assert "Чек №%d" % номер in текст
    assert "Чек №120" not in текст
    assert "и ещё 21 чек." in текст
    assert текст.startswith("Подтвердите категорию у 26 чеков")
    assert текст.endswith(ФРАЗА)


def test_при_пяти_и_меньше_все_поимённо_без_остатка():
    текст = текст_отказа(_чеки(3))
    assert текст.count("Чек №") == 3 and "и ещё" not in текст
    assert текст.startswith("Подтвердите категорию у 3 чеков")


@pytest.mark.parametrize(
    "всего, у_скольких, остаток",
    [
        (6, "у 6 чеков", "и ещё 1 чек."),
        (7, "у 7 чеков", "и ещё 2 чека."),
        (16, "у 16 чеков", "и ещё 11 чеков."),
        (26, "у 26 чеков", "и ещё 21 чек."),
        (27, "у 27 чеков", "и ещё 22 чека."),
    ],
)
def test_числительные_по_правилам(всего, у_скольких, остаток):
    текст = текст_отказа(_чеки(всего))
    assert у_скольких in текст and остаток in текст


def test_один_чек_в_родительном():
    assert текст_отказа(_чеки(1)).startswith("Подтвердите категорию у 1 чека ")


def test_держат_выгрузку_только_неподтверждённые_с_флагом():
    чеки = [
        {"id": 1, "category_confirm_required": True, "category_manual": False},
        {"id": 2, "category_confirm_required": True, "category_manual": True},
        {"id": 3, "category_confirm_required": False, "category_manual": False},
    ]
    assert [ч["id"] for ч in неподтверждённые(чеки)] == [1]
