"""Сторож разбора markdown-таблиц и согласованности трекера (T30).

ПОЧЕМУ ЭТО ТЕСТ, А НЕ РАЗОВЫЙ СКРИПТ. Разбор текста не падает, когда врёт, —
он молча отдаёт другое число. Значит проверять его надо на КАЖДОМ прогоне,
а не в тот день, когда писали. Контрольный пример лежит фикстурой в
`tests/tools/fixtures/md_control.tsv`: инструмент можно переписать, ответ
должен остаться.

Проверяются три вещи, и третья — не про инструмент, а про документ:
① разбор верен на известных ответах; ② он ЛОВИТ заведомо битую таблицу
(иначе «расхождений 0» ничего не значит); ③ в `docs/TASKS.md` каждая строка
таблицы совпадает по числу ячеек со своим заголовком. Лишняя ячейка не
рендерится вовсе — так однажды стало невидимым содержимое T7 и T8.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tests" / "tools"))

import md_table  # noqa: E402


def test_контрольный_пример_разбирается_верно():
    assert md_table.самопроверка(), (
        "Разбор markdown разошёлся с контрольным примером "
        "(tests/tools/fixtures/md_control.tsv). Чинить разбор, а не фикстуру: "
        "правка ожиданий под сломанный разбор превращает сторож в декорацию."
    )


def test_экранированный_столб_не_делит_ячейку():
    строка = r"| S-02 | текст с \| внутри | 🟡 | ⬜ | — | — | и тут \| тоже |"
    assert len(md_table.ячейки(строка)) == 7


def test_ловит_битую_таблицу(tmp_path):
    """Известный ПЛОХОЙ ответ: без него «расхождений 0» ничего не доказывает."""
    файл = tmp_path / "битая.md"
    файл.write_text(
        "| A | B | C |\n| --- | --- | --- |\n| 1 | 2 | 3 |\n| 1 | 2 | 3 | 4 |\n",
        encoding="utf-8",
    )
    беды = md_table.проверить_файл(str(файл))
    assert len(беды) == 1, f"лишняя ячейка не поймана: {беды}"
    assert ":4:" in беды[0], f"не указана строка с бедой: {беды[0]}"


def test_трекер_согласован_по_числу_ячеек():
    трекер = Path(md_table.КОРЕНЬ) / "docs" / "TASKS.md"
    беды = md_table.проверить_файл(str(трекер))
    assert not беды, "Строки трекера разъехались:\n" + "\n".join(беды)
