#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЗАМЕР ВОЗМОЖНОСТЕЙ ПЛОЩАДКИ 1С — ТОЛЬКО ЧТЕНИЕ (1C-23, заход ①).

⚠️⚠️ НИ ОДНОЙ ЗАПИСИ. Скрипт шлёт ТОЛЬКО GET и проверяет это сам: любой
другой метод отвергается до сети, отдельно от общего списка клиента (там
POST и PATCH разрешены — они нужны выгрузке, но не здесь). Ни `POST`, ни
`PATCH`, ни тем более `DELETE` из этого файла уйти не может.

⚠️ ЗАПУСКАЕТ ВЛАДЕЛЕЦ, НЕ АГЕНТ. В оболочке агента доступов к 1С нет и не
будет; «проверил на живой базе» из неё невозможно в принципе.

ЗАЧЕМ. На площадке 1С:Фреш опробованы РОВНО ДВА инструмента запроса:
`$filter` — мёртв (девять проб 17.09.2026, все 500 «Операция не разрешена
в предложении ГДЕ») и `$select` — работает. `$top`, `$skip`, `$orderby`,
счётчик записей и продолжение страницы не пробовались НИ РАЗУ (улика
24.09.2026). Без них нельзя ни найти документ после обрыва связи, ни даже
назвать цену поиска: справочники конечны и замерены, документы копятся.

⚠️ МЕТКА ПРОГОНА ПЕРВОЙ СТРОКОЙ (принцип замера №5). Вывод этого скрипта
попадёт в отчёт; без метки старый вывод неотличим от свежего, и однажды
это уже чуть не стоило разбора (журнал заливки, 18.08.2026).

⚠️ САМОПРОВЕРКА ДО ЗАМЕРА, ОБЕ ПОЛОВИНЫ (принцип замера №3):
  · заведомо ЖИВОЕ — `$metadata` обязан ответить 200. Не ответил: доступы
    или сеть, замерять нечего, выходим;
  · заведомо МЁРТВОЕ — `$filter` обязан ответить ошибкой. Ответил 200 —
    ЭТО НЕ ПОВОД РАДОВАТЬСЯ: значит либо площадка сменилась, либо мы
    говорим не с той базой. Прогон останавливается и просит показать вывод.
Без второй половины «всё зелено» неотличимо от «проверка не выполнялась».

ЗАПУСК (на машине владельца, из корня репозитория бэкенда):
    ./venv/bin/python scripts/probe_1c_read.py

Переменные окружения нужны те же, что выгрузке: ODATA_URL, ODATA_LOGIN,
ODATA_PASSWORD. Скрипт ничего не пишет на диск и не печатает ни адреса
целиком, ни логина — только безопасный вид адреса.
"""

from __future__ import annotations

import asyncio
import datetime
import getpass
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app import odata_client  # noqa: E402

ДОКУМЕНТЫ = "Document_АвансовыйОтчет"
СПРАВОЧНИК = "ChartOfAccounts_Хозрасчетный"
# Поля, ради которых всё и затевается: по «Комментарию» опознаётся НАШ
# документ («AOCG AI Офис · отчёт №N»), по `Posted` — проведён ли он.
ПОЛЯ = "Ref_Key,Number,Date,Posted,Комментарий"


# ⚠️ СВОЙ ЗАПРЕТ, А НЕ ССЫЛКА НА ЧУЖОЙ. В клиенте разрешены GET, POST
# и PATCH — они нужны выгрузке. Здесь замер, и записи быть не должно вовсе:
# правило, которое держится обещанием в докстроке, ничего не держит.
ТОЛЬКО = "GET"


async def прочитать(путь: str, параметры: dict | None = None, метод: str = ТОЛЬКО):
    """ТОЛЬКО GET. Возвращает (код, размер ответа в байтах, разобранное тело)."""
    if метод != ТОЛЬКО:
        raise RuntimeError("замер шлёт только %s, а не %s" % (ТОЛЬКО, метод))
    код, ответ = await odata_client.запросить(путь, метод=ТОЛЬКО, параметры=параметры)
    тело = (ответ or {}).get("тело")
    размер = len(json.dumps(тело, ensure_ascii=False)) if тело is not None else 0
    return код, размер, тело


def строк(тело) -> str:
    """Сколько записей вернулось — или почему сказать нечего."""
    if not isinstance(тело, dict):
        return "тело не словарь"
    if "value" not in тело:
        return "поля value нет"
    return str(len(тело["value"]))


def счётчик(тело) -> str:
    """Счётчик записей, если площадка его отдала. Имена у v3 и v4 разные."""
    if not isinstance(тело, dict):
        return "—"
    for имя in ("odata.count", "@odata.count", "__count"):
        if имя in тело:
            return "%s = %s" % (имя, тело[имя])
    return "нет"


def продолжение(тело) -> str:
    if not isinstance(тело, dict):
        return "—"
    for имя in ("odata.nextLink", "@odata.nextLink", "__next"):
        if имя in тело:
            return "ЕСТЬ (%s)" % имя
    return "нет"


class НечегоСпросить(RuntimeError):
    """Доступов нет и спросить некого — ввод не с клавиатуры."""


def спросить_доступы():
    """Доступы из окружения, а если их там нет — с клавиатуры.

    ⚠️ НИЧЕГО НЕ СОХРАНЯЕТСЯ И НЕ ПЕЧАТАЕТСЯ. Введённое живёт только
    в памяти этого процесса: ни файла, ни истории оболочки, ни вывода.
    Пароль читается `getpass` — без эха, поэтому на экране его не увидит
    ни человек за спиной, ни снимок экрана.

    ⚠️ ПОЧЕМУ НЕ ПРЕДЛАГАЕМ ВПИСАТЬ ИХ В КОМАНДУ. Команда с паролем
    попадает в историю оболочки и остаётся там надолго — это тот же класс,
    что файл со строкой подключения, забытый на диске (замер 18.08.2026).

    ⚠️ ВВОД НЕ С КЛАВИАТУРЫ — НЕ СПРАШИВАЕМ. Скрипт, запущенный из
    конвейера или планировщика, повиснет на `input` молча; лучше честный
    отказ, чем прогон, который никогда не кончится.
    """
    try:
        return odata_client.настройки()
    except odata_client.НетДоступов:
        pass
    if not sys.stdin.isatty():
        print("ДОСТУПЫ НЕ ЗАДАНЫ, а спросить некого: ввод не с клавиатуры.")
        print(
            "Задайте %s, %s и %s — или запустите скрипт в терминале."
            % (
                odata_client.ПЕРЕМЕННАЯ_АДРЕСА,
                odata_client.ПЕРЕМЕННАЯ_ЛОГИНА,
                odata_client.ПЕРЕМЕННАЯ_ПАРОЛЯ,
            )
        )
        raise НечегоСпросить
    print("ДОСТУПОВ К 1С В ОКРУЖЕНИИ НЕТ — спрошу здесь, ничего не сохраняя.")
    print("Взять их в панели Timeweb → приложение бэкенда → Переменные:")
    print("  %s     — адрес интерфейса OData" % odata_client.ПЕРЕМЕННАЯ_АДРЕСА)
    print("  %s   — логин пользователя 1С" % odata_client.ПЕРЕМЕННАЯ_ЛОГИНА)
    print("  %s — пароль (вводится без эха)\n" % odata_client.ПЕРЕМЕННАЯ_ПАРОЛЯ)
    адрес = input("Адрес (%s): " % odata_client.ПЕРЕМЕННАЯ_АДРЕСА).strip()
    логин = input("Логин (%s): " % odata_client.ПЕРЕМЕННАЯ_ЛОГИНА).strip()
    пароль = getpass.getpass(
        "Пароль (%s, ввод не виден): " % odata_client.ПЕРЕМЕННАЯ_ПАРОЛЯ
    )
    if not (адрес and логин and пароль):
        print("Пусто — замерять нечего.")
        raise НечегоСпросить
    # Кладём в окружение ЭТОГО процесса: клиент читает доступы оттуда,
    # а процесс кончится вместе с прогоном и заберёт их с собой.
    os.environ[odata_client.ПЕРЕМЕННАЯ_АДРЕСА] = адрес
    os.environ[odata_client.ПЕРЕМЕННАЯ_ЛОГИНА] = логин
    os.environ[odata_client.ПЕРЕМЕННАЯ_ПАРОЛЯ] = пароль
    print()
    return odata_client.настройки()


async def main() -> int:
    начало = datetime.datetime.now().astimezone()
    print("МЕТКА ПРОГОНА: %s" % начало.strftime("%d.%m.%Y %H:%M:%S %z"))
    try:
        полный, _логин, _пароль = спросить_доступы()
    except НечегоСпросить:
        return 2
    адрес = odata_client.безопасный_адрес(полный)
    # ⚠️ ЦЕЛЬ НАЗЫВАЕТСЯ В ОТЧЁТЕ (правило про прибор, прибитый к цели):
    # зелёный результат без адреса ничего не говорит о том, ЧТО измерено.
    print("ЦЕЛЬ: %s" % адрес)
    print("МЕТОД: только GET, записи нет ни одной\n")

    print("── САМОПРОВЕРКА ──")
    код, _, _ = await прочитать("$metadata")
    print("  заведомо живое  · $metadata                 → код %s" % код)
    if код != 200:
        print("  ✗ СТОП: база не отвечает на схему. Дальше мерить нечего —")
        print("    это доступы или сеть, а не возможности запроса.")
        return 1
    код_ф, _, тело_ф = await прочитать(СПРАВОЧНИК, {"$filter": "Code eq '26'"})
    print("  заведомо мёртвое · $filter по плану счетов   → код %s" % код_ф)
    if код_ф == 200:
        print("  ✗ СТОП И ПОКАЗАТЬ ВЫВОД: $filter ОТВЕТИЛ УСПЕХОМ, хотя девять")
        print("    проб 17.09.2026 дали 500. Либо площадка сменилась, либо мы")
        print("    говорим не с той базой. Верить остальным числам нельзя.")
        print("    Ответ: %s" % json.dumps(тело_ф, ensure_ascii=False)[:200])
        return 1
    print("  ✓ обе половины сошлись: живое отвечает, мёртвое отказывает\n")

    print("── ЗАМЕР: ЧТО УМЕЕТ ЗАПРОС ──")
    опыты = [
        ("$top=1", ДОКУМЕНТЫ, {"$top": "1"}),
        ("$top=1 + $select нужных полей", ДОКУМЕНТЫ, {"$top": "1", "$select": ПОЛЯ}),
        (
            "$orderby=Date desc + $top=1",
            ДОКУМЕНТЫ,
            {"$orderby": "Date desc", "$top": "1"},
        ),
        ("$skip=1 + $top=1", ДОКУМЕНТЫ, {"$skip": "1", "$top": "1"}),
        (
            "$inlinecount=allpages (OData v3)",
            ДОКУМЕНТЫ,
            {"$top": "1", "$inlinecount": "allpages"},
        ),
        ("$count=true (OData v4)", ДОКУМЕНТЫ, {"$top": "1", "$count": "true"}),
    ]
    for имя, путь, параметры in опыты:
        код, размер, тело = await прочитать(путь, параметры)
        print(
            "  %-34s → код %-3s · записей %-4s · счётчик %-22s · продолжение %s"
            % (имя, код, строк(тело), счётчик(тело), продолжение(тело))
        )

    print("\n── ЗАМЕР: СКОЛЬКО ВЕСЯТ ДОКУМЕНТЫ ──")
    print("  ⚠️ Следующий запрос читает журнал документов БЕЗ ограничения.")
    print("  Если площадка не умеет $top, узнать объём иначе нечем. Ждём до")
    print("  20 секунд (таймаут клиента); не дождались — так и запишем.")
    код, размер, тело = await прочитать(ДОКУМЕНТЫ, {"$select": ПОЛЯ})
    print(
        "  весь журнал с $select → код %s · записей %s · %s КБ · продолжение %s"
        % (код, строк(тело), round(размер / 1024, 1), продолжение(тело))
    )

    print("\n── ЗАМЕР: ЧИТАЮТСЯ ЛИ POSTED И КОММЕНТАРИЙ ──")
    код, _, тело = await прочитать(ДОКУМЕНТЫ, {"$top": "3", "$select": ПОЛЯ})
    записи = тело.get("value") if isinstance(тело, dict) else None
    if код == 200 and записи:
        for з in записи[:3]:
            есть = [п for п in ПОЛЯ.split(",") if п in з]
            # ⚠️ КОММЕНТАРИЙ ПЕЧАТАЕТСЯ УСЕЧЁННЫМ: это чужой документ, и в нём
            # может стоять что угодно, включая имя человека.
            print(
                "  поля пришли: %-45s · Posted=%s · комментарий «%s…»"
                % (
                    ",".join(есть) or "НИ ОДНОГО",
                    з.get("Posted", "поля нет"),
                    str(з.get("Комментарий", ""))[:40],
                )
            )
    else:
        print("  записей не пришло (код %s) — читать нечего" % код)

    print(
        "\nМЕТКА ОКОНЧАНИЯ: %s"
        % datetime.datetime.now().astimezone().strftime("%d.%m.%Y %H:%M:%S %z")
    )
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
