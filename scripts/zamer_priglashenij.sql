\echo '── ① КТО СЕЙЧАС В ОРГАНИЗАЦИИ 1 ──────────────────────────────────'
SELECT
    id,
    email,
    role,
    is_active                     AS активен,
    is_email_verified             AS почта_подтверждена,
    created_at                    AS заведён
FROM users
WHERE org_id = 1
ORDER BY created_at;

\echo ''
\echo '── ② ПРИГЛАШЕНИЯ: НА КОГО ВЫПИСАНЫ И ЧТО С НИМИ ──────────────────'
-- uses_count против max_uses отвечает «использовано ли»; is_active —
-- погасла ли ссылка. Токен НЕ печатаем целиком: он даёт вход в организацию,
-- а вывод копируют в переписку. Хвоста хватает, чтобы отличить одну от другой.
SELECT
    id,
    right(token, 6)               AS токен_хвост,
    email                         AS почта_в_приглашении,
    first_name || ' ' || COALESCE(last_name, '') AS имя_в_приглашении,
    role                          AS роль,
    uses_count || ' из ' || max_uses AS использований,
    is_active                     AS ссылка_жива,
    created_at                    AS выписано,
    sent_at                       AS отправлено,
    expires_at                    AS истекает
FROM invite_links
WHERE org_id = 1
ORDER BY created_at;

\echo ''
\echo '── ③ СОВПАЛА ЛИ ПОЧТА: ПРИГЛАШЕНИЕ ПРОТИВ ЗАВЕДЁННОГО ЧЕЛОВЕКА ───'
-- ⚠️ ГЛАВНЫЙ ВОПРОС. Сегодня сервер НЕ сверяет адрес: регистрация берёт
-- почту из формы, а из приглашения — только организацию и роль. Этот запрос
-- показывает, разошлись ли они по факту.
-- Сопоставляем по времени: человек заведён ПОСЛЕ выписки ссылки и раньше
-- следующей — точной связи «кто по какой ссылке вошёл» в базе нет, и это
-- само по себе находка (связь не хранится).
SELECT
    i.id                          AS приглашение,
    i.email                       AS звали_на_почту,
    u.email                       AS зарегистрировался_под,
    CASE
        WHEN u.email IS NULL THEN 'по этой ссылке ещё не входили'
        WHEN lower(COALESCE(i.email, '')) = lower(u.email) THEN 'СОВПАЛА'
        ELSE '⚠️ РАЗОШЛАСЬ'
    END                           AS вердикт,
    i.role                        AS роль_в_приглашении,
    u.role                        AS роль_фактическая,
    u.created_at                  AS человек_заведён
FROM invite_links i
LEFT JOIN LATERAL (
    SELECT *
    FROM users u2
    WHERE u2.org_id = i.org_id
      AND u2.created_at >= i.created_at
    ORDER BY u2.created_at
    LIMIT 1
) u ON TRUE
WHERE i.org_id = 1
ORDER BY i.created_at;

\echo ''
\echo '── ④ ЛОВУШКА T103: НЕ ЗАВЁЛ ЛИ ВОШЕДШИЙ СЕБЕ ОТДЕЛЬНУЮ ОРГАНИЗАЦИЮ ─'
-- Регистрация ПО ССЫЛКЕ берёт организацию из приглашения и своей не создаёт
-- (проверено по коду). Но обычная регистрация — создаёт. Если человек зашёл
-- не по ссылке, а через общий экран, он окажется в СВОЕЙ организации, и его
-- чеки будут не видны в вашей. Здесь видно все организации и их население.
SELECT
    o.id,
    o.name                        AS организация,
    o.created_at                  AS создана,
    count(u.id)                   AS людей,
    string_agg(u.email, ', ' ORDER BY u.created_at) AS почты
FROM organizations o
LEFT JOIN users u ON u.org_id = o.id
GROUP BY o.id, o.name, o.created_at
ORDER BY o.id;

\echo ''
\echo '── ⑤ ГАСНЕТ ЛИ ССЫЛКА ПОСЛЕ ИСПОЛЬЗОВАНИЯ ────────────────────────'
-- По коду: после регистрации uses_count увеличивается на единицу, а is_active
-- становится ложью, когда счётчик достиг max_uses. При max_uses = 1 (умолчание)
-- ссылка гаснет с первого входа. Запрос показывает, так ли это на деле.
SELECT
    id,
    right(token, 6)               AS токен_хвост,
    uses_count                    AS использований,
    max_uses                      AS предел,
    is_active                     AS ссылка_жива,
    CASE
        WHEN uses_count >= max_uses AND is_active THEN '⚠️ ИСЧЕРПАНА, НО ЖИВА'
        WHEN uses_count >= max_uses THEN 'исчерпана и погашена — верно'
        WHEN is_active THEN 'ещё можно войти'
        ELSE 'погашена досрочно'
    END                           AS вердикт
FROM invite_links
WHERE org_id = 1
ORDER BY created_at;

