def _вставка_вида(вид: str, статья: str, ссылка: str, признак: str) -> str:
    return (
        "INSERT INTO org_expense_kind_map (org_id, tax_kind, expense_ref,"
        " expense_name, usn_reflection)\n"
        "VALUES (%d, '%s', '%s', '%s', '%s')\n"
        "ON CONFLICT (org_id, tax_kind) DO UPDATE SET"
        " expense_ref = EXCLUDED.expense_ref,"
        " expense_name = EXCLUDED.expense_name,"
        " usn_reflection = EXCLUDED.usn_reflection, updated_at = NOW();"
        % (ОРГАНИЗАЦИЯ, вид, ссылка, статья, признак)
    )


def _проверки() -> list:
    return [
        "-- ① Профиль организации. Ожидается ОДНА строка с '%s' и счётом '%s'.\n"
        "SELECT legal_form, tax_regime, vat_mode, combines_psn,"
        " default_account_code, auto_post_policy\n"
        "  FROM org_accounting_profile WHERE org_id = %d;"
        % (ПРОФИЛЬ["tax_regime"], ПРОФИЛЬ["default_account_code"], ОРГАНИЗАЦИЯ),
        "-- ② Правил по видам расхода. Ожидается %d.\n"
        "SELECT count(*) AS правил FROM org_expense_kind_map WHERE org_id = %d;"
        % (len(ПРАВИЛА_ВИДОВ), ОРГАНИЗАЦИЯ),
        "-- ③ Виды расхода БЕЗ правила: ожидается %d — те, что ждут статей.\n"
        "SELECT DISTINCT c.tax_kind AS без_правила FROM categories c\n"
        "  LEFT JOIN org_expense_kind_map m\n"
        "    ON m.tax_kind = c.tax_kind AND m.org_id = c.org_id\n"
        " WHERE c.org_id = %d AND m.id IS NULL ORDER BY 1;"
        % (len(ЖДУТ_СТАТЬЮ), ОРГАНИЗАЦИЯ),
        "-- ④ Сколько чеков попадёт «без соответствия» при нынешних правилах.\n"
        "SELECT c.tax_kind, count(r.id) AS чеков FROM receipts r\n"
        "  JOIN categories c ON c.id = r.category_id\n"
        "  LEFT JOIN org_expense_kind_map m\n"
        "    ON m.tax_kind = c.tax_kind AND m.org_id = c.org_id\n"
        " WHERE r.org_id = %d AND m.id IS NULL GROUP BY c.tax_kind ORDER BY 2 DESC;"
        % ОРГАНИЗАЦИЯ,
    ]


def напечатать_sql(закрепить: bool) -> None:
    print(
        "-- ЗАСЕВ ПРОФИЛЯ И ПРАВИЛ ПО ВИДАМ РАСХОДА (1C-22), организация %d"
        % ОРГАНИЗАЦИЯ
    )
    if закрепить:
        print("-- ⚠️⚠️ ЭТО ЗАПИСЬ: в конце COMMIT. Сначала прогоните сухой вариант.")
    else:
        print("-- ⚠️ СУХОЙ ПРОГОН: в конце ROLLBACK, база останется как была.")
    print("BEGIN;")
    print(_вставка_профиля())
    for вид, статья, ссылка, признак, _почему in ПРАВИЛА_ВИДОВ:
        print(_вставка_вида(вид, статья, ссылка, признак))
    for замер in _проверки():
        print(замер)
    print("COMMIT;" if закрепить else "ROLLBACK;")
    print(
        "-- Правил в засеве: %d. Ждут статей: %d."
        % (len(ПРАВИЛА_ВИДОВ), len(ЖДУТ_СТАТЬЮ))
    )
    for вид, статья, _ссылка, _признак, почему in ПРАВИЛА_ВИДОВ:
        print("--   %s → «%s» (%s)" % (вид, статья, почему))
    for вид, что, признак in ЖДУТ_СТАТЬЮ:
        print("--   ЖДЁТ: %s → завести %s, признак %s" % (вид, что, признак))


async def прогнать(адрес: str, закрепить: bool) -> int:
    import asyncpg

    соединение = await asyncpg.connect(адрес)
    try:
        сделка = соединение.transaction()
        await сделка.start()
        закреплено = False
        try:
            строка_орг = await соединение.fetchrow(
                "SELECT tax_system FROM organizations WHERE id=$1", ОРГАНИЗАЦИЯ
            )
            if строка_орг is None:
                print("  ✗ ОРГАНИЗАЦИИ %d В БАЗЕ НЕТ — засев отменён" % ОРГАНИЗАЦИЯ)
                return 1
            в_карточке = строка_орг["tax_system"]
            ожидаемый = РЕЖИМ_ОРГАНИЗАЦИИ.get(ПРОФИЛЬ["tax_regime"])
            if ожидаемый is None or в_карточке != ожидаемый:
                # ⚠️ ОТКАЗ ЦЕЛИКОМ, А НЕ ПРЕДУПРЕЖДЕНИЕ: разошедшиеся режимы
                # означают, что экран и документ считают по-разному.
                print(
                    "  ✗ РЕЖИМ РАСХОДИТСЯ: в профиле «%s», в карточке организации "
                    "«%s» (ожидалось «%s») — засев отменён"
                    % (ПРОФИЛЬ["tax_regime"], в_карточке, ожидаемый)
                )
                return 1
            await соединение.execute(_вставка_профиля())
            for вид, статья, ссылка, признак, _почему in ПРАВИЛА_ВИДОВ:
                await соединение.execute(_вставка_вида(вид, статья, ссылка, признак))

            профилей = await соединение.fetchval(
                "SELECT count(*) FROM org_accounting_profile WHERE org_id=$1",
                ОРГАНИЗАЦИЯ,
            )
            правил = await соединение.fetchval(
                "SELECT count(*) FROM org_expense_kind_map WHERE org_id=$1",
                ОРГАНИЗАЦИЯ,
            )
            print(
                "  профиль: %d строка · правил по видам: %d (ожидалось %d)"
                % (профилей, правил, len(ПРАВИЛА_ВИДОВ))
            )
            for вид, что, признак in ЖДУТ_СТАТЬЮ:
                print("    ждёт статью: %s → %s (%s)" % (вид, что, признак))
            if профилей != 1 or правил != len(ПРАВИЛА_ВИДОВ):
                print("  ✗ СОСТАВ НЕ СОШЁЛСЯ — не закрепляю")
                return 1
            if закрепить:
                await сделка.commit()
                закреплено = True
                print("  ✓ ЗАКРЕПЛЕНО")
            else:
                print("  ✓ сухой прогон сошёлся, ничего не записано")
        finally:
            if not закреплено:
                await сделка.rollback()
        return 0
    finally:
        await соединение.close()


def main() -> int:
    if "--sql" in sys.argv or "--sql-apply" in sys.argv:
        напечатать_sql("--sql-apply" in sys.argv)
        return 0
    адрес = os.getenv("DATABASE_URL", "").strip()
    if not адрес:
        print("DATABASE_URL не задан. Запускать с бастиона либо с ключом --sql.")
        return 1
    закрепить = "--apply" in sys.argv
    print(
        "\nЗАСЕВ ПРОФИЛЯ И ПРАВИЛ: %s\n"
        % ("С ЗАПИСЬЮ (--apply)" if закрепить else "сухой прогон, запись выключена")
    )
    return asyncio.run(прогнать(адрес, закрепить))


if __name__ == "__main__":
    sys.exit(main())
