def _вставка_профиля() -> str:
    return (
        "INSERT INTO org_accounting_profile (org_id, legal_form, tax_regime,"
        " vat_mode, combines_psn, default_account_code, auto_post_policy)\n"
        "VALUES (%d, '%s', '%s', '%s', %s, '%s', '%s')\n"
        "ON CONFLICT (org_id) DO UPDATE SET legal_form = EXCLUDED.legal_form,"
        " tax_regime = EXCLUDED.tax_regime, vat_mode = EXCLUDED.vat_mode,"
        " combines_psn = EXCLUDED.combines_psn,"
        " default_account_code = EXCLUDED.default_account_code,"
        " auto_post_policy = EXCLUDED.auto_post_policy, updated_at = NOW();"
        % (
            ОРГАНИЗАЦИЯ,
            ПРОФИЛЬ["legal_form"],
            ПРОФИЛЬ["tax_regime"],
            ПРОФИЛЬ["vat_mode"],
            "TRUE" if ПРОФИЛЬ["combines_psn"] else "FALSE",
            ПРОФИЛЬ["default_account_code"],
            ПРОФИЛЬ["auto_post_policy"],
        )
    )


