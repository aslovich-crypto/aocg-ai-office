def _строка_вставки(имя: str, статья: str, ссылка: str) -> str:
    """Одна вставка. ⚠️ ЧЕРЕЗ SELECT ИЗ `categories`: идентификатор берётся
    из базы по имени, а не подставляется числом."""
    return (
        "INSERT INTO odata_category_map (org_id, category_id, account_code,"
        " expense_ref, expense_name, usn_reflection)\n"
        "SELECT %d, c.id, '%s', '%s', '%s', '%s' FROM categories c\n"
        " WHERE c.org_id = %d AND c.name = '%s'\n"
        "ON CONFLICT (org_id, category_id) DO UPDATE SET"
        " account_code = EXCLUDED.account_code,"
        " expense_ref = EXCLUDED.expense_ref,"
        " expense_name = EXCLUDED.expense_name,"
        " usn_reflection = EXCLUDED.usn_reflection,"
        " updated_at = NOW();"
        % (ОРГАНИЗАЦИЯ, СЧЁТ, ссылка, статья, ПРИНИМАЮТСЯ, ОРГАНИЗАЦИЯ, имя)
    )


def _проверки() -> list:
    """Замеры ПОСЛЕ вставки: сколько легло и какие категории остались."""
    имена = ",".join("('%s')" % имя for имя, _, _ in СОПОСТАВЛЕНИЕ)
    return [
        "-- ① Имена, которых нет в справочнике категорий. Ожидается НОЛЬ строк.\n"
        "SELECT ж.name AS не_найдена FROM (VALUES %s) AS ж(name)\n"
        " WHERE NOT EXISTS (SELECT 1 FROM categories c\n"
        "                    WHERE c.org_id = %d AND c.name = ж.name);"
        % (имена, ОРГАНИЗАЦИЯ),
        "-- ② Сколько правил у организации. Ожидается %d.\n"
        "SELECT count(*) AS правил FROM odata_category_map WHERE org_id = %d;"
        % (len(СОПОСТАВЛЕНИЕ), ОРГАНИЗАЦИЯ),
        "-- ③ Категории БЕЗ правила. Ожидается %d — те, что ждут статью.\n"
        "SELECT c.name AS без_правила FROM categories c\n"
        " LEFT JOIN odata_category_map m ON m.category_id = c.id AND m.org_id = c.org_id\n"
        " WHERE c.org_id = %d AND m.id IS NULL ORDER BY c.name;"
        % (len(ЖДУТ_СТАТЬЮ), ОРГАНИЗАЦИЯ),
    ]


def напечатать_sql(закрепить: bool) -> None:
    print("-- ЗАСЕВ СООТВЕТСТВИЙ КАТЕГОРИЙ (1C-22), организация %d" % ОРГАНИЗАЦИЯ)
    if закрепить:
        print("-- ⚠️⚠️ ЭТО ЗАПИСЬ: в конце COMMIT. Сначала прогоните сухой вариант.")
    else:
        print("-- ⚠️ СУХОЙ ПРОГОН: в конце ROLLBACK, база останется как была.")
    print("BEGIN;")
    for имя, статья, ссылка in СОПОСТАВЛЕНИЕ:
        print(_строка_вставки(имя, статья, ссылка))
    for замер in _проверки():
        print(замер)
    print("COMMIT;" if закрепить else "ROLLBACK;")
    print(
        "-- Правил в засеве: %d. Ждут статью: %d. Всего категорий: %d."
        % (len(СОПОСТАВЛЕНИЕ), len(ЖДУТ_СТАТЬЮ), len(СОПОСТАВЛЕНИЕ) + len(ЖДУТ_СТАТЬЮ))
    )
    for имя, статья, усн in ЖДУТ_СТАТЬЮ:
        print("--   ждёт: %s → «%s» (%s)" % (имя, статья, усн))


async def прогнать(адрес: str, закрепить: bool) -> int:
    import asyncpg

    соединение = await asyncpg.connect(адрес)
    try:
        сделка = соединение.transaction()
        await сделка.start()
        закреплено = False
        try:
            нет = [
                имя
                for имя, _, _ in СОПОСТАВЛЕНИЕ
                if not await соединение.fetchval(
                    "SELECT 1 FROM categories WHERE org_id=$1 AND name=$2",
                    ОРГАНИЗАЦИЯ,
                    имя,
                )
            ]
            if нет:
                # ⚠️ НИЧЕГО НЕ ПИШЕМ ВООБЩЕ: частичный засев хуже отсутствующего.
                print("  ✗ НЕ НАЙДЕНЫ КАТЕГОРИИ (%d): %s" % (len(нет), ", ".join(нет)))
                return 1
            for имя, статья, ссылка in СОПОСТАВЛЕНИЕ:
                await соединение.execute(_строка_вставки(имя, статья, ссылка))
            правил = await соединение.fetchval(
                "SELECT count(*) FROM odata_category_map WHERE org_id=$1", ОРГАНИЗАЦИЯ
            )
            без_правила = [
                з["name"]
                for з in await соединение.fetch(
                    "SELECT c.name FROM categories c"
                    " LEFT JOIN odata_category_map m"
                    "   ON m.category_id = c.id AND m.org_id = c.org_id"
                    " WHERE c.org_id=$1 AND m.id IS NULL ORDER BY c.name",
                    ОРГАНИЗАЦИЯ,
                )
            ]
            print(
                "  правил после засева: %d (ожидалось %d)"
                % (правил, len(СОПОСТАВЛЕНИЕ))
            )
            print(
                "  категорий без правила: %d (ожидалось %d)"
                % (len(без_правила), len(ЖДУТ_СТАТЬЮ))
            )
            for имя in без_правила:
                print("    ждёт статью: %s" % имя)
            if правил != len(СОПОСТАВЛЕНИЕ) or len(без_правила) != len(ЖДУТ_СТАТЬЮ):
                print("  ✗ СОСТАВ НЕ СОШЁЛСЯ — не закрепляю")
                return 1
            if закрепить:
                await сделка.commit()
                закреплено = True
                print("  ✓ ЗАКРЕПЛЕНО")
            else:
                print("  ✓ сухой прогон сошёлся, ничего не записано")
        finally:
            if not закреплено:
                await сделка.rollback()
        return 0
    finally:
        await соединение.close()


def main() -> int:
    if "--sql" in sys.argv or "--sql-apply" in sys.argv:
        напечатать_sql("--sql-apply" in sys.argv)
        return 0
    адрес = os.getenv("DATABASE_URL", "").strip()
    if not адрес:
        print("DATABASE_URL не задан. Запускать с бастиона либо с ключом --sql.")
        return 1
    закрепить = "--apply" in sys.argv
    print(
        "\nЗАСЕВ СООТВЕТСТВИЙ КАТЕГОРИЙ: %s\n"
        % ("С ЗАПИСЬЮ (--apply)" if закрепить else "сухой прогон, запись выключена")
    )
    return asyncio.run(прогнать(адрес, закрепить))


if __name__ == "__main__":
    sys.exit(main())
