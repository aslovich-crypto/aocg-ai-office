# -*- coding: utf-8 -*-
"""Боевые значения против описи (S-49, сторож ②).

ЛОВИТ ГЛАВНОЕ: переменную, которая в панели годами не соответствует
замыслу. Именно так `SECURITY_AUTH_RATE_LIMIT` простоял 50 при умолчании
кода 5 — сверка нашлась случайно 27.08.2026, а до неё 502 зелёных теста
мерили умолчание, то есть прибор смотрел не туда, где стояло значение.

⚠️ ЗАПУСКАТЬ ТАМ, ГДЕ ЖИВЁТ ПРИЛОЖЕНИЕ: внутри прод-контейнера или на
бастионе с тем же окружением. Локальный прогон покажет ЛОКАЛЬНЫЕ значения
и ничего не скажет о панели — поэтому прибор сам называет, где он.

⚠️ ЗНАЧЕНИЯ СЕКРЕТОВ НЕ ПЕЧАТАЮТСЯ НИКОГДА. Про них говорится только
«задан / не задан» и длина: вывод прибора попадает в журналы и в переписку,
и распечатанный ключ подписи там жил бы вечно.

КОДЫ ВЫХОДА: 0 — сошлось · 1 — расхождение с описью · 3 — не выполнено.
"""

import os
import socket
import sys

# Что проверяем: имя → (ожидание, пояснение при расхождении).
# Ожидание — либо точное значение, либо ("<=", N), либо «задан»/«пусто».
СЕКРЕТЫ = {
    "JWT_SECRET_KEY",
    "POSTBOX_SMTP_PASSWORD",
    "S3_ACCESS_KEY",
    "S3_SECRET_KEY",
    "MAX_RELAY_TOKEN",
    "MAX_TOKEN",
    "ANTHROPIC_API_KEY",
    "PROVERKACHEKA_TOKEN",
    "DATABASE_URL",
    "SENTRY_DSN",
}

ОЖИДАНИЯ = [
    # (имя, вид, значение, пояснение)
    (
        "JWT_SECRET_KEY",
        "задан",
        None,
        "без него приложение не стартует; утечка = подделка любого токена",
    ),
    (
        "JWT_ALGORITHM",
        "равно_или_пусто",
        "HS256",
        "вне белого списка код применит HS256 и напишет в журнал",
    ),
    ("ACCESS_TOKEN_EXPIRE_MINUTES", "не_больше", 240, "срок жизни украденного токена"),
    ("REFRESH_TOKEN_EXPIRE_DAYS", "не_больше", 90, "срок жизни долгой сессии"),
    (
        "SECURITY_AUTH_RATE_LIMIT",
        "не_больше",
        20,
        "перебор по многим учёткам с одного адреса",
    ),
    (
        "SECURITY_AUTO_BAN_THRESHOLD",
        "не_больше",
        20,
        "большой порог обесценивает лимиты",
    ),
    (
        "SECURITY_ENFORCE_HTTPS",
        "не_выключено",
        None,
        "выключение открывает канал для токена в заголовке",
    ),
    (
        "CORS_ORIGINS",
        "задан",
        None,
        "пустая переменная разрешает обращения с ЛЮБОГО сайта",
    ),
    ("APP_URL", "задан", None, "адрес в письмах подтверждения и восстановления"),
    ("DATABASE_URL", "задан", None, "без неё нет ни одной операции"),
    ("POSTBOX_SMTP_HOST", "задан", None, "без почты регистрация САМОПОДТВЕРЖДАЕТСЯ"),
    ("POSTBOX_SMTP_USER", "задан", None, "то же"),
    ("POSTBOX_SMTP_PASSWORD", "задан", None, "то же"),
    ("POSTBOX_FROM", "задан", None, "то же"),
    ("MAX_RELAY_TOKEN", "задан", None, "единственная защита ручек /internal/max/*"),
    (
        "BOOTSTRAP_ADMIN_EMAIL",
        "пусто",
        None,
        "заданный адрес заведёт лишнего администратора (S-23)",
    ),
    (
        "ENVIRONMENT",
        "равно_или_пусто",
        "production",
        "метка события в приёмнике ошибок",
    ),
    ("S3_BUCKET", "задан", None, "без хранилища фото остаются в базе"),
    ("S3_ENDPOINT", "задан", None, "то же"),
]

ЯВНОЕ_НЕТ = {"0", "false", "no", "off"}


def _показать(имя: str, сырое) -> str:
    if сырое is None:
        return "НЕ ЗАДАНА"
    if имя in СЕКРЕТЫ:
        return f"задан ({len(сырое)} знаков)" if сырое else "ПУСТАЯ СТРОКА"
    return f"«{сырое}»" if сырое else "ПУСТАЯ СТРОКА"


def main() -> int:
    где = os.getenv("HOSTNAME") or socket.gethostname()
    есть_база = bool(os.getenv("DATABASE_URL"))
    print("БОЕВЫЕ ЗНАЧЕНИЯ ПРОТИВ ОПИСИ (AOCG-ENV-001)")
    print(f"  замер снят на: {где}")
    if not есть_база:
        # Признак «это не прод»: без DATABASE_URL приложение здесь не работает.
        print("  ⚠️ DATABASE_URL не задана — похоже, это НЕ окружение приложения.")
        print("     Прибор покажет локальные значения; для сверки с панелью")
        print("     запускайте его внутри прод-контейнера или на бастионе.")

    беды = []
    for имя, вид, эталон, пояснение in ОЖИДАНИЯ:
        сырое = os.getenv(имя)
        значение = (сырое or "").strip()
        ок = True
        если_нет = ""

        if вид == "задан":
            ок = bool(значение)
            если_нет = "обязана быть задана"
        elif вид == "пусто":
            ок = not значение
            если_нет = "обязана оставаться пустой"
        elif вид == "равно_или_пусто":
            ок = (not значение) or значение == эталон
            если_нет = f"ожидалось «{эталон}»"
        elif вид == "не_больше":
            if not значение:
                ок = True  # умолчание кода уже безопасно
            else:
                try:
                    ок = int(значение) <= эталон
                except ValueError:
                    ок = False
                если_нет = f"должно быть не больше {эталон}"
        elif вид == "не_выключено":
            ок = значение.lower() not in ЯВНОЕ_НЕТ
            если_нет = "защита выключена явно"

        знак = "✓" if ок else "✗"
        print(f"  {знак} {имя}: {_показать(имя, сырое)}")
        if not ок:
            print(f"      {если_нет} — {пояснение}")
            беды.append(имя)

    print()
    if беды:
        print(f"  ⚠️ РАСХОЖДЕНИЙ С ОПИСЬЮ: {len(беды)} — {', '.join(беды)}")
        print("     Правьте значение в панели ЛИБО опись, если замысел изменился.")
        return 1
    print("  ✓ боевые значения совпали с описью")
    return 0


if __name__ == "__main__":
    sys.exit(main())
