"""Боевые значения против описи (S-49, сторож ②) — ручной запуск.

⚠️ ЛОГИКА ЖИВЁТ В `app/env_check.py`, ЗДЕСЬ ТОЛЬКО ВЫВОД. Вторая копия
правил разошлась бы с первой молча — так уже разошлась копия скилла
task-update и копия пакета безопасности. Одна сверка, два входа: на старте
контейнера (журнал деплоя, виден владельцу в панели) и этой командой.

⚠️ ЗАПУСКАТЬ ТАМ, ГДЕ ЖИВЁТ ПРИЛОЖЕНИЕ: внутри прод-контейнера. Локальный
прогон покажет ЛОКАЛЬНЫЕ значения и о панели не скажет ничего — поэтому
прибор сам называет, где он, и предупреждает, если это не то место.

⚠️ ЗНАЧЕНИЯ СЕКРЕТОВ НЕ ПЕЧАТАЮТСЯ НИКОГДА: только «задан» и длина. Вывод
попадает в журналы и в переписку, и распечатанный ключ подписи жил бы там
вечно.

КОДЫ ВЫХОДА: 0 — сошлось · 1 — расхождение с описью.
"""

import os
import socket
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.env_check import ОЖИДАНИЯ, показать, сверить  # noqa: E402


def main() -> int:
    где = os.getenv("HOSTNAME") or socket.gethostname()
    print("БОЕВЫЕ ЗНАЧЕНИЯ ПРОТИВ ОПИСИ (AOCG-ENV-001)")
    print(f"  замер снят на: {где}")
    if not os.getenv("DATABASE_URL"):
        # Признак «это не прод»: без DATABASE_URL приложение здесь не работает.
        print("  ⚠️ DATABASE_URL не задана — похоже, это НЕ окружение приложения.")
        print("     Значения ниже локальные; для сверки с панелью запускайте")
        print("     прибор внутри прод-контейнера.")

    расхождения = {имя: угроза for имя, _видно, угроза in сверить()}
    for имя, _вид, _эталон, _угроза in ОЖИДАНИЯ:
        сырое = os.getenv(имя)
        плохо = имя in расхождения
        print(f"  {'✗' if плохо else '✓'} {имя}: {показать(имя, сырое)}")
        if плохо:
            print(f"      {расхождения[имя]}")

    print()
    if расхождения:
        имена = ", ".join(расхождения)
        print(f"  ⚠️ РАСХОЖДЕНИЙ С ОПИСЬЮ: {len(расхождения)} — {имена}")
        print("     Правьте значение в панели ЛИБО опись, если замысел изменился.")
        return 1
    print(f"  ✓ боевые значения совпали с описью (проверено {len(ОЖИДАНИЯ)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
