# -*- coding: utf-8 -*-
"""Предел входа, измеренный СНАРУЖИ — как его видит нападающий (S-49, ③).

ЗАЧЕМ ТРЕТИЙ ПРИБОР, КОГДА ЕСТЬ ДВА. Сторож описи читает КОД, сторож
боевых значений читает ОКРУЖЕНИЕ. Оба могут быть зелёными, а предел
не работать: значение прочитано верно, но обратный прокси площадки
отдаёт всем один адрес, или ограничитель обходится другим путём.
Единственный честный ответ даёт попытка.

⚠️ ОСТАНАВЛИВАЕМСЯ НА ПЕРВОМ ЖЕ ОТКАЗЕ. Каждое превышение лимита
приближает автобан адреса (порог 10, бан 5 минут), а забаненный
измеритель — это «проверка не выполнена» на четверть часа. Поэтому
шлём по одной попытке и выходим, как только увидели 429.

⚠️ ПАРОЛЬ И АДРЕС ЗАВЕДОМО НЕСУЩЕСТВУЮЩИЕ. Прибор не должен трогать
живые учётные записи: неудачные попытки по НАСТОЯЩЕМУ адресу копят
`failed_attempts` и блокируют человека на 15 минут (app/routers/auth.py).

ЗАПУСК:
    python scripts/check_rate_limit_live.py                  # прод
    python scripts/check_rate_limit_live.py http://127.0.0.1:8000

КОДЫ ВЫХОДА: 0 — предел сработал не позже ожидаемого · 1 — не сработал
(или сработал слишком рано) · 3 — проверка не выполнена.
"""

import sys
import urllib.error
import urllib.request
import json

АДРЕС_ПО_УМОЛЧАНИЮ = "https://api.aocgai.ru"
# Потолок строгого лимита в коде (aocg_security/middleware.py). Ожидаем
# отказ не позже, чем на попытке ПОТОЛОК+1; запас в 4 попытки — на случай,
# если окно ограничителя частично занято чужими запросами.
ПОТОЛОК = 20
ПОТОЛОК_ПОПЫТОК = ПОТОЛОК + 5


def _попытка(база: str, номер: int) -> int:
    тело = json.dumps(
        {
            # Адрес заведомо несуществующий: домен .invalid зарезервирован
            # стандартом и не может принадлежать человеку.
            "phone_or_email": f"probe-{номер}@example.invalid",
            "password": "wrong-on-purpose",
        }
    ).encode()
    запрос = urllib.request.Request(
        f"{база}/api/auth/login",
        data=тело,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(запрос, timeout=15) as ответ:
            return ответ.status
    except urllib.error.HTTPError as e:
        return e.code
    except Exception as e:  # noqa: BLE001 — владельцу нужна причина, не трейс
        print(f"  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: сеть не ответила — {type(e).__name__}: {e}")
        sys.exit(3)


def main() -> int:
    база = (sys.argv[1] if len(sys.argv) > 1 else АДРЕС_ПО_УМОЛЧАНИЮ).rstrip("/")
    print("ПРЕДЕЛ ВХОДА, ИЗМЕРЕННЫЙ СНАРУЖИ")
    print(f"  адрес: {база} · ожидаем отказ не позже попытки {ПОТОЛОК + 1}")

    for номер in range(1, ПОТОЛОК_ПОПЫТОК + 1):
        код = _попытка(база, номер)
        if код == 429:
            print(f"  попытка {номер}: 429 — предел сработал")
            if номер <= 2:
                # Слишком рано — тоже беда: значит по своим бьёт сильнее,
                # чем по чужим, и утренний вход из офиса упрётся в предел.
                print("  ✗ предел сработал СЛИШКОМ РАНО: своим войти не дадут")
                return 1
            print(f"\n  ✓ отказ по частоте на попытке {номер} (потолок {ПОТОЛОК})")
            return 0
        if код not in (401, 403, 422):
            print(f"  попытка {номер}: неожиданный код {код}")
            print("  ✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: ручка отвечает не как обычно")
            return 3

    print(f"\n  ✗ ЗА {ПОТОЛОК_ПОПЫТОК} ПОПЫТОК ОТКАЗА ПО ЧАСТОТЕ НЕ БЫЛО.")
    print("     Перебор паролей по многим учёткам с одного адреса не ограничен.")
    print("     Смотрите SECURITY_AUTH_RATE_LIMIT в панели и потолок в коде.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
