# -*- coding: utf-8 -*-
"""Опись боевых настроек против КОДА (S-49, сторож ①).

ЛОВИТ: переменную, которую код читает, а опись о ней не знает — и наоборот.
Без этого сторожа опись устареет молча, ровно как устаревала карта
архитектуры: её писали, по ней не работали, и расхождение нашлось спустя
месяц отдельным аудитом (T52).

ЧТО СЧИТАЕТСЯ ЧТЕНИЕМ ПЕРЕМЕННОЙ: `os.getenv("ИМЯ"...)` и
`os.environ.get("ИМЯ"...)`, а также `os.environ["ИМЯ"]`. Имена берутся
РАЗБОРОМ ИСХОДНИКА (ast), а не регулярным выражением: регулярка спотыкается
о перенос строки и о вызовы внутри f-строк, и «не нашла» выглядело бы как
«переменной нет».

⚠️ ИМЕНА ЧЕРЕЗ КОНСТАНТУ ТОЖЕ НАХОДЯТСЯ. `app/email_service.py` читает
почтовые настройки как `os.getenv(SMTP_HOST)`, где `SMTP_HOST` — строковая
константа модуля. Разбор подставляет значения таких констант, иначе четыре
почтовые переменные (а с ними самоподтверждение регистрации) выпали бы
из-под сторожа целиком.

КОДЫ ВЫХОДА: 0 — сошлось · 1 — расхождение · 3 — проверка не выполнена.
"""

import ast
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ОПИСЬ = КОРЕНЬ / "docs/AOCG-ENV-001-2026_Opis_boevyh_nastroek.md"
ШАБЛОН = КОРЕНЬ / ".env.example"
КАТАЛОГИ = ("app", "aocg_security")

# Читаются самим прибором/тестами, не приложением: в описи им не место.
# Функции, читающие окружение внутри себя: первый аргумент — имя переменной.
# ⚠️ СПИСОК ПОПОЛНЯЕТСЯ ВМЕСТЕ С КОДОМ, и сторож сам об этом скажет:
# `_не_дольше` появилась 04.09.2026 в app/auth.py, и прибор тут же
# объявил два срока жизни токенов «мёртвыми». Это не ложное
# срабатывание, а его работа: новое чтение окружения обязано быть
# либо прямым, либо через известную обёртку.
ОБЁРТКИ = {"_env_int", "_env_bool", "_защита_выключена_явно", "_не_дольше"}

НЕ_БОЕВЫЕ = {
    "AOCG_BACKEND",  # путь к репозиторию для проб фронта
    "TEST_DATABASE_URL",  # живой контур тестов
    "PYTEST_CURRENT_TEST",
}


def _имена_из_файла(путь: Path) -> set:
    дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
    # Строковые константы модуля: SMTP_HOST = "POSTBOX_SMTP_HOST"
    константы = {}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Assign) and isinstance(узел.value, ast.Constant):
            if isinstance(узел.value.value, str):
                for цель in узел.targets:
                    if isinstance(цель, ast.Name):
                        константы[цель.id] = узел.value.value

    имена = set()

    def _строка(узел):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            return узел.value
        if isinstance(узел, ast.Name):
            return константы.get(узел.id)
        return None

    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Call) and узел.args:
            ф = узел.func
            if isinstance(ф, ast.Attribute):
                владелец = ф.value
                # os.getenv / os.environ.get
                if ф.attr == "getenv" and getattr(владелец, "id", "") == "os":
                    имя = _строка(узел.args[0])
                    if имя:
                        имена.add(имя)
                elif ф.attr == "get" and isinstance(владелец, ast.Attribute):
                    if владелец.attr == "environ":
                        имя = _строка(узел.args[0])
                        if имя:
                            имена.add(имя)
            # ⚠️ ОБЁРТКИ СЧИТАЮТСЯ ЧТЕНИЕМ, И БЕЗ ЭТОГО СТОРОЖ СЛЕП НА САМОЕ
            # ВАЖНОЕ. Все четыре SECURITY_* читаются через `_env_int(...)`,
            # то есть os.getenv стоит ВНУТРИ обёртки с параметром-именем.
            # Первая редакция прибора искала только прямые вызовы и объявила
            # ровно те переменные, ради которых заведена S-49, «мёртвыми».
            elif isinstance(ф, ast.Name) and ф.id in ОБЁРТКИ:
                имя = _строка(узел.args[0])
                if имя:
                    имена.add(имя)
        # os.environ["ИМЯ"]
        if isinstance(узел, ast.Subscript) and isinstance(узел.value, ast.Attribute):
            if узел.value.attr == "environ":
                срез = узел.slice
                имя = _строка(срез)
                if имя:
                    имена.add(имя)
    return имена


def main() -> int:
    if not ОПИСЬ.exists():
        print(f"✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: описи нет по пути {ОПИСЬ}")
        return 3

    в_коде = set()
    файлов = 0
    for каталог in КАТАЛОГИ:
        for путь in (КОРЕНЬ / каталог).rglob("*.py"):
            файлов += 1
            try:
                в_коде |= _имена_из_файла(путь)
            except SyntaxError as e:  # noqa: PERF203 — причина нужна пофайлово
                print(f"✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: {путь} не разобрался — {e}")
                return 3
    if not файлов:
        print("✗ ПРОВЕРКА НЕ ВЫПОЛНЕНА: исходников не найдено — это поломка замера")
        return 3
    в_коде -= НЕ_БОЕВЫЕ

    текст = ОПИСЬ.read_text(encoding="utf-8")
    # ⚠️ ИМЕНА БЕРУТСЯ ИЗ ПЕРВОГО СТОЛБЦА ТАБЛИЦ, А НЕ ОТОВСЮДУ. Первая
    # редакция собирала любые слова в обратных кавычках и притащила `HS256` —
    # это ЗНАЧЕНИЕ переменной, а не имя, и сторож требовал найти его в коде.
    # Ложное срабатывание отменяет сторожа: на него перестают смотреть.
    в_описи = set()
    for строка in текст.splitlines():
        if not строка.startswith("| `"):
            continue
        ячейка = строка.split("|")[1]
        в_описи |= set(re.findall(r"`([A-Z][A-Z0-9_]{2,})`", ячейка))

    # ⚠️ ВТОРАЯ СВЕРКА — ШАБЛОН `.env.example` (T64). Он объясняет человеку,
    # какие переменные бывают, и разошёлся с кодом однажды настолько, что
    # строка T61 говорила про «18 мёртвых имён и 18 недостающих». Замер
    # 04.09.2026 показал другое: мёртвых ноль, недостающих пять — и все пять
    # про защиту (четыре SECURITY_* и API_DOCS_PUBLIC). Человек, читающий
    # шаблон, не узнал бы о них вовсе.
    в_шаблоне = set()
    if ШАБЛОН.exists():
        for строка in ШАБЛОН.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if строка and not строка.startswith("#") and "=" in строка:
                в_шаблоне.add(строка.split("=")[0].strip())

    нет_в_описи = sorted(в_коде - в_описи)
    нет_в_коде = sorted(
        и for и in в_описи - в_коде if not и.startswith(("VITE_", "RAILWAY_", "GH_"))
    )

    print("ОПИСЬ БОЕВЫХ НАСТРОЕК ПРОТИВ КОДА")
    print(f"  переменных читает код: {len(в_коде)} · названо в описи: {len(в_описи)}")
    if нет_в_описи:
        print(f"\n  ✗ ЧИТАЮТСЯ КОДОМ, НО НЕ ОПИСАНЫ ({len(нет_в_описи)}):")
        for и in нет_в_описи:
            print(f"      {и}")
        print("    Допишите их в опись: последствие неверного значения должно")
        print("    быть названо ДО того, как оно случится на проде.")
    if нет_в_коде:
        print(f"\n  ⚠️ ОПИСАНЫ, НО КОД ИХ НЕ ЧИТАЕТ ({len(нет_в_коде)}):")
        for и in нет_в_коде:
            print(f"      {и}")
        print("    Либо переменная мертва и её пора убрать из панели,")
        print("    либо её чтение снесли, а опись не поправили.")
    нет_в_шаблоне = sorted(в_коде - в_шаблоне) if в_шаблоне else []
    мёртвые_в_шаблоне = sorted(в_шаблоне - в_коде) if в_шаблоне else []

    if not ШАБЛОН.exists():
        print("\n  ⚠️ .env.example не найден — сверка шаблона НЕ ВЫПОЛНЕНА")
    else:
        print(f"  шаблон .env.example: имён {len(в_шаблоне)}")
    if нет_в_шаблоне:
        print(f"\n  ✗ ЧИТАЮТСЯ КОДОМ, НО НЕ НАЗВАНЫ В ШАБЛОНЕ ({len(нет_в_шаблоне)}):")
        for и in нет_в_шаблоне:
            print(f"      {и}")
        print("    Человек, поднимающий приложение, о них не узнает.")
    if мёртвые_в_шаблоне:
        print(
            f"\n  ✗ НАЗВАНЫ В ШАБЛОНЕ, НО КОД ИХ НЕ ЧИТАЕТ ({len(мёртвые_в_шаблоне)}):"
        )
        for и in мёртвые_в_шаблоне:
            print(f"      {и}")
        print("    Мёртвое имя в шаблоне переживает свою переменную и вводит")
        print("    в заблуждение того, кто настраивает окружение с нуля.")

    if нет_в_описи or нет_в_коде or нет_в_шаблоне or мёртвые_в_шаблоне:
        return 1
    print("\n  ✓ код, опись и шаблон сошлись")
    return 0


if __name__ == "__main__":
    sys.exit(main())
